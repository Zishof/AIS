	/**
	 * <b>Status keluar tujuan</b> yang diberlakukan kepada seluruh anggota kelompok (Lulus,
	 * Drop Out, Mengundurkan Diri, dan seterusnya) &mdash; relasi {@code @ManyToOne} lazy ke
	 * {@link StatusKeluar} lewat kolom {@code status_keluar_mahasiswa} yang {@code NOT NULL}.
	 *
	 * <p><b>Getter menulis balik ke field</b> (pola standar entity AIS): hasil
	 * {@code GeneralValueObject.check(Object)} ditugaskan kembali ke {@code statusKeluar} sebelum
	 * dikembalikan, karena {@code check()} dapat mengembalikan <i>instance lain</i> &mdash;
	 * instance kanonik dari {@code EntityIdentityMap}, hasil cache, atau hasil muat ulang. Bila
	 * object ini sudah <i>detached</i>, {@code check()} dapat membuka sesi Hibernate sendiri untuk
	 * memuat ulang relasi lalu menutupnya kembali; ia tidak pernah melempar exception dan tidak
	 * pernah mengembalikan {@code null} untuk argumen non-null.</p>
	 *
	 * <p><b>Dampak nilai ini jauh melampaui baris kelompok.</b> {@link Mahasiswa#getStatusKeluar()}
	 * mengganti status keluar perorangan setiap anggotanya dengan nilai dari sini, sekaligus
	 * melewati pemeriksaan kelengkapan data kelulusan yang berlaku untuk jalur perorangan. Karena
	 * status keluar menjadi penjaga di banyak modul (penagihan, KRS, kelayakan wisuda, pelaporan
	 * PDDikti), mengubah nilai ini pada kelompok yang sudah punya anggota mengubah status akademik
	 * seluruh anggotanya seketika, tanpa langkah konfirmasi tambahan dan tanpa jejak per-mahasiswa.</p>
	 *
	 * <p>{@code CascadeType.PERSIST}/{@code MERGE} berarti menyimpan kelompok ikut menyimpan
	 * perubahan pada object {@link StatusKeluar} yang tertaut &mdash; bukan menghapusnya
	 * ({@code REMOVE} sengaja tidak disertakan, karena master status keluar dipakai bersama).</p>
	 *
	 * @return status keluar tujuan; secara skema tidak boleh {@code null}, tetapi bisa {@code null}
	 *         pada object di memori yang belum diisi.
	 */
	@ManyToOne(cascade = { CascadeType.PERSIST, CascadeType.MERGE }, fetch = FetchType.LAZY)
	@JoinColumn(name = "status_keluar_mahasiswa", nullable = false)
	public StatusKeluar getStatusKeluar() {
		statusKeluar = check(statusKeluar);
		return statusKeluar;
	}

