	/**
	 * Tahun akademik berlakunya SK, dalam format {@code "2024/2025"}. Kolom {@code NOT NULL}.
	 *
	 * <p><b>Getter dengan nilai default terhitung.</b> Bila field masih {@code null}, yang
	 * dikembalikan adalah {@code Common.getCurrentTahunAkademik()} &mdash; tahun akademik yang
	 * sedang berjalan menurut konfigurasi sistem. Karena kelas ini memakai <i>property access</i>
	 * (anotasi JPA pada getter), <b>nilai default inilah yang ikut tersimpan ke database</b> saat
	 * baris baru di-{@code INSERT} meski pemanggil tidak pernah memanggil setter-nya. Efeknya
	 * ganda:</p>
	 * <ul>
	 *   <li>batasan {@code NOT NULL} praktis tidak pernah dilanggar &mdash; jalur tulis yang lupa
	 *       mengisi periode tetap lolos, diam-diam memakai periode berjalan;</li>
	 *   <li>nilai yang dikembalikan bersifat <b>tidak stabil</b> selama field masih {@code null}:
	 *       object yang sama bisa menjawab berbeda setelah pergantian periode akademik. Nilai baru
	 *       "membeku" begitu baris tersimpan (karena Hibernate lalu mengisi field saat memuat
	 *       ulang), bukan sebelumnya.</li>
	 * </ul>
	 * <p>Perhatikan juga bahwa getter ini <b>tidak</b> menulis balik ke field &mdash; berbeda dari
	 * pola {@code check()} pada {@link #getStatusKeluar()}. Jadi selama belum tersimpan,
	 * {@code kelompok.tahunAkademik} tetap {@code null} sementara {@code getTahunAkademik()}
	 * mengembalikan nilai; jangan menyimpulkan "sudah diisi" dari hasil getter.</p>
	 *
	 * <p>Nilai ini bukan sekadar label periode: bersama {@link #getSemester()} ia dipakai
	 * {@code Mahasiswa.hitungSmtLulus(StatusKeluar, Mahasiswa)} untuk <b>menghitung ulang semester
	 * lulus</b> setiap anggota (menimpa nilai perorangan), dan oleh
	 * {@code ais.action.master.resources.FeederResource} untuk merakit kode periode keluar yang
	 * dilaporkan ke PDDikti.</p>
	 *
	 * @return tahun akademik SK; tidak pernah {@code null} selama konfigurasi tahun akademik
	 *         berjalan tersedia.
	 */
	@Column(name = "tahun_akademik", nullable = false)
	public String getTahunAkademik() {
		return tahunAkademik == null ? Common.getCurrentTahunAkademik() : tahunAkademik;
	}

