	/**
	 * Mengembalikan saklar berlakunya baris ini.
	 *
	 * <p><b>Kuirk penting:</b> {@code null} dipetakan menjadi {@code true} — baris yang belum
	 * pernah disetel <b>dianggap AKTIF</b>. Sikap ini <i>fail-safe</i> untuk keamanan (baris daftar
	 * hitam berlaku selama tidak dinonaktifkan eksplisit) dan membuat baris bawaan hasil
	 * penyemaian {@code InitDataHelper} ({@code kode = "23.106.*"}, {@code aktif} tak diisi)
	 * langsung berlaku di setiap instalasi baru.</p>
	 *
	 * <p>Karena kelas ini memakai <i>property access</i>, nilai {@code true} inilah yang dibaca
	 * Hibernate saat <i>dirty checking</i>, sehingga baris ber-{@code aktif NULL} yang dimuat lalu
	 * di-<i>flush</i> dapat ter-{@code UPDATE} menjadi {@code true} secara permanen. Semantiknya
	 * tidak berubah, tetapi riwayat Envers akan mencatat perubahan yang tidak pernah diminta
	 * operator.</p>
	 *
	 * <p>Dibaca gerbang penegakan {@code FilterLoginAis.saveLoginAndCheckBlacklist(...)} sebelum
	 * memanggil {@link #chek(String)}, serta oleh <i>checkbox</i> "Aktif" pada grid
	 * {@code BlacklistIpAction}.</p>
	 *
	 * @return {@code true} bila baris berlaku (termasuk saat nilai tersimpan {@code null})
	 */
