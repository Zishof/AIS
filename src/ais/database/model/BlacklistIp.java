	/**
	 * Mengembalikan pola alamat IP yang diblokir, sudah dipangkas spasi tepinya.
	 *
	 * <p><b>Kuirk:</b> {@code null} dikembalikan sebagai {@code ""} — sengaja, supaya
	 * {@link #chek(String)} tidak pernah melempar {@code NullPointerException} pada sisi pola.
	 * Efek sampingnya, karena Hibernate membaca nilai lewat <i>getter</i> ini saat
	 * <i>dirty checking</i>, baris dengan {@code kode} {@code NULL} di basis data dapat
	 * ter-{@code UPDATE} menjadi string kosong, dan spasi tepi terhapus permanen, hanya karena
	 * barisnya dimuat dalam sesi yang kemudian di-<i>flush</i>.</p>
	 *
	 * @return pola IP yang sudah di-<i>trim</i>; {@code ""} bila belum diisi (tidak pernah {@code null})
	 */
	public String getKode() {
		return kode == null ? "" : kode.trim();
	}

