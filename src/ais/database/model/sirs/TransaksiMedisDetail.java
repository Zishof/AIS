	/**
	 * Mengembalikan nilai rupiah diskon per satuan, dengan menghitung ulang dari persentase untuk baris
	 * non-racikan.
	 *
	 * <p><b>Getter destruktif.</b> Bila {@code racikan} kosong, field {@code diskon} dinormalkan dari
	 * {@code null} menjadi {@code 0.0} lalu <i>ditimpa</i> dengan
	 * {@code getAmount() * (getDiskonPersen() / 100.0)}. Karena getter dipetakan Hibernate, hasil hitung
	 * itu ikut tersimpan pada flush berikutnya.</p>
	 * <p>Konsekuensi yang perlu dipahami:</p>
	 * <ul>
	 *   <li><b>Diskon rupiah tidak dapat diberikan.</b> Syarat penimpaan adalah
	 *       {@code getDiskonPersen() != null}, sedangkan {@link #getDiskonPersen()} dirancang tidak pernah
	 *       mengembalikan {@code null} (ia menormalkan {@code null} menjadi {@code 0.0}). Syarat itu
	 *       karenanya SELALU terpenuhi. Diskon rupiah yang diisi manual lewat
	 *       {@link #setDiskon(Double)} akan berubah menjadi {@code 0.0} pada pembacaan pertama bila
	 *       persentasenya nol — dan nilai nol itu ikut tersimpan. Pemberian potongan dalam rupiah
	 *       (misalnya pembulatan ke bawah, atau potongan kebijakan sebesar nilai tertentu) tidak mungkin
	 *       dilakukan lewat entity ini; satu-satunya jalan adalah menyatakannya sebagai persentase.</li>
	 *   <li><b>Diskon dihitung per satuan, bukan per baris.</b> Pengalinya adalah {@link #getAmount()}
	 *       (harga satuan), bukan {@code amount * qty}. Hal ini konsisten dengan
	 *       {@link #getHasilPenghitunganTotal()} yang mengalikan seluruh selisih dengan kuantitas, jadi
	 *       hasil akhirnya benar — tetapi angka yang tersimpan di kolom {@code diskon} bermakna "diskon per
	 *       satuan", bukan "diskon baris". Laporan yang menjumlahkan kolom itu secara langsung akan
	 *       melaporkan total diskon yang terlalu kecil untuk baris berkuantitas lebih dari satu.</li>
	 *   <li><b>Baris racikan berperilaku sebaliknya.</b> Bila {@code racikan} terisi, seluruh blok
	 *       dilewati dan nilai yang tersimpan dikembalikan apa adanya — termasuk {@code null}. Jadi
	 *       {@link #getHasilPenghitunganTotal()} dapat melempar {@code NullPointerException} pada baris
	 *       racikan yang kolom diskonnya belum pernah diisi, karena operasi {@code getAmount() -
	 *       getDiskon()} membuka bungkus {@link Double} yang bernilai {@code null}. Perbedaan perilaku
	 *       antara baris racikan dan non-racikan ini mudah terlewat karena tidak tampak dari tanda tangan
	 *       method.</li>
	 *   <li><b>Bergantung pada harga.</b> Karena pengalinya {@link #getAmount()}, mengubah harga satuan —
	 *       termasuk lewat harga manual {@link #getAmountCustom()} — otomatis mengubah nilai rupiah diskon
	 *       pada pembacaan berikutnya, tanpa ada yang menyentuh kolom diskon.</li>
	 * </ul>
	 *
	 * @return nilai rupiah diskon per satuan; untuk baris racikan dapat {@code null}.
	 */
	public Double getDiskon() {
		if (racikan == null) {
			if (diskon == null) {
				diskon = 0.0;
			}

			if (getDiskonPersen() != null && getAmount() != null) {
				diskon = getAmount() * (getDiskonPersen() / 100.0);
			}
		}
		return diskon;
	}

