	/**
	 * Mengembalikan harga satuan yang ditagihkan, setelah menerapkan harga manual dan nilai mutlak.
	 *
	 * <p><b>Getter destruktif.</b> Dua penimpaan terjadi berurutan:</p>
	 * <ol>
	 *   <li>Bila {@link #getMenggunakanAmountCustom()} bernilai benar, {@code amount} diganti dengan
	 *       {@link #getAmountCustom()} (atau {@code 0.0} bila harga manual kosong).</li>
	 *   <li>{@code amount} kemudian dinormalkan menjadi {@code Math.abs(...)}, dengan {@code null}
	 *       diperlakukan sebagai {@code 0.0}.</li>
	 * </ol>
	 * <p>Konsekuensi yang perlu dipahami:</p>
	 * <ul>
	 *   <li><b>Nilai negatif berbalik menjadi tagihan.</b> Pemaksaan nilai mutlak berarti harga
	 *       {@code -50.000} berubah menjadi {@code +50.000}. Baris yang dimaksudkan sebagai koreksi atau
	 *       potongan — cara yang lazim dipakai untuk membatalkan sebagian tagihan tanpa menghapus jejak —
	 *       akan <i>menambah</i> tagihan alih-alih menguranginya, dan karena getter ini dipetakan
	 *       Hibernate, tanda minusnya hilang permanen dari database pada flush berikutnya. Pembatalan
	 *       sebagian karena itu harus ditempuh lewat mekanisme retur ({@link TransaksiRetur}), bukan lewat
	 *       harga negatif. Perhatikan bahwa pemaksaan ini tidak melindungi total baris: persentase diskon
	 *       di atas 100 tetap dapat membuat {@link #getHasilPenghitunganTotal()} negatif.</li>
	 *   <li><b>Harga manual mengalahkan master tarif tanpa jejak.</b> Bila penanda harga manual menyala,
	 *       tarif dari master {@link ItemMedis}/{@link Tindakan}/{@link AlatMedis} tidak dilihat sama
	 *       sekali dan tidak ada apa pun di entity ini yang membatasi selisihnya, mencatat alasannya, atau
	 *       menuntut persetujuan. Satu-satunya jejak perubahan harga adalah tabel audit Envers.</li>
	 *   <li><b>Harga manual yang kosong berarti gratis.</b> Menyalakan penanda tanpa mengisi nilainya
	 *       membuat harga satuan menjadi {@code 0.0} secara diam-diam, bukan memicu kesalahan.</li>
	 *   <li><b>Dua buku besar ikut terpengaruh.</b> {@link DetailTransaksiPasien#getAmount()} dan
	 *       {@link DetailTransaksiLayanan#getAmount()} menyalin nilai dari method ini setiap kali dibaca,
	 *       sehingga perubahan harga di sini merambat ke kedua buku besar tanpa proses tersendiri.</li>
	 * </ul>
	 *
	 * @return harga satuan yang ditagihkan; selalu bernilai nol atau positif.
	 */
	public Double getAmount() {

		if (getMenggunakanAmountCustom()) {
			amount = getAmountCustom() == null ? 0.0 : getAmountCustom();
		}

		amount = Math.abs(amount == null ? 0.0 : amount);
		return amount;
	}

