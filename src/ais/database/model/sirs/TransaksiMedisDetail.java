	/**
	 * Mengembalikan nilai total baris, dihitung ulang sebagai
	 * {@code qty * ((amount - diskon) + pajak)}.
	 *
	 * <p><b>Getter destruktif dan getter terhitung.</b> Seluruh komponennya dibaca lewat getter, sehingga
	 * satu pemanggilan method ini memicu seluruh rantai perhitungan di kelas ini sekaligus: harga manual
	 * pada {@link #getAmount()}, kuantitas sewa alat pada {@link #getQty()}, serta diskon dan pajak dari
	 * persentase. Semua penimpaan yang terjadi di sepanjang rantai itu ikut tersimpan pada flush
	 * berikutnya, jadi membaca total baris <i>bukan</i> operasi baca murni.</p>
	 * <p>Hal-hal yang perlu diperhatikan:</p>
	 * <ul>
	 *   <li><b>Diskon dan pajak bersifat per satuan.</b> Keduanya dikurangkan/ditambahkan pada harga
	 *       satuan lebih dahulu, baru seluruhnya dikalikan kuantitas. Rumusnya konsisten, tetapi berbeda
	 *       dari model "diskon atas nilai baris" yang lazim dipakai laporan; menjumlahkan kolom
	 *       {@code diskon} apa adanya akan meremehkan total diskon.</li>
	 *   <li><b>Tidak ada penjaga nilai negatif.</b> Persentase diskon di atas 100 menghasilkan total baris
	 *       negatif, yang kemudian mengurangi total nota tanpa penolakan di mana pun. Berbeda dengan
	 *       {@link #getAmount()} yang memaksa nilai mutlak, hasil method ini tidak dinormalkan.</li>
	 *   <li><b>Baris racikan berisiko {@code NullPointerException}.</b> Untuk baris yang menunjuk
	 *       {@link Racikan}, {@link #getDiskon()} dan {@link #getPajak()} tidak menormalkan {@code null},
	 *       sehingga baris racikan lama yang kolomnya kosong akan gagal dihitung di sini.</li>
	 *   <li><b>{@code amountJasa} tidak dilibatkan.</b> Komponen jasa disimpan terpisah dan tidak ikut
	 *       menambah nilai tagihan lewat method ini.</li>
	 *   <li><b>Koleksi {@link #getDiskons()} dan {@link #getPajaks()} tidak dilibatkan.</b> Master diskon
	 *       dan pajak yang menempel pada baris tidak memengaruhi angka mana pun di sini.</li>
	 * </ul>
	 *
	 * @return nilai total baris hasil hitung.
	 */
	public Double getHasilPenghitunganTotal() {
		Double jumlah = ((getAmount() - getDiskon()) + getPajak());
		hasilPenghitunganTotal = getQty() * jumlah;
		return hasilPenghitunganTotal;
	}

