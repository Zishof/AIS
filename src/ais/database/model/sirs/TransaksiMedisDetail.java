	/**
	 * Mengembalikan dokter pelaksana/penanggung jawab baris ini, setelah proxy lazy diselesaikan lewat
	 * {@link GeneralValueObject#check(Object)}.
	 *
	 * @return dokter pelaksana, boleh {@code null}.
	 */
	@ManyToOne(cascade = { CascadeType.PERSIST, CascadeType.MERGE }, fetch = FetchType.LAZY)
	@JoinColumn(name = "dokter", nullable = true)
	public Dokter getDokter() {
		dokter = check(dokter);
		return dokter;
	}

