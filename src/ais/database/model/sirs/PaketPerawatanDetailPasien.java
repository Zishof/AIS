	/**
	 * Menghitung ulang dan mengembalikan penanda apakah item yang dipakai berbeda dari rencana
	 * paket — <b>getter destruktif yang membuang nilai yang disetel pemanggil, dan rawan
	 * {@code NullPointerException}</b>.
	 *
	 * <p>Alur kerjanya: setel {@code adaGanti = false}, lalu untuk masing-masing dari empat
	 * jenis ({@link ItemMedis}, {@link Racikan}, {@link Tindakan}, {@link AlatMedis}) — bila
	 * field {@code *DigantiDengan} terisi, bandingkan {@code id}-nya dengan {@code id} field
	 * senama pada {@link #getPaketPerawatanDetail()}, dan setel {@code adaGanti} menjadi
	 * {@code true} bila berbeda. Hasil akhirnya disimpan ke field lalu dikembalikan.</p>
	 *
	 * <p><b>Masalah pertama: setter yang dibuang.</b> Method ini mengabaikan sepenuhnya nilai
	 * yang pernah ditulis {@link #setAdaGanti(Boolean)} — baris pertamanya menimpa field dengan
	 * {@code false} tanpa membacanya lebih dulu. Akibatnya pemanggilan
	 * {@code paketPerawatanDetailPasien.setAdaGanti(tempAdaGanti)} pada
	 * {@code CommonPendaftaranUtil} baris 2765 <b>tidak berpengaruh apa pun</b>: nilai
	 * {@code tempAdaGanti} yang diturunkan dari keadaan layar tersimpan ke kolom, lalu langsung
	 * hilang pada pembacaan berikutnya. Ini pola "setter mati" — setter dan getter untuk properti
	 * yang sama menjalankan kontrak yang saling bertentangan, dan kontrak getter yang menang.
	 * Bila keadaan layar sebenarnya perlu dipertahankan (mis. petugas menandai penggantian secara
	 * manual walaupun id item kebetulan sama), maka niat itu tidak pernah terlaksana dan tidak
	 * ada tanda kegagalan apa pun.</p>
	 *
	 * <p><b>Masalah kedua: nilai turunan yang tetap dipersistensi.</b> Field {@code adaGanti}
	 * tidak diberi {@code @Transient}, sehingga ia dipetakan sebagai kolom biasa pada entity
	 * yang {@code dynamicUpdate = true}. Setiap pemanggilan getter ini menandai entity sebagai
	 * kotor bagi Hibernate dan memicu {@code UPDATE} pada akhir transaksi, yang pada gilirannya
	 * memicu {@link #onUpdate()} dan mencatat revisi Envers baru. Sekadar <i>memeriksa</i> apakah
	 * ada penggantian karena itu meninggalkan jejak audit seolah-olah ada perubahan data.
	 * Karena getter selalu menghitung ulang, kolom itu sendiri tidak pernah menjadi sumber
	 * kebenaran — ia murni beban tanpa manfaat.</p>
	 *
	 * <p><b>Masalah ketiga: {@code NullPointerException}.</b> Ekspresi
	 * {@code getPaketPerawatanDetail().getItem().getId()} mendereferensi dua tingkat tanpa
	 * null-guard, sementara skema mengizinkan keduanya kosong:
	 * {@link #getPaketPerawatanDetail()} dianotasi {@code nullable = true}, dan keempat FK pada
	 * {@link PaketPerawatanDetail} ({@code item}, {@code racikan}, {@code tindakan},
	 * {@code alatMedis}) juga {@code nullable = true}. Skenario paling mungkin adalah asimetri:
	 * petugas mengisi {@link #getItemDigantiDengan()} pada baris paket yang rencananya
	 * <i>bukan</i> tentang obat (sehingga {@code paketPerawatanDetail.getItem()} {@code null}) —
	 * dan getter langsung melempar. Karena method ini dipanggil dari tiga titik pada jalur
	 * penyimpanan transaksi ({@code CommonPendaftaranUtil} baris 2803, 2867, 2911), kegagalannya
	 * membatalkan penyimpanan transaksi medis, bukan sekadar merusak satu tampilan. Perbaikan
	 * yang tepat adalah membandingkan lewat helper null-safe yang memperlakukan "salah satu sisi
	 * kosong" sebagai penggantian (arah yang aman untuk penagihan) alih-alih melempar.</p>
	 *
	 * <p><b>Masalah keempat: keempat pemeriksaan saling menimpa.</b> Blok-bloknya berurutan
	 * dengan penugasan ({@code adaGanti = ...}), bukan akumulasi ({@code adaGanti = adaGanti ||
	 * ...}). Untuk baris yang mengisi lebih dari satu field {@code *DigantiDengan} — keadaan
	 * yang tidak dilarang di mana pun — hanya pemeriksaan <b>terakhir yang fieldnya terisi</b>
	 * yang menentukan hasil. Penggantian obat yang nyata dapat tertutup oleh pemeriksaan alat
	 * medis yang kebetulan sama, dan hasilnya {@code false} padahal seharusnya {@code true}.
	 * Dalam praktik satu baris {@link PaketPerawatanDetail} memang hanya mengisi satu jenis,
	 * sehingga cacat ini belum berdampak — tetapi ia bergantung pada konvensi yang tidak
	 * ditegakkan, bukan pada jaminan.</p>
	 *
	 * <p>Perlu ditegaskan bahwa nilai kembalian method ini adalah <b>gerbang penagihan</b>: pada
	 * {@code CommonPendaftaranUtil} baris 2867 dan 2911, biaya penggantian
	 * ({@link #getAmountGanti()}) hanya ditagihkan bila method ini bernilai {@code true}. Salah
	 * menghitung berarti salah menagih — ke arah mana pun.</p>
	 *
	 * @return {@code true} bila item yang dipakai berbeda dari rencana paket; tidak pernah
	 *         {@code null}
	 * @throws NullPointerException bila {@link #getPaketPerawatanDetail()} atau field jenis
	 *         yang bersesuaian padanya bernilai {@code null} sementara field
	 *         {@code *DigantiDengan} di sini terisi
	 */
	public Boolean getAdaGanti() {

		adaGanti = false;

		if (getItemDigantiDengan() != null) {
			adaGanti = !getItemDigantiDengan().getId().equals(getPaketPerawatanDetail().getItem().getId());
		}

		if (getRacikanDigantiDengan() != null) {
			adaGanti = !getRacikanDigantiDengan().getId().equals(getPaketPerawatanDetail().getRacikan().getId());
		}

		if (getTindakanDigantiDengan() != null) {
			adaGanti = !getTindakanDigantiDengan().getId().equals(getPaketPerawatanDetail().getTindakan().getId());
		}

		if (getAlatMedisDigantiDengan() != null) {
			adaGanti = !getAlatMedisDigantiDengan().getId().equals(getPaketPerawatanDetail().getAlatMedis().getId());
		}

		return adaGanti;
	}

	/**
	 * Menyetel penanda ada-tidaknya penggantian — <b>setter mati: nilainya akan dibuang</b>.
	 *
	 * <p>Nilai yang disetel di sini memang tersimpan ke kolom, tetapi hilang pada pemanggilan
	 * {@link #getAdaGanti()} berikutnya karena getter itu selalu menghitung ulang dari nol.
	 * Satu-satunya pemanggil di basis kode ({@code CommonPendaftaranUtil} baris 2765) karena itu
	 * tidak berpengaruh apa pun. Setter ini tetap diperlukan Hibernate untuk memuat kolom
	 * {@code adaGanti} dari basis data; memanggilnya dari kode aplikasi dengan harapan
	 * memengaruhi perilaku adalah kekeliruan.</p>
	 *
	 * @param adaGanti penanda penggantian; akan diabaikan oleh {@link #getAdaGanti()}
	 */
	public void setAdaGanti(Boolean adaGanti) {
		this.adaGanti = adaGanti;
	}

