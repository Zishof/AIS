	/**
	 * Mengembalikan biaya tambahan yang ditagihkan akibat penggantian item, menormalkan
	 * {@code null} menjadi {@code 0.0}.
	 *
	 * <p><b>Ini nilai yang langsung menjadi uang.</b> {@code CommonPendaftaranUtil} membacanya
	 * di empat titik penagihan: baris 2877 menyetelnya sebagai {@code amount} pada
	 * {@link DetailTransaksiLayanan}, baris 2903 dan 2944 sebagai {@code jumlah} pada baris
	 * {@link Biaya} baru, dan baris 2920 sebagai {@code amount} pada
	 * {@link DetailTransaksiPasien}. Tidak ada alur persetujuan yang menyaringnya — apa yang
	 * diketik petugas pada layar itulah yang ditagihkan.</p>
	 *
	 * <p>Normalisasi {@code null} → {@code 0.0} menulis ke field, sehingga secara teknis ini
	 * getter destruktif — tetapi tidak berbahaya, karena untuk nilai uang {@code null} dan
	 * {@code 0.0} memang setara secara bisnis. Bandingkan dengan {@link #getAdaGanti()} pada
	 * kelas yang sama, tempat pola penulisan-di-getter benar-benar merusak.</p>
	 *
	 * <p>Bertipe {@code Double}, bukan {@code BigDecimal} — pilihan seragam seluruh model AIS,
	 * dengan keterbatasan presisi biner yang lazim. Tidak ada penjaga nilai negatif: biaya
	 * penggantian bernilai negatif akan diterima dan menjadi potongan tagihan yang tidak
	 * terlihat sebagai potongan.</p>
	 *
	 * <p>Properti tidak dianotasi {@code @Column} sehingga memakai nama kolom default
	 * {@code amountGanti}.</p>
	 *
	 * @return biaya tambahan penggantian; tidak pernah {@code null}
	 */
	public Double getAmountGanti() {
		if (amountGanti == null) {
			amountGanti = 0.0;
		}
		return amountGanti;
	}

