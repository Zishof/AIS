	/**
	 * Menghitung dan mengembalikan umur pasien dalam tahun penuh — <b>getter destruktif yang
	 * mewarisi kerusakan {@link #getTanggalLahir()}</b>.
	 *
	 * <p>Method menghitung selisih tahun antara {@link #getTanggalLahir()} dan waktu sekarang
	 * memakai {@code org.joda.time.Years.yearsBetween(...)}, <b>menuliskan hasilnya ke field
	 * {@code umur}</b>, lalu mengembalikannya. Nilai parameter apa pun yang pernah disetel lewat
	 * {@link #setUmur(Integer)} diabaikan sepenuhnya — field {@code umur} adalah nilai turunan
	 * murni yang, karena tidak diberi {@code @Transient}, tetap dipetakan sebagai kolom basis
	 * data dan ikut ter-{@code flush}.</p>
	 *
	 * <p><b>Rantai kerusakan dari tanggal lahir.</b> Karena {@link #getTanggalLahir()} mengisi
	 * tanggal lahir yang {@code null} dengan hari ini, pasien yang tanggal lahirnya belum
	 * diketahui akan menghasilkan {@code yearsBetween(hari ini, hari ini) == 0}. Umur {@code 0}
	 * tahun bukan nilai netral di rumah sakit — ia adalah kategori <b>neonatus/bayi</b>, kelompok
	 * dengan aturan dosis obat paling ketat dan protokol penanganan paling berbeda. Sistem
	 * pendukung keputusan, formularium, dan kalkulator dosis yang membaca {@link #getUmur()}
	 * akan memperlakukan orang dewasa yang datanya tidak lengkap sebagai bayi. Dan karena getter
	 * ini menuliskan {@code 0} ke kolom, angka itu bertahan di basis data walaupun tanggal
	 * lahirnya kemudian diperbaiki — sampai getter dipanggil lagi. Ini efek berantai dari dua
	 * getter destruktif yang saling bergantung, dan efeknya paling parah tepat pada kasus yang
	 * paling sering terjadi di pendaftaran darurat: pasien tak sadar tanpa identitas.</p>
	 *
	 * <p><b>Perbedaan dengan {@link CetakKartuPasien#getUmur()}.</b> Entity kartu pasien juga
	 * punya field {@code umur}, tetapi getternya mengembalikan field apa adanya tanpa menghitung
	 * ulang — di sana umur memang <i>snapshot</i> pada saat kartu dicetak, dan menyimpannya
	 * benar. Di sini, kolom {@code umur} bukan snapshot melainkan cache yang tidak pernah
	 * dipercaya. Dua entity dengan nama field sama tetapi semantik berlawanan; jangan menyalin
	 * asumsi dari satu ke yang lain.</p>
	 *
	 * <p><b>Perilaku perhitungan.</b> {@code Years.yearsBetween} menghitung tahun <i>penuh</i>
	 * yang telah terlewati (ulang tahun ke-N harus sudah lewat), sesuai dengan pengertian umur
	 * sehari-hari di Indonesia. Perhitungannya memakai zona waktu default JVM lewat
	 * {@code new DateTime(...)} — pada server yang zonanya berbeda dari zona fasilitas, pasien
	 * yang berulang tahun hari itu bisa terhitung berbeda satu tahun selama beberapa jam. Untuk
	 * pasien di bawah satu tahun, method ini selalu mengembalikan {@code 0}: tidak ada
	 * representasi umur dalam bulan atau hari, padahal itu justru yang dibutuhkan untuk dosis
	 * neonatus. Konsumen yang butuh presisi harus menghitung sendiri dari
	 * {@link #getTanggalLahir()}.</p>
	 *
	 * <p><b>Biaya.</b> Method mengalokasikan dua objek {@code DateTime} dan satu {@code Date}
	 * setiap kali dipanggil. Pada grid yang merender kolom umur untuk ratusan baris ini bukan
	 * masalah besar, tetapi kombinasinya dengan penulisan field berarti setiap render daftar
	 * pasien berpotensi menandai ratusan baris sebagai "kotor" bagi Hibernate — memicu
	 * {@code UPDATE} yang sebenarnya tidak perlu pada akhir transaksi.</p>
	 *
	 * <p>Perbaikan yang benar berpasangan dengan perbaikan {@link #getTanggalLahir()}: tandai
	 * field ini {@code @Transient} (menghilangkan penulisan kolom yang tidak perlu) dan
	 * kembalikan {@code null} bila tanggal lahir tidak diketahui, sehingga pemanggil dipaksa
	 * menangani keadaan "umur tidak diketahui" alih-alih menerima {@code 0} yang menyesatkan.
	 * Keduanya <b>belum dikerjakan</b> karena merambat ke banyak titik render.</p>
	 *
	 * @return umur pasien dalam tahun penuh; {@code 0} bila tanggal lahir tidak diketahui —
	 *         nilai yang tidak dapat dibedakan dari bayi berusia di bawah satu tahun
	 */
	public Integer getUmur() {
		umur = Years.yearsBetween(new DateTime(getTanggalLahir()), new DateTime(new Date())).getYears();
		return umur;
	}

