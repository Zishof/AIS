	/**
	 * Mengembalikan tanggal lahir pasien — <b>GETTER DESTRUKTIF: memalsukan tanggal lahir yang
	 * belum diketahui menjadi hari ini</b>.
	 *
	 * <p>Bila field {@code tanggalLahir} masih {@code null}, method ini <b>menulis
	 * {@code new Date()} ke field</b> lalu mengembalikannya. Ini bukan sekadar "default
	 * tampilan": karena {@code Pasien} adalah entity terkelola dengan {@code dynamicUpdate = true},
	 * nilai palsu itu ikut ter-{@code flush} ke kolom {@code tanggal_lahir} pada akhir transaksi
	 * mana pun yang kebetulan memanggil getter ini. Cukup sekali membuka layar detail pasien,
	 * mencetak kartu, atau menyusun daftar yang merender kolom umur, dan tanggal lahir pasien
	 * yang semula "belum diketahui" berubah permanen menjadi tanggal hari itu.</p>
	 *
	 * <p><b>Mengapa ini serius pada data medis.</b> Tanggal lahir bukan atribut kosmetik di
	 * rumah sakit; ia dipakai untuk (a) verifikasi identitas pasien saat pemberian obat —
	 * kombinasi nama + tanggal lahir adalah dua pengenal wajib pada praktik keselamatan pasien;
	 * (b) perhitungan dosis pediatrik dan geriatrik lewat {@link #getUmur()}; (c) pencocokan
	 * peserta pada verifikasi eligibilitas BPJS; dan (d) pencegahan duplikasi rekam medis pada
	 * MPI. Tanggal lahir yang diam-diam menjadi "hari ini" membuat setiap pasien tanpa data
	 * lahir tampak <b>berusia 0 tahun</b> — lihat {@link #getUmur()} yang menurunkan nilainya
	 * dari sini — dan itu adalah kategori usia dengan aturan dosis paling ketat. Lebih buruk
	 * lagi, kerusakan ini <i>tidak terlihat</i>: karena Envers merekamnya sebagai perubahan sah
	 * oleh pengguna yang sedang login, riwayat audit justru mengukuhkan nilai palsu itu
	 * seolah-olah hasil input manusia.</p>
	 *
	 * <p><b>Mengapa polanya bisa muncul.</b> Pola "getter mengisi default" berulang di seluruh
	 * basis kode AIS dan lazimnya tidak berbahaya — mis. {@code getNilai()} pada
	 * {@link DepositPasien} yang mengganti {@code null} dengan {@code 0.0}, atau
	 * {@code getDiambil()} pada kelas yang sama. Untuk nilai numerik, {@code null} dan
	 * {@code 0.0} memang setara secara bisnis. Untuk tanggal lahir, {@code null} berarti "belum
	 * diketahui" sedangkan {@code new Date()} berarti "lahir hari ini" — dua pernyataan yang
	 * sama sekali berbeda. Templat yang sama diterapkan pada tipe data yang tidak cocok.</p>
	 *
	 * <p><b>Yang perlu diperhatikan sebelum memperbaiki.</b> Mengubah method ini menjadi
	 * mengembalikan {@code null} apa adanya akan merambat ke semua pemanggil yang saat ini
	 * mengandalkan jaminan non-null: {@link #getUmur()} akan melempar {@code NullPointerException}
	 * lewat {@code new DateTime(null)}; renderer ZK yang memformat tanggal tanpa null-guard akan
	 * gagal; dan {@code ApotikApiHelper} sudah punya null-guard sendiri
	 * ({@code pasien.getTanggalLahir() == null ? "" : ...}) sehingga aman. Perbaikan yang benar
	 * karena itu berpasangan: (1) getter mengembalikan {@code null} apa adanya; (2)
	 * {@link #getUmur()} mengembalikan {@code null} bila tanggal lahir {@code null}; (3) setiap
	 * titik render diberi null-guard. Selain itu diperlukan audit data historis untuk
	 * mengidentifikasi baris yang tanggal lahirnya sama persis dengan tanggal pembuatan atau
	 * tanggal perubahan barisnya — kandidat kuat korban efek samping ini. Kedua langkah itu
	 * <b>belum dikerjakan</b> dan tidak dapat dikerjakan tanpa akses basis data produksi.</p>
	 *
	 * <p>Dipetakan {@code TemporalType.DATE} (tanpa komponen jam), kolom {@code tanggal_lahir},
	 * nullable pada tingkat skema — yang justru menegaskan bahwa "belum diketahui" adalah
	 * keadaan yang sah dan seharusnya bertahan.</p>
	 *
	 * @return tanggal lahir pasien; tidak pernah {@code null} — bila field kosong, method
	 *         mengisinya dengan tanggal saat ini dan mengembalikan nilai itu
	 */
	@Temporal(TemporalType.DATE)
	@Column(name = "tanggal_lahir")
	public Date getTanggalLahir() {
		if (tanggalLahir == null) {
			tanggalLahir = new Date();
		}
		return tanggalLahir;
	}

