	/**
	 * Mengembalikan status lunas nota, dihitung ulang dari {@link Pembayaran} yang menempel.
	 *
	 * <p><b>Getter destruktif dan getter terhitung sekaligus.</b> Rumusnya:
	 * {@code pembayaran != null && pembayaran.getTotalBiaya() <= (pembayaran.getBayarTunai() +
	 * pembayaran.getBayarNonTunai())}. Nilai hasil hitung ditulis ke field {@code lunas}, dan karena getter
	 * ini dipetakan Hibernate tanpa {@code @Transient}, nilai itu ikut tersimpan ke kolom {@code lunas}
	 * pada flush berikutnya. Beberapa hal yang wajib dipahami sebelum mengandalkan atau mengubah method
	 * ini:</p>
	 * <ul>
	 *   <li><b>Deposit tidak dihitung.</b> Rumus di atas hanya menjumlahkan tunai dan non tunai, padahal
	 *       {@link Pembayaran#getBayar()} — yang berada di kelas yang sama dengan sumber angkanya —
	 *       menjumlahkan tunai, non tunai, DAN {@link Pembayaran#getTotalDeposit()}. Jadi ada dua definisi
	 *       "sudah dibayar" yang saling bertentangan di dalam satu rantai. Akibat nyatanya: nota yang
	 *       dilunasi seluruhnya memakai deposit pasien (lihat {@link DepositPunyaPembayaran}) akan terbaca
	 *       <b>belum lunas</b> oleh method ini, dan pembacaan itu kemudian menimpa kolom {@code lunas} yang
	 *       sebelumnya sudah ditandai lunas oleh alur pembayaran. Nota yang sudah dibayar dapat kembali
	 *       muncul sebagai piutang.</li>
	 *   <li><b>Field dibaca langsung, bukan lewat getter.</b> Method ini memakai variabel {@code pembayaran}
	 *       apa adanya, bukan {@link #getPembayaran()}. Karena relasi pembayaran dipetakan eager dengan
	 *       {@code @Fetch(FetchMode.SELECT)} hal ini umumnya aman, namun bila entity berada dalam keadaan
	 *       detached dan relasi belum termuat, hasilnya adalah {@code false} — bukan pengecualian —
	 *       sehingga kegagalan pemuatan menyamar sebagai "belum lunas".</li>
	 *   <li><b>Tidak ada penjaga keseimbangan.</b> Operator yang dipakai adalah {@code <=}, sehingga
	 *       pembayaran berlebih tetap dianggap lunas — itu memang benar. Yang tidak ada adalah sisi
	 *       sebaliknya: tidak ada apa pun di kelas ini, di {@link Pembayaran}, maupun di setter
	 *       {@link #setLunas(Boolean)} yang mencegah nota ditandai lunas ketika yang dibayar lebih kecil
	 *       dari yang ditagih. Alur pembayaran di lapisan action menandai lunas secara langsung lewat
	 *       {@link #setLunas(Boolean)} tanpa membandingkan nilai bayar dengan nilai tagihan lebih dahulu,
	 *       sehingga pelunasan sebagian dapat menutup tagihan penuh.</li>
	 *   <li><b>Nilai nol dianggap lunas.</b> Bila {@link Pembayaran#getTotalBiaya()} bernilai {@code 0.0}
	 *       (misalnya pembayaran baru dibuat dan belum diisi rinciannya), rumus {@code 0 <= 0} bernilai
	 *       benar dan nota langsung terbaca lunas walau belum ada uang yang diterima. Untuk tagihan yang
	 *       memang nol rupiah hasil itu masuk akal, tetapi untuk pembayaran yang masih setengah jadi
	 *       hasilnya menyesatkan.</li>
	 *   <li><b>Status medis tidak dilibatkan.</b> Tidak ada pemeriksaan terhadap {@link #getValidasi()},
	 *       terhadap keberadaan baris {@link TransaksiMedisDetail}, maupun terhadap selesainya layanan.
	 *       Nota tanpa satu pun baris rincian tetap dapat berstatus lunas.</li>
	 *   <li><b>Rumus ini punya kembaran.</b> {@link Pembayaran#getLunas()} memuat rumus yang sama persis
	 *       (juga tanpa deposit). Setiap perbaikan harus dilakukan pada keduanya sekaligus, jika tidak
	 *       kedua tempat akan memberi jawaban berbeda untuk pertanyaan yang sama.</li>
	 * </ul>
	 *
	 * @return {@code true} bila pembayaran yang menempel menutup total biaya menurut rumus di atas.
	 */
	public Boolean getLunas() {
		lunas = pembayaran != null
				&& pembayaran.getTotalBiaya() <= (pembayaran.getBayarTunai() + pembayaran.getBayarNonTunai());
		return lunas;
	}

