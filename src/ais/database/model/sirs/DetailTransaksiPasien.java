	/**
	 * Mengembalikan nilai rupiah diskon per satuan, dihitung ulang dari persentase.
	 *
	 * <p><b>Getter destruktif.</b> Nilai {@code null} atau {@code NaN} dinormalkan menjadi {@code 0.0},
	 * lalu field {@code diskon} <i>ditimpa</i> dengan
	 * {@code getAmount() * (getDiskonPersen() / 100.0)}. Hasilnya ikut tersimpan pada flush berikutnya.</p>
	 * <p>Konsekuensi yang perlu dipahami:</p>
	 * <ul>
	 *   <li><b>Diskon rupiah tidak dapat diberikan.</b> Syarat penimpaan adalah
	 *       {@code getDiskonPersen() != null}, sedangkan {@link #getDiskonPersen()} tidak pernah
	 *       mengembalikan {@code null} karena menormalkan {@code null}/{@code NaN} menjadi {@code 0.0}.
	 *       Syarat itu karenanya SELALU terpenuhi, dan diskon rupiah yang diisi manual berubah menjadi
	 *       {@code 0.0} pada pembacaan pertama — lalu nol itu tersimpan permanen. Potongan dalam rupiah
	 *       (pembulatan, potongan kebijakan bernilai tetap) tidak mungkin dinyatakan lewat entity ini.</li>
	 *   <li><b>Berbeda dari kembarannya di baris nota.</b> {@link TransaksiMedisDetail#getDiskon()}
	 *       melewati seluruh blok ini bila barisnya menunjuk {@link Racikan}. Kelas ini <b>tidak</b>
	 *       memiliki pengecualian tersebut, padahal ia pun memiliki relasi {@link #getRacikan()} dan
	 *       {@link #getRacikanDetail()}. Akibatnya baris racikan diperlakukan berbeda di kedua tempat:
	 *       di baris nota diskonnya dibiarkan, di jurnal ini dihitung ulang. Nilai diskon untuk barang yang
	 *       sama dapat berbeda antara nota dan jurnal persediaannya.</li>
	 *   <li><b>Bergantung pada harga yang disalin.</b> Karena pengalinya {@link #getAmount()} — yang untuk
	 *       baris penjualan disalin dari nota — mengubah harga di baris nota otomatis mengubah nilai
	 *       rupiah diskon pada jurnal ini, termasuk untuk baris yang sudah diposting.</li>
	 *   <li><b>Diskon bermakna per satuan.</b> Pengalinya harga satuan, bukan nilai baris. Laporan yang
	 *       menjumlahkan kolom {@code diskon} apa adanya akan meremehkan total diskon untuk baris
	 *       berkuantitas lebih dari satu.</li>
	 * </ul>
	 *
	 * @return nilai rupiah diskon per satuan; tidak pernah {@code null}.
	 */
	public Double getDiskon() {
		if (diskon == null || Double.isNaN(diskon)) {
			diskon = 0.0;
		}

		if (getDiskonPersen() != null && getAmount() != null) {
			diskon = getAmount() * (getDiskonPersen() / 100.0);
		}
		return diskon;
	}

