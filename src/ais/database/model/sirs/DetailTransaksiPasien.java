	/**
	 * Mengembalikan nilai total baris, dihitung ulang sebagai {@code qty * ((amount - diskon) + pajak)}.
	 *
	 * <p><b>Getter destruktif dan getter terhitung.</b> Seluruh komponennya dibaca lewat getter, sehingga
	 * satu pemanggilan memicu seluruh rantai perhitungan sekaligus — termasuk penyalinan harga dari
	 * {@link TransaksiMedisDetail} pada {@link #getAmount()} serta penimpaan diskon dan pajak dari
	 * persentase. Semua penimpaan itu ikut tersimpan pada flush berikutnya, jadi membaca nilai persediaan
	 * <i>bukan</i> operasi baca murni.</p>
	 * <p>Hal-hal yang perlu diperhatikan:</p>
	 * <ul>
	 *   <li><b>Baris yang sudah diposting tetap dapat berubah nilainya.</b> Karena harga disalin ulang dari
	 *       baris nota setiap kali dibaca, dan diskon serta pajak dihitung ulang dari harga itu, nilai
	 *       mutasi persediaan yang sudah masuk jurnal akuntansi dapat bergeser hanya karena harga di nota
	 *       diubah. Tidak ada pembekuan nilai pada saat posting, dan tidak ada pembandingan dengan angka
	 *       yang sudah dijurnal.</li>
	 *   <li><b>Kuantitas bonus tidak dihitung.</b> {@link #getQtyBonus()} sengaja dikecualikan karena
	 *       barang bonus menambah stok tanpa menambah nilai. Laporan stok dan laporan nilai persediaan
	 *       karenanya harus memakai kolom yang berbeda.</li>
	 *   <li><b>{@link #getAmountTambahan()} tidak dihitung.</b> Nilai tambahan sama sekali tidak masuk
	 *       rumus ini.</li>
	 *   <li><b>Tidak ada penjaga nilai negatif.</b> Meski {@link #setQty(Double)} dan
	 *       {@link #setAmount(Double)} memaksa nilai mutlak, persentase diskon di atas 100 tetap membuat
	 *       hasil method ini negatif tanpa penolakan.</li>
	 *   <li><b>Diskon dan pajak bersifat per satuan.</b> Keduanya diterapkan pada harga satuan lebih
	 *       dahulu, baru seluruhnya dikalikan kuantitas — konsisten, tetapi berbeda dari model "diskon
	 *       atas nilai baris" yang lazim dipakai laporan.</li>
	 * </ul>
	 *
	 * @return nilai total baris hasil hitung.
	 */
	public Double getHasilPenghitunganTotal() {
		Double jumlah = ((getAmount() - getDiskon()) + getPajak());
		hasilPenghitunganTotal = getQty() * jumlah;
		return hasilPenghitunganTotal;
	}

