	/**
	 * Menghitung ulang total yang sudah ditarik dari deposit ini dengan menjalankan agregat
	 * {@code SUM} ke basis data — <b>entity yang melakukan query sendiri</b>.
	 *
	 * <p>Method menjumlahkan kolom {@code nilai} pada seluruh baris
	 * {@link DepositPunyaPembayaran} yang menunjuk deposit ini, lalu menyimpan hasilnya ke field
	 * {@code diambil}. Bila {@link #getId()} masih {@code null} — deposit belum tersimpan,
	 * sehingga mustahil ada penarikan — total langsung ditetapkan {@code 0.0} tanpa query.
	 * Hasil {@code SUM} yang {@code null} (tidak ada baris penarikan sama sekali) juga
	 * dinormalkan menjadi {@code 0.0}.</p>
	 *
	 * <p><b>Pelanggaran lapisan dan biayanya.</b> Model AIS umumnya menempatkan entity sebagai
	 * pemegang data murni; method ini keluar dari pola itu dengan memanggil
	 * {@code HibernateUtil.currentSession()} langsung. Konsekuensinya konkret: entity menjadi
	 * bergantung pada adanya session aktif, tidak dapat diuji tanpa basis data, dan — yang paling
	 * terasa — <b>menjalankan satu query agregat setiap kali dipanggil</b>. Kedua pemanggilnya
	 * berada persis di tempat yang paling mahal: {@code DepositAction} baris 184 dan
	 * {@code PembayaranAction} baris 777, keduanya di dalam <i>row renderer</i> yang dieksekusi
	 * sekali untuk setiap baris grid. Daftar 50 deposit menghasilkan 50 query {@code SUM}
	 * terpisah, di luar query N+1 dari {@link #getPendaftaran()} dan
	 * {@link #getPostingHistory()} yang eager. Perbaikan yang tepat adalah satu query agregat
	 * ber-{@code group by} untuk seluruh daftar sebelum rendering, bukan per baris.</p>
	 *
	 * <p><b>Efek samping persistensi yang tidak kentara.</b> Field {@code diambil} dipetakan
	 * sebagai kolom biasa (tidak {@code @Transient}), dan entity ini {@code dynamicUpdate = true}.
	 * Menulis ke field karena itu menandai entity sebagai kotor bagi Hibernate: sekadar
	 * <i>menampilkan</i> daftar deposit akan memicu {@code UPDATE} pada akhir transaksi, yang
	 * pada gilirannya memicu {@link #onUpdate()} dan memperbarui
	 * {@link #getTanggal_dirubah()} — dan, karena entity dianotasi {@code @Audited}, Envers
	 * mencatatnya sebagai revisi baru. Riwayat audit deposit karena itu memuat revisi yang
	 * sebenarnya hanya hasil membuka layar, bukan perubahan bermakna oleh pengguna. Efek ini
	 * bersifat menyembunyikan sinyal, bukan merusak data — tetapi ia membuat penelusuran
	 * "siapa mengubah deposit ini" jauh lebih sulit.</p>
	 *
	 * <p><b>Yang harus diingat pemanggil.</b> Method ini <b>tidak dipanggil otomatis</b> oleh
	 * {@link #getDiambil()}. Nilai yang tersimpan di kolom {@code diambil} adalah cache dari
	 * pemanggilan terakhir yang kebetulan terjadi, dan bisa basi bila ada penarikan baru dibuat
	 * lewat jalur lain. Kedua pemanggil yang ada sudah benar — keduanya memanggil
	 * {@code hitungDiambil()} tepat sebelum membaca {@link #getDiambil()} dan sebelum menghitung
	 * sisa deposit. Setiap kode baru yang menghitung sisa deposit <b>wajib</b> mengikuti urutan
	 * yang sama; membaca {@link #getDiambil()} langsung dari kolom berisiko menghasilkan sisa
	 * yang lebih besar dari sebenarnya, dan itu berarti mengizinkan penarikan melebihi saldo.</p>
	 *
	 * <p><b>Tidak ada penguncian.</b> Method membaca tanpa {@code LockMode} apa pun, sehingga
	 * dua kasir yang secara bersamaan menarik dari deposit yang sama dapat sama-sama membaca
	 * total lama dan sama-sama lolos pemeriksaan sisa — pola TOCTOU klasik. Penjagaannya, bila
	 * diperlukan, harus dipasang di lapisan transaksi/layar, bukan di sini.</p>
	 */
	public void hitungDiambil() {
		if (getId() != null) {
			Number jumlahTotalDiambil = (Number) HibernateUtil.currentSession()
					.createCriteria(DepositPunyaPembayaran.class).add(Restrictions.eq("deposit.id", getId()))
					.setProjection(Projections.sum("nilai")).uniqueResult();
			diambil = (jumlahTotalDiambil == null ? 0.0 : jumlahTotalDiambil.doubleValue());
		} else {
			diambil = 0.0;
		}
	}

	/**
	 * Mengembalikan total yang sudah ditarik dari deposit ini, menormalkan {@code null} menjadi
	 * {@code 0.0} — <b>nilai cache, bukan perhitungan segar</b>.
	 *
	 * <p>Method ini <b>tidak</b> memanggil {@link #hitungDiambil()}. Ia mengembalikan apa pun
	 * yang terakhir tersimpan di kolom {@code diambil}, yang bisa saja berasal dari pemanggilan
	 * {@code hitungDiambil()} beberapa menit lalu, atau dari sesi pengguna lain sama sekali.
	 * Pemanggil yang membutuhkan angka mutakhir <b>wajib</b> memanggil {@link #hitungDiambil()}
	 * lebih dulu — itulah yang dilakukan {@code DepositAction} dan {@code PembayaranAction}.</p>
	 *
	 * <p>Nilai ini dipakai untuk menghitung sisa deposit
	 * ({@code getNilai() - getDiambil()}) yang menentukan berapa banyak lagi yang boleh ditarik,
	 * dan untuk mengakumulasi total deposit terpakai pada {@code PembayaranAction} baris 813.
	 * Karena perannya menentukan batas penarikan, membaca nilai basi di sini berdampak langsung
	 * pada uang: sisa yang terlalu besar berarti penarikan melebihi saldo dapat lolos. Model ini
	 * tidak menyediakan penjaga apa pun untuk itu — tidak ada
	 * {@code bolehDiambil(nilai)} maupun validasi di setter. Seluruh tanggung jawab ada pada
	 * layar pemanggil.</p>
	 *
	 * <p>Normalisasi {@code null} → {@code 0.0} menulis ke field, sama seperti
	 * {@link #getNilai()}, dan tidak berbahaya dengan alasan yang sama. Properti tidak dianotasi
	 * {@code @Column} sehingga memakai nama kolom default {@code diambil}.</p>
	 *
	 * @return total yang sudah ditarik menurut perhitungan terakhir; tidak pernah {@code null}
	 * @see #hitungDiambil()
	 */
	public Double getDiambil() {
		if (diambil == null) {
			diambil = 0.0;
		}
		return diambil;
	}

