	/**
	 * Menormalkan daftar NIM menjadi bentuk baku <b>"dibungkus dan dipisah koma"</b>
	 * ({@code ",123,124,125,"}), atau string kosong bila daftarnya kosong.
	 *
	 * <p>Bentuk berbungkus koma itu bukan hiasan &mdash; ia yang membuat pencocokan "apakah NIM
	 * X ada di daftar" bisa dilakukan sebagai pencarian substring {@code ",X,"} tanpa risiko
	 * NIM {@code "123"} ikut cocok pada {@code "1234"}. Pola itu dipakai di dua tempat: SQL
	 * {@code ilike '%,<nim>,%'} pada {@code PembayaranUtil.restrictionKhususUntukNim(...)}, dan
	 * {@code getKhususUntukNim().contains("," + nim + ",")} di belasan helper bank
	 * ({@code BniCommon}, {@code BriCommon}, {@code BsiCommon}, {@code CimbCommon},
	 * {@code DokuCommon}, {@code FaspayCommon}, {@code FinpayCommon}, {@code IpaymuCommon},
	 * {@code JatelindoCommon}, berbagai {@code DownloadNoUjian*}/{@code DownloadNoRegistrasi*},
	 * {@code TagihanUIBuilder}, {@code DaftarUlangMahasiswa*Action}).</p>
	 *
	 * <p>Langkah-langkahnya: {@code null} atau string yang isinya persis {@code ","} langsung
	 * menjadi {@code ""}; selain itu argumen di-{@code trim} lalu dibungkus koma, koma ganda
	 * dirapatkan (tiga kali {@code replaceAll(",,", ",")}), dan seluruh spasi dibuang. Hasil
	 * yang tinggal berupa {@code ","}, {@code ",,"}, atau {@code ",,,"} dianggap daftar kosong
	 * dan diubah menjadi {@code ""}.</p>
	 *
	 * <p><b>Idempoten:</b> memanggilnya atas hasilnya sendiri menghasilkan nilai yang sama
	 * ({@code ",123," → ",,123,," → ",123,"}), sehingga aman dipanggil berulang &mdash; dan itu
	 * memang terjadi, karena {@link #getKhususUntukNim()} memanggilnya setiap kali.</p>
	 *
	 * <p><b>Batas yang perlu diketahui</b> (dicatat, tidak diperbaiki):</p>
	 * <ul>
	 *   <li>Hanya <b>spasi</b> yang dibuang &mdash; tab dan ganti baris tidak. Textbox "Khusus
	 *   untuk NIM" di layar bersifat multibaris ({@code setRows(4)}), jadi NIM yang diketik per
	 *   baris akan menyimpan {@code \n} dan tidak akan pernah cocok dengan pola
	 *   {@code ",<nim>,"}.</li>
	 *   <li>{@code replaceAll(",,", ",")} diulang tiga kali, jadi deretan koma yang sangat
	 *   panjang ({@code ",,,,,,,,,"}) bisa tersisa. Tiga pengulangan
	 *   {@code replaceAll(" ", "")} yang menyertainya redundan (dua terakhir tidak berefek).</li>
	 *   <li>Cabang {@code equals(",,")} dan {@code equals(",,,")} praktis tak terjangkau setelah
	 *   perapatan koma di atas; sisa kode defensif.</li>
	 *   <li>Method ini <b>menugasi ulang parameternya</b> ({@code khususUntukNim = ...}) &mdash;
	 *   tidak berbahaya karena Java mengirim salinan referensi, tetapi menyulitkan pembacaan.</li>
	 * </ul>
	 *
	 * <p>Dipanggil dari {@link #getKhususUntukNim()} dan dari
	 * {@code JadwalPembayaranAction.onSave(...)} (untuk membentuk nilai pembanding saat
	 * memeriksa jadwal duplikat).</p>
	 *
	 * @param khususUntukNim daftar NIM mentah dari pengguna, boleh {@code null}, boleh
	 *        berantakan komanya
	 * @return daftar NIM dalam bentuk baku berbungkus koma, atau {@code ""} bila kosong; tidak
	 *         pernah {@code null}
	 */
	public static String formatNim(String khususUntukNim) {
		khususUntukNim = (khususUntukNim == null || khususUntukNim.trim().equalsIgnoreCase(",") ? ""
				: "," + khususUntukNim.trim() + ",").replaceAll(",,", ",").replaceAll(",,", ",").replaceAll(",,", ",")
				.replaceAll(" ", "").replaceAll(" ", "").replaceAll(" ", "");

		if (khususUntukNim.equals(",")) {
			khususUntukNim = "";
		} else if (khususUntukNim.equals(",,")) {
			khususUntukNim = "";
		} else if (khususUntukNim.equals(",,,")) {
			khususUntukNim = "";
		}
		return khususUntukNim.trim();
	}

