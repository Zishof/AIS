	/**
	 * Membandingkan dua rincian tunggakan berdasarkan {@link ItemBiaya#getKode()}, untuk keperluan
	 * pengurutan koleksi {@link GeneralValueObject}.
	 *
	 * <p>Perilaku sebenarnya, apa adanya dari kode — beberapa hal di sini menyimpang dari kontrak
	 * {@link Comparable} dan sengaja dicatat, bukan diperbaiki:</p>
	 *
	 * <ul>
	 *   <li><b>Urutan terbalik.</b> Perbandingan ditulis {@code o.kode.compareTo(this.kode)}, bukan
	 *       {@code this.kode.compareTo(o.kode)}. Hasilnya pengurutan <b>menurun</b> — koleksi yang
	 *       "diurutkan naik" justru tampil Z ke A.</li>
	 *   <li><b>Dua pemeriksaan {@code null} yang tidak berguna.</b> Ekspresi
	 *       {@code o.itemBiaya.getKode().trim() != null} dan pasangannya selalu bernilai
	 *       {@code true}, sebab {@code String#trim()} tidak pernah mengembalikan {@code null}.
	 *       Maksud aslinya jelas memeriksa {@code getKode() != null}, tapi {@code .trim()} sudah
	 *       dipanggil <b>sebelum</b> pemeriksaan — sehingga item biaya dengan kode {@code null}
	 *       justru menimbulkan {@link NullPointerException} tepat di baris pemeriksaan itu, bukan
	 *       tersaring. NPE ini muncul saat pengurutan, jauh dari tempat data cacatnya
	 *       diisikan.</li>
	 *   <li><b>Mengembalikan 0 untuk kasus tak terbandingkan.</b> Bila argumen bukan
	 *       {@code TunggakanMahasiswaDetail} atau salah satu {@code itemBiaya} bernilai
	 *       {@code null}, method mengembalikan {@code 0} — artinya "sama" bagi
	 *       {@code TreeSet}/{@code TreeMap}, yang berakibat baris-baris tersebut saling menggusur
	 *       (hanya satu yang bertahan). Untuk {@code Collections.sort} efeknya lebih jinak: urutan
	 *       relatifnya dipertahankan.</li>
	 *   <li>Membandingkan kode, bukan {@link #getNama()} — sementara kedua pembaca laporan justru
	 *       mengurutkan/menampilkan berdasarkan nama. Jadi method ini praktis tidak berpengaruh
	 *       pada tampilan tunggakan; {@code NewUiStudentArrearsService} memakai
	 *       {@code Order.asc("nama")} di level query.</li>
	 * </ul>
	 *
	 * @param object obyek pembanding; hanya diproses bila bertipe {@code TunggakanMahasiswaDetail}
	 * @return hasil perbandingan kode item biaya dalam urutan terbalik, atau {@code 0} bila tidak
	 *         terbandingkan
	 */
	@Override
	public int compareTo(GeneralValueObject object) {
		if (object instanceof TunggakanMahasiswaDetail) {
			TunggakanMahasiswaDetail o = (TunggakanMahasiswaDetail) object;
			if (o.itemBiaya != null && itemBiaya != null && o.itemBiaya.getKode().trim() != null
					&& itemBiaya.getKode().trim() != null) {
				return o.itemBiaya.getKode().trim().compareTo(itemBiaya.getKode().trim());
			}
		}
		return 0;
	}

