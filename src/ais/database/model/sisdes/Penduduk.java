	/**
	 * @return alamat email dinormalisasi (koma ganda dirapikan, di-trim, spasi dihapus) — getter ini MEMUTASI
	 *         field {@link #alamatEmail} in-memory sebagai efek samping, dan bila email masih kosong DAN
	 *         konfigurasi {@code alamat_email_default} tersedia, method ini juga MEMBUAT alamat email placeholder
	 *         dari nama (disanitasi) + angka acak + domain default.
	 */
	public String getAlamatEmail() {
		if (alamatEmail != null && alamatEmail.contains(",,")) {
			for (int i = 0; i < 5; i++) {
				alamatEmail = alamatEmail.replaceAll(",,", ",");
			}
		}
		if (alamatEmail == null) {
			alamatEmail = "";
		}
		if (alamatEmail.trim().equals(",")) {
			alamatEmail = "";
		}

		alamatEmail = this.alamatEmail == null || this.alamatEmail.length() < 3 ? "" : this.alamatEmail.trim();

		if (nama != null && !nama.trim().isEmpty() && alamatEmail.trim().isEmpty()
				&& !Common.getKonfigurasi("alamat_email_default", "@eschool.id").getNilai().trim().isEmpty()) {

			alamatEmail = nama.toLowerCase().replaceAll("[^\\sa-zA-Z0-9]", "").replaceAll(" ", "")
					+ ThreadLocalRandom.current().nextLong(100, 999)
					+ Common.getKonfigurasi("alamat_email_default", "").getNilai().trim();
		}

		return this.alamatEmail.trim().replaceAll(" ", "");
	}

	/** @param alamatEmail alamat email (nilai mentah, dinormalisasi saat dibaca oleh {@link #getAlamatEmail()}). */
	public void setAlamatEmail(String alamatEmail) {
		this.alamatEmail = alamatEmail;
	}

	/**
	 * Tambahkan satu alamat email ke daftar {@link #alamatEmail} (dipisah koma), NO-OP bila {@code alamatEmail}
	 * sudah ada di daftar (cek substring, bukan pemisahan token per-koma yang presisi), bukan email valid
	 * (lihat {@code Common.isValidEmailAddress}), atau diawali {@code "@"}.
	 *
	 * @param alamatEmail alamat email yang akan ditambahkan.
	 */
	public void appendEmail(String alamatEmail) {
		if (this.alamatEmail != null && alamatEmail != null && !alamatEmail.trim().isEmpty()
				&& StringUtils.contains(this.alamatEmail, alamatEmail)) {
			return;
		}
		if (alamatEmail != null && !alamatEmail.trim().isEmpty() && Common.isValidEmailAddress(alamatEmail)
				&& !alamatEmail.startsWith("@")) {
			this.alamatEmail = this.alamatEmail == null || this.alamatEmail.trim().isEmpty() ? alamatEmail
					: this.alamatEmail + "," + alamatEmail;
		}
	}

