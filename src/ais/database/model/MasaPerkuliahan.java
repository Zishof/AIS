	/**
	 * Tanggal akhir kegiatan belajar mengajar pada masa ini.
	 *
	 * <p><b>Efek samping:</b> bila field masih {@code null}, method menghitung
	 * {@code getMulai() + 6 bulan} lewat {@link Calendar} dan <b>menugaskannya ke field</b>.
	 * Perhitungan itu memanggil {@link #getMulai()}, yang juga bisa menulis balik &mdash; satu
	 * pembacaan dapat mengubah dua field sekaligus.</p>
	 *
	 * <p><b>Catatan implementasi:</b> penambahan bulan memakai
	 * {@code calendar.set(Calendar.MONTH, calendar.get(Calendar.MONTH) + 6)} alih-alih
	 * {@code calendar.add(...)}. Hasilnya tetap benar karena {@link Calendar} bersifat lenient
	 * (nilai bulan &gt; 11 berguling ke tahun berikutnya), tetapi bentuknya tidak idiomatik dan
	 * akan salah bila suatu saat {@code lenient} dimatikan di {@code WaktuUtil}.</p>
	 *
	 * <p>Dipetakan {@link TemporalType#DATE}. Nilai ini tidak menghentikan apa pun secara
	 * otomatis: tidak ada logika yang memblokir pertemuan setelah tanggal ini; ia dipakai sebagai
	 * label, kunci pencocokan sinkronisasi, dan penyaring laporan.</p>
	 *
	 * @return tanggal selesai; tidak pernah {@code null} setelah method ini dipanggil.
	 */
	@Temporal(TemporalType.DATE)
	public Date getSampai() {
		if (sampai == null) {
			Calendar calendar = ais.ui.util.WaktuUtil.getCalendar();
			calendar.setTime(getMulai());
			calendar.set(Calendar.MONTH, calendar.get(Calendar.MONTH) + 6);
			sampai = calendar.getTime();
		}
		return sampai;
	}

