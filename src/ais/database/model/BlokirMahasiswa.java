	/**
	 * Mengembalikan label mahasiswa yang diblokir dalam bentuk {@code "<nim>_<nama>"}.
	 *
	 * <p><b>Getter ini tidak murni membaca &mdash; ia menulis.</b> Bila relasi
	 * {@link #getMahasiswa() mahasiswa} terisi, field {@link #nama} <b>selalu dihitung ulang
	 * dan ditimpa</b> dari NIM + nama mahasiswa pada setiap pemanggilan. Pada instance yang
	 * masih <i>attached</i> ke session Hibernate, penimpaan itu membuat entity menjadi
	 * <i>dirty</i> sehingga dapat memicu UPDATE kolom {@code nama} saat flush &mdash; sekadar
	 * karena baris blokirnya dibaca. Karena {@code dynamicUpdate} aktif, UPDATE yang terbit
	 * hanya menyentuh kolom {@code nama}. Efeknya juga menjaga label tetap sinkron bila nama
	 * atau NIM mahasiswa berubah di master.</p>
	 *
	 * <p>Nilai yang dikembalikan sudah di-{@code trim()}, tetapi <b>field-nya tidak</b> &mdash;
	 * yang tersimpan ke database adalah versi belum-trim. Bila relasi mahasiswa kosong, nilai
	 * field apa adanya yang dikembalikan; karena kolomnya {@code nullable = false}, menyimpan
	 * baris tanpa mahasiswa dan tanpa {@link #setNama(String)} akan gagal di level database.</p>
	 *
	 * <p>Dipakai antara lain oleh {@code RevisiHelper.createNewRevisi(...)} saat merender kolom
	 * "Mahasiswa" di grid layar blokir, dan oleh {@code Common.cetakData}/{@code uploadData}
	 * yang mendaftarkan {@code "nama"} sebagai salah satu kolom.</p>
	 *
	 * @return label {@code "<nim>_<nama>"} mahasiswa yang diblokir (sudah di-trim), atau
	 *         {@code null} bila belum ada mahasiswa maupun nilai tersimpan
	 */
	@Column(name = "nama", nullable = false, length = 255)
	public String getNama() {
		if (getMahasiswa() != null) {
			nama = getMahasiswa().getNim() + "_" + getMahasiswa().getNama();
		}
		return this.nama == null ? null : this.nama.trim();
	}

