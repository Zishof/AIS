	/**
	 * Mengembalikan mahasiswa yang dikenai blokir.
	 *
	 * <p>Relasi {@code LAZY}, karena itu getter memanggil {@link GeneralValueObject#check(Object)}
	 * lebih dulu dan <b>menugaskan hasilnya kembali ke field</b> &mdash; pola standar seluruh
	 * entity AIS. Penugasan ulang itu penting: objek yang dikembalikan bisa jadi instance lain
	 * (kanonik dari identity map, dari cache, atau hasil reload), bukan proxy semula. Method ini
	 * tidak membuka maupun menutup session Hibernate sendiri; bila diperlukan, hal itu ditangani
	 * di dalam {@code check(...)} dan selalu ditutup di sana.</p>
	 *
	 * <p>Kolom FK-nya {@code nullable}, jadi getter dapat mengembalikan {@code null}. Baris
	 * seperti itu tidak akan cocok dengan query penegakan mana pun. Cascade
	 * {@code PERSIST, MERGE} berarti menyimpan baris blokir ikut men-<i>cascade</i> ke objek
	 * mahasiswa yang ditempelkan.</p>
	 *
	 * @return mahasiswa yang diblokir, atau {@code null} bila baris tidak menunjuk mahasiswa
	 */
	@ManyToOne(cascade = { CascadeType.PERSIST, CascadeType.MERGE }, fetch = FetchType.LAZY)
	@JoinColumn(name = "mahasiswa", nullable = true)
	public Mahasiswa getMahasiswa() {
		mahasiswa = check(mahasiswa);
		return mahasiswa;
	}

