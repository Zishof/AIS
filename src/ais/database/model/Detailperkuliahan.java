	public Boolean getLulus() {
		if (kunciGlobalNilaiAktif() && lulusKunci != null) {
			return lulusKunci;
		}
		// Samakan status Lulus dengan KONFIGURASI Nilai Huruf yang DIPEROLEH (permintaan user): cari
		// NilaiHuruf yang cocok dgn huruf ini dari cache ConstantValues.nilaiHurufs (prioritas per
		// Jurusan -> Fakultas -> global, sama seperti getTotalNilai) lalu pakai flag lulus-nya. Ini
		// MENGOREKSI 'lulus' tersimpan yang basi (mis. huruf "A" tetapi tersimpan belum lulus). Karena
		// getLulus di-map property-access, nilai terkoreksi ikut tersimpan saat flush (self-heal).
		try {
			if (nilaiHuruf != null && !nilaiHuruf.trim().isEmpty()) {
				Boolean cfg = ConstantValues.lulusDariNilaiHuruf(nilaiHuruf, getMahasiswa());
				if (cfg != null) {
					if (lulus == null || !lulus.equals(cfg)) {
						lulus = cfg;
					}
					return lulus;
				}
			}
		} catch (Exception e) { ais.common.ErrorAuditUtil.record(e, "auto-audit(empty-catch) src/ais/database/model/Detailperkuliahan.java:1419");
		}
		if (lulus == null && nilaiHuruf != null) {
			if (nilaiHuruf.toUpperCase().contains("D") || nilaiHuruf.toUpperCase().contains("E")
					|| nilaiHuruf.toUpperCase().contains("T")) {
				lulus = false;
			} else {
				lulus = true;
			}
		} else if (lulus == null) {
			lulus = true;
		}
		return lulus;
	}


