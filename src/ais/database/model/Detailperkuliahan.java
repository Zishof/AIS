			// impor massal dapat menganggap tidak ada referensi lalu mengisi komponen
			// yang sebenarnya sudah dikunci.
			entriLive = kunciFormat + ",0,0,"
					+ (formatNilai.getPersen() == null ? 0.0 : formatNilai.getPersen())
					+ ",false,0";
