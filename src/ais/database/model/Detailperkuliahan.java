	/**
	 * Mengembalikan <b>nilai akhir dalam huruf</b> (A/B/C/D/E/T dan seterusnya), menghitungnya ulang
	 * bila yang tersimpan dinilai tidak lagi sahih.
	 *
	 * <p><b>Jalur terkunci yang perlu dicermati.</b> Ketika kunci global aktif dan
	 * {@link #nilaiHurufKunci} ada, metode <b>tidak langsung</b> mengembalikan snapshot huruf itu.
	 * Ia lebih dulu memetakan ulang {@link #totalNilaiKunci} lewat
	 * {@link #ambilNilaiHurufSesuaiTotal(Double)} dan mengembalikan hasilnya bila ada; snapshot huruf
	 * hanya dipakai sebagai cadangan. Konsekuensinya penting untuk dipahami: <b>huruf yang dibekukan
	 * tidak sepenuhnya beku</b> &mdash; bila admin mengubah rentang pada tabel Format Nilai Huruf,
	 * huruf yang ditampilkan untuk kelas terkunci pun ikut berubah, sementara angkanya tetap.
	 * Perilaku ini konsisten dengan {@link #getTotalIP()} yang menerapkan pola sama.
	 *
	 * <p><b>Penyembunyian nilai.</b> Bila kelas menyembunyikan nilai yang belum diverifikasi dan
	 * baris berstatus {@link #NOT_VERIFIED}, huruf dikosongkan.
	 *
	 * <p><b>Kapan huruf dihitung ulang.</b> Perhitungan dipicu bila huruf tersimpan kosong, bernilai
	 * &quot;E&quot;, <b>atau basi</b>. Pemeriksaan kebasian adalah bagian terpenting: tabel Format
	 * Nilai Huruf dapat diubah admin kapan saja, sehingga huruf yang dulu benar bisa tidak lagi
	 * memiliki baris yang rentang {@code mulai}&ndash;{@code sampai}-nya mencakup nilai angka
	 * sekarang. Bila tidak ada satu pun baris yang cocok, huruf dianggap basi dan dihitung ulang
	 * &mdash; jangan pernah menampilkan huruf lama yang sudah tidak sesuai tabel.
	 *
	 * <p>Perhitungan ulang memakai {@code Common.getNilaiHuruf(...)} dengan konteks lengkap (tahun
	 * angkatan, jurusan, fakultas, tahun akademik, ganjil/genap, kode mata kuliah, jenis nilai huruf),
	 * dan hanya dijalankan bila nilai angka lebih dari 0,1 serta mahasiswa diketahui. Kegagalan
	 * resolusi relasi ditangkap dan dicatat; huruf sebelumnya dipertahankan alih-alih melempar
	 * kesalahan.
	 *
	 * <p><b>Efek samping.</b> Metode memanggil {@link #getTotalNilai()} (yang sendiri menulis balik),
	 * lalu menulis hasilnya ke field {@link #nilaiHuruf}. Nilai kembalian selalu sudah dipangkas
	 * spasinya dan tidak pernah {@code null} &mdash; string kosong dipakai sebagai ganti.
	 *
	 * @return nilai huruf, atau string kosong bila belum dapat ditentukan atau sedang disembunyikan.
	 */
	@Column(name = "nilai_huruf", nullable = true, length = 2)
	public String getNilaiHuruf() {
		if (kunciGlobalNilaiAktif() && nilaiHurufKunci != null) {
			NilaiHuruf hurufSesuaiTotal = ambilNilaiHurufSesuaiTotal(totalNilaiKunci == null ? totalNilai : totalNilaiKunci);
			if (hurufSesuaiTotal != null && hurufSesuaiTotal.getNilaiHuruf() != null) {
				return hurufSesuaiTotal.getNilaiHuruf().trim();
			}
			return nilaiHurufKunci.trim();
		}
		perkuliahan = getPerkuliahan();
		mahasiswa = getMahasiswa();
		if (perkuliahan != null && perkuliahan.getSembunyikanNilaiJikaBelumDiverifikasi()
				&& getVerify().equals(NOT_VERIFIED)) {
			nilaiHuruf = "";
		} else {
			getTotalNilai();
			boolean perluHitungHuruf = nilaiHuruf == null || nilaiHuruf.trim().isEmpty()
					|| nilaiHuruf.trim().equalsIgnoreCase("E");
			// Format Nilai Huruf (rentang mulai-sampai per huruf) bisa DIUBAH admin kapan saja lewat
			// menu Format Nilai Huruf. Huruf yang SUDAH TERSIMPAN sebelumnya bisa jadi BASI: tidak ada
			// lagi baris format nilai untuk huruf tsb yang rentangnya mencakup totalNilai sekarang. Bila
			// begitu, paksa hitung ulang -- jangan tampilkan huruf lama yang sudah tidak sesuai tabel.
			if (!perluHitungHuruf && totalNilai != null) {
				boolean masihSesuaiTabel = false;
				try {
					for (NilaiHuruf nh : ConstantValues.nilaiHurufs) {
						if (nh != null && nh.getNilaiHuruf() != null
								&& nh.getNilaiHuruf().equalsIgnoreCase(nilaiHuruf.trim()) && nh.getMulai() != null
								&& nh.getSampai() != null && totalNilai >= nh.getMulai()
								&& totalNilai <= nh.getSampai()) {
							masihSesuaiTabel = true;
							break;
						}
					}
				} catch (Exception exCekBasi) { ais.common.ErrorAuditUtil.record(exCekBasi, "auto-audit(empty-catch) src/ais/database/model/Detailperkuliahan.java:getNilaiHuruf-cekBasi");
				}
				perluHitungHuruf = !masihSesuaiTabel;
			}
			if (perluHitungHuruf
					&& totalNilai != null && totalNilai > 0.1 && mahasiswa != null) {
				try {
					// FIX LazyInitializationException: lihat catatan di getTotalNilai() --
					// bila proxy mahasiswa.getJurusan() tak bisa diakses, lewati kalkulasi
					// nilai huruf (nilaiHuruf tetap seperti sebelumnya), jangan crash.
					Detailperkuliahan detailperkuliahan = this;
					Matakuliah matakuliah = detailperkuliahan == null ? null
							: detailperkuliahan.getPerkuliahan() != null
									? detailperkuliahan.getPerkuliahan().getMatakuliah()
									: detailperkuliahan.getMatakuliahKonversi();

					Jurusan jurusanMahasiswa = mahasiswa.getJurusan();
					Fakultas fakultasMahasiswa = jurusanMahasiswa == null ? null : jurusanMahasiswa.getFakultas();
					NilaiHuruf nh = Common.getNilaiHuruf(totalNilai, mahasiswa.getTahunangkatan(), jurusanMahasiswa,
							fakultasMahasiswa, tahunAkademik,
							getSemester() % 2 == 0 ? Perkuliahan.GENAP : Perkuliahan.GANJIL,
							matakuliah == null ? "" : matakuliah.getKode(),
							matakuliah == null ? null : matakuliah.getJenisNilaiHuruf());
					if (nh != null) {
						nilaiHuruf = nh.getNilaiHuruf();
					}
				} catch (Exception exLazy) { ais.common.ErrorAuditUtil.record(exLazy, "auto-audit(empty-catch) src/ais/database/model/Detailperkuliahan.java:getNilaiHuruf-lazy");
				}
			}
		}

		return nilaiHuruf == null ? "" : nilaiHuruf.trim();
	}

