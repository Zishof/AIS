	/**
	 * Menghasilkan <b>alasan/penjelasan mengapa mata kuliah ini berstatus "Belum/Tidak
	 * Lulus"</b>, dalam bahasa Indonesia yang mudah dipahami awam, atau string kosong bila
	 * mata kuliah sudah <i>lulus</i>. Metode ini adalah pasangan penjelas dari
	 * {@link #getLulus()}: bila {@code getLulus()} menentukan lulus/tidak, metode ini
	 * menjelaskan <i>mengapa</i> sebuah baris belum lulus, sehingga staf akademik, dosen
	 * wali, maupun mahasiswa langsung tahu tindak lanjut yang diperlukan tanpa menebak.
	 *
	 * <p><b>Konsistensi dengan {@link #getLulus()}.</b> Metode ini memanggil
	 * {@code getLulus()} sebagai sumber kebenaran tunggal status kelulusan; jika hasilnya
	 * lulus, dikembalikan string kosong. Dengan begitu narasi tidak pernah bertentangan
	 * dengan badge status yang ditampilkan. Aturan {@code getLulus()}: nilai huruf yang
	 * mengandung D, E, atau T dianggap tidak lulus; huruf lain (mis. A/B/C) dianggap
	 * lulus bila bendera {@code lulus} belum diisi; bila bendera {@code lulus} sudah diisi,
	 * nilai bendera itulah yang dipakai.
	 *
	 * <p><b>Tiga kemungkinan penyebab</b> yang dibedakan agar penjelasannya tepat sasaran:
	 * <ol>
	 *   <li><i>Nilai huruf memang kategori tidak lulus</i> — huruf mengandung D/E/T.
	 *       Solusi umum: perbaikan nilai melalui remedial/ujian ulang.</li>
	 *   <li><i>Nilai huruf belum ada</i> — {@code nilaiHuruf} kosong sehingga status
	 *       kelulusan belum dapat ditetapkan dari nilai. Solusi: lengkapi & sinkronkan
	 *       nilai.</li>
	 *   <li><i>Bendera kelulusan belum sinkron</i> — huruf sebenarnya sudah memenuhi
	 *       syarat (mis. A/B/C) tetapi bendera {@code lulus} tersimpan bernilai "tidak
	 *       lulus". Ini biasanya karena data belum dihitung ulang setelah nilai berubah.
	 *       Solusi: lakukan hitung/sinkron ulang nilai agar status kelulusan mengikuti
	 *       nilai terbaru.</li>
	 * </ol>
	 *
	 * <p><b>Efek samping.</b> Sama seperti {@code getLulus()}, metode ini dapat mengisi
	 * bendera {@code lulus} di memori bila sebelumnya {@code null} (tanpa menyimpan ke
	 * basis data). Metode aman dari {@code NullPointerException} untuk nilai huruf kosong.
	 *
	 * @return kalimat alasan bila belum/tidak lulus; string kosong ("") bila sudah lulus.
	 */
	public String alasanBelumLulus() {
		if (Boolean.TRUE.equals(getLulus())) {
			return "";
		}
		String huruf = nilaiHuruf == null ? "" : nilaiHuruf.trim();
		String besar = huruf.toUpperCase();
		if (besar.contains("D") || besar.contains("E") || besar.contains("T")) {
			return "Nilai huruf \"" + huruf + "\" termasuk kategori tidak lulus (D/E/T). "
					+ "Perbaiki nilai melalui remedial / ujian ulang agar dapat lulus.";
		}
		if (huruf.length() == 0) {
			return "Nilai huruf belum ada, sehingga status kelulusan belum bisa ditetapkan. "
					+ "Lengkapi dan sinkronkan nilai mata kuliah ini.";
		}
		return "Nilai huruf \"" + huruf + "\" sebenarnya sudah memenuhi syarat lulus, tetapi status "
				+ "kelulusan tersimpan \"belum lulus\". Kemungkinan data belum disinkronkan — silakan "
				+ "lakukan hitung / sinkron ulang nilai agar status kelulusan mengikuti nilai terbaru.";
	}

