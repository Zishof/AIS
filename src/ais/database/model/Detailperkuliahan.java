	public void bersihkanNilaiKeDefault(List<FormatNilai> formatNilais) {
		String formatbaru = "";

		if (detailNilai != null && !detailNilai.trim().isEmpty()) {
			String[] s = StringUtils.split(detailNilai, ";");

			List<Long> ids = new ArrayList<Long>();
			for (FormatNilai formatNilai : formatNilais) {
				// PENTING (fix "nilai kolom tertentu tidak terhitung"): JANGAN saring dengan
				// getAktif() di sini. Semua format yang SEDANG DIPAKAI (ada di formatNilais =
				// komponen yang ditampilkan & bisa diisi pada layar Input Nilai) harus dipertahankan
				// nilainya, meskipun StatusPertemuan-nya kebetulan non-aktif. Filter getAktif() lama
				// membuat nilai komponen yang tampil (mis. "Praktikum") DIBUANG saat rekalkulasi
				// (hitungTotalNilai) sehingga tidak pernah tersimpan/terhitung ke nilai akhir
				// (totalPersen < 100). Entri untuk format yang BUKAN komponen aktif tetap dibuang
				// oleh filter "ids.contains(...)" di bawah.
				Long kunciFormat = ambilKunciFormatNilai(formatNilai);
				if (kunciFormat != null) {
					ids.add(kunciFormat);
				}
			}

			List<Long> idFormatNilais = new ArrayList<Long>();
			for (String ss : s) {
				String[] sss = StringUtils.split(ss, ",");
				Long idFormatNilai = Long.parseLong(sss[0].trim());
				if (!idFormatNilais.contains(idFormatNilai)) {
					idFormatNilais.add(idFormatNilai);
					if (ids.contains(idFormatNilai)) {
						formatbaru += formatbaru.isEmpty() ? ss : ";" + ss;
					}
				}
			}

			detailNilai = formatbaru;
		}
	}

	public void refreshNilaiKeDefault() {
		perkuliahan = getPerkuliahan();
		// FIX "nilai hilang setelah Refresh": grid membaca kotak input per-komponen dari string
		// detailNilai, sedangkan kolom Total membaca field tersimpan totalNilai (getTotalNilai, TIDAK
		// dihitung ulang dari komponen). Bila keduanya DESYNC — detailNilai kosong ATAU semua komponennya
		// bernilai 0, padahal totalNilai tersimpan > 1.0 (mis. nilai diimpor sebagai TOTAL dari Feeder,
		// atau breakdown per-komponen belum sempat tersimpan) — maka kotak tampil 0 seolah nilai "hilang"
		// walau Total masih benar. Dulu pemulihan ini HANYA jalan saat detailNilai benar-benar kosong;
		// entri "semua 0" lolos sehingga kotak tetap 0. Kini kasus "semua 0" diperlakukan sama seperti
		// kosong -> dibangun ulang dari totalNilai agar kotak menampilkan nilai (konsisten dengan Total).
		boolean perluBangunUlang = (detailNilai == null || detailNilai.trim().isEmpty());
		if (!perluBangunUlang) {
			perluBangunUlang = semuaKomponenDetailNilaiNol();
		}
		if (perluBangunUlang && totalNilai != null && totalNilai > 1.0) {
			String formatbaru = "";
			List<FormatNilai> formatNilais = Common.getFormatNilais(HibernateUtil.currentSession(), perkuliahan);

			for (FormatNilai formatNilai : formatNilais) {
				Long kunciFormat = ambilKunciFormatNilai(formatNilai);
				if (kunciFormat != null) {
					String aformatBaru = kunciFormat + "," + totalNilai + ",0," + persenAman(formatNilai)
							+ ",false," + totalNilai;
					formatbaru += formatbaru.isEmpty() ? aformatBaru : ";" + aformatBaru;
				}
			}

			detailNilai = formatbaru;
		}
	}

	/**
	 * Mengembalikan true bila SELURUH komponen pada string {@code detailNilai} bernilai 0 (baik nilai
	 * terverifikasi pada indeks ke-1 maupun nilai-belum-verify pada indeks ke-5), atau bila detailNilai
	 * kosong. Dipakai {@link #refreshNilaiKeDefault()} untuk mendeteksi kondisi "desync" — komponen 0
	 * padahal totalNilai tersimpan > 1.0 — agar kotak input dibangun ulang dari total dan nilai tidak
	 * tampak hilang. Ditulis defensif: entri yang tak bisa di-parse diabaikan (dianggap 0), sehingga
	 * data rusak tidak menghentikan pemulihan.
	 */
	public boolean semuaKomponenDetailNilaiNol() {
		if (detailNilai == null || detailNilai.trim().isEmpty()) {
			return true;
		}
		String[] s = StringUtils.split(detailNilai, ";");
		for (String ss : s) {
			try {
				String[] sss = StringUtils.split(ss, ",");
				double n1 = (sss.length > 1 && Common.isNumber(sss[1].trim())) ? Double.parseDouble(sss[1].trim())
						: 0.0;
				double n5 = (sss.length > 5 && Common.isNumber(sss[5].trim())) ? Double.parseDouble(sss[5].trim())
						: 0.0;
				if (n1 > 0.01 || n5 > 0.01) {
					return false;
				}
			} catch (Exception e) { ais.common.ErrorAuditUtil.record(e, "auto-audit(empty-catch) src/ais/database/model/Detailperkuliahan.java:768");
			}
		}
		return true;
	}

