	private Double batasiNilaiMaksimal100(Double nilai) {
		if (nilai == null || nilai.isNaN() || nilai.isInfinite()) {
			return 0.0;
		}
		if (nilai < 0.0) {
			return 0.0;
		}
		if (nilai > 100.0) {
			return 100.0;
		}
		return nilai;
	}

	public Double retreiveDetailNilai(FormatNilai formatIdSource, boolean check) {

		refreshNilaiKeDefault();

		if (formatIdSource != null && formatIdSource.getId() != null) {
			String sumberNilai = ambilSumberDetailNilai(formatIdSource);
			String[] nilais = sumberNilai == null ? new String[] {} : sumberNilai.split(";");
			for (String nn : nilais) {
				try {
					String[] s = nn.split(",");
					// FIX NumberFormatException: baris detailNilai kosong/rusak (s[0]="") -- lewati,
					// bukan error.
					if (s.length == 0 || s[0] == null || s[0].trim().isEmpty()) {
						continue;
					}
					Long formatId = Long.parseLong(s[0]);
					Long kunciFormat = formatIdSource.getStatusPertemuan() != null
							? formatIdSource.getStatusPertemuan().getId() : formatIdSource.getId();
					if (kunciFormat.equals(formatId)) {
						// FIX ArrayIndexOutOfBoundsException: baris detailNilai rusak/pendek (kurang
						// dari 2 kolom, s[1]="nilai" tak ada) -- lewati baris ini, bukan error (sama
						// seperti guard s[0] di atas). Sebelumnya s[1] diakses langsung tanpa cek
						// panjang; hasil AIOOBE tertangkap catch generik di bawah lalu dicatat ke
						// ErrorAuditUtil berulang-ulang (noise), padahal perilakunya sama saja dengan
						// continue: baris ini dilewati dan method jatuh ke fallback di akhir.
						if (s.length <= 1 || s[1] == null) {
							continue;
						}
						Double n = !Common.isNumber(s[1].trim()) ? 0.0 : Double.parseDouble(s[1].trim());
						n = batasiNilaiMaksimal100(n);
						if (n.intValue() == 0 && check) {
							Double temp = retreiveDetailNilaiBelumVerify(formatIdSource, false);
							if (temp > 0.1) {
								return batasiNilaiMaksimal100(temp);
							}
						}

						return batasiNilaiMaksimal100(n);
					}
				} catch (Exception e) { ais.common.ErrorAuditUtil.record(e, "auto-audit(empty-catch) src/ais/database/model/Detailperkuliahan.java:799");

				}
			}
		}

		return 0.0;
	}

