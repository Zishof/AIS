	@Column(name = "total_nilai", nullable = true, precision = 15)
	public Double getTotalNilai() {
		perkuliahan = getPerkuliahan();
		mahasiswa = getMahasiswa();
		if (totalNilai == null) {
			totalNilai = 0.0;
		}
		if (totalNilai > 100.0) {
			totalNilai = 100.0;
		}

		if (totalNilai <= 4.0 && totalNilai > 0.1 && this.nilaiHuruf != null && !this.nilaiHuruf.isEmpty()
				&& !this.nilaiHuruf.equalsIgnoreCase("E") && !this.nilaiHuruf.equalsIgnoreCase("T")
				&& mahasiswa != null) {
			try {
				// FIX LazyInitializationException: mahasiswa bisa berupa instance
				// canonical/shared (AuditTimestampInterceptor) yang proxy jurusan-nya
				// terikat ke Session lain yang sudah closed -> jangan biarkan getter ini
				// crash, cukup lewati koreksi totalNilai (nilai tetap dipakai apa adanya).
				NilaiHuruf nilaiHuruf = null;
				Detailperkuliahan detailperkuliahan = this;
				for (NilaiHuruf huruf : ConstantValues.nilaiHurufs) {
					if (huruf != null && huruf.getNilaiHuruf() != null
							&& huruf.getNilaiHuruf().equalsIgnoreCase(this.nilaiHuruf) && huruf.getJurusan() != null
							&& huruf.getJurusan().getId() != null
							&& huruf.getJurusan().getId().equals(detailperkuliahan.getMahasiswa().getJurusan().getId())) {
						nilaiHuruf = huruf;
						break;
					}
				}

				if (nilaiHuruf == null) {
					for (NilaiHuruf huruf : ConstantValues.nilaiHurufs) {
						if (huruf != null && huruf.getNilaiHuruf() != null
								&& huruf.getNilaiHuruf().equalsIgnoreCase(this.nilaiHuruf) && huruf.getFakultas() != null
								&& huruf.getFakultas().getId() != null && huruf.getFakultas().getId()
										.equals(detailperkuliahan.getMahasiswa().getJurusan().getFakultas().getId())) {
							nilaiHuruf = huruf;
							break;
						}
					}
				}

				if (nilaiHuruf == null) {
					for (NilaiHuruf huruf : ConstantValues.nilaiHurufs) {
						if (huruf != null && huruf.getNilaiHuruf() != null
								&& huruf.getNilaiHuruf().equalsIgnoreCase(this.nilaiHuruf)) {
							nilaiHuruf = huruf;
							break;
						}
					}
				}

				if (nilaiHuruf != null) {
					totalNilai = (nilaiHuruf.getMulai() + nilaiHuruf.getSampai()) / 2.0;
				}
			} catch (Exception exLazy) { ais.common.ErrorAuditUtil.record(exLazy, "auto-audit(empty-catch) src/ais/database/model/Detailperkuliahan.java:getTotalNilai-lazy");
			}
		}

		if (perkuliahan != null && perkuliahan.getSembunyikanNilaiJikaBelumDiverifikasi()
				&& getVerify().equals(NOT_VERIFIED)) {
			totalNilai = 0.0;
		} else {
			if (totalNilai < 0.01 && getTotalNilaiSementara() > 0.1) {
				totalNilai = getTotalNilaiSementara();
			}
		}

		return totalNilai;
	}

