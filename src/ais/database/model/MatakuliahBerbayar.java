	/**
	 * Mengembalikan jenjang pendidikan yang menjadi cakupan aturan ini.
	 *
	 * <p><b>Satu-satunya getter di kelas ini yang menulis balik ke field-nya sendiri</b>: relasi
	 * dipetakan {@code FetchType.LAZY}, jadi getter memanggil
	 * {@link GeneralValueObject#check(Object)} lebih dulu dan menugaskan hasilnya kembali ke
	 * {@code jenjang}. Penugasan balik itu wajib karena {@code check()} bisa mengembalikan
	 * <i>instance lain</i> (kanonik dari identity map, dari cache, atau hasil <i>reload</i> lewat
	 * session baru), bukan proxy semula.</p>
	 * <p>Efek sampingnya terbatas pada penggantian referensi proxy: nilai bisnis tidak diubah,
	 * dan karena kolom pemetaannya adalah kunci asing yang sama, pembacaan ini tidak
	 * memicu {@code UPDATE} maupun revisi Envers palsu. {@code check()} juga tidak pernah
	 * melempar exception dan tidak menutup {@code Session} milik pemanggil.</p>
	 *
	 * @return jenjang cakupan yang sudah teresolusi, atau {@code null} bila berlaku untuk semua
	 *         jenjang
	 */
	@ManyToOne(cascade = { CascadeType.PERSIST, CascadeType.MERGE }, fetch = FetchType.LAZY)
	@JoinColumn(name = "jenjang")
	public Jenjang getJenjang() {
		jenjang = check(jenjang);
		return this.jenjang;
	}

