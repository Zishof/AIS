	@ManyToOne(cascade = { CascadeType.PERSIST, CascadeType.MERGE }, fetch = FetchType.LAZY)
	@JoinColumn(name = "jenis_pembayaran_barang", nullable = true)
	public JenisPembayaranBarang getJenisPembayaranBarang() {
		jenisPembayaranBarang = check(jenisPembayaranBarang);
		return jenisPembayaranBarang;
	}

	/**
	 * Menyetel jenis pembayaran barang yang berlaku untuk dokumen ini.
	 *
	 * @param jenisPembayaranBarang jenis pembayaran barang.
	 */
	public void setJenisPembayaranBarang(JenisPembayaranBarang jenisPembayaranBarang) {
		this.jenisPembayaranBarang = jenisPembayaranBarang;
	}

	/**
	 * Mengambil status aktif dokumen. Getter shadow dengan flag SATU ARAH: status
	 * {@link #disposisiSop} hanya bisa memaksa {@link #aktif} menjadi {@code false} (baik karena
	 * disposisi tidak aktif, maupun karena disposisi berakhir dengan penolakan pada alur SOP)
	 * -- tidak ada jalur di getter ini yang mengembalikan status dari {@code false} ke
	 * {@code true} berdasarkan status disposisi.
	 *
	 * @return {@code true} bila dokumen aktif (default bila belum diset dan disposisi tidak
	 *         menyatakan sebaliknya).
	 */
	public Boolean getAktif() {
		disposisiSop = getDisposisiSop();
		if (disposisiSop != null && !disposisiSop.getAktif()) {
			aktif = false;
		}

		if (disposisiSop != null && disposisiSop.getDisposisiEnd() != null
				&& disposisiSop.getDisposisiEnd().getAlurSop() != null
				&& disposisiSop.getDisposisiEnd().getAlurSop().getPenolakanAdaDiSini()) {
			aktif = false;
		}

		return aktif == null ? true : aktif;
	}

	/**
	 * Menyetel status aktif dokumen secara langsung. Nilai ini masih bisa dipaksa {@code false}
	 * oleh {@link #getAktif()} berdasarkan status disposisi SOP pada pemanggilan berikutnya.
	 *
	 * @param aktif status aktif.
	 */
	public void setAktif(Boolean aktif) {
		this.aktif = aktif;
	}
