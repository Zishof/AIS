	/**
	 * Mengembalikan TANGGAL REALISASI KAS baris pembayaran ini, diturunkan dari perintah transfer
	 * bila tersedia.
	 *
	 * <p><b>Mengapa berbeda dari {@link #getTanggalDibayar()}.</b> Tanggal dibayar adalah tanggal
	 * dokumen — kapan perintah pembayaran dibuat. Tanggal transaksi adalah kapan uang benar-benar
	 * berpindah dari rekening organisasi. Keduanya kerap berbeda beberapa hari karena proses
	 * pengajuan dan pelaksanaan transfer. Untuk penjurnalan pengeluaran kas dan untuk rekonsiliasi
	 * terhadap mutasi bank, tanggal transaksi inilah yang relevan.</p>
	 *
	 * <p><b>Tiga jalur penentuan nilai, dievaluasi berurutan:</b></p>
	 * <ol>
	 *   <li><i>Transfer transitori.</i> Bila pengajuan transfer ditandai sebagai transitori — yaitu
	 *       dana melewati rekening penampungan sebelum sampai ke vendor — dan data transitorinya
	 *       memiliki proses yang sudah berjalan, tanggal diambil dari tanggal pembuatan proses
	 *       transitori tersebut.</li>
	 *   <li><i>Transfer langsung.</i> Bila pengajuan memiliki proses transfer biasa, tanggal
	 *       diambil dari tanggal realisasinya; bila proses tersebut belum direalisasikan, dipakai
	 *       tanggal pembuatannya. Susunan ini membuat baris yang sudah diajukan namun belum cair
	 *       tetap memiliki tanggal yang masuk akal.</li>
	 *   <li><i>Tanpa pengajuan transfer.</i> Tanggal mundur ke {@link #getTanggalDibayar()}, yang
	 *       sendiri bertingkat ke tanggal dokumen induk lalu ke waktu server.</li>
	 * </ol>
	 *
	 * <p><b>Penanganan galat.</b> Seluruh blok dibungkus {@code try-catch} karena rantai
	 * pemanggilan yang panjang ({@code daftarPengajuanTransfer} &rarr; {@code transitoriData}
	 * &rarr; {@code prosesTransitori}) melibatkan beberapa relasi lazy yang proxy-nya dapat
	 * terikat Session yang sudah tertutup. Bila terjadi kegagalan, nilai yang sudah sempat
	 * terbentuk dipertahankan dan pengecualiannya dicatat lewat {@code ErrorAuditUtil}. Perlu
	 * dicatat konsekuensinya: apabila kegagalan terjadi SEBELUM salah satu cabang sempat menetapkan
	 * nilai, metode mengembalikan isi field {@code tanggalTransaksi} apa adanya — yang dapat
	 * berupa nilai lama dari pemanggilan sebelumnya atau {@code null}. Berbeda dengan
	 * {@link #getTanggalDibayar()}, metode ini karenanya DAPAT mengembalikan {@code null} dan
	 * pemanggil perlu memeriksanya.</p>
	 *
	 * <p>Perhatikan pula bahwa cabang pertama memanggil {@code getTransitori()} tanpa pemeriksaan
	 * {@code null} pada nilai baliknya; bila kolom tersebut kosong pada pengajuan transfer, unboxing
	 * {@code Boolean} melempar dan tertangkap oleh {@code try-catch} pembungkus, sehingga tanggal
	 * transaksi tidak terisi sama sekali alih-alih mundur ke cabang berikutnya.</p>
	 *
	 * <p><b>Getter destruktif:</b> menulis hasil penurunan ke field {@code tanggalTransaksi}.</p>
	 *
	 * @return tanggal realisasi kas; dapat {@code null} bila penurunan gagal sebelum sempat
	 *         menetapkan nilai
	 */
	@Temporal(TemporalType.TIMESTAMP)
	@Column(name = "tanggal_transaksi")
	public Date getTanggalTransaksi() {
		try {
			// FIX LazyInitializationException: daftarPengajuanTransfer bisa berupa instance canonical/shared
			// (AuditTimestampInterceptor) yang proxy-nya terikat ke Session lain yang sudah closed
			// -> jangan biarkan getter ini crash, cukup lewati bagian ini (nilai fallback dipertahankan).
			if (getDaftarPengajuanTransfer() != null && daftarPengajuanTransfer.getTransitori()
					&& daftarPengajuanTransfer.getTransitoriData() != null
					&& daftarPengajuanTransfer.getTransitoriData().getProsesTransitori() != null) {
				tanggalTransaksi = daftarPengajuanTransfer.getTransitoriData().getProsesTransitori().getTanggalPembuatan();
			} else if (getDaftarPengajuanTransfer() != null && daftarPengajuanTransfer.getProsesTransfer() != null) {
				tanggalTransaksi = daftarPengajuanTransfer.getProsesTransfer().getTanggalRealisasikan() == null
						? daftarPengajuanTransfer.getProsesTransfer().getTanggalPembuatan()
						: daftarPengajuanTransfer.getProsesTransfer().getTanggalRealisasikan();
			} else {
				tanggalTransaksi = getTanggalDibayar();
			}
		} catch (Exception exLazy) { ais.common.ErrorAuditUtil.record(exLazy, "auto-audit(empty-catch) src/ais/database/model/asset/PembayaranPengadaanMasterAssetDetail.java:getTanggalTransaksi-lazy");
		}
		return tanggalTransaksi;
	}

