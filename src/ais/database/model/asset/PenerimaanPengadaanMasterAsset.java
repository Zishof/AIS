	private static void konfirmasiBatalkanTagihanPenerimaan(final PenerimaanPengadaanMasterAsset penerimaanPengadaanMasterAsset,
			final EventListener reload) throws Exception {
		if (penerimaanPengadaanMasterAsset == null) {
			return;
		}
		MyMessageboxConfig.show("Apakah yakin ingin membatalkan atau menghapus tagihan vendor dari penerimaan barang/jasa ini ?",
				"Pertanyaan", MyMessageboxConfig.OK | MyMessageboxConfig.CANCEL, MyMessageboxConfig.QUESTION,
				new EventListener() {
					@Override
					public void onEvent(Event event) throws Exception {
						int i = Integer.parseInt(event.getData().toString());
						if (i != MyMessageboxConfig.OK) {
							return;
						}
						try {
							Session session = HibernateUtil.currentSession();
							session.refresh(penerimaanPengadaanMasterAsset);
							SaldoAwalMasterAsset saldoAwalMasterAsset = penerimaanPengadaanMasterAsset.getSaldoAwalMasterAsset();
							if (saldoAwalMasterAsset == null || saldoAwalMasterAsset.getId() == null) {
								return;
							}
							session.refresh(saldoAwalMasterAsset);
							hapusSaldoAwalDetailDanTransaksi(session, saldoAwalMasterAsset);
							penerimaanPengadaanMasterAsset.setSaldoAwalMasterAsset(null);
							Common.refreshUpdate(session, penerimaanPengadaanMasterAsset);
							session.flush();
							Common.refreshDelete(session, saldoAwalMasterAsset);
							session.flush();
							Common.createDefaultTimer(reload);
						} catch (Exception e) {
							Common.tampilErrorJikaAdmin(e);
							MyMessageboxConfig.show("Error :" + e.getMessage());
						}
					}
				});
	}

	private static void konfirmasiBatalkanTagihanSaldo(final SaldoAwalMasterAsset saldoAwalMasterAsset,
			final EventListener reload) throws Exception {
		if (saldoAwalMasterAsset == null || saldoAwalMasterAsset.getId() == null) {
			return;
		}
		MyMessageboxConfig.show("Apakah yakin ingin membatalkan atau menghapus tagihan vendor ini ?", "Pertanyaan",
				MyMessageboxConfig.OK | MyMessageboxConfig.CANCEL, MyMessageboxConfig.QUESTION, new EventListener() {
					@Override
					public void onEvent(Event event) throws Exception {
						int i = Integer.parseInt(event.getData().toString());
						if (i != MyMessageboxConfig.OK) {
							return;
						}
						try {
							Session session = HibernateUtil.currentSession();
							hapusSaldoAwalDetailDanTransaksi(session, saldoAwalMasterAsset);
							Common.refreshDelete(session, saldoAwalMasterAsset);
							session.flush();
							Common.createDefaultTimer(reload);
						} catch (Exception e) {
							Common.tampilErrorJikaAdmin(e);
							MyMessageboxConfig.show("Error :" + e.getMessage());
						}
					}
				});
	}

	@SuppressWarnings("unchecked")
	private static void hapusSaldoAwalDetailDanTransaksi(Session session, SaldoAwalMasterAsset saldoAwalMasterAsset)
			throws Exception {
		if (saldoAwalMasterAsset == null || saldoAwalMasterAsset.getId() == null) {
			return;
		}
		session.createSQLQuery(
				"delete from asset.detail_transaksi_asset where saldo_awal_master_asset_detail in (select id from asset.saldo_awal_master_asset_detail where saldo_awal_master_asset = "
						+ saldoAwalMasterAsset.getId() + ");")
				.executeUpdate();
		session.createSQLQuery(
				"update rab.penggunaan_anggaran set saldo_awal_master_asset_detail=null where saldo_awal_master_asset_detail in (select id from asset.saldo_awal_master_asset_detail where saldo_awal_master_asset = "
						+ saldoAwalMasterAsset.getId() + ");")
				.executeUpdate();
		List<SaldoAwalMasterAssetDetail> details = session.createCriteria(SaldoAwalMasterAssetDetail.class)
				.addOrder(Order.desc("id")).add(Restrictions.eq("saldoAwal", saldoAwalMasterAsset)).list();
		for (SaldoAwalMasterAssetDetail detail : details) {
			Common.refreshDelete(session, detail);
			session.flush();
		}
	}

