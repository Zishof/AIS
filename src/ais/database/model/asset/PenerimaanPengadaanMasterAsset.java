	/**
	 * Membersihkan seluruh turunan sebuah tagihan vendor sebelum tagihan itu sendiri dihapus.
	 *
	 * <p>Tiga tahap dijalankan berurutan, dan urutannya menentukan keberhasilan penghapusan karena
	 * setiap tahap melepaskan referensi yang menghalangi tahap berikutnya:</p>
	 *
	 * <p><b>Tahap 1 — menghapus transaksi aset.</b> Baris {@code asset.detail_transaksi_asset}
	 * yang merujuk detail tagihan dihapus lewat SQL asli bersubkueri. Tabel inilah yang mencatat
	 * mutasi aset (kuantitas dan nilai) sehingga penghapusannya mengembalikan posisi aset ke
	 * keadaan sebelum tagihan dibentuk.</p>
	 *
	 * <p><b>Tahap 2 — melepas tautan penggunaan anggaran.</b> Kolom
	 * {@code saldo_awal_master_asset_detail} pada {@code rab.penggunaan_anggaran} di-NULL-kan,
	 * BUKAN dihapus. Perbedaan ini disengaja: baris penggunaan anggaran adalah catatan RAB
	 * tersendiri yang boleh bertahan meski tagihan yang dulu membebaninya hilang. Namun akibatnya,
	 * baris penggunaan anggaran tersebut menjadi yatim secara semantik — ia masih membebani pagu
	 * anggaran tetapi tidak lagi menunjuk dokumen sumber mana pun. Populasi baris seperti ini
	 * layak diperiksa dalam rekonsiliasi anggaran.</p>
	 *
	 * <p><b>Tahap 3 — menghapus detail tagihan.</b> Seluruh {@code SaldoAwalMasterAssetDetail}
	 * milik tagihan diambil lewat Criteria (diurutkan menurun berdasarkan id) lalu dihapus satu
	 * per satu dengan {@code flush()} setelah masing-masing. Penghapusan lewat sesi Hibernate —
	 * bukan SQL massal — dipilih agar kait Envers tetap berjalan dan riwayat perubahan tetap
	 * terekam.</p>
	 *
	 * <p><b>Catatan keamanan: perakitan SQL.</b> Kedua pernyataan SQL asli dirangkai lewat
	 * penggabungan string yang menyisipkan {@code saldoAwalMasterAsset.getId()}. Nilai tersebut
	 * bertipe {@link Long} dan berasal dari kunci primer entitas yang sudah dimuat dari database,
	 * bukan dari masukan pengguna, sehingga jalur injeksi SQL tidak terbuka di sini. Meski
	 * demikian, penggunaan parameter terikat ({@code setParameter}) akan lebih aman terhadap
	 * perubahan kode di masa depan dan memungkinkan pemakaian ulang rencana kueri.</p>
	 *
	 * <p><b>Yang tidak dilakukan.</b> Metode ini murni menghapus. Ia tidak memeriksa
	 * {@code postingHistory} pada tagihan maupun pada detailnya, tidak memeriksa apakah tagihan
	 * sudah dibayar, dan tidak membalik jurnal yang mungkin sudah terbentuk. Seluruh tanggung
	 * jawab pemeriksaan berada pada pemanggil — yang, sebagaimana didokumentasikan pada kedua
	 * metode konfirmasi di atas, juga tidak melakukannya.</p>
	 *
	 * @param session               sesi Hibernate aktif tempat penghapusan dijalankan
	 * @param saldoAwalMasterAsset  tagihan yang turunannya akan dibersihkan; diabaikan bila
	 *                              {@code null} atau belum tersimpan
	 * @throws Exception bila salah satu pernyataan penghapusan gagal dijalankan
	 */
	@SuppressWarnings("unchecked")
	private static void hapusSaldoAwalDetailDanTransaksi(Session session, SaldoAwalMasterAsset saldoAwalMasterAsset)
			throws Exception {
		if (saldoAwalMasterAsset == null || saldoAwalMasterAsset.getId() == null) {
			return;
		}
		session.createSQLQuery(
				"delete from asset.detail_transaksi_asset where saldo_awal_master_asset_detail in (select id from asset.saldo_awal_master_asset_detail where saldo_awal_master_asset = "
						+ saldoAwalMasterAsset.getId() + ");")
				.executeUpdate();
		session.createSQLQuery(
				"update rab.penggunaan_anggaran set saldo_awal_master_asset_detail=null where saldo_awal_master_asset_detail in (select id from asset.saldo_awal_master_asset_detail where saldo_awal_master_asset = "
						+ saldoAwalMasterAsset.getId() + ");")
				.executeUpdate();
		List<SaldoAwalMasterAssetDetail> details = session.createCriteria(SaldoAwalMasterAssetDetail.class)
				.addOrder(Order.desc("id")).add(Restrictions.eq("saldoAwal", saldoAwalMasterAsset)).list();
		for (SaldoAwalMasterAssetDetail detail : details) {
			Common.refreshDelete(session, detail);
			session.flush();
		}
	}

