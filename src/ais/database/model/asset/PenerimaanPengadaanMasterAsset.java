	/**
	 * Mengembalikan status aktif dokumen penerimaan.
	 *
	 * <p><b>Flag satu arah.</b> Metode ini hanya dapat MENURUNKAN status menjadi {@code false};
	 * ia tidak pernah mengembalikannya menjadi {@code true}. Dua kondisi memicu penurunan:</p>
	 * <ol>
	 *   <li>Disposisi SOP dokumen sudah tidak aktif — alur dibatalkan atau ditutup.</li>
	 *   <li>Langkah akhir disposisi berada pada simpul alur yang ditandai sebagai titik penolakan
	 *       ({@code getPenolakanAdaDiSini()}), yaitu dokumen ditolak penyetuju.</li>
	 * </ol>
	 *
	 * <p>Sifat satu arah ini disengaja untuk dokumen finansial: sekali dokumen dinyatakan tidak
	 * aktif karena ditolak, ia tidak boleh kembali hidup hanya karena disposisinya berubah lagi.
	 * Dokumen yang perlu diproses ulang harus diajukan sebagai dokumen baru dengan alur baru.</p>
	 *
	 * <p>Bila kolom {@code aktif} belum pernah diisi dan tidak ada kondisi penurunan yang
	 * terpenuhi, dokumen dianggap aktif ({@code true}). Dengan demikian dokumen lama tanpa alur
	 * SOP tetap muncul di daftar.</p>
	 *
	 * <p><b>Getter destruktif:</b> menulis ke field {@code aktif} dan {@code disposisiSop},
	 * sehingga penurunan status ikut tersimpan begitu dokumen dibaca dan di-flush.</p>
	 *
	 * @return {@code true} bila dokumen masih aktif; tidak pernah {@code null}
	 */
	public Boolean getAktif() {
		disposisiSop = getDisposisiSop();
		if (disposisiSop != null && !disposisiSop.getAktif()) {
			aktif = false;
		}
		if (disposisiSop != null && disposisiSop.getDisposisiEnd() != null
				&& disposisiSop.getDisposisiEnd().getAlurSop() != null
				&& disposisiSop.getDisposisiEnd().getAlurSop().getPenolakanAdaDiSini()) {
			aktif = false;
		}
		return aktif == null ? true : aktif;
	}

