	/**
	 * Membentuk dan mengembalikan kunci alternatif unik baris penerimaan.
	 *
	 * <p><b>Peran.</b> Kolom ini dipetakan {@code unique} dan berfungsi sebagai pengaman terhadap
	 * penggandaan baris: satu barang pada satu BAST untuk satu permintaan tidak boleh muncul dua
	 * kali. Kunci selalu DIHITUNG ULANG setiap kali getter dipanggil dan ditulis ke field,
	 * sehingga nilai yang tersimpan selalu mengikuti relasi terkini.</p>
	 *
	 * <p><b>Bentuk kunci.</b> Basisnya {@code "<masterAssetId>_<penerimaanId>"}, ditambah satu
	 * sufiks pembeda menurut aturan yang dijelaskan pada komentar implementasi di bawah:
	 * identitas baris permintaan bila tautan permintaan tersedia (langsung maupun lewat baris PO),
	 * atau {@code "_d<idBarisIni>"} bila tidak. Bila salah satu dari barang maupun BAST belum
	 * memiliki identitas, kunci dikembalikan {@code null} — PostgreSQL mengizinkan banyak NULL
	 * pada kolom unik, sehingga baris yang belum tersimpan tidak saling bertabrakan.</p>
	 *
	 * <p><b>Batas perlindungan.</b> Karena pembeda dapat berupa identitas baris itu sendiri,
	 * kunci ini menjamin keunikan TEKNIS (tidak ada dua baris berkode sama) tetapi tidak menjamin
	 * keunikan BISNIS: dua baris yang menerima barang yang sama pada BAST yang sama, tanpa tautan
	 * permintaan, akan memperoleh kunci berbeda dan keduanya sah tersimpan. Deteksi penggandaan
	 * semacam itu perlu dilakukan di lapisan aksi.</p>
	 *
	 * <p><b>Getter destruktif:</b> menulis ke field {@code kodeUnik}.</p>
	 *
	 * @return kunci alternatif baris, atau {@code null} bila barang atau BAST belum tersimpan
	 */
	@Column(unique = true)
	public String getKodeUnik() {
		// WAJIB kedua id (masterAsset & penerimaan) sudah ada. Bila parent
		// (PenerimaanPengadaanMasterAsset) belum ter-persist (id == null), JANGAN bentuk kode
		// "<masterAssetId>_null" karena akan bentrok unik antar-detail. Kembalikan null
		// (Postgres mengizinkan banyak NULL pada kolom unik); kode benar terbentuk setelah
		// parent tersimpan dan punya id.
		//
		// PENTING (fix duplikat "<master>_<penerimaan>"): dua baris detail bisa punya
		// masterAsset + penerimaan yang SAMA namun TANPA tautan permintaan (mis. satu BAST
		// menerima item master yang sama pada dua baris terpisah). Tanpa pembeda, keduanya
		// menghasilkan kode identik (mis. "3291_885") -> "duplicate key value violates unique
		// constraint penerimaan_pengadaan_master_asset_detail_kodeunik_key" + transaksi abort.
		// Karena itu:
		//  - bila ADA tautan permintaan  -> sufiks "_<permintaanDetailId>" (sudah unik per baris);
		//  - bila TANPA tautan & id ada  -> sufiks "_d<idDetailIni>" (pembeda pasti unik; prefix
		//    'd' mencegah tabrakan dgn format permintaanDetailId di atas);
		//  - bila TANPA tautan & id null -> null saat insert (diisi benar pada update berikutnya).
		if (getMasterAsset() != null && getMasterAsset().getId() != null
				&& getPenerimaanPengadaanMasterAsset() != null
				&& getPenerimaanPengadaanMasterAsset().getId() != null) {
			String base = getMasterAsset().getId() + "_" + getPenerimaanPengadaanMasterAsset().getId();
			if (getPermintaanPengadaanMasterAsset() != null && getPermintaanPengadaanMasterAsset().getId() != null) {
				kodeUnik = base + "_" + getPermintaanPengadaanMasterAsset().getId();
			} else if (getPemesananPengadaanMasterAssetDetail() != null && getPemesananPengadaanMasterAssetDetail()
					.getPermintaanPengadaanMasterAssetDetail() != null) {
				kodeUnik = base + "_" + getPemesananPengadaanMasterAssetDetail()
						.getPermintaanPengadaanMasterAssetDetail().getId();
			} else if (getId() != null) {
				kodeUnik = base + "_d" + getId();
			} else {
				kodeUnik = null;
			}
		} else {
			kodeUnik = null;
		}
		return kodeUnik;
	}

