	/**
	 * Menghitung dan mengembalikan NILAI TOTAL baris penerimaan — angka yang akhirnya menjadi
	 * bagian dari tagihan vendor.
	 *
	 * <p><b>Rumus.</b> Perhitungan berjalan dalam empat tahap:</p>
	 * <pre>
	 *   DPP     = diterima &times; hargaBeli          (atau = hargaBeli saja bila dokumen bertermin)
	 *   potongan= diskonPersen ? (hargaPotongan/100 &times; DPP) : hargaPotongan
	 *   DPP     = DPP - potongan
	 *   PPN     = persenPpn/100 &times; DPP
	 *   PPh     = pph_mengurangi_lpj ? (persenPph/100 &times; DPP) : 0
	 *   TOTAL   = (DPP + PPN) - PPh
	 * </pre>
	 *
	 * <p><b>Tahap 1 — dasar pengenaan pajak (DPP).</b> Secara normal DPP adalah kuantitas
	 * diterima dikalikan harga satuan. Namun bila dokumen BAST induk memiliki payload termin
	 * ({@link PenerimaanPengadaanMasterAsset#getJsonTermin()}), DPP menjadi harga satuan itu
	 * SENDIRI tanpa dikalikan kuantitas. Pengecualian ini konsisten dengan
	 * {@link #getHargaBeli()} yang pada dokumen bertermin sudah mengganti "harga satuan" dengan
	 * nilai penagihan termin — mengalikannya lagi dengan kuantitas akan menggandakan nilai
	 * termin sebanyak jumlah barang. Konsekuensinya, pada dokumen bertermin kuantitas diterima
	 * tidak berpengaruh sama sekali terhadap nilai tagihan.</p>
	 *
	 * <p><b>Tahap 2 — potongan.</b> {@link #getHargaPotongan()} ditafsirkan sebagai persentase
	 * dari DPP bila {@link #getDiskonDalamBentukPersen()} bernilai {@code true}, atau sebagai
	 * nominal rupiah bila {@code false}. Hasilnya dikurangkan dari DPP. Tidak ada pembatasan
	 * bahwa potongan harus lebih kecil dari DPP: potongan yang melebihi DPP menghasilkan DPP
	 * negatif, yang lalu mengalir ke perhitungan pajak dan total tanpa penjagaan apa pun.</p>
	 *
	 * <p><b>Tahap 3 — PPN.</b> Dihitung sebagai persentase dari DPP setelah potongan, sesuai
	 * kaidah perpajakan bahwa PPN dikenakan atas nilai setelah diskon.</p>
	 *
	 * <p><b>Tahap 4 — PPh dan pengaruh konfigurasi.</b> Perlakuan PPh dikendalikan konfigurasi
	 * global {@code pph_mengurangi_lpj} yang dibaca lewat {@code Common.bolehKonfigurasi(...)}.
	 * Bila aktif, PPh dihitung dari DPP dan DIKURANGKAN dari total — mencerminkan skema pemotongan
	 * di sumber, ketika organisasi memotong PPh vendor dan menyetorkannya sendiri sehingga yang
	 * ditransfer kepada vendor sudah bersih dari PPh. Bila tidak aktif, PPh diperlakukan nol pada
	 * baris ini dan penyetorannya diurus terpisah; nilai penuh ditransfer ke vendor.</p>
	 *
	 * <p><b>Implikasi penting dari konfigurasi tersebut.</b> Karena ia global dan dibaca setiap
	 * kali metode ini dipanggil, mengubahnya akan mengubah nilai total SELURUH baris penerimaan
	 * yang dibaca setelahnya — termasuk baris dari dokumen lama yang sudah diposting ke buku
	 * besar dan sudah dibayar. Nilai total tidak "dibekukan" pada saat dokumen disetujui; ia
	 * selalu dihitung ulang. Pemeriksaan rekonsiliasi antara nilai jurnal historis dan nilai yang
	 * ditampilkan sistem perlu memperhitungkan hal ini.</p>
	 *
	 * <p><b>Penanganan galat.</b> Seluruh perhitungan dibungkus {@code try-catch} lebar. Bila
	 * terjadi pengecualian di tengah — misalnya {@code NullPointerException} saat unboxing pada
	 * {@link #getJenisPajakPpn()}, atau kegagalan pemuatan lazy — metode TIDAK melempar melainkan
	 * mengembalikan nilai {@code hargaTotal} yang tersimpan dari perhitungan SEBELUMNYA, atau
	 * {@code null} bila belum pernah dihitung. Perilaku diam ini menjaga layar tetap tergambar,
	 * tetapi berarti nilai total yang keliru atau usang dapat ditampilkan tanpa tanda apa pun;
	 * pengecualiannya hanya tercatat lewat {@code ErrorAuditUtil}. Pemanggil yang memerlukan
	 * kepastian sebaiknya memeriksa {@code null} pada nilai balik.</p>
	 *
	 * <p><b>Getter destruktif:</b> menulis hasil perhitungan ke field {@code hargaTotal}.</p>
	 *
	 * @return nilai total baris setelah potongan, PPN, dan (opsional) pengurangan PPh; dapat
	 *         {@code null} bila perhitungan gagal dan belum pernah berhasil sebelumnya
	 */
	public Double getHargaTotal() {
		boolean pph_mengurangi_lpj = Common.bolehKonfigurasi("pph_mengurangi_lpj");

		try {
			PenerimaanPengadaanMasterAssetDetail penerimaanPengadaanMasterAssetDetail = this;
			Double dpp = (penerimaanPengadaanMasterAssetDetail.getDiterima()
					* penerimaanPengadaanMasterAssetDetail.getHargaBeli());

			try {
				if (penerimaanPengadaanMasterAssetDetail.getPenerimaanPengadaanMasterAsset() != null
						&& penerimaanPengadaanMasterAssetDetail.getPenerimaanPengadaanMasterAsset()
								.getJsonTermin() != null) {
					dpp = penerimaanPengadaanMasterAssetDetail.getHargaBeli();
				}
			} catch (Exception e) {
				e.printStackTrace(); ais.common.ErrorAuditUtil.record(e, "auto-audit src/ais/database/model/asset/PenerimaanPengadaanMasterAssetDetail.java:388");
			}

			Double potongan = getDiskonDalamBentukPersen()
					? ((penerimaanPengadaanMasterAssetDetail.getHargaPotongan() / 100.0) * dpp)
					: penerimaanPengadaanMasterAssetDetail.getHargaPotongan();
			dpp = dpp - potongan;

			Double ppn = ((penerimaanPengadaanMasterAssetDetail.getPersenPpn() / 100.0) * dpp);

			Double pph = !pph_mengurangi_lpj ? 0.0
					: ((penerimaanPengadaanMasterAssetDetail.getPersenPph() / 100.0) * dpp);

			hargaTotal = (dpp + ppn) - (pph);
		} catch (Exception e) { ais.common.ErrorAuditUtil.record(e, "auto-audit(empty-catch) src/ais/database/model/asset/PenerimaanPengadaanMasterAssetDetail.java:402");
			// TODO: handle exception
		}

		return hargaTotal;
	}

