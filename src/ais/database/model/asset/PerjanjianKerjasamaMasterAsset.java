	/**
	 * Mengambil status aktif dokumen. Getter shadow dengan flag SATU ARAH: status
	 * {@link #disposisiSop} hanya bisa memaksa {@link #aktif} menjadi {@code false} (baik karena
	 * disposisi tidak aktif, maupun karena disposisi berakhir dengan penolakan pada alur SOP
	 * yang menandai {@code getPenolakanAdaDiSini()}) -- tidak ada jalur di getter ini yang bisa
	 * mengembalikan {@code aktif} dari {@code false} ke {@code true} berdasarkan status disposisi.
	 * Ini adalah pola arsitektur berulang di paket asset (bandingkan dengan entity lain seperti
	 * {@code PembayaranDpMasterAsset}/{@code PembayaranTerminMasterAsset}) dan disengaja untuk
	 * mencegah dokumen yang sudah tidak valid "hidup kembali" secara otomatis; membalik status ke
	 * aktif tetap bisa dilakukan lewat {@link #setAktif(Boolean)} secara eksplisit.
	 *
	 * @return {@code true} bila dokumen aktif (default bila belum diset dan disposisi tidak
	 *         menyatakan sebaliknya).
	 */
	public Boolean getAktif() {
		disposisiSop = getDisposisiSop();
		if (disposisiSop != null && !disposisiSop.getAktif()) {
			aktif = false;
		}
		if (disposisiSop != null && disposisiSop.getDisposisiEnd() != null
				&& disposisiSop.getDisposisiEnd().getAlurSop() != null
				&& disposisiSop.getDisposisiEnd().getAlurSop().getPenolakanAdaDiSini()) {
			aktif = false;
		}
		return aktif == null ? true : aktif;
	}

