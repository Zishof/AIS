	public String getBahasa() {

		mahasiswa = getMahasiswa();
		dosen = getDosen();
		guru = getGuru();
		pegawai = getPegawai();
		siswa = getSiswa();

		// Perbaikan bug "bahasa nyangkut ke Indonesia":
		// 1) UTAMAKAN field 'bahasa' milik Tbmuser sendiri — inilah yang di-persist otoritatif saat
		//    pengguna mengganti bahasa (Tbmuser SELALU punya kolom bahasa). Entitas terkait
		//    (dosen/mahasiswa/…) hanya CADANGAN, karena getBahasa()-nya mengembalikan "Bahasa Indonesia"
		//    saat null sehingga dapat MENUTUPI pilihan pengguna bila didahulukan.
		// 2) JANGAN menimpa field 'bahasa' (hilangkan efek samping lama yang merusak nilai).
		String b = takKosongBahasa(bahasa); // field milik Tbmuser sendiri (otoritatif)
		if (b == null) {
			b = takKosongBahasa(dosen != null ? dosen.getBahasa() : null);
		}
		if (b == null) {
			b = takKosongBahasa(mahasiswa != null ? mahasiswa.getBahasa() : null);
		}
		if (b == null) {
			b = takKosongBahasa(siswa != null ? siswa.getBahasa() : null);
		}
		if (b == null) {
			b = takKosongBahasa(guru != null ? guru.getBahasa() : null);
		}
		if (b == null) {
			b = takKosongBahasa(pegawai != null ? pegawai.getBahasa() : null);
		}
		return b == null ? INDONESIA : b;
	}

	private static String takKosongBahasa(String s) {
		return (s == null || s.trim().isEmpty()) ? null : s.trim();
	}

