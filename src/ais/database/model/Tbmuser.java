	public Boolean getAktif() {

		if (getAnggotaKoperasi() != null) {
			aktif = getAnggotaKoperasi().getAktif();
			return aktif;
		}

		if (getPedagang() != null) {
			aktif = getPedagang().getAktif();
			return aktif;
		}

		if (aktif == null) {
			aktif = true;
		}
		if (!ConstantValues.aktifkan_akun_demo) {
			if (userId != null && userId.trim().equalsIgnoreCase("demo")) {
				aktif = false;
			}
		}

		if (ConstantValues.aktifkan_akun_demo) {
			if (userId != null && userId.trim().equalsIgnoreCase("demo")) {
				aktif = true;
			}
		}

		if (getOrangTua() == null && getUserRole() != null && getUserRole().getRoleId().equals(Tbmrole.ORANG_TUA)) {
			aktif = false;
		}

		/*
		 * Akun "yatim role": punya role DOSEN/GURU tetapi tidak punya entitas
		 * Dosen/Guru → dinonaktifkan otomatis. PENGECUALIAN: bila akun dimiliki
		 * oleh PEGAWAI (pegawai bisa merangkap/diberi role mengajar), jangan
		 * dipaksa nonaktif di sini — keaktifannya cukup ditentukan aturan pegawai
		 * di bawah (mengikuti status aktif pegawai). Tanpa pengecualian ini, akun
		 * pengguna milik pegawai yang AKTIF tidak akan pernah bisa diaktifkan
		 * (getAktif() selalu mengembalikan false meski sudah dicentang & disimpan).
		 */
		if (getDosen() == null && getPegawai() == null && ambilRolesId().contains(Tbmrole.DOSEN)) {
			aktif = false;
		}

		if (getGuru() == null && getPegawai() == null && ambilRolesId().contains(Tbmrole.GURU)) {
			aktif = false;
		}

		if (ConstantValues.pegawai_non_aktif_otomatis_tidak_bisa_login) {
			if (getPegawai() != null && !getPegawai().getAktif()) {
				aktif = false;
			}
		}

		return aktif;
	}

