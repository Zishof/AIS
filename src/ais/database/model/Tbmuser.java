	public static String tambahToken(String gcpToken, String existingGcpToken) {
		String tokenBaru = "";
		if (existingGcpToken != null && !existingGcpToken.trim().isEmpty()) {
			for (String t : existingGcpToken.split(";")) {
				if (!t.isEmpty() && !t.equalsIgnoreCase(gcpToken)) {
					tokenBaru += tokenBaru.isEmpty() ? t : ";" + t;
				}
			}
		}
		tokenBaru += tokenBaru.isEmpty() ? gcpToken : ";" + gcpToken;

		String tokenFilter = "";
		Set<String> ada = new HashSet<String>();
		for (String t : tokenBaru.split(";")) {
			if (!t.isEmpty() && !ada.contains(t)) {
				ada.add(t);
				tokenFilter += tokenFilter.isEmpty() ? t : ";" + t;
			}
		}
		ada.clear();
		ada = null;
		tokenBaru = null;
		return tokenFilter;
	}

