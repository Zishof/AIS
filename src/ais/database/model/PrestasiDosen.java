	/**
	 * Mengembalikan tahun prestasi, <b>diturunkan ulang dari {@code tahunAkademik} setiap kali
	 * dipanggil</b>.
	 *
	 * <p><b>Efek samping berbahaya (kelompok B pada Javadoc class).</b> Bila field
	 * {@code tahunAkademik} tidak {@code null}, method ini <b>selalu menimpa</b> field {@code tahun}
	 * dengan potongan pertama {@code tahunAkademik} sebelum tanda "/" — bahkan bila {@code tahun}
	 * sudah bernilai lain yang sengaja diisi pengguna lewat {@link #setTahun(Integer)} atau lewat
	 * kotak isian "Tahun" di form. Karena {@code tahun} adalah kolom terpetakan sungguhan (bukan
	 * {@code @Transient}), penimpaan itu ikut ter-{@code UPDATE} permanen ke database pada
	 * {@code flush} berikutnya bila entity sedang <i>managed</i> — tanpa aksi simpan dari
	 * pengguna.</p>
	 *
	 * <p>Perhatikan juga bahwa yang dibaca adalah <b>field</b> {@code tahunAkademik}, bukan
	 * {@link #getTahunAkademik()}. Jadi bila {@code tahunAkademik} masih {@code null} dan
	 * {@link #getTahunAkademik()} belum pernah dipanggil, tidak ada penurunan nilai sama sekali dan
	 * {@code tahun} dikembalikan apa adanya.</p>
	 *
	 * <p>Kegagalan penguraian angka (mis. {@code tahunAkademik} tidak berformat
	 * {@code "2025/2026"}) ditelan blok {@code catch} yang hanya mencatat lewat
	 * {@code ErrorAuditUtil} — penanda {@code auto-audit(empty-catch)} pada baris itu berasal dari
	 * inisiatif audit blok catch kosong, bukan dari inisiatif Javadoc.</p>
	 *
	 * <p>Dipakai laporan SAPTO {@code LaporanProfileDosen_A_4_5_4} dan rekap lintas-pelaku
	 * {@code DasbordPrestasi}.</p>
	 *
	 * @return tahun prestasi, atau {@code null} bila tidak pernah diisi maupun diturunkan
	 */
	public Integer getTahun() {
		if (tahunAkademik != null) {
			try {
				tahun = Integer.parseInt(tahunAkademik.split("/")[0]);
			} catch (Exception e) { ais.common.ErrorAuditUtil.record(e, "auto-audit(empty-catch) src/ais/database/model/PrestasiDosen.java:295");

			}
		}
		return tahun;
	}

