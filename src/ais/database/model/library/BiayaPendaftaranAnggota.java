	/**
	 * Mengembalikan perpustakaan tempat tarif ini berlaku, mengisi perpustakaan aktif bila kosong.
	 *
	 * <p>
	 * <b>Getter destruktif.</b> Bila field masih <code>null</code>, method memanggil
	 * {@link ais.common.Common#getCurrentPerpustakaan()} dan MENULIS hasilnya ke dalam field, lalu
	 * melewatkannya melalui <code>check(...)</code> untuk memastikan referensinya terikat pada sesi
	 * Hibernate yang aktif. Karena Hibernate memakai getter yang sama saat menulis baris, nilai itu
	 * tersimpan permanen pada flush berikutnya.
	 * </p>
	 *
	 * <p>
	 * Dampaknya bersifat menyempitkan cakupan. Pada entity kebijakan bersaudaranya, kolom
	 * perpustakaan yang NULL tidak diperlakukan sebagai wildcard melainkan dicocokkan persis
	 * (<code>eq("perpustakaan", ...)</code>), tetapi apa pun konvensinya, pengisian otomatis ini
	 * berarti baris yang dibuat lewat layar CRUD <b>tidak akan pernah</b> berkolom NULL: setiap tarif
	 * otomatis tercakup ke perpustakaan operator yang menyimpannya. Membuat tarif yang berlaku
	 * lintas-perpustakaan hanya mungkin lewat INSERT/UPDATE langsung ke database.
	 * </p>
	 *
	 * <p>
	 * Perhatikan pula bahwa {@link ais.common.Common#getCurrentPerpustakaan()} bergantung pada konteks
	 * sesi pengguna; dipanggil dari thread tanpa konteks (proses batch, penjadwal, atau endpoint REST)
	 * ia dapat mengembalikan <code>null</code>, sehingga perilaku entity berbeda tergantung dari mana
	 * ia dibuat.
	 * </p>
	 *
	 * @return perpustakaan tempat tarif berlaku, atau <code>null</code> bila tidak ada konteks
	 *         perpustakaan aktif.
	 */
	@ManyToOne(cascade = { CascadeType.PERSIST, CascadeType.MERGE }, fetch = FetchType.LAZY)
	@JoinColumn(name = "perpustakaan", nullable = true)
	public Perpustakaan getPerpustakaan() {
		if (perpustakaan == null) {
			perpustakaan = Common.getCurrentPerpustakaan();
		}
		perpustakaan = check(perpustakaan);
		return perpustakaan;
	}

