	/**
	 * Mengembalikan perpustakaan tempat blokir ini berlaku, mengisi perpustakaan aktif bila kosong.
	 *
	 * <p>
	 * <b>Getter destruktif dengan konsekuensi kebijakan.</b> Bila field masih <code>null</code>,
	 * method ini memanggil {@link ais.common.Common#getCurrentPerpustakaan()} dan MENULIS hasilnya ke
	 * dalam field, lalu melewatkannya melalui <code>check(...)</code> untuk memastikan referensinya
	 * terikat pada sesi Hibernate yang aktif. Karena Hibernate memakai getter yang sama saat menulis
	 * baris, nilai itu tersimpan permanen pada flush berikutnya.
	 * </p>
	 *
	 * <p>
	 * Dampaknya terhadap cakupan blokir bersifat menyempitkan. Query penegakan memperlakukan kolom
	 * <code>perpustakaan</code> yang NULL sebagai blokir <b>global</b> yang berlaku di semua
	 * perpustakaan — <code>or(isNull("perpustakaan"), eq("perpustakaan", currentPerpustakaan))</code>.
	 * Namun karena getter ini mengisi sendiri perpustakaan operator yang sedang bekerja, baris yang
	 * dibuat lewat layar CRUD <b>tidak akan pernah</b> berkolom NULL. Dengan kata lain, blokir global
	 * praktis tidak dapat dibuat melalui antarmuka; setiap blokir otomatis menjadi blokir lokal satu
	 * perpustakaan, dan anggota yang sama tetap dapat meminjam di perpustakaan lain dalam instalasi
	 * yang sama. Blokir global hanya bisa dibuat dengan INSERT/UPDATE langsung ke database.
	 * </p>
	 *
	 * <p>
	 * Perhatikan pula bahwa {@link ais.common.Common#getCurrentPerpustakaan()} bergantung pada konteks
	 * sesi pengguna. Dipanggil dari thread tanpa konteks — proses batch, penjadwal, atau endpoint REST
	 * — ia dapat mengembalikan <code>null</code>, sehingga field tetap kosong dan barisnya justru
	 * menjadi blokir global. Perilaku entity ini karenanya berbeda tergantung dari mana ia dibuat.
	 * </p>
	 *
	 * @return perpustakaan tempat blokir berlaku, atau <code>null</code> bila tidak ada konteks
	 *         perpustakaan aktif — yang berarti blokir berlaku global.
	 */
	@ManyToOne(cascade = { CascadeType.PERSIST, CascadeType.MERGE }, fetch = FetchType.LAZY)
	@JoinColumn(name = "perpustakaan", nullable = true)
	public Perpustakaan getPerpustakaan() {
		if (perpustakaan == null) {
			perpustakaan = Common.getCurrentPerpustakaan();
		}
		perpustakaan = check(perpustakaan);
		return perpustakaan;
	}

