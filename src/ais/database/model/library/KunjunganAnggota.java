	public void setKeterangan(String keterangan) {
		this.keterangan = keterangan;
	}

	/**
	 * Mengembalikan anggota yang berkunjung.
	 *
	 * <p>
	 * Getter murni — <b>tidak destruktif</b>: ia tidak memanggil <code>check(...)</code> dan tidak
	 * mengisi nilai bawaan. Relasi sengaja dipetakan tanpa <code>fetch = FetchType.LAZY</code> dan
	 * dengan <code>&#64;Fetch(FetchMode.SELECT)</code>, sehingga anggota dimuat lewat SELECT terpisah
	 * dan selalu tersedia; memuat daftar kunjungan di layar menghasilkan pola query N+1.
	 * </p>
	 *
	 * <p>
	 * Kolomnya nullable. Baris dengan <code>anggota</code> NULL tidak akan pernah cocok dengan query
	 * deduplikasi harian (yang memakai <code>eq("anggota", ...)</code>), dan justru pada baris seperti
	 * itulah ketiga kolom bayangan {@link #getKode()}, {@link #getNama()}, dan {@link #getAlamat()}
	 * mempertahankan nilai tersimpannya alih-alih ditimpa.
	 * </p>
	 *
	 * @return anggota yang berkunjung, atau <code>null</code>.
	 */
	@ManyToOne(cascade = { CascadeType.PERSIST, CascadeType.MERGE })
	@Fetch(FetchMode.SELECT)
	@JoinColumn(name = "anggota", nullable = true)
	public Anggota getAnggota() {
		return anggota;
	}

	/**
	 * Menetapkan anggota yang berkunjung.
	 *
	 * <p>
	 * Setter mentah tanpa validasi. Perhatikan bahwa mengganti anggota pada baris yang sudah tersimpan
	 * akan membuat ketiga kolom bayangan ({@link #getKode()}, {@link #getNama()},
	 * {@link #getAlamat()}) ikut berpindah ke anggota yang baru pada pembacaan berikutnya, sehingga
	 * baris kunjungan lama benar-benar berubah kepemilikannya tanpa jejak selain revisi Envers.
	 * </p>
	 *
	 * @param anggota anggota yang berkunjung; <code>null</code> diterima.
	 */
	public void setAnggota(Anggota anggota) {
		this.anggota = anggota;
	}

	/**
	 * Mengembalikan cap waktu kedatangan yang presisi (TIMESTAMP).
	 *
	 * <p>
	 * Getter murni — tidak destruktif dan tidak mengisi nilai bawaan; nilai awalnya berasal dari
	 * inisialisasi field. Bandingkan dengan {@link #getTgl()} yang menyimpan harinya saja.
	 * </p>
	 *
	 * <p>
	 * Karena mekanisme deduplikasi harian tidak pernah memperbarui baris yang sudah ada, nilai ini
	 * selalu menunjuk kedatangan <b>pertama</b> anggota pada hari itu, bukan kedatangan terakhir dan
	 * bukan pula rata-rata. Laporan yang ingin mengetahui pola jam kunjungan hanya dapat melihat jam
	 * kedatangan pertama.
	 * </p>
	 *
	 * @return cap waktu kedatangan; bisa <code>null</code> bila dibaca dari baris DB lama yang
	 *         kolomnya kosong.
	 */
	@Temporal(TemporalType.TIMESTAMP)
	public Date getTanggal() {
		return tanggal;
	}

	/**
	 * Menetapkan cap waktu kedatangan.
	 *
	 * <p>
	 * Setter mentah tanpa validasi konsistensi terhadap {@link #getTgl()}: menetapkan
	 * <code>tanggal</code> pada hari yang berbeda dari <code>tgl</code> diterima diam-diam dan
	 * menghasilkan baris yang tidak konsisten. Kedua pemakai yang ada selalu menetapkan keduanya dari
	 * satu pemanggilan {@link ais.ui.util.WaktuUtil#getDate()} yang sama.
	 * </p>
	 *
	 * @param tanggal cap waktu kedatangan; <code>null</code> diterima.
	 */
	public void setTanggal(Date tanggal) {
		this.tanggal = tanggal;
	}

	/**
	 * Mengembalikan perpustakaan yang dikunjungi, mengisi perpustakaan aktif bila kosong.
	 *
	 * <p>
	 * <b>Getter destruktif.</b> Bila field masih <code>null</code>, method memanggil
	 * {@link ais.common.Common#getCurrentPerpustakaan()} dan MENULIS hasilnya ke dalam field, lalu
	 * melewatkannya melalui <code>check(...)</code> untuk memastikan referensinya terikat pada sesi
	 * Hibernate yang aktif. Karena Hibernate memakai getter yang sama saat menulis baris, nilai itu
	 * tersimpan permanen pada flush berikutnya.
	 * </p>
	 *
	 * <p>
	 * Untuk entity ini pengisian otomatis tersebut jarang berpengaruh, sebab kedua pembuat kunjungan
	 * selalu menetapkan perpustakaannya secara eksplisit sebelum menyimpan. Namun perlu diketahui
	 * bahwa pengisian ini berjalan juga saat <b>membaca</b> baris lama yang kolomnya NULL: baris hasil
	 * migrasi akan diam-diam tercakup ke perpustakaan operator yang kebetulan membukanya, dan sejak
	 * saat itu ikut terhitung pada statistik perpustakaan tersebut.
	 * </p>
	 *
	 * <p>
	 * {@link ais.common.Common#getCurrentPerpustakaan()} bergantung pada konteks sesi pengguna;
	 * dipanggil dari thread tanpa konteks (proses batch atau penjadwal) ia dapat mengembalikan
	 * <code>null</code> sehingga field tetap kosong.
	 * </p>
	 *
	 * @return perpustakaan yang dikunjungi, atau <code>null</code> bila tidak ada konteks perpustakaan
	 *         aktif.
	 */
	@ManyToOne(cascade = { CascadeType.PERSIST, CascadeType.MERGE }, fetch = FetchType.LAZY)
	@JoinColumn(name = "perpustakaan", nullable = true)
	public Perpustakaan getPerpustakaan() {
		if (perpustakaan == null) {
			perpustakaan = Common.getCurrentPerpustakaan();
		}
		perpustakaan = check(perpustakaan);
		return perpustakaan;
	}

	/**
	 * Menetapkan perpustakaan yang dikunjungi.
	 *
	 * <p>
	 * Setter mentah. Menetapkan <code>null</code> di sini tidak bertahan bila ada konteks perpustakaan
	 * aktif, karena {@link #getPerpustakaan()} akan mengisinya kembali pada pembacaan berikutnya —
	 * termasuk pembacaan yang dilakukan Hibernate sendiri saat menulis baris.
	 * </p>
	 *
	 * @param perpustakaan perpustakaan yang dikunjungi.
	 */
	public void setPerpustakaan(Perpustakaan perpustakaan) {
		this.perpustakaan = perpustakaan;
	}

	/**
	 * Mengembalikan hari kunjungan (DATE, tanpa jam).
	 *
	 * <p>
	 * Getter murni — tidak destruktif dan tidak mengisi nilai bawaan. Inilah kolom yang berperan
	 * sebagai <b>kunci deduplikasi harian</b>: kedua pembuat kunjungan mencari baris yang sudah ada
	 * dengan <code>eq("tgl", WaktuUtil.getDate())</code> sebelum memutuskan membuat baris baru.
	 * Pencocokan itu bekerja karena Hibernate mengikat parameter memakai tipe properti yang dipetakan
	 * — yaitu {@link javax.persistence.TemporalType#DATE} — sehingga bagian jam pada nilai pembanding
	 * dibuang lebih dulu.
	 * </p>
	 *
	 * <p>
	 * Karena itu jangan mengubah pemetaan properti ini menjadi TIMESTAMP. Perubahan tersebut akan
	 * membuat pembanding ikut membawa jam, pencocokan tidak pernah berhasil, dan sistem membuat baris
	 * kunjungan baru pada setiap peminjaman maupun setiap pembukaan portal — menggelembungkan
	 * statistik kunjungan tanpa ada pesan kesalahan apa pun.
	 * </p>
	 *
	 * @return hari kunjungan; bisa <code>null</code> bila dibaca dari baris DB lama yang kolomnya
	 *         kosong.
	 */
	@Temporal(TemporalType.DATE)
	public Date getTgl() {
		return tgl;
	}

	/**
	 * Menetapkan hari kunjungan.
	 *
	 * <p>
	 * Setter mentah tanpa normalisasi: nilai yang dikirim boleh membawa jam, dan bagian jam itu baru
	 * dibuang saat ditulis ke database karena pemetaan kolomnya DATE. Objek yang masih di memori tetap
	 * membawanya, sehingga membandingkan <code>getTgl()</code> antar dua objek dengan
	 * <code>equals()</code> di sisi Java dapat memberi hasil berbeda dari perbandingan di database.
	 * Bandingkan lewat query, atau normalkan sendiri lebih dulu.
	 * </p>
	 *
	 * @param tgl hari kunjungan; <code>null</code> diterima tetapi membuat baris tidak dapat
	 *            dideduplikasi.
	 */
	public void setTgl(Date tgl) {
		this.tgl = tgl;
	}

	/**
	 * Mengembalikan alamat anggota yang berkunjung, menyalinnya ulang dari {@link #getAnggota()}.
	 *
	 * <p>
	 * <b>Getter destruktif.</b> Bila relasi <code>anggota</code> terisi, method MENULIS
	 * <code>anggota.getAlamat()</code> ke dalam field <code>alamat</code> milik baris kunjungan
	 * sebelum mengembalikannya. Karena Hibernate memakai getter yang sama saat menulis baris,
	 * penulisan itu ikut tersimpan permanen pada flush berikutnya.
	 * </p>
	 *
	 * <p>
	 * Berbeda dari {@link #getKode()} dan {@link #getNama()}, method ini <b>tidak</b> menormalkan
	 * <code>null</code> menjadi String kosong — ia dapat mengembalikan <code>null</code>. Asimetri
	 * kecil ini mudah terlewat oleh kode pemanggil yang menganggap ketiga kolom bayangan berperilaku
	 * sama. Rantai destruktifnya juga lebih dangkal, karena {@link Anggota#getAlamat()} adalah getter
	 * murni yang tidak menulis apa pun.
	 * </p>
	 *
	 * <p>
	 * Seperti dua kolom bayangan lainnya, nilai ini <b>bukan</b> snapshot historis: perubahan alamat
	 * anggota merambat ke seluruh baris kunjungan lamanya. Perlu diperhatikan juga bahwa alamat adalah
	 * data pribadi; menyalinnya ke setiap baris kunjungan memperluas jangkauan data tersebut ke
	 * laporan dan ekspor kunjungan yang mungkin tidak dimaksudkan memuatnya.
	 * </p>
	 *
	 * <p>
	 * Properti tidak diberi anotasi <code>&#64;Column</code>, sehingga Hibernate memetakannya ke kolom
	 * bernama <code>alamat</code> mengikuti konvensi bawaan.
	 * </p>
	 *
	 * @return alamat anggota, atau <code>null</code>.
	 */
	public String getAlamat() {
		if (anggota != null) {
			alamat = anggota.getAlamat();
		}
		return alamat;
	}

	/**
	 * Menetapkan alamat anggota pada baris kunjungan.
	 *
	 * <p>
	 * Setter mentah. Nilai yang ditetapkan di sini <b>tidak bertahan</b> bila relasi
	 * {@link #getAnggota()} terisi, karena {@link #getAlamat()} akan menimpanya pada pembacaan
	 * berikutnya. Setter ini hanya berpengaruh nyata pada baris yang anggotanya <code>null</code>.
	 * </p>
	 *
	 * @param alamat alamat anggota; <code>null</code> diperbolehkan.
	 */
	public void setAlamat(String alamat) {
		this.alamat = alamat;
	}

