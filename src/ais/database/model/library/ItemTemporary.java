	/**
	 * Menghitung dan mengembalikan kunci unik bibliografis gabungan baris ini.
	 *
	 * <p>Kunci dirakit dari {@link #getIsbn()}, {@link #getIsbn10()}, {@link #getIssn()}, judul huruf
	 * kecil yang disandikan {@code URLEncoder} UTF-8, lalu &mdash; hanya bila terisi &mdash;
	 * {@code edisi} dan {@code kode}, semuanya dipisah garis bawah. Penyandian judul diperlukan
	 * karena nilai ini disimpan pada kolom {@code kode__unik_buku} yang dipetakan
	 * {@code unique = true}.</p>
	 *
	 * <p>Hal yang perlu diperhatikan: nilai <b>selalu dihitung ulang</b> (nilai tersimpan diabaikan
	 * dan ditimpa), perhitungannya memanggil empat getter destruktif sehingga sekaligus menormalkan
	 * ISBN/ISSN/judul, dan blok {@code catch} cadangan merakit kunci dengan judul <b>tanpa</b>
	 * penyandian &mdash; menghasilkan nilai berbeda untuk judul yang sama sehingga kegagalan
	 * penyandian dapat memunculkan duplikat logis yang tetap lolos batasan unik DB.</p>
	 *
	 * @return kunci unik bibliografis gabungan; tidak pernah {@code null}.
	 */
	@Column(name = "kode__unik_buku", unique = true, nullable = true, columnDefinition = "text")
	public String getKodeUnikBuku() {
		try {
			kodeUnikBuku = getIsbn() + "_" + getIsbn10() + "_" + getIssn() + "_"
					+ URLEncoder.encode(getNama().toLowerCase().trim(), "UTF-8")
					+ (edisi == null || edisi.trim().isEmpty() ? "" : "_" + edisi)
					+ (kode == null || kode.trim().isEmpty() ? "" : "_" + kode);
		} catch (Exception e) {
			kodeUnikBuku = getIsbn() + "_" + getIsbn10() + "_" + getIssn() + "_" + getNama().toLowerCase().trim()
					+ (edisi == null || edisi.trim().isEmpty() ? "" : "_" + edisi)
					+ (kode == null || kode.trim().isEmpty() ? "" : "_" + kode);
		}
		return kodeUnikBuku;
	}

