	/**
	 * Mengembalikan daftar pengarang sebagai satu string ternormalisasi (denormalisasi dari relasi
	 * pengarang).
	 *
	 * <p>Getter destruktif: {@code null} menjadi string kosong, seluruh koma diganti titik koma
	 * &mdash; karena nama pengarang sendiri kerap mengandung koma ({@code "Sutanto, Budi"})
	 * sehingga koma tidak dapat menjadi pemisah antar-pengarang &mdash; kurung siku sisa impor larik
	 * JSON dibuang, lalu hasilnya dipangkas dan ditulis balik ke field. Pemisah pada nilai tersimpan
	 * karena itu adalah titik koma.</p>
	 *
	 * @return daftar pengarang dipisah titik koma; string kosong bila belum diisi.
	 */
	public String getPengarangs() {
		if (pengarangs == null) {
			pengarangs = "";
		}
		pengarangs = org.apache.commons.lang3.StringUtils.replace(pengarangs, ",", ";");
		pengarangs = org.apache.commons.lang3.StringUtils.replace(pengarangs, "[", "");
		pengarangs = org.apache.commons.lang3.StringUtils.replace(pengarangs, "]", "").trim();
		return pengarangs.trim();
	}

	/**
	 * Menetapkan daftar pengarang dengan pembersihan koma ganda (sepuluh lintasan berturut-turut,
	 * cara sederhana menangani rentetan koma tanpa regex) dan <b>pemotongan permanen</b> ke 253
	 * karakter.
	 *
	 * @param pengarangs daftar pengarang; {@code null} diperlakukan sebagai string kosong.
	 */
	public void setPengarangs(String pengarangs) {
		if (pengarangs == null) {
			pengarangs = "";
		}
		for (int i = 0; i < 10; i++) {
			pengarangs = org.apache.commons.lang3.StringUtils.replace(pengarangs, ",,", "");
		}
		if (pengarangs.length() > 254) {
			pengarangs = pengarangs.substring(0, 253);
		}
		this.pengarangs = pengarangs;
	}

