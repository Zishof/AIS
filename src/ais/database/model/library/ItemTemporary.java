	/**
	 * Mengembalikan URL sampul untuk tampilan besar sekaligus sumber unduhan
	 * {@link #checkApakahGambarSudahTersimpanDiLocal()}.
	 *
	 * <p>Baris pertama mengganti {@code zoom=1} menjadi {@code zoom=3} pada URL Google Books
	 * &mdash; parameter resolusi thumbnail &mdash; tetapi baris berikutnya
	 * ({@code imageUrlBesar = imageUrl;}) langsung <b>menimpanya kembali</b> dengan URL asli,
	 * sehingga peningkatan resolusi itu tidak pernah berlaku. Kejanggalan yang sama juga ada pada
	 * {@code Item.getImageUrlBesar()}.</p>
	 *
	 * <p>Bila URL kosong sementara baris sudah punya ID, method merakit URL internal
	 * {@code /AmbilMedia?id=...&clazz=ais.database.model.file.FotoGambarItem&property=item} dengan
	 * awalan host dari {@code Common.getRequestHostWithProtocol()}. URL internal inilah yang membuat
	 * {@code checkApakahGambarSudahTersimpanDiLocal()} melewati nilai bermuatan {@code "localhost"}
	 * &mdash; menyalin berkas dari diri sendiri tidak ada gunanya. Karena bergantung pada host
	 * request, method ini hanya menghasilkan URL benar dalam konteks request HTTP.</p>
	 *
	 * @return URL sampul besar, URL internal {@code /AmbilMedia}, atau {@code null}.
	 */
	public String getImageUrlBesar() {
		if (imageUrl != null && !imageUrl.trim().isEmpty()) {
			imageUrlBesar = org.apache.commons.lang3.StringUtils.replace(imageUrl, "zoom=1", "zoom=3");
		}
		imageUrlBesar = imageUrl;

		if (id != null) {
			if (imageUrlBesar == null || imageUrlBesar.trim().isEmpty()) {
				imageUrlBesar = Common.getRequestHostWithProtocol() + "/AmbilMedia?id=" + id
						+ "&name=nama&foto=foto&clazz=ais.database.model.file.FotoGambarItem&property=item";
			}
		}
		return imageUrlBesar;
	}

