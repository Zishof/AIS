	/**
	 * Mengembalikan daftar ID jurusan yang tersimpan pada kolom {@code by_statement}, setelah
	 * disinkronkan dari {@link #getJurusan()} dan dinormalkan.
	 *
	 * <h3>Kolom berperan ganda</h3>
	 * <p>Aslinya kolom ini menyimpan "pernyataan tanggung jawab" bibliografis (bagian <i>by ...</i>
	 * pada kartu katalog) yang ikut terbawa saat impor. Pada kode yang berjalan sekarang kolom itu
	 * dialihfungsikan menjadi tempat menyimpan ID {@link Jurusan} berformat {@code ",id,"}.</p>
	 *
	 * <h3>Cara kerja</h3>
	 * <p>Bila {@link #getJurusan()} terisi sementara teksnya belum memuat {@code ",id,"} jurusan
	 * tersebut, seluruh isi kolom <b>ditimpa</b> menjadi {@code ",id,"} milik jurusan itu &mdash;
	 * ditimpa, bukan ditambahi, sehingga kolom ini efektif hanya sanggup menyimpan satu jurusan
	 * meskipun formatnya menyerupai daftar. Setelah itu nilai dibungkus koma di kedua sisi agar
	 * pemeriksaan keanggotaan cukup mencari substring, koma ganda diringkas dengan tiga kali
	 * {@code replaceAll(",,", ",")} berturut-turut (satu lintasan tidak menangani rentetan koma
	 * yang tumpang tindih), dan hasil yang ternyata hanya berisi koma dianggap kosong.</p>
	 *
	 * <h3>Perbedaan penting terhadap {@link Item}</h3>
	 * <p>Di kelas ini sinkronisasinya <b>searah</b>: jurusan menentukan teks, tetapi teks tidak
	 * pernah menentukan jurusan. Pada {@code Item}, {@code getJurusan()} justru mengurai balik teks
	 * ini dan menimpa kolom kunci asing {@code jurusan} &mdash; hubungan melingkar yang tidak
	 * berlaku di sini. Selain itu logika penyaringan di sini ditulis inline, bukan dipisah ke method
	 * {@code saringJurusan()} seperti pada {@code Item}.</p>
	 *
	 * @return daftar ID jurusan berformat koma; string kosong bila tidak ada.
	 */
	public String getBy_statement() {

		jurusan = getJurusan();
		if (jurusan != null) {
			if (by_statement == null || !by_statement.contains("," + jurusan.getId() + ",")) {
				by_statement = "," + jurusan.getId() + ",";
			}
		}

		by_statement = (by_statement == null || by_statement.trim().equalsIgnoreCase(",") ? ""
				: "," + by_statement.trim() + ",").replaceAll(",,", ",").replaceAll(",,", ",").replaceAll(",,", ",");

		if (by_statement.equals(",")) {
			by_statement = "";
		} else if (by_statement.equals(",,")) {
			by_statement = "";
		} else if (by_statement.equals(",,,")) {
			by_statement = "";
		}
		by_statement = by_statement == null ? "" : by_statement.trim();

		return by_statement;
	}

