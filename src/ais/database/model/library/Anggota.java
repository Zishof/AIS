	public String getNama() {

		mahasiswa = getMahasiswa();
		dosen = getDosen();
		guru = getGuru();
		siswa = getSiswa();
		pegawai = getPegawai();
		tbmuser = getTbmuser();

		if (siswa != null) {
			nama = siswa.getNama();
		} else if (guru != null) {
			nama = guru.getNama();
		} else if (mahasiswa != null) {
			nama = mahasiswa.getNama();
		} else if (dosen != null) {
			nama = dosen.getNama();
		} else if (pegawai != null) {
			nama = pegawai.getNama();
		} else if (tbmuser != null) {
			nama = tbmuser.getUserId();
		}
		return nama;
	}

