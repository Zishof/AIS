	/**
	 * Menormalkan isi {@code by_statement} menjadi daftar ID jurusan berformat koma yang rapi.
	 *
	 * <h3>Konteks: kolom yang berperan ganda</h3>
	 * <p>Kolom {@code by_statement} aslinya adalah "pernyataan tanggung jawab" bibliografis (bagian
	 * <i>by ...</i> pada kartu katalog) yang ikut terbawa saat impor dari katalog eksternal. Pada
	 * kode yang berjalan sekarang kolom itu <b>dialihfungsikan</b> menjadi tempat menyimpan daftar
	 * ID {@link Jurusan} dalam bentuk {@code ",12,"}. Pengalihfungsian inilah yang membuat method
	 * penyaring ini diperlukan.</p>
	 *
	 * <h3>Cara kerja</h3>
	 * <p>Nilai dibungkus koma di kedua sisi ({@code "," + nilai + ","}) supaya pencarian
	 * keanggotaan cukup memeriksa substring {@code ",id,"} tanpa perlu memecah string. Setelah itu
	 * koma ganda diringkas dengan tiga kali {@code replaceAll(",,", ",")} berturut-turut &mdash;
	 * pengulangan diperlukan karena satu lintasan tidak menangani rentetan koma yang saling
	 * tumpang tindih. Terakhir, hasil yang ternyata hanya berisi koma ({@code ","},
	 * {@code ",,"}, {@code ",,,"}) dianggap kosong dan diubah menjadi string kosong.</p>
	 *
	 * <h3>Efek samping</h3>
	 * <p>Method menulis langsung ke field {@code by_statement} <b>dan</b> mengembalikannya. Karena
	 * ia dipanggil dari {@link #getBy_statement()} maupun {@link #getJurusan()}, sekadar membaca
	 * jurusan sebuah item sudah cukup untuk menormalkan &mdash; dan pada baris hasil impor lama,
	 * <b>menghapus</b> &mdash; pernyataan tanggung jawab bibliografis yang tersimpan di kolom itu.
	 * Data teks {@code by_statement} yang bukan berupa ID angka tidak dapat dipulihkan setelahnya.</p>
	 *
	 * @return isi {@code by_statement} yang sudah dinormalkan; tidak pernah {@code null}.
	 */
	private String saringJurusan() {
		by_statement = (by_statement == null || by_statement.trim().equalsIgnoreCase(",") ? ""
				: "," + by_statement.trim() + ",").replaceAll(",,", ",").replaceAll(",,", ",").replaceAll(",,", ",");

		if (by_statement.equals(",")) {
			by_statement = "";
		} else if (by_statement.equals(",,")) {
			by_statement = "";
		} else if (by_statement.equals(",,,")) {
			by_statement = "";
		}
		by_statement = by_statement == null ? "" : by_statement.trim();
		return by_statement;
	}

	/**
	 * Mengembalikan daftar ID jurusan yang tersimpan pada kolom {@code by_statement}, setelah
	 * disinkronkan dengan {@link #getJurusan()} dan dinormalkan {@code saringJurusan()}.
	 *
	 * <h3>Arah sinkronisasi</h3>
	 * <p>Method ini bekerja dari <b>jurusan menuju teks</b>: ia memanggil {@link #getJurusan()},
	 * dan bila jurusan terisi sementara {@code by_statement} belum memuat {@code ",id,"}
	 * jurusan tersebut, seluruh isi {@code by_statement} <b>ditimpa</b> menjadi {@code ",id,"}
	 * milik jurusan itu. Perhatikan kata "ditimpa": nilai lama tidak ditambahi, melainkan diganti,
	 * sehingga kolom ini efektif hanya sanggup menyimpan satu jurusan meskipun formatnya menyerupai
	 * daftar.</p>
	 *
	 * <h3>Hubungan melingkar dengan {@link #getJurusan()}</h3>
	 * <p>{@link #getJurusan()} bekerja pada arah sebaliknya &mdash; dari <b>teks menuju jurusan</b>
	 * &mdash; dengan mengurai ID pertama pada {@code by_statement} dan menimpa field {@code jurusan}
	 * bila baris master-nya ditemukan. Kedua getter karena itu saling menyuapi. Implikasi yang perlu
	 * diingat: <b>teks {@code by_statement} berkuasa atas kolom FK {@code jurusan}</b>. Siapa pun
	 * yang dapat menulis {@code by_statement} (mis. lewat impor, atau lewat endpoint CRUD generik
	 * yang memetakan properti berdasarkan nama) dapat memindahkan kepemilikan jurusan sebuah item
	 * tanpa menyentuh field {@code jurusan} sama sekali. Karena {@code jurusan} termasuk whitelist
	 * {@code scopeBindings()} Generic CRUD v2, kolom teks ini secara tidak langsung ikut menentukan
	 * pembatas cakupan data &mdash; sesuatu yang tidak terlihat dari nama kolomnya.</p>
	 *
	 * @return daftar ID jurusan berformat koma; string kosong bila tidak ada.
	 */
	@Column(name = "by_statement", nullable = true, columnDefinition = "text")
	public String getBy_statement() {

		jurusan = getJurusan();
		if (jurusan != null) {
			if (by_statement == null || !by_statement.contains("," + jurusan.getId() + ",")) {
				by_statement = "," + jurusan.getId() + ",";
			}
		}

		return saringJurusan();
	}

