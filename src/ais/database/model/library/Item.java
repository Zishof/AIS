	/**
	 * Mengembalikan kelas DDC item yang dipakai tampilan dan pencetakan label, dengan urutan
	 * prioritas sumber yang tegas.
	 *
	 * <h3>Langkah</h3>
	 * <ol>
	 *   <li>Bila field {@code deweyDecimalClass} terisi, artefak impor JSON ({@code "["},
	 *       {@code "]"}, tanda kutip) dibuang dan hasilnya dipangkas spasi &mdash; lalu ditulis
	 *       balik ke field.</li>
	 *   <li>{@code null} dinormalkan menjadi string kosong.</li>
	 *   <li><b>Penimpaan berprioritas:</b> bila {@link #getLabelItem()} memiliki DDC tidak kosong,
	 *       nilainya menang. Jika tidak, dan {@code ddcItem} memiliki kode tidak kosong, kode itulah
	 *       yang dipakai. Nilai yang tersimpan pada kolom sendiri hanya bertahan bila kedua sumber
	 *       di atas kosong.</li>
	 * </ol>
	 *
	 * <p>Urutan ini menjadikan {@link LabelItem} sumber kebenaran klasifikasi, {@link DdcItem}
	 * cadangan pertama, dan kolom {@code deweyDecimalClass} sekadar cache. Karena penimpaan ditulis
	 * balik ke field, cache tersebut ikut diperbarui saat flush &mdash; sekaligus berarti nilai DDC
	 * yang pernah dientri manual akan <b>hilang</b> begitu item dikaitkan ke label yang punya DDC
	 * sendiri.</p>
	 *
	 * <p>Seperti pada {@link #getDdcItem()}, pemeriksaan membaca field mentah {@code labelItem} dan
	 * {@code ddcItem}, bukan getter-nya, sehingga proksi lazy yang belum dimuat tidak memicu
	 * kueri.</p>
	 *
	 * @return kelas DDC efektif; tidak pernah {@code null}.
	 */
	public String getDeweyDecimalClass() {

		if (deweyDecimalClass != null) {
			deweyDecimalClass = org.apache.commons.lang3.StringUtils.replace(deweyDecimalClass, "[", "");
			deweyDecimalClass = org.apache.commons.lang3.StringUtils.replace(deweyDecimalClass, "]", "");
			deweyDecimalClass = org.apache.commons.lang3.StringUtils.replace(deweyDecimalClass, "\"", "");
			deweyDecimalClass = deweyDecimalClass.trim();
		}
		if (deweyDecimalClass == null) {
			deweyDecimalClass = "";
		}

		if (labelItem != null && labelItem.getDeweyDecimalClass() != null
				&& !labelItem.getDeweyDecimalClass().trim().isEmpty()) {
			deweyDecimalClass = labelItem.getDeweyDecimalClass();
		} else if (ddcItem != null && ddcItem.getKode() != null && !ddcItem.getKode().trim().isEmpty()) {
			deweyDecimalClass = ddcItem.getKode();
		}

		return deweyDecimalClass;
	}

