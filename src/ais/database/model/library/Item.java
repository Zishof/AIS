	/**
	 * Menyatakan apakah item aktif (tidak dihapus lunak) &mdash; dengan satu aturan pemaksaan
	 * global.
	 *
	 * <h3>Aturan pemaksaan</h3>
	 * <p>Bila saklar global {@code ConstantValues.googleBookAktif} bernilai {@code false} dan item
	 * ini memiliki {@link #getGoogleBookId()} yang tidak kosong, field {@code aktif}
	 * <b>dipaksa</b> menjadi {@code false}. Artinya seluruh koleksi hasil penarikan Google Books
	 * dapat disembunyikan sekaligus lewat satu saklar konfigurasi, tanpa perlu memperbarui baris
	 * satu per satu.</p>
	 *
	 * <h3>Sifat dua arah dan konsekuensinya</h3>
	 * <p>Pemaksaan itu hanya berjalan satu arah: saklar yang mati mematikan item, tetapi saklar yang
	 * kembali menyala <b>tidak</b> menghidupkannya lagi &mdash; nilai {@code false} yang sudah
	 * telanjur ditulis ke field akan ikut tersimpan saat flush dan menetap. Selain itu method
	 * memanggil {@link #getGoogleBookId()} yang mengurai JSON {@code infoLain} pada setiap
	 * pemanggilan, sehingga getter yang tampak sepele ini sebenarnya melakukan penguraian JSON tiap
	 * kali daftar dirender.</p>
	 *
	 * <p>Bila nilai tersimpan {@code null}, method mengembalikan {@code true} &mdash; item lama yang
	 * belum pernah punya penanda dianggap aktif.</p>
	 *
	 * @return {@code true} bila item aktif.
	 */
	public Boolean getAktif() {

		if (!ConstantValues.googleBookAktif) {
			if (getGoogleBookId() != null && !getGoogleBookId().isEmpty()) {
				aktif = false;
			}
		}
		return aktif == null ? true : aktif;
	}

