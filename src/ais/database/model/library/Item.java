	/**
	 * Menghitung dan mengembalikan kunci unik bibliografis gabungan item.
	 *
	 * <h3>Susunan kunci</h3>
	 * <p>Kunci dirakit dari enam komponen berurutan yang dipisah garis bawah:
	 * {@link #getIsbn()}, {@link #getIsbn10()}, {@link #getIssn()}, judul dalam huruf kecil yang
	 * disandikan {@code URLEncoder} UTF-8, lalu &mdash; hanya bila terisi &mdash; {@code edisi} dan
	 * {@code kode}. Penyandian judul diperlukan karena judul boleh mengandung spasi dan karakter
	 * apa pun, sementara nilai ini disimpan pada kolom yang dipetakan {@code unique = true}.</p>
	 *
	 * <h3>Perilaku yang perlu diperhatikan</h3>
	 * <ul>
	 *   <li><b>Selalu dihitung ulang.</b> Nilai yang pernah tersimpan pada field diabaikan; setiap
	 *       pemanggilan menimpanya dengan hasil hitungan terbaru. Karena Hibernate membaca properti
	 *       lewat getter, mengubah judul/ISBN/edisi otomatis mengubah kolom {@code kode__unik_buku}
	 *       pada flush berikutnya.</li>
	 *   <li><b>Bergantung pada getter destruktif.</b> Ia memanggil {@link #getIsbn()},
	 *       {@link #getIsbn10()}, {@link #getIssn()}, dan {@link #getNama()} &mdash; jadi
	 *       menghitung kunci ini sekaligus menormalkan keempat field tersebut.</li>
	 *   <li><b>Kolom unik + nilai turunan.</b> Dua baris berbeda yang kebetulan sama judul, ISBN,
	 *       edisi, dan kodenya akan menghasilkan kunci identik dan ditolak DB saat penyimpanan.
	 *       Untuk item tanpa ISBN sama sekali, pembeda satu-satunya tinggal judul, edisi, dan kode
	 *       &mdash; dua eksemplar judul sama karena itu wajib dibedakan lewat {@code edisi} atau
	 *       {@code kode}, bukan dengan menambah baris {@code Item} baru.</li>
	 *   <li><b>Jalur cadangan.</b> Bila {@code URLEncoder} gagal (mis. pengodean tidak didukung),
	 *       blok {@code catch} merakit ulang kunci dengan judul <b>tanpa</b> penyandian. Nilai yang
	 *       dihasilkan berbeda dari jalur normal untuk judul yang sama, sehingga kegagalan
	 *       penyandian dapat memunculkan duplikat logis yang lolos batasan unik DB.</li>
	 * </ul>
	 *
	 * @return kunci unik bibliografis gabungan; tidak pernah {@code null}.
	 */
	@Column(name = "kode__unik_buku", unique = true, nullable = true, columnDefinition = "text")
	public String getKodeUnikBuku() {
		try {
			kodeUnikBuku = getIsbn() + "_" + getIsbn10() + "_" + getIssn() + "_"
					+ URLEncoder.encode(getNama().toLowerCase().trim(), "UTF-8")
					+ (edisi == null || edisi.trim().isEmpty() ? "" : "_" + edisi)
					+ (kode == null || kode.trim().isEmpty() ? "" : "_" + kode);
		} catch (Exception e) {
			kodeUnikBuku = getIsbn() + "_" + getIsbn10() + "_" + getIssn() + "_" + getNama().toLowerCase().trim()
					+ (edisi == null || edisi.trim().isEmpty() ? "" : "_" + edisi)
					+ (kode == null || kode.trim().isEmpty() ? "" : "_" + kode);
		}
		return kodeUnikBuku;
	}

