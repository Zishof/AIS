	/**
	 * Mengembalikan daftar pengarang item sebagai satu string ternormalisasi.
	 *
	 * <h3>Peran field</h3>
	 * <p>Relasi pengarang yang sebenarnya bersifat many-to-many lewat {@link ItemPunyaPengarang}.
	 * Field {@code pengarangs} adalah <b>denormalisasi</b> dari relasi itu: satu kolom teks yang
	 * memuat semua nama pengarang sekaligus, agar daftar katalog, pencarian sederhana, dan cetakan
	 * tidak perlu melakukan {@code JOIN} untuk setiap baris.</p>
	 *
	 * <h3>Normalisasi destruktif</h3>
	 * <p>Getter menulis balik hasil pembersihan ke field, sehingga bentuk bersih inilah yang
	 * tersimpan pada flush berikutnya:</p>
	 * <ul>
	 *   <li>{@code null} menjadi string kosong;</li>
	 *   <li>seluruh koma {@code ","} diganti titik koma {@code ";"} &mdash; ini penting karena
	 *       nama pengarang sendiri kerap mengandung koma ({@code "Sutanto, Budi"}), sehingga koma
	 *       tidak dapat dipakai sebagai pemisah antar-pengarang;</li>
	 *   <li>karakter {@code "["} dan {@code "]"} dibuang &mdash; sisa impor larik JSON dari Google
	 *       Books/OpenLibrary yang pernah tersimpan mentah;</li>
	 *   <li>hasil akhirnya dipangkas spasi.</li>
	 * </ul>
	 *
	 * <p>Perhatikan bahwa pemisah pada nilai TERSIMPAN karena itu adalah titik koma, sementara
	 * {@link #setPengarangs(String)} justru membersihkan koma ganda &mdash; peninggalan masa ketika
	 * pemisahnya masih koma. Pemanggil yang mengurai daftar ini sebaiknya menerima kedua pemisah.</p>
	 *
	 * @return daftar pengarang dipisah titik koma; string kosong bila belum diisi.
	 */
	public String getPengarangs() {
		if (pengarangs == null) {
			pengarangs = "";
		}
		pengarangs = org.apache.commons.lang3.StringUtils.replace(pengarangs, ",", ";");
		pengarangs = org.apache.commons.lang3.StringUtils.replace(pengarangs, "[", "");
		pengarangs = org.apache.commons.lang3.StringUtils.replace(pengarangs, "]", "").trim();
		return pengarangs.trim();
	}

	/**
	 * Menetapkan daftar pengarang dengan pembersihan dan pembatasan panjang.
	 *
	 * <p>Langkahnya: {@code null} diubah menjadi string kosong; koma ganda {@code ",,"} dibuang
	 * dengan sepuluh kali lintasan berturut-turut (cara sederhana menangani rentetan koma seperti
	 * {@code ",,,,"} tanpa regex); lalu isi dipotong ke 253 karakter bila melebihi 254. Pemotongan
	 * ini <b>tidak dapat dibatalkan</b> &mdash; daftar pengarang yang sangat panjang akan kehilangan
	 * ekornya, dan relasi lengkapnya hanya tersisa di {@link ItemPunyaPengarang}.</p>
	 *
	 * @param pengarangs daftar pengarang; {@code null} diperlakukan sebagai string kosong.
	 */
	public void setPengarangs(String pengarangs) {
		if (pengarangs == null) {
			pengarangs = "";
		}
		for (int i = 0; i < 10; i++) {
			pengarangs = org.apache.commons.lang3.StringUtils.replace(pengarangs, ",,", "");
		}
		if (pengarangs.length() > 254) {
			pengarangs = pengarangs.substring(0, 253);
		}
		this.pengarangs = pengarangs;
	}

