	/**
	 * Membangun ulang isi {@link #getScanLinks()} dari seluruh berkas hasil pindai per halaman
	 * yang tersimpan untuk item ini.
	 *
	 * <h3>Tujuan</h3>
	 * <p>Modul perpustakaan menyimpan hasil scan buku sebagai kumpulan baris
	 * {@link ais.database.model.file.FotoImagePerHalamanItem} &mdash; satu baris per halaman yang
	 * dipindai, masing-masing memegang gambar dan nomor halamannya. Untuk keperluan penyajian
	 * (pembaca daring, unduhan, penanda {@link #getHasScan()}), UI membutuhkan bentuk yang jauh
	 * lebih murah dibanding menarik seluruh baris gambar: satu string tunggal berisi pasangan
	 * {@code "nomorHalaman,url"} yang dipisahkan titik koma. Method ini menghasilkan string
	 * tersebut dan menaruhnya pada field {@code scanLinks} lewat {@link #setScanLinks(String)}.</p>
	 *
	 * <h3>Cara kerja</h3>
	 * <ol>
	 *   <li>Bila {@link #getId()} masih {@code null} (item belum tersimpan), tidak ada yang bisa
	 *       dicari; method langsung menetapkan {@code scanLinks} menjadi string kosong.</li>
	 *   <li>Untuk item yang sudah punya ID, method membuka <b>sesi Hibernate streaming sendiri</b>
	 *       melalui {@code StreamingHibernateUtil.getInstance().currentSession()}. Sesi terpisah ini
	 *       dipakai karena method dapat dipanggil dari konteks rendering daftar yang panjang dan
	 *       tidak boleh mengotori sesi utama.</li>
	 *   <li>Kriteria yang dijalankan sengaja memakai {@link org.hibernate.criterion.ProjectionList}
	 *       berisi hanya dua properti, {@code id} dan {@code halaman}, sehingga yang ditarik dari DB
	 *       adalah dua kolom skalar &mdash; <b>bukan</b> entity beserta muatan gambarnya. Ini
	 *       penting: satu item bisa memiliki ratusan halaman hasil pindai, dan menarik BLOB-nya akan
	 *       meledakkan memori.</li>
	 *   <li>Penyaringnya {@code Restrictions.eq("item", getId())} &mdash; perhatikan bahwa yang
	 *       dibandingkan adalah properti asosiasi {@code item} dengan sebuah {@code Long}. Ini
	 *       bekerja karena Hibernate membandingkan langsung nilai kolom kunci asing, dan menghindari
	 *       kebutuhan memuat entity {@code Item} ke dalam sesi streaming.</li>
	 *   <li>Hasil diurutkan menaik berdasarkan {@code halamanIndex} agar urutan halaman pada pembaca
	 *       daring benar (urutan alami DB tidak dijamin).</li>
	 *   <li>Untuk setiap baris, URL berkas dirakit oleh
	 *       {@code CommonMedia.getImageItemPerHalaman(idItem, idFoto, halaman, null, null, false)},
	 *       lalu ditambahkan ke akumulator dengan pemisah {@code ";"} (tanpa pemisah untuk elemen
	 *       pertama).</li>
	 * </ol>
	 *
	 * <h3>Penanganan galat dan pengelolaan sesi</h3>
	 * <p>Seluruh blok kueri dibungkus {@code try}/{@code catch}. Bila terjadi galat, transaksi pada
	 * sesi streaming di-<i>rollback</i> dan pesan ditampilkan hanya kepada admin lewat
	 * {@code Common.tampilErrorJikaAdmin(e)}; pemanggil TIDAK menerima exception. Konsekuensinya,
	 * kegagalan sebagian bersifat senyap: {@code scanLinks} akan diisi string yang terbentuk sampai
	 * sebelum galat (bahkan bisa kosong), dan pemanggil tidak punya cara membedakan "memang tidak ada
	 * hasil pindai" dari "kueri gagal". {@code closeSession()} dipanggil di luar {@code try} sehingga
	 * sesi tetap ditutup pada jalur sukses maupun jalur galat.</p>
	 *
	 * <h3>Catatan pemakaian</h3>
	 * <p>Method ini <b>tidak</b> dipanggil otomatis oleh getter mana pun; ia harus dipanggil
	 * eksplisit oleh Action/Helper sebelum {@link #getScanLinks()} atau {@link #getHasScan()}
	 * dianggap mutakhir. Karena ia menulis ke field yang dipetakan ke kolom {@code scan_links},
	 * memanggilnya pada entity yang sedang <i>managed</i> akan membuat Hibernate menandai baris
	 * sebagai kotor dan menuliskannya saat flush &mdash; jadi jangan memanggilnya di dalam
	 * perulangan render tanpa alasan.</p>
	 */
	@SuppressWarnings("unchecked")
	public void populateScanLinks() {
		String links = "";

		if (getId() != null) {
			Session mysession = StreamingHibernateUtil.getInstance().currentSession();

			try {

				ProjectionList projectionList = Projections.projectionList();
				projectionList.add(Projections.property("id"));
				projectionList.add(Projections.property("halaman"));

				List<Object[]> obs = mysession.createCriteria(FotoImagePerHalamanItem.class)
						.setProjection(projectionList).add(Restrictions.eq("item", getId()))
						.addOrder(Order.asc("halamanIndex")).list();

				for (Object[] row : obs) {
					Long id = ((Number) row[0]).longValue();
					String halaman = row[1].toString();

					String s = CommonMedia.getImageItemPerHalaman(getId(), id, halaman, null, null, false);

					links += links.isEmpty() ? (halaman + "," + s) : ";" + (halaman + "," + s);
				}

			} catch (Exception e) {
				StreamingHibernateUtil.getInstance().rollbackTransaction();
				Common.tampilErrorJikaAdmin(e);
			}

			StreamingHibernateUtil.getInstance().closeSession();
		}

		setScanLinks(links);
	}

