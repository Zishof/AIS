	/**
	 * Mengembalikan batas waktu berlakunya reservasi, menghitung nilai bawaan bila belum ada.
	 *
	 * <p>
	 * <b>Getter destruktif.</b> Bila <code>kadaluarsa</code> masih <code>null</code> <i>dan</i>
	 * <code>tanggal</code> terisi, method menghitung <code>tanggal + 1 hari</code> lewat
	 * {@link java.util.Calendar} dan MENULIS hasilnya ke dalam field sebelum mengembalikannya. Karena
	 * Hibernate memakai getter yang sama saat menulis baris, nilai itu tersimpan permanen pada flush
	 * berikutnya. Perhitungannya memakai <code>calendar.set(Calendar.DATE, get(DATE) + 1)</code>, yang
	 * menangani pergantian bulan dan tahun dengan benar karena {@link java.util.Calendar} melakukan
	 * normalisasi sendiri.
	 * </p>
	 *
	 * <p>
	 * Tenggang bawaan satu hari ini <b>hanya jaring pengaman</b>, bukan kebijakan yang sebenarnya.
	 * Jalur pembuatan reservasi yang nyata sudah menetapkan batas waktunya sendiri:
	 * <code>LibraryMemberApi</code> membaca konfigurasi <code>kadaluarsa.pemesanan.item</code>
	 * (bawaan <code>"24"</code> jam) dan menambahkannya ke waktu sekarang. Ubahlah konfigurasi itu bila
	 * ingin mengubah masa berlaku reservasi portal; mengubah perhitungan di sini tidak akan
	 * berpengaruh pada jalur tersebut.
	 * </p>
	 *
	 * <p>
	 * <b>Kolom inilah yang benar-benar menegakkan kedaluwarsa.</b> Setiap konsumen menyaring dengan
	 * predikat SQL atas kolom <code>kadaluarsa</code> — <code>kadaluarsa &gt;= current_timestamp</code>
	 * pada <code>LibraryMemberApi</code> dan <code>LibraryItemDetailService</code>, atau
	 * <code>date(kadaluarsa) &gt; date(hariIni)</code> pada
	 * <code>PeminjamanPengadaanItemDetailAction</code>. Perhatikan bahwa kedua bentuk itu
	 * <b>tidak setara</b>: yang pertama membandingkan sampai detik dan masih menerima reservasi yang
	 * berakhir nanti hari ini, sedangkan yang kedua memotong ke tanggal dan memakai
	 * <code>&gt;</code> tegas sehingga reservasi yang berakhir hari ini <i>sudah</i> ditolak di meja
	 * peminjaman. Reservasi 24 jam yang dibuat kemarin sore karenanya masih tampak aktif di portal
	 * anggota tetapi tidak lagi dapat dipakai petugas — perbedaan yang tampak sebagai keluhan
	 * "reservasi saya hilang" padahal masih tertera di layar anggota.
	 * </p>
	 *
	 * <p>
	 * Nilai <code>null</code> pada kolom ini bersifat khusus: seluruh predikat SQL di atas menghasilkan
	 * NULL (bukan TRUE) sehingga barisnya <b>tidak pernah</b> terpilih konsumen mana pun, sementara di
	 * sisi Java {@link #getStatus()} justru tidak akan pernah mengedaluwarsakannya. Baris seperti itu
	 * tampak hidup selamanya di memori tetapi tidak terlihat oleh sistem.
	 * </p>
	 *
	 * @return batas waktu berlakunya reservasi; dapat tetap <code>null</code> bila
	 *         {@link #getTanggal()} juga <code>null</code>.
	 */
	@Temporal(TemporalType.TIMESTAMP)
	public Date getKadaluarsa() {
		if (kadaluarsa == null && tanggal != null) {
			Calendar calendar = ais.ui.util.WaktuUtil.getCalendar();
			calendar.setTime(tanggal);
			calendar.set(Calendar.DATE, calendar.get(Calendar.DATE) + 1);
			kadaluarsa = calendar.getTime();
		}
		return kadaluarsa;
	}

