	/**
	 * Mengembalikan tipe item eksemplar ini, <b>menurunkannya dari tipe judul bila masih
	 * kosong</b>.
	 *
	 * <p>Bila field {@code tipeItem} bernilai {@code null} dan field {@code item} terisi, method
	 * mengambil {@code item.getTipeItem()} dan <b>menuliskannya ke field</b>. Ini getter
	 * destruktif ringan: tidak ada penulisan eksplisit ke database seperti pada
	 * {@link #getPerpustakaan()}, tetapi pada entity yang sedang dikelola Hibernate dengan
	 * {@code dynamicUpdate = true} penulisan field itu dapat menandai baris sebagai <i>dirty</i>
	 * sehingga kolom {@code tipe_item} ikut tersimpan pada flush berikutnya.</p>
	 *
	 * <p>Penurunan ini bersifat <b>sekali jalan dan menempel</b>: setelah tersimpan, perubahan
	 * tipe pada judul tidak lagi tercermin pada eksemplar yang terlanjur mengambil salinannya.
	 * Akibatnya eksemplar dari judul yang sama dapat memiliki tipe berbeda tergantung kapan
	 * masing-masing pertama kali dibaca. Bila keseragaman tipe per judul memang diinginkan,
	 * jangan mengandalkan mekanisme ini.</p>
	 *
	 * <p>Seperti di beberapa method lain pada kelas ini, kondisi diuji terhadap <b>field mentah</b>
	 * {@code item} dan bukan {@link #getItem()}, sehingga proxy lazy tidak diselesaikan lebih
	 * dulu; pemanggilan {@link #getItem()} terlebih dahulu dapat mengubah hasil method ini.</p>
	 *
	 * @return tipe item eksemplar, atau {@code null} bila tidak dapat ditentukan
	 */
	@ManyToOne(cascade = { CascadeType.PERSIST, CascadeType.MERGE })
	@Fetch(FetchMode.SELECT)
	@JoinColumn(name = "tipe_item", nullable = true)
	public TipeItem getTipeItem() {
		if (tipeItem == null && item != null) {
			tipeItem = item.getTipeItem();
		}
		return tipeItem;
	}

