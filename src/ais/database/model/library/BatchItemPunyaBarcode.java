	/**
	 * Mengembalikan kode identitas batch, <b>membangkitkannya bila masih kosong</b>.
	 *
	 * <h3>Perilaku</h3>
	 * <p>Bila field {@code kode} bernilai {@code null}, method memanggil
	 * {@code ais.common.BarcodeCommon.generateCode()} dan <b>menuliskan hasilnya ke field</b>
	 * sebelum mengembalikannya. Ini getter destruktif: pada entity terkelola, kode yang baru
	 * dibangkitkan dapat ikut tersimpan pada flush berikutnya. Konsekuensi praktisnya, <b>sekadar
	 * membaca kode batch akan menetapkannya secara permanen</b> — termasuk dari laporan atau
	 * ekspor yang semestinya hanya membaca.</p>
	 *
	 * <h3>Kode yang dibangkitkan tidak dijamin unik</h3>
	 * <p>Perlu dibedakan dari barcode eksemplar: nilai di sini berasal dari
	 * {@code BarcodeCommon.generateCode()} <i>tanpa argumen</i>, bukan dari implementasi
	 * {@code BarcodeGenerator} yang dipakai {@link ItemPunyaBarcode}. Method tanpa argumen itu
	 * menyusun kode dari stempel milidetik digabung tiga digit terakhir sebuah penghitung statis
	 * {@code long} yang dinaikkan dengan {@code ++} <b>tanpa sinkronisasi apa pun</b>. Tiga
	 * kelemahan mengikutinya:</p>
	 * <ul>
	 *   <li>Penaikan {@code ++} pada field statis bukan operasi atomik, sehingga dua thread dapat
	 *   memperoleh nilai yang sama.</li>
	 *   <li>Hanya tiga digit terakhir penghitung yang dipakai, sehingga nilainya berulang setiap
	 *   seribu pembangkitan; dua pembangkitan dalam milidetik yang sama dengan sisa penghitung yang
	 *   sama menghasilkan kode identik.</li>
	 *   <li>Penghitung kembali ke nilai awal setiap kali JVM dimulai ulang, dan tidak dibagi antar
	 *   node pada penyebaran lebih dari satu instans.</li>
	 * </ul>
	 * <p>Berbeda dari kolom {@code barcode} pada {@link ItemPunyaBarcode} yang dilindungi batasan
	 * unik, kolom {@code kode} di kelas ini <b>tidak memiliki batasan unik</b> dan tidak ada
	 * pemeriksaan duplikat di jalur ini sama sekali. Bentrok karena itu tidak akan tertangkap dan
	 * akan tersimpan diam-diam. Polanya setipe dengan kerusakan penomoran yang pernah ditemukan
	 * pada modul aset; perlakukan kode batch sebagai <b>tidak dapat diandalkan sebagai kunci
	 * bisnis</b> dan pakai {@link #getId()} bila dibutuhkan identitas yang pasti.</p>
	 *
	 * @return kode batch, dibangkitkan bila sebelumnya kosong
	 */
	public String getKode() {
		if (kode == null) {
			kode = BarcodeCommon.generateCode();
		}
		return kode;
	}

