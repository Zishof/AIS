	@Column(name = "nilai", nullable = true, columnDefinition = "text")
	public String getNilai() {

		if ((nilai == null || nilai.trim().isEmpty() || nilai.equals(AKTIF) || nilai.equals(TIDAK_AKTIF))
				&& nama != null && nama.equals("ISTILAH_PENDAFTARAN_CALON_MAHASISWA")) {
			nilai = ConstantUtil.PENDAFTARAN_CALON_MAHASISWA;
		} else if ((nilai == null || nilai.trim().isEmpty() || nilai.equals(AKTIF) || nilai.equals(TIDAK_AKTIF))
				&& nama != null && nama.equals("ISTILAH_PENDAFTARAN_MAHASISWA_LAMA")) {
			nilai = ConstantUtil.PENDAFTARAN_MAHASISWA_LAMA;
		} else if ((nilai == null || nilai.trim().isEmpty() || nilai.equals(AKTIF) || nilai.equals(TIDAK_AKTIF))
				&& nama != null && nama.equals("PENDAFTARAN_ULANG_MAHASISWA_BARU")) {
			nilai = ConstantUtil.PENDAFTARAN_ULANG_MAHASISWA_BARU;
		} else if ((nilai == null || nilai.trim().isEmpty() || nilai.equals(AKTIF) || nilai.equals(TIDAK_AKTIF))
				&& nama != null && nama.equals("ISTILAH_PENDAFTARAN_WISUDA")) {
			nilai = ConstantUtil.PENDAFTARAN_WISUDA;
		} else if ((nilai == null || nilai.trim().isEmpty() || nilai.equals(AKTIF) || nilai.equals(TIDAK_AKTIF))
				&& nama != null && nama.equals("ISTILAH_PEMBAYARAN_SP")) {
			nilai = ConstantUtil.PEMBAYARAN_SP;
		}

		if (nilai == null) {
			nilai = AKTIF;
		}

		kalenderAkademik = getKalenderAkademik();
		if (kalenderAkademik != null && kalenderAkademik.getTanggalMulai() != null
				&& kalenderAkademik.getTanggalSelesai() != null) {
			Date date = WaktuUtil.getDate();
			if ((Common.dateFormat1.get().format(kalenderAkademik.getTanggalMulai()).equals(Common.dateFormat1.get().format(date))
					|| kalenderAkademik.getTanggalMulai().before(date))
					&& (Common.dateFormat1.get().format(kalenderAkademik.getTanggalSelesai()).equals(
							Common.dateFormat1.get().format(date)) || kalenderAkademik.getTanggalSelesai().after(date))) {
				nilai = AKTIF;
			} else {
				nilai = TIDAK_AKTIF;
			}

			setTahunAkademik(kalenderAkademik.getTahunAjaran());
			if (kalenderAkademik.getGanjilGenap() != null && !kalenderAkademik.getGanjilGenap().isEmpty()) {
				setInfo1(kalenderAkademik.getGanjilGenap());
			}
		}

		if (getDikunci() != null) {
			nilai = nilaiDikunci;
		}

		if (nama != null && nama.trim().equals("recapcha_home")) {
			nilai = "login";
		}
		return nilai;
	}

