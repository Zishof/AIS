	/**
	 * Mengembalikan label bulan untuk ditampilkan ke pengguna. Dipakai di lebih dari seratus
	 * titik (renderer daftar tagihan, laporan, API tagihan, deskripsi jurnal posting).
	 *
	 * <p>Dua bentuk label, ditentukan oleh
	 * {@link ItemBiaya#getMenggunakanIstilahBayarAngsuran()} pada item biaya induk:</p>
	 * <ul>
	 *   <li><b>Istilah angsuran menyala</b> &rarr; {@code "Angsuran n"}, dengan
	 *   <code>n = bulan + 6 * (semesterDetailBiaya - 1)</code>. Angka {@code 6} adalah asumsi
	 *   keras "satu semester = 6 angsuran"; penomoran karena itu berjalan kumulatif lintas
	 *   semester ("Angsuran 7" untuk bulan ke-1 semester 2, dan seterusnya). Semester
	 *   {@code null} diperlakukan sebagai {@code 1}.</li>
	 *   <li><b>Sebaliknya</b> &rarr; nama bulan Bahasa Indonesia dari {@code Common.BULAN},
	 *   diindeks dengan {@link #getRealBulan()}. Bila bulan riil di luar rentang 1..12 (mis.
	 *   {@code 0} karena data induk belum lengkap), field {@code namaBulan} <b>tidak diubah</b>
	 *   sehingga nilai lama/{@code null} bertahan dan yang dikembalikan menjadi string
	 *   kosong.</li>
	 * </ul>
	 *
	 * <p><b>Getter yang menulis balik ke kolom terpetakan</b> ({@code namabulan}), setiap kali
	 * dipanggil dan tanpa syarat "hanya bila null". Ikut memanggil {@link #getRealBulan()} yang
	 * juga menulis balik. Inilah salah satu penyebab dirty-check semu yang ditangkal
	 * {@code KegiatanHelper} dengan {@code session.setReadOnly(...)}.</p>
	 *
	 * @return label bulan siap tampil; tidak pernah {@code null}, bisa string kosong
	 * @see #getRealBulan()
	 */
	public String getNamaBulan() {
		if (detailBiaya != null && detailBiaya.getItemBiaya() != null
				&& detailBiaya.getItemBiaya().getMenggunakanIstilahBayarAngsuran()) {
			int semesterDetail = detailBiaya.getSemester() == null ? 1 : detailBiaya.getSemester().intValue();
			namaBulan = "Angsuran " + (getBulan() + (6 * (semesterDetail - 1)));
		} else {
			int bulanReal = getRealBulan() == null ? 0 : getRealBulan().intValue();
			if (bulanReal >= 1 && bulanReal <= Common.BULAN.length) {
				namaBulan = Common.BULAN[bulanReal - 1];
			}
		}
		return namaBulan == null ? "" : namaBulan;
	}

