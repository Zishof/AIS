	/**
	 * Mengembalikan <b>bulan kalender</b> (1..12) tempat angsuran ke-{@link #getBulan()} jatuh.
	 *
	 * <p>Terjemahannya didelegasikan ke {@link #hitungRealBulan(DetailBiaya, int)}, lalu hasilnya
	 * dilipat dengan {@code % 12} bila melebihi 12 (terjadi pada item biaya dengan jumlah
	 * angsuran lebih dari 6 per semester). <b>Perhatikan kuirk pelipatan ini:</b> nilai tepat
	 * {@code 12} lolos apa adanya (Desember, benar), tetapi kelipatan 12 berikutnya seperti
	 * {@code 24} menjadi {@code 0} &mdash; bukan {@code 12} &mdash; sehingga
	 * {@link #getNamaBulan()} akan menghasilkan string kosong untuk kasus itu. Dengan konfigurasi
	 * bawaan ({@code pembayaranSemesterGanjilMulaiDiBulan = 7},
	 * {@code pembayaranSemesterGenapMulaiDiBulan = 1}) dan maksimal 6 angsuran per semester,
	 * kasus tersebut tidak pernah tercapai.</p>
	 *
	 * <p><b>Getter yang menulis balik ke kolom terpetakan</b> ({@code realbulan}) setiap kali
	 * {@code detailBiaya} terisi. Dipakai luas (sekitar 90 titik pemanggilan), antara lain oleh
	 * {@link DetailKegiatan#getTanggal()} dan {@link CicilanPembayaran#getTanggalTagihan()}
	 * untuk menentukan bulan jatuh tempo.</p>
	 *
	 * @return bulan kalender 1..12; {@code 0} bila belum bisa ditentukan (tidak pernah
	 *         {@code null})
	 * @see #hitungRealBulan(DetailBiaya, int)
	 * @see #getRealBulanTahun()
	 */
	public Integer getRealBulan() {
		if (detailBiaya != null && getBulan() != null) {
			realBulan = PengaturanPembayaranBulanan.hitungRealBulan(detailBiaya, getBulan());
			if (realBulan > 12) {
				realBulan = realBulan % 12;
			}
		}

		return realBulan == null ? 0 : realBulan;
	}

