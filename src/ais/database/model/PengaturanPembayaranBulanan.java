	/**
	 * Mengembalikan periode baris ini dalam bentuk bilangan bulat {@code YYYYMM} (mis.
	 * {@code 202509} untuk September 2025) &mdash; gabungan tahun kalender yang benar dengan
	 * {@link #getRealBulan()} yang di-<i>pad</i> dua digit.
	 *
	 * <p>Tahunnya dipilih dari salah satu paruh tahun akademik berformat {@code "2025/2026"},
	 * dengan aturan yang sejalan dengan {@link #hitungRealBulan(DetailBiaya, int)}: bila
	 * {@link DetailBiaya#getMulaiBelajarDiSemester()} adalah {@link Perkuliahan#GANJIL} maka
	 * semester genap memakai paruh kedua ({@code "2026"}) dan semester ganjil paruh pertama
	 * ({@code "2025"}); bila mulai di semester Genap, keduanya tertukar.</p>
	 *
	 * <p><b>Prasyarat lengkap sebelum dihitung</b> (dijaga eksplisit): {@code detailBiaya},
	 * {@code semester}, {@code bulan}, {@code tahunAkademik}, dan {@code mulaiBelajarDiSemester}
	 * harus terisi. Kondisi "belum lengkap" adalah <b>normal</b> pada data yang baru dibuat lewat
	 * form Tambah, bukan tanda kerusakan &mdash; karena itu ada penjagaan eksplisit dan
	 * {@code try/catch} defensif (menangkap {@code ArrayIndexOutOfBoundsException} bila tahun
	 * akademik tidak memuat garis miring, dan {@code NumberFormatException} bila potongannya
	 * bukan angka), bukan membiarkan {@code NullPointerException} lolos.</p>
	 *
	 * <p><b>Getter yang menulis balik ke kolom terpetakan</b> ({@code realbulantahun}) setiap
	 * kali prasyaratnya terpenuhi. Ikut memanggil {@link #getRealBulan()} yang juga menulis
	 * balik.</p>
	 *
	 * <p><b>Dipanggil dari:</b> API tagihan mahasiswa
	 * ({@code ais.action.servlet.api.TagihanMahasiswa}, field JSON {@code bulan_tahun}) dan
	 * laporan rekap host-to-host cicilan per item bulanan.</p>
	 *
	 * @return periode {@code YYYYMM}, atau {@code 0} bila belum bisa dihitung (tidak pernah
	 *         {@code null})
	 */
	public Integer getRealBulanTahun() {
		// detailBiaya/semester bisa terisi duluan sementara tahunAkademik/mulaiBelajarDiSemester
		// belum (mis. data baru dibuat lewat form Tambah, belum lengkap diisi user) -- itu
		// KONDISI NORMAL, bukan error, jadi dijaga eksplisit + try-catch defensif (bukan
		// dibiarkan NPE tak tertangkap) sebelum diproses.
		if (detailBiaya != null && detailBiaya.getSemester() != null && getBulan() != null
				&& detailBiaya.getTahunAkademik() != null && detailBiaya.getMulaiBelajarDiSemester() != null) {
			try {
				String b = "0000" + getRealBulan();
				String tahun = "";
				if (detailBiaya.getMulaiBelajarDiSemester().equals(Perkuliahan.GANJIL)) {
					tahun = (detailBiaya.getSemester() % 2 == 0) ? detailBiaya.getTahunAkademik().split("/")[1]
							: detailBiaya.getTahunAkademik().split("/")[0];
				} else {
					tahun = (detailBiaya.getSemester() % 2 == 0) ? detailBiaya.getTahunAkademik().split("/")[0]
							: detailBiaya.getTahunAkademik().split("/")[1];
				}
				realBulanTahun = Integer.parseInt(tahun + b.substring(b.length() - 2));
			} catch (Exception e) {
				ais.common.ErrorAuditUtil.record(e,
						"auto-audit(empty-catch) src/ais/database/model/PengaturanPembayaranBulanan.java:getRealBulanTahun");
			}
		}

		return realBulanTahun == null ? 0 : realBulanTahun;
	}

