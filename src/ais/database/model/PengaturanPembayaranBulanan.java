	/**
	 * Menambahkan denda keterlambatan ke sebuah nominal, bila tanggal bayar melewati batas akhir
	 * yang berlaku. Method ini hanya <b>penerus</b>: seluruh logikanya ada di
	 * {@link DetailBiaya#checkDenda(Double, Date, JadwalPembayaran, JenisKegiatan,
	 * PengaturanPembayaranBulanan)}, dengan {@code this} disisipkan sebagai argumen terakhir
	 * supaya induk bisa membaca {@link #getDeadline()} milik baris bulanan ini.
	 *
	 * <p>Ringkasan yang dikerjakan induk: memilih deadline (deadline baris ini &rarr;
	 * {@code jadwalPembayaran.getEndDate()} bila jenis kegiatannya mengenakan denda atau
	 * jadwalnya khusus per NIM &rarr; {@code detailBiaya.getDefaultTanggalDeadline()}),
	 * menentukan persentase denda (per prodi dari JSON {@code dendaPerProdi}, atau dari jenis
	 * kegiatan, atau bawaan item biaya), membandingkan tanggal tanpa memperhitungkan jam, lalu
	 * menaikkan nominal dan mengisi {@code infoDenda}.</p>
	 *
	 * <p><b>Efek samping:</b> mengisi {@code infoDenda} pada {@link DetailBiaya} induk (yang
	 * kemudian bisa disalin ke sini lewat {@link #getInfoDenda()}). Bila
	 * {@link #getDetailBiaya()} {@code null}, method mengembalikan {@code nominalModifikasi}
	 * apa adanya tanpa melakukan apa pun.</p>
	 *
	 * @param nominalModifikasi nominal yang akan dikenai denda (umumnya hasil
	 *        {@link #ambilNominalModifikasi(Mahasiswa, Integer)})
	 * @param tanggalBayar tanggal uang benar-benar dibayarkan
	 * @param jadwalPembayaran jadwal pembayaran yang berlaku; boleh {@code null}
	 * @param old jenis kegiatan pembanding (konteks kegiatan sebelumnya); boleh {@code null}
	 * @return nominal setelah denda, atau nilai masukan apa adanya bila induk {@code null}
	 * @see #checkDendaCicilan(CicilanPembayaran, JadwalPembayaran)
	 */
	public Double checkDenda(Double nominalModifikasi, Date tanggalBayar, JadwalPembayaran jadwalPembayaran,
			JenisKegiatan old) {
		if (getDetailBiaya() != null) {
			nominalModifikasi = getDetailBiaya().checkDenda(nominalModifikasi, tanggalBayar, jadwalPembayaran, old,
					this);
		}
		return nominalModifikasi;
	}

	/**
	 * Varian {@link #checkDenda(Double, Date, JadwalPembayaran, JenisKegiatan)} untuk sebuah
	 * cicilan yang sudah terbentuk: nominal awal maupun tanggal bayar tidak diberikan pemanggil,
	 * melainkan dibaca induk dari {@code cicilanPembayaran} itu sendiri. Meneruskan ke
	 * {@link DetailBiaya#checkDendaCicilan(CicilanPembayaran, JadwalPembayaran,
	 * PengaturanPembayaranBulanan)} dengan {@code this} sebagai argumen terakhir.
	 *
	 * <p><b>Perhatikan nilai kembalian saat induk kosong:</b> berbeda dengan
	 * {@link #checkDenda(Double, Date, JadwalPembayaran, JenisKegiatan)} yang mengembalikan
	 * masukannya, method ini memulai dari {@code 0.0} dan mengembalikan {@code 0.0} bila
	 * {@link #getDetailBiaya()} {@code null} &mdash; jadi denda dianggap nol, bukan "tidak
	 * diketahui".</p>
	 *
	 * @param cicilanPembayaran cicilan yang sedang diperiksa
	 * @param jadwalPembayaran jadwal pembayaran yang berlaku; boleh {@code null}
	 * @return nominal denda hasil perhitungan; {@code 0.0} bila induk {@code null}
	 */
	public Double checkDendaCicilan(CicilanPembayaran cicilanPembayaran, JadwalPembayaran jadwalPembayaran) {
		Double nominalModifikasi = 0.0;
		if (getDetailBiaya() != null) {
			nominalModifikasi = getDetailBiaya().checkDendaCicilan(cicilanPembayaran, jadwalPembayaran, this);
		}
		return nominalModifikasi;
	}
