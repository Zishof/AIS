	public Double getJumlahLemburMasuk() {
		DetailJenisShiftPegawai detailJenisShiftPegawaiLembur = getDetailJenisShiftPegawaiLembur();
		DetailJenisShiftPegawai shiftPegawai = getDetailJenisShiftPegawai();
		if (detailJenisShiftPegawaiLembur != null) {
			shiftPegawai = detailJenisShiftPegawaiLembur;
		}
		Date pulangJam = ambilPulangjam();

		jumlahLemburMasuk = 0.0;

		Date masukjam = getMasukjam();

		if (shiftPegawai != null && shiftPegawai.getLemburMulai() != null && shiftPegawai.getSampai() != null
				&& masukjam != null && pulangJam != null
				&& getTimeAsDouble(shiftPegawai.getLemburMulai()) < getTimeAsDouble(shiftPegawai.getSampai())) {

			Double jamMasukMax = hitungJumlahJamMasuk(masukjam, shiftPegawai.getLemburMulai());
			Double jamMasuk = hitungJumlahJamMasuk(masukjam, pulangJam);

			if (Boolean.TRUE.equals(shiftPegawai.getLemburDihitungDariAwalMasuk())) {
				lamburMulai = masukjam;
				lamburSampai = pulangJam;
				jumlahLemburMasuk = jamMasuk;
			} else if (jamMasuk > jamMasukMax) {

				lamburMulai = masukjam;
				lamburSampai = pulangJam;

				jumlahLemburMasuk = jamMasuk - jamMasukMax;
			} else {

				lamburMulai = null;
				lamburSampai = null;

				jumlahLemburMasuk = 0.0;
			}

			if (shiftPegawai != null) {
				jumlahLemburMasuk = konversi(jumlahLemburMasuk, shiftPegawai);
			}

		} else if (pulangJam != null && shiftPegawai != null
				&& Boolean.TRUE.equals(shiftPegawai.getLemburDihitungDariAwalMasuk())) {
			jumlahLemburMasuk = getJumlahJamMasuk();

			lamburMulai = masukjam;
			lamburSampai = pulangJam;

			if (shiftPegawai != null) {
				jumlahLemburMasuk = konversi(jumlahLemburMasuk, shiftPegawai);
			}

		} else if (shiftPegawai != null && shiftPegawai.getLemburMulai() != null && pulangJam != null
				&& getTimeAsDouble(shiftPegawai.getLemburMulai()) < getTimeAsDouble(pulangJam)) {
			lamburMulai = shiftPegawai.getLemburMulai();
			lamburSampai = pulangJam;
			jumlahLemburMasuk = ambilJumlahLemburMasuk(this, shiftPegawai.getLemburMulai(), pulangJam);
		}

		return jumlahLemburMasuk;
	}

	public static Double ambilJumlahLemburMasuk(StatuskehadiranKaryawanHarian statuskehadiranKaryawanHarian,
			Date lemburMulai, Date lemburSampai) {

		Double jumlahLemburMasuk = 0.0;

		DetailJenisShiftPegawai detailJenisShiftPegawaiLembur = statuskehadiranKaryawanHarian
				.getDetailJenisShiftPegawaiLembur();
		DetailJenisShiftPegawai shiftPegawai = statuskehadiranKaryawanHarian.getDetailJenisShiftPegawai();
		if (detailJenisShiftPegawaiLembur != null) {
			shiftPegawai = detailJenisShiftPegawaiLembur;
		}

		if (lemburMulai != null && lemburSampai != null) {

			Calendar calendar = ais.ui.util.WaktuUtil.getCalendar();

			Calendar calendarMulai = Calendar.getInstance();
			calendarMulai.setTime(lemburMulai);
			calendarMulai.set(Calendar.DATE, calendar.get(Calendar.DATE));
			calendarMulai.set(Calendar.MONTH, calendar.get(Calendar.MONTH));
			calendarMulai.set(Calendar.YEAR, calendar.get(Calendar.YEAR));

			Calendar calendarSampai = Calendar.getInstance();
			calendarSampai.setTime(lemburSampai);
			calendarSampai.set(Calendar.DATE, calendar.get(Calendar.DATE));
			calendarSampai.set(Calendar.MONTH, calendar.get(Calendar.MONTH));
			calendarSampai.set(Calendar.YEAR, calendar.get(Calendar.YEAR));

			if (statuskehadiranKaryawanHarian.getTimeAsDouble(lemburMulai) > statuskehadiranKaryawanHarian
					.getTimeAsDouble(lemburSampai)) {
				calendarSampai.add(Calendar.DATE, 1);
			}

			DateTime startDateTime = new DateTime(calendarMulai.getTime());
			DateTime endDateTime = new DateTime(calendarSampai.getTime());

			Seconds hours = Seconds.secondsBetween(startDateTime, endDateTime);
			jumlahLemburMasuk = hours.getSeconds() / 3600.0;

			if (jumlahLemburMasuk < 0.0) {
				jumlahLemburMasuk = 0.0;
			}

			if (shiftPegawai != null && hours != null && shiftPegawai.getLemburMaks() != null
					&& shiftPegawai.getLemburMaks() > 0.1) {
				double jumlahLemburMasukMenit = hours.getSeconds() / 60.0;
				if (shiftPegawai.getLemburMaks() > jumlahLemburMasukMenit) {
					jumlahLemburMasuk = shiftPegawai.getLemburMaks() / 60.0;
				}
			}

		} else {
			jumlahLemburMasuk = 0.0;
		}

		jumlahLemburMasuk = konversi(jumlahLemburMasuk, shiftPegawai);

		return jumlahLemburMasuk;
	}

	private static Double konversi(Double jumlahLemburMasuk, DetailJenisShiftPegawai shiftPegawai) {
		if (jumlahLemburMasuk > 0.01 && shiftPegawai != null && shiftPegawai.getKonversiJamLembur() != null
				&& !shiftPegawai.getKonversiJamLembur().trim().isEmpty()) {

			if (shiftPegawai.getLemburMaks() != null && shiftPegawai.getLemburMaks() < jumlahLemburMasuk) {
				jumlahLemburMasuk = shiftPegawai.getLemburMaks();
			}

			try {
				for (String s : StringUtils.split(shiftPegawai.getKonversiJamLembur().trim(), ";")) {
					try {
						if (!s.trim().isEmpty()) {
							String[] aa = StringUtils.split(s, "=");
							Double dd1 = Double.parseDouble(StringUtils.replace(aa[0].trim(), ",", "."));
							Double dd2 = Double.parseDouble(StringUtils.replace(aa[1].trim(), ",", "."));

							if (jumlahLemburMasuk <= dd1) {
								jumlahLemburMasuk = dd2;
								break;
							}
						}
					} catch (Exception e) {
						e.printStackTrace(); ais.common.ErrorAuditUtil.record(e, "auto-audit src/ais/database/model/StatuskehadiranKaryawanHarian.java:1098");
					}
				}
			} catch (Exception e) {
				e.printStackTrace(); ais.common.ErrorAuditUtil.record(e, "auto-audit src/ais/database/model/StatuskehadiranKaryawanHarian.java:1102");
			}
		}

		return jumlahLemburMasuk;
	}

