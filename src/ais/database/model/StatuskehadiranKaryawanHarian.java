	/**
	 * KOREKSI "shadow": jam pulang yang TERSIMPAN (pulangJamManual/pulangJamState) LEBIH AWAL dari scan
	 * pulang GENUINE terakhir hari itu. Gejala ini terjadi karena jalur tulis absensi TIDAK konsisten —
	 * sebagian ({@code AbsensiApiAction} state="1") mengeset pulangJamState+Manual, sebagian lain
	 * ({@code ScanBerhasilAction} QR &amp; jalur legacy) hanya {@code setPulangJam} (temp). Bila scan awal
	 * atau duplikat sempat mengeset State/Manual (mis. 07:31) lalu scan pulang ASLI (mis. 15:38) masuk
	 * lewat jalur temp, maka {@link #getPulangJam()} mengembalikan State/Manual lama (07:31) dan menutupi
	 * pulang asli — kolom "Jam Pulang" tampak salah/tidak ter-update.
	 *
	 * <p>Mengembalikan scan pulang genuine terakhir HANYA bila: ada ≥2 scan; scan terakhir SETELAH scan
	 * masuk; scan terakhir jelas LEBIH LAMBAT (&gt;~1 menit) dari jam pulang tersimpan; dan durasi kerja
	 * aktual (masuk→pulang genuine) MELEBIHI "Waktu minimal bekerja (jam)" shift (menjaga aturan
	 * penggajian yang sama). Selain itu {@code null}. TIDAK menyimpan.</p>
	 */
	public Date hitungPulangShadowTerkoreksi() {
		try {
			if (Boolean.TRUE.equals(getTidakAdaKepulangan())) {
				return null;
			}
			java.util.TreeSet<Date> scans = kumpulkanScanHariIni();
			if (scans.size() < 2) {
				return null;
			}
			Date masuk = scans.first();
			Date pulangGenuine = scans.last();
			if (!pulangGenuine.after(masuk)) {
				return null;
			}

			// Jam pulang yang saat ini efektif ditampilkan/dihitung: pulangJamManual > pulangJamState.
			Date pulangTersimpan = (pulangJamManual != null) ? pulangJamManual
					: (getPulangJamState() != null ? getPulangJamState() : null);
			if (pulangTersimpan == null) {
				// Jam pulang KOSONG -> bukan kasus shadow; ditangani hitungPulangOtomatisDariSejarah().
				return null;
			}

			// Hanya koreksi bila scan genuine terakhir BENAR-BENAR lebih lambat (bandingkan jam-hari).
			double tGenuine = getTimeAsDouble(pulangGenuine);
			double tSimpan = getTimeAsDouble(pulangTersimpan);
			if (tGenuine <= tSimpan + 0.005) {
				return null;
			}

			// Jaga aturan durasi minimal shift: hanya koreksi bila durasi kerja aktual > minimal.
			double durasiJam = (pulangGenuine.getTime() - masuk.getTime()) / 3600000.0;
			if (durasiJam <= 0) {
				return null;
			}
			DetailJenisShiftPegawai shift = check(detailJenisShiftPegawai);
			Double minKerja = (shift != null && shift.getJenisShiftPegawai() != null)
					? shift.getJenisShiftPegawai().getWaktuBekerjaMinimal()
					: null;
			double minJam = (minKerja == null) ? 0.0 : minKerja.doubleValue();

			System.out.println("[KOREKSI-PULANG] id=" + getId() + " tersimpan=" + pulangTersimpan + " genuine="
					+ pulangGenuine + " durasiJam=" + durasiJam + " minKerja=" + minJam + " → koreksi="
					+ (minJam < durasiJam));

			if (minJam < durasiJam) {
				return pulangGenuine;
			}
		} catch (Exception e) {
			e.printStackTrace(); ais.common.ErrorAuditUtil.record(e, "auto-audit StatuskehadiranKaryawanHarian.hitungPulangShadowTerkoreksi");
		}
		return null;
	}

