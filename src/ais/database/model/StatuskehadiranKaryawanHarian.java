	// ---------------------------------------------------------
	// 1. HELPER: NORMALISASI KALENDER (PENTING UNTUK AKURASI)
	// ---------------------------------------------------------
	private Calendar getNormalizedCalendar(Date timePart) {
		if (timePart == null || getTanggal() == null)
			return null;

		Calendar cal = ais.ui.util.WaktuUtil.getCalendar();
		cal.setTime(getTanggal()); // Kunci akurasi: Gunakan tanggal record, BUKAN tanggal hari ini

		Calendar timeCal = ais.ui.util.WaktuUtil.getCalendar();
		timeCal.setTime(timePart);

		cal.set(Calendar.HOUR_OF_DAY, timeCal.get(Calendar.HOUR_OF_DAY));
		cal.set(Calendar.MINUTE, timeCal.get(Calendar.MINUTE));
		cal.set(Calendar.SECOND, timeCal.get(Calendar.SECOND));
		cal.set(Calendar.MILLISECOND, 0);
		return cal;
	}

	// ---------------------------------------------------------
	// 2. PERBAIKAN LOGIKA SHIFT MALAM (ANTI DOUBLE-COUNT & SALAH TARIK)
	// ---------------------------------------------------------
	public Date ambilMasukjam() {
		Date masuk = getMasukjam();
		Date pulang = getPulangJam();
		DetailJenisShiftPegawai shift = getDetailJenisShiftPegawai();

		if (shift != null && shift.getMulai() != null && shift.getSampai() != null
				&& getTimeAsDouble(shift.getMulai()) > getTimeAsDouble(shift.getSampai())) {

			// JIKA SHIFT MALAM: Jam Masuk WAJIB Sore/Malam (>= 14:00)
			Date bestMasuk = null;
			if (masuk != null && getTimeAsDouble(masuk) >= 14.0)
				bestMasuk = masuk;
			if (pulang != null && getTimeAsDouble(pulang) >= 14.0) {
				if (bestMasuk == null || pulang.before(bestMasuk))
					bestMasuk = pulang;
			}
			return bestMasuk != null ? bestMasuk : masuk;

		} else {
			// JIKA SHIFT NORMAL: Cegah menarik kepulangan shift malam kemarin
			if (getBack() != null) {
				DetailJenisShiftPegawai shiftKemarin = getBack().getDetailJenisShiftPegawai();
				if (shiftKemarin != null && shiftKemarin.getMulai() != null && shiftKemarin.getSampai() != null
						&& getTimeAsDouble(shiftKemarin.getMulai()) > getTimeAsDouble(shiftKemarin.getSampai())) {
					// Kemarin shift malam. Jam absen hari ini (< 12:00) adalah pulang shift
					// kemarin, jangan dihitung masuk!
					if (masuk != null && getTimeAsDouble(masuk) < 12.0) {
						return null;
					}
				}
			}
		}
		return masuk;
	}

	public Date ambilPulangjam() {
		Date masuk = getMasukjam();
		Date pulang = getPulangJam();
		DetailJenisShiftPegawai shift = getDetailJenisShiftPegawai();

		if (shift != null && shift.getMulai() != null && shift.getSampai() != null
				&& getTimeAsDouble(shift.getMulai()) > getTimeAsDouble(shift.getSampai())) {

			// SHIFT MALAM: Jam Pulang WAJIB Pagi Hari (< 14:00) DI HARI BERIKUTNYA
			if (getNext() != null) {
				Date nextMasuk = getNext().getMasukjam();
				Date nextPulang = getNext().getPulangJam();

				Date bestPulang = null;
				if (nextMasuk != null && getTimeAsDouble(nextMasuk) < 14.0)
					bestPulang = nextMasuk;
				if (nextPulang != null && getTimeAsDouble(nextPulang) < 14.0) {
					if (bestPulang == null || nextPulang.before(bestPulang))
						bestPulang = nextPulang;
				}
				if (bestPulang != null)
					return bestPulang;
			}

			// Fallback: Jika dia pulang sebelum tengah malam di hari yang sama (misal izin
			// sakit jam 23:50)
			if (pulang != null && masuk != null && getTimeAsDouble(pulang) > getTimeAsDouble(masuk)) {
				return pulang;
			}

			return null; // Belum absen pulang
		}

		return pulang;
	}

	// ---------------------------------------------------------
	// 3. KALKULASI DURASI KERJA (CEPAT & AKURAT MENGGUNAKAN MILLISECONDS)
	// ---------------------------------------------------------
	public Double hitungJumlahJamMasuk(Date masuk, Date pulang) {
		if (masuk == null || pulang == null || getTanggal() == null)
			return 0.0;

		Calendar start = getNormalizedCalendar(masuk);
		Calendar end = getNormalizedCalendar(pulang);

		// Deteksi Lintas Hari (Cross-Date Shift Malam)
		if (getTimeAsDouble(masuk) > getTimeAsDouble(pulang)) {
			end.add(Calendar.DATE, 1);
		}

		long diffMs = end.getTimeInMillis() - start.getTimeInMillis();
		double hours = diffMs / 3600000.0; // Detik ke Jam

		return Math.max(0.0, hours);
	}

	public Double getJumlahJamMasuk() {
		this.jumlahJamMasuk = 0.0;
		Date masuk = ambilMasukjam();
		Date pulang = ambilPulangjam();
		DetailJenisShiftPegawai shift = getDetailJenisShiftPegawai();

		if (masuk == null || pulang == null)
			return 0.0;

		Date batasAkhir = pulang;

		// Batasi jam kerja reguler jika ada lembur
		if (shift != null && shift.getLemburMulai() != null && shift.getSampai() != null) {
			if (getTimeAsDouble(shift.getLemburMulai()) < getTimeAsDouble(shift.getSampai())) {
				batasAkhir = shift.getLemburMulai();
			}
		}

		this.jumlahJamMasuk = hitungJumlahJamMasuk(masuk, batasAkhir);
		return this.jumlahJamMasuk;
	}

	// ---------------------------------------------------------
	// 4. KALKULASI PELANGGARAN (KETERLAMBATAN & PULANG CEPAT)
	// ---------------------------------------------------------
	public Double getJumlahTerlambat() {
		Date masuk = ambilMasukjam();
		DetailJenisShiftPegawai shift = getDetailJenisShiftPegawai();

		if (masuk == null || shift == null || shift.getMulai() == null)
			return 0.0;

		Calendar limitStart = getNormalizedCalendar(shift.getMulai());
		Calendar actualIn = getNormalizedCalendar(masuk);

		if (actualIn.after(limitStart)) {
			double toleransiMenit = shift.getJamSetelahJamMulai() != null ? shift.getJamSetelahJamMulai() : 0.0;
			long diffSecs = (actualIn.getTimeInMillis() - limitStart.getTimeInMillis()) / 1000;
			double jamTerlambat = (diffSecs / 3600.0) - (toleransiMenit / 60.0);
			return Math.max(0.0, jamTerlambat);
		}
		return 0.0;
	}

	public Double getJumlahCepatKeluar() {
		Date pulang = ambilPulangjam();
		DetailJenisShiftPegawai shift = getDetailJenisShiftPegawai();

		if (pulang == null || shift == null || shift.getSampai() == null)
			return 0.0;

		Calendar limitEnd = getNormalizedCalendar(shift.getSampai());
		Calendar actualOut = getNormalizedCalendar(pulang);

		// Deteksi Cross-Date
		if (getTimeAsDouble(shift.getMulai()) > getTimeAsDouble(shift.getSampai())) {
			limitEnd.add(Calendar.DATE, 1);
		}
		Date masuk = ambilMasukjam();
		if (masuk != null && getTimeAsDouble(masuk) > getTimeAsDouble(pulang)) {
			actualOut.add(Calendar.DATE, 1);
		}

		if (actualOut.before(limitEnd)) {
			double toleransiMenit = shift.getJamSebelumJamSampai() != null ? shift.getJamSebelumJamSampai() : 0.0;
			long diffSecs = (limitEnd.getTimeInMillis() - actualOut.getTimeInMillis()) / 1000;
			double jamCepatKeluar = (diffSecs / 3600.0) - (toleransiMenit / 60.0);
			return Math.max(0.0, jamCepatKeluar);
		}
		return 0.0;
	}
