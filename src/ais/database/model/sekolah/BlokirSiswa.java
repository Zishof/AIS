	/**
	 * Mengembalikan siswa yang dikenai blokir ini (relasi {@code @ManyToOne} lazy ke kolom FK
	 * {@code siswa}, {@code nullable = true}).
	 *
	 * <p>Getter memanggil {@link GeneralValueObject#check(Object)} lebih dulu untuk meresolusi
	 * proxy lazy &mdash; berurutan mencoba cache in-memory, session aktif, lalu session baru; bila
	 * semuanya gagal, argumen dikembalikan apa adanya. Karena itu getter ini dapat menyentuh
	 * database walau tampak sepele.</p>
	 *
	 * <p><b>Catatan penegakan:</b> query blokir mencocokkan {@code Restrictions.eq("siswa", siswa)},
	 * jadi baris dengan relasi {@code null} tidak pernah cocok dengan siapa pun (blokir yatim yang
	 * inert). {@code CascadeType.PERSIST}/{@code MERGE} berarti menyimpan baris blokir ikut
	 * mem-persist/merge object siswa yang terpaut &mdash; perhatikan bila object {@code Siswa}
	 * dirakit manual dari jalur non-standar.</p>
	 *
	 * @return siswa yang diblokir, atau {@code null} bila baris tidak menunjuk siswa mana pun
	 */
	@ManyToOne(cascade = { CascadeType.PERSIST, CascadeType.MERGE }, fetch = FetchType.LAZY)
	@JoinColumn(name = "siswa", nullable = true)
	public Siswa getSiswa() {
		siswa = check(siswa);
		return siswa;
	}

