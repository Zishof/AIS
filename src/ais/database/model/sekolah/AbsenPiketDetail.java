	/**
	 * Merakit kunci gabungan {@code <i>mahasiswaId</i>_<i>siswaId</i>_<i>tahunAkademik</i>_<i>semester</i>}
	 * <b>tanpa memerlukan instance</b> &mdash; berguna untuk mencari baris lewat kolom
	 * {@code kodeUnik} sebelum objeknya dimuat.
	 *
	 * <p>Sisi yang kosong diisi literal {@code "0"} agar posisi ruas tetap. Perhatikan bahwa
	 * {@code semester} di sini bertipe {@code String}, sementara pada instance
	 * ({@link #getKodeUnik()}) yang dirangkai adalah {@code Integer} &mdash; pemanggil wajib
	 * memastikan representasi teksnya sama persis, jika tidak kunci yang dihasilkan tidak akan
	 * cocok dengan yang tersimpan.</p>
	 *
	 * <p>Method ini tidak dipakai oleh {@link #getKodeUnik()} maupun oleh {@code ambil(...)};
	 * keduanya merakit ulang string yang sama secara terpisah &mdash; duplikasi logika yang
	 * berpotensi menyimpang bila salah satu diubah.</p>
	 *
	 * @param mahasiswa     mahasiswa pemilik baris, atau {@code null} untuk mengisi {@code "0"}
	 * @param siswa         siswa pemilik baris, atau {@code null} untuk mengisi {@code "0"}
	 * @param tahunAkademik tahun akademik; dirangkai apa adanya, {@code null} menjadi teks
	 *                      {@code "null"}
	 * @param semester      semester sebagai teks; perlakuan {@code null} sama
	 * @return kunci gabungan siap pakai
	 */
	public static String ambilKodeUnik(Mahasiswa mahasiswa, Siswa siswa, String tahunAkademik, String semester) {
		return (mahasiswa == null ? "0" : mahasiswa.getId()) + "_" + (siswa == null ? "0" : siswa.getId()) + "_"
				+ tahunAkademik + "_" + semester;
	}

	/**
	 * Mengembalikan kunci gabungan turunan
	 * {@code <i>mahasiswaId</i>_<i>siswaId</i>_<i>tahunAkademik</i>_<i>semester</i>}, dipetakan ke
	 * kolom {@code unique} sehingga <b>basis data-lah yang memaksakan aturan "satu baris per
	 * peserta didik per semester"</b>.
	 *
	 * <p><b>Getter paling destruktif di kelas ini.</b> Setiap kali dipanggil ia menimpa
	 * <b>tiga</b> field sekaligus: {@code mahasiswa} dan {@code siswa} (lewat
	 * {@link #getMahasiswa()}/{@link #getSiswa()}, yang keduanya sendiri sudah menulis balik hasil
	 * {@code check(...)}), lalu {@code kodeUnik}. Karena Hibernate memanggil getter ini pada
	 * setiap pemuatan dan setiap {@code flush}, satu operasi baca dapat menghapus relasi yang tidak
	 * lagi valid <i>sekaligus</i> menulis ulang kunci uniknya.</p>
	 *
	 * <p><b>Kuirk penting:</b> kunci dirakit dari <b>field mentah</b> {@code tahunAkademik} dan
	 * {@code semester}, <b>bukan</b> dari {@link #getTahunAkademik()}/{@link #getSemester()} yang
	 * menyediakan nilai pengganti. Baris yang kedua kolom itu masih kosong menghasilkan kunci
	 * seperti {@code "0_123_null_null"}. Karena kolomnya {@code unique}, <b>baris kedua dengan pola
	 * yang sama akan ditolak basis data</b> &mdash; kegagalan penyimpanan yang tampak tidak
	 * berhubungan dengan sebabnya. Perhatikan pula bahwa {@code jamke} <b>tidak</b> ikut menjadi
	 * bagian kunci, padahal ia ikut dipakai sebagai pembeda oleh {@code ambil(...)}; dua baris
	 * berbeda jam-ke untuk siswa dan semester yang sama karenanya bertabrakan di kolom unik ini.</p>
	 *
	 * @return kunci gabungan yang baru dirakit; tidak pernah {@code null}
	 */
	@Column(unique = true)
	public String getKodeUnik() {
		mahasiswa = getMahasiswa();
		siswa = getSiswa();
		kodeUnik = (mahasiswa == null ? "0" : mahasiswa.getId()) + "_" + (siswa == null ? "0" : siswa.getId()) + "_"
				+ tahunAkademik + "_" + semester;
		return kodeUnik;
	}

