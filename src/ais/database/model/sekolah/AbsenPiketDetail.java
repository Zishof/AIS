	/**
	 * Menghitung <b>selisih menit</b> antara sebuah waktu acuan dari konfigurasi dan sebuah waktu
	 * kejadian, keduanya dinormalkan ke tanggal HARI INI.
	 *
	 * <p>Cara kerja: {@code konf} diurai dengan {@code Common.timeFormat2} (format jam saja) lalu
	 * bagian tahun/bulan/tanggalnya ditimpa dengan tanggal server saat ini; hal yang sama dilakukan
	 * pada {@code masukjam}. Selisih keduanya dihitung dalam detik memakai Joda-Time lalu dibagi 60.
	 * Karena kedua sisi dipaksa ke tanggal yang sama, method ini <b>mengabaikan sepenuhnya komponen
	 * tanggal dari {@code masukjam}</b> &mdash; memanggilnya dengan waktu kemarin tetap menghasilkan
	 * selisih jam dalam hari yang sama.</p>
	 *
	 * <p>Hasilnya <b>bertanda</b>: negatif bila {@code masukjam} lebih awal dari waktu acuan,
	 * positif bila lebih lambat. Pemanggil pada umumnya membungkusnya dengan {@code Math.abs(...)}
	 * lalu membandingkannya dengan ambang toleransi &mdash; lihat {@link #jamKe(Long)} dan
	 * {@code ais.database.model.sekolah.AbsenGuruPiket} yang memakai method ini untuk jalur guru.</p>
	 *
	 * @param masukjam waktu kejadian (mis. saat pemindaian kartu); hanya bagian jam/menit/detiknya
	 *                 yang dipakai
	 * @param konf     waktu acuan dalam bentuk teks konfigurasi (mis. {@code "07.30"}); di-{@code trim}
	 *                 lebih dulu
	 * @return selisih dalam menit, bertanda; negatif berarti lebih awal dari acuan
	 * @throws Exception bila {@code konf} tidak dapat diurai sebagai jam, atau {@code masukjam}
	 *                   {@code null}; seluruh pemanggil di kelas ini menangkapnya secara lokal
	 */
	public static Double waktu(Date masukjam, String konf) throws Exception {
		Calendar now = ais.ui.util.WaktuUtil.getCalendar();

		Calendar start = ais.ui.util.WaktuUtil.getCalendar();
		start.setTime(Common.timeFormat2.get().parse(konf.trim()));
		start.set(Calendar.YEAR, now.get(Calendar.YEAR));
		start.set(Calendar.MONTH, now.get(Calendar.MONTH));
		start.set(Calendar.DATE, now.get(Calendar.DATE));

		Calendar end = ais.ui.util.WaktuUtil.getCalendar();
		end.setTime(masukjam);
		end.set(Calendar.YEAR, now.get(Calendar.YEAR));
		end.set(Calendar.MONTH, now.get(Calendar.MONTH));
		end.set(Calendar.DATE, now.get(Calendar.DATE));

		DateTime startDateTime = new DateTime(start.getTime());
		DateTime endDateTime = new DateTime(end.getTime());

		Seconds s = Seconds.secondsBetween(startDateTime, endDateTime);
		double jumlahMenitAbsenFotoSaatHadir = s.getSeconds() / 60.0;
		return jumlahMenitAbsenFotoSaatHadir;
	}

