			// (bila sudah dibayar sudah ter-"rescue" true di blok isRescued di atas).
			if (Boolean.TRUE.equals(nonaktifManual)) {
				return this.aktif = false;
			}

			if ((nb != null && Boolean.TRUE.equals(nb.getBukanTagihan())) || ambilBukanTagihanData()) {
				return this.aktif = false;
			}

