	/**
	 * Mengembalikan status aktif kategori, dengan <b>normalisasi {@code null} menjadi
	 * {@code true}</b>.
	 *
	 * <p><b>Mengapa ini penting.</b> Pemetaan kelas ini memakai akses properti (anotasi
	 * {@code @Id} berada pada getter), sehingga Hibernate membaca nilai kolom {@code aktif}
	 * lewat method ini. Nilai hasil normalisasi itulah yang benar-benar ditulis ke basis data:
	 * baris baru lahir dengan {@code aktif = true} meskipun formulir Tambah tidak punya isian
	 * "Aktif" sama sekali. Ini membedakan entity ini dari beberapa master sejenis di modul
	 * sekolah yang kolom {@code aktif}-nya tidak pernah ditulis layar master sehingga barisnya
	 * tak pernah muncul di combobox.</p>
	 *
	 * <p><b>Siapa yang benar-benar menyaring kolom ini:</b></p>
	 * <ul>
	 * <li>{@code GuruAction} — combobox "Jenis Guru" memakai
	 * {@code isNull("aktif") OR eq("aktif", true)}, jadi kategori non-aktif hilang dari pilihan.
	 * Perhatikan pemuatan <i>pertama</i> combo itu belum menyaring sekolah sama sekali;
	 * penyaringan {@code isNull("sekolah") OR eq("sekolah", s)} baru ditambahkan oleh listener
	 * yang dijalankan {@code Common.createDefaultTimer(...)}/{@code onChange} combo Sekolah.
	 * Selama jeda singkat itu (atau bila timer gagal berjalan) daftar memuat kategori milik
	 * sekolah lain.</li>
	 * <li>{@code DasboardGuru} — combo filter dan seluruh kriteria memakai penyaring setara
	 * ({@code aktif = true OR aktif IS NULL}).</li>
	 * <li>{@code JenisGuruAction#initCriteria(boolean)} — <b>tidak</b> menyaring kolom ini,
	 * meski {@code jenis_guru.zul} menyediakan kotak centang "Tampilkan hanya yang aktif" yang
	 * tercentang secara bawaan. Lihat catatan pada Javadoc kelas.</li>
	 * </ul>
	 *
	 * @return {@code true} bila kategori aktif atau belum pernah disetel; {@code false} hanya
	 *         bila secara eksplisit dinonaktifkan. Tidak pernah {@code null}
	 */
	public Boolean getAktif() {
		return aktif == null ? true : aktif;
	}

