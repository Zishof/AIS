		if (pakaiDefaultTemplate) {
			template = bangunTemplateDefaultDaftarUlang(siswa, calonSiswa, total, rincianDefault.toString(), d,
					tahunCurrent, bulanCurrent);
		}

		closeOpenedSessionQuietly(session);
		session = null;

		if (total < 0.01) {
			return false;
		}

