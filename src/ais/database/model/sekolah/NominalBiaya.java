	/**
	 * Peninggalan yang tidak dipakai logika bisnis mana pun.
	 *
	 * <p>Properti ini <b>dipetakan</b> ke kolom {@code baru} (tidak ada {@code @Transient}),
	 * dengan null-coalescing {@code null} &rarr; {@code true}. Penelusuran repo tidak menemukan
	 * satu pun pembaca {@code getBaru()}/{@code setBaru(...)} pada {@code NominalBiaya} —
	 * berbeda dari properti senama di modul SIRS ({@code Pendaftaran}, {@code BookingRegistrasi})
	 * yang benar-benar dipakai layar.</p>
	 *
	 * <p><b>Bug boot yang no-op.</b> {@code InitDataHelper} bagian "Sinkronisasi Tabel Nominal
	 * Biaya" memindai <i>semua</i> baris ber-{@code baru IS NULL}, lalu untuk setiap id
	 * menjalankan HQL terisolasi {@code "update NominalBiaya set baru = baru where id = :id"}.
	 * Pernyataan itu menulis {@code NULL} kembali menjadi {@code NULL}, sehingga baris tersebut
	 * <i>tetap</i> terjaring pada boot berikutnya. Efek nettonya: satu transaksi UPDATE per
	 * baris {@code NULL} pada setiap start-up, selamanya, tanpa mengubah apa pun. Pada
	 * instalasi besar (satu baris per siswa &times; item biaya &times; periode) ini beban
	 * boot yang nyata. Getter dengan coalescing {@code null} &rarr; {@code true} tidak
	 * membantu, karena HQL bulk update tidak melewati getter.</p>
	 *
	 * @return {@code true} bila kolom {@code baru} bernilai {@code true} atau {@code null}
	 */
	public Boolean getBaru() {
		return baru == null ? true : baru;
	}

