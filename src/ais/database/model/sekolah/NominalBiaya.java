	/**
	 * Nominal rupiah yang ditagihkan, <b>dihitung ulang setiap kali dipanggil</b>.
	 *
	 * <p>Ini getter yang dipetakan ke kolom {@code nominal} ({@code nullable = false}), dan
	 * sekaligus method paling berbahaya di kelas ini: nilainya <b>ditulis balik ke field</b>,
	 * sehingga — karena pemetaan Hibernate memakai property access — angka hasil perhitungan
	 * inilah yang ter-flush ke database, bahkan ketika pengguna tidak mengubah apa pun.</p>
	 *
	 * <h4>Urutan penentuan nilai</h4>
	 * <ol>
	 *   <li><b>Jalur parameter tambahan.</b> Bila {@code getItemBiayaSekolah().getParameterTambahan()}
	 *       terisi, nominal <b>ditimpa total</b> oleh skor parameter tambahan milik orang yang
	 *       bersangkutan: {@code getCalonSiswa().ambilSkor(...)} bila ada calon siswa, selain
	 *       itu {@code getSiswa().ambilSkor(...)}. Skor dibaca dari string
	 *       {@code parameterTambahan} pada biodata (format {@code nama<=>nilai<=>...<=>id}) dan
	 *       hanya dijumlahkan untuk parameter bertipe {@code PILIHAN_CUSTOM}. Inilah jalur
	 *       "tarif mengikuti atribut/nilai siswa"; di layar rincian, kotak isian nominal
	 *       otomatis diganti label baca-saja untuk item seperti ini.</li>
	 *   <li><b>Tarif terkunci.</b> Selain itu, bila {@link #getPengaturanBiayaItemBiaya()}
	 *       menandai tarif tetap — {@code maksimalBiaya > 0.1} dan
	 *       {@code maksimalBiaya.intValue() == minimalBiaya.intValue()} — nominal dipaksa sama
	 *       dengan {@code maksimalBiaya}. Perhatikan pembandingan memakai {@code intValue()},
	 *       sehingga selisih pecahan di bawah 1 rupiah dianggap sama.</li>
	 *   <li><b>Penjepitan ke lantai/plafon.</b> Bila tidak terkunci: nominal dinaikkan ke
	 *       {@code minimalBiaya} bila berada di bawahnya, lalu diturunkan ke
	 *       {@code maksimalBiaya} bila melewatinya (plafon hanya berlaku bila
	 *       {@code maksimalBiaya > 0.1}, yang menjadi konvensi "0 berarti tanpa plafon").</li>
	 *   <li><b>Bukan tagihan.</b> Terakhir, bila {@link #getBukanTagihan()} bernilai
	 *       {@code true}, nominal dipaksa {@code 0.0}.</li>
	 * </ol>
	 *
	 * <h4>Peringatan</h4>
	 * <ul>
	 *   <li><b>Kehilangan data pada langkah 4.</b> Nilai {@code 0.0} ditulis ke <i>field</i>,
	 *       bukan sekadar dikembalikan. Setelah sebuah baris dicentang "bukan tagihan" dan
	 *       getternya terpanggil sekali dalam sesi yang ter-flush, angka rupiah aslinya hilang
	 *       permanen — menghapus centangnya tidak mengembalikannya (paling jauh nominal
	 *       terangkat kembali ke {@code minimalBiaya} pada langkah 3).</li>
	 *   <li><b>Terpanggil dari mana-mana.</b> {@link #toString()} memanggil getter ini, begitu
	 *       pula Hibernate sendiri pada setiap dirty-check. Perubahan angka
	 *       {@code minimal}/{@code maksimal} pada baris tarif katalog karenanya menyusul
	 *       mengubah nominal siswa yang sudah terbentuk — berlawanan dengan
	 *       {@code defaultBiaya} yang hanya berlaku saat baris pertama kali dibuat.</li>
	 *   <li><b>Preseden kerusakan nyata.</b> Komentar panjang pada {@code Tagihan.setNominal(Double)}
	 *       mendokumentasikan bug produksi ketika penulisan balik semacam ini membentuk umpan
	 *       balik yang membuat tagihan membesar setiap kali tombol "Cari" diklik.</li>
	 *   <li>Penjaga {@code != null} pada {@code getMinimalBiaya()}/{@code getMaksimalBiaya()}
	 *       tidak pernah gagal: keempat getter {@code Double} di
	 *       {@link PengaturanBiayaItemBiaya} sudah melakukan null-coalescing ke {@code 0.0}.</li>
	 * </ul>
	 *
	 * @return nominal rupiah yang harus ditagihkan; {@code 0.0} bila belum terisi atau bila
	 *         baris ini ditandai bukan tagihan
	 * @see #ambilNominal()
	 * @see PengaturanBiayaItemBiaya#getMinimalBiaya()
	 * @see PengaturanBiayaItemBiaya#getMaksimalBiaya()
	 */
	@Column(name = "nominal", nullable = false, precision = 17, scale = 17)
	public Double getNominal() {

		itemBiayaSekolah = getItemBiayaSekolah();
		if (itemBiayaSekolah != null && itemBiayaSekolah.getParameterTambahan() != null) {
			if (getCalonSiswa() != null) {
				nominal = getCalonSiswa().ambilSkor(itemBiayaSekolah.getParameterTambahan()).doubleValue();
			} else if (getSiswa() != null) {
				nominal = getSiswa().ambilSkor(itemBiayaSekolah.getParameterTambahan()).doubleValue();
			}
		} else {
			pengaturanBiayaItemBiaya = getPengaturanBiayaItemBiaya();

			if (pengaturanBiayaItemBiaya != null && pengaturanBiayaItemBiaya.getMaksimalBiaya() != null
					&& pengaturanBiayaItemBiaya.getMinimalBiaya() != null
					&& pengaturanBiayaItemBiaya.getMaksimalBiaya() > 0.1 && pengaturanBiayaItemBiaya.getMaksimalBiaya()
							.intValue() == pengaturanBiayaItemBiaya.getMinimalBiaya().intValue()) {
				nominal = pengaturanBiayaItemBiaya.getMaksimalBiaya();
			} else {

				if (nominal != null && pengaturanBiayaItemBiaya != null
						&& pengaturanBiayaItemBiaya.getMinimalBiaya() > nominal) {
					nominal = pengaturanBiayaItemBiaya.getMinimalBiaya();
				}

				if (nominal != null && pengaturanBiayaItemBiaya != null
						&& pengaturanBiayaItemBiaya.getMaksimalBiaya() != null
						&& pengaturanBiayaItemBiaya.getMaksimalBiaya() > 0.1
						&& pengaturanBiayaItemBiaya.getMaksimalBiaya() < nominal) {
					nominal = pengaturanBiayaItemBiaya.getMaksimalBiaya();
				}
			}
		}

		if (getBukanTagihan()) {
			nominal = 0.0;
		}

		return this.nominal == null ? 0.0 : nominal;
	}

