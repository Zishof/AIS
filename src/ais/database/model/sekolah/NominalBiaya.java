	/**
	 * Jumlah angsuran efektif untuk baris nominal ini.
	 *
	 * <p><b>Getter destruktif:</b> nilainya dihitung ulang dan ditulis balik ke field menurut
	 * periode jenis biaya, sehingga hasil perhitungan inilah yang ter-flush ke kolom.</p>
	 *
	 * <h4>Urutan penentuan</h4>
	 * <ol>
	 *   <li><b>Bulanan</b> &rarr; dipaksa {@code 1}. Biaya bulanan tidak mengenal angsuran;
	 *       pemecahan periodenya diwakili baris {@link Tagihan} per bulan, bukan per angsuran.
	 *       Konsisten dengan {@code Tagihan.getBayarKe()} yang juga memaksa {@code 1} untuk
	 *       periode Bulanan.</li>
	 *   <li><b>Harian</b> (dan {@code tahunbulan > 2100}) &rarr; jumlah <i>hari</i> dalam bulan
	 *       yang bersangkutan. Bulan/tahun diurai dari {@code tahunbulan} berformat
	 *       {@code yyyyMM}; bulan di luar 1..12 mengembalikan {@code 1} lebih awal.
	 *       <b>Catatan:</b> yang dipakai adalah {@code Calendar.getMaximum(Calendar.DATE)},
	 *       yang selalu mengembalikan <b>31</b> untuk kalender Gregorian — bukan
	 *       {@code getActualMaximum(...)} yang peka bulan/tahun kabisat. Jadi Februari pun
	 *       menghasilkan 31 angsuran harian. Perhatikan pula bahwa {@code tahunbulan} dibaca
	 *       dari field mentah di sini, sementara {@link #getTahunbulan()} bisa
	 *       meng-{@code null}-kannya.</li>
	 *   <li>Selain itu, bila {@link #getDibayarSebayakManual()} terisi dan &gt; 0, nilainya
	 *       dipakai apa adanya — inilah jalur normal untuk biaya Insidentil yang diangsur.</li>
	 * </ol>
	 *
	 * <p>Nilai akhir selalu dinormalkan: {@code null} atau &lt; 1 menjadi {@code 1}.</p>
	 *
	 * <p>Angka ini juga menjadi gerbang beberapa aturan uang lain: diskon "lunas sekali bayar"
	 * ({@code PengaturanBiayaItemBiaya.getDiskonBiaya()}) hanya berlaku bila hasilnya
	 * {@code 1}, dan {@code Tagihan.getNominal()} memakai kondisi yang sama untuk memutuskan
	 * apakah nominal tagihan diambil bulat-bulat dari baris ini.</p>
	 *
	 * @return jumlah angsuran, selalu &ge; 1
	 */
	public Integer getDibayarSebayak() {
		if (getPengaturanBiaya() != null
				&& getPengaturanBiaya().getJenisBiayaSekolah().getPeriode().equals("Bulanan")) {
			dibayarSebayak = 1;
		} else if (getPengaturanBiaya() != null
				&& getPengaturanBiaya().getJenisBiayaSekolah().getPeriode().equals("Harian") && tahunbulan != null
				&& tahunbulan > 2100) {
			int tahun = Integer.parseInt((tahunbulan + "").substring(0, 4));
			int bulan = Integer.parseInt((tahunbulan + "").substring(4));
			if (bulan > 12 || bulan < 1) {
				return 1;
			}
			Calendar cal = ais.ui.util.WaktuUtil.getCalendar();
			cal.set(Calendar.DAY_OF_MONTH, 1);
			cal.set(Calendar.MONTH, bulan - 1);
			cal.set(Calendar.YEAR, tahun);
			dibayarSebayak = cal.getMaximum(Calendar.DATE);
		} else if (getDibayarSebayakManual() != null && getDibayarSebayakManual().intValue() > 0) {
			dibayarSebayak = getDibayarSebayakManual();
		}
		return dibayarSebayak == null || dibayarSebayak < 1 ? 1 : dibayarSebayak;
	}

