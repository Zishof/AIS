	@SuppressWarnings("unchecked")
	public static void populate(Siswa siswa) {

		if (siswa.getId() != null) {

			String riwayatPengaturanPembayaran = "";
			String riwayatJenisPembayaran = "";
			String riwayatPembayaran = "";
			String riwayatTagihan = "";

			try {
				Session session = HibernateUtil.currentNativeSession();
				session.refresh(siswa);
				List<PembayaranSiswaDetail> riwayatPembayarans = session.createCriteria(PembayaranSiswaDetail.class)
						.createAlias("pembayaranSiswa", "pembayaranSiswa").add(Restrictions.isNotNull("tagihan"))
						.add(Restrictions.eq("pembayaranSiswa.siswa", siswa)).addOrder(Order.asc("id")).list();

				for (PembayaranSiswaDetail r : riwayatPembayarans) {
					Tagihan tagihan = r.getTagihan();

					if (tagihan.getPembayaranSiswaDetail() != null) {
						Long pemId = r.getId();
						Long jenisId = tagihan.getPengaturanBiaya() != null
								&& tagihan.getPengaturanBiaya().getJenisBiayaSekolah() != null
										? tagihan.getPengaturanBiaya().getJenisBiayaSekolah().getId()
										: -1L;
						Long pengId = tagihan.getPengaturanBiaya() != null ? tagihan.getPengaturanBiaya().getId() : -1L;

						if (tagihan.getPengaturanBiaya().getJenisBiayaSekolah().getPeriode().equals("Bulanan")) {
							riwayatPengaturanPembayaran += riwayatPengaturanPembayaran.isEmpty()
									? (pengId + "_" + tagihan.getBulan() + "_" + tagihan.getTahun())
									: "," + (pengId + "_" + tagihan.getBulan() + "_" + tagihan.getTahun());
						} else {
							riwayatPengaturanPembayaran += riwayatPengaturanPembayaran.isEmpty() ? pengId.toString()
									: "," + pengId;
						}

						riwayatJenisPembayaran += riwayatJenisPembayaran.isEmpty() ? jenisId.toString() : "," + jenisId;

						riwayatPembayaran += riwayatPembayaran.isEmpty() ? pemId.toString() : "," + pemId;

						riwayatTagihan += riwayatTagihan.isEmpty() ? tagihan.getId().toString() : "," + tagihan.getId();
					}

				}
				riwayatPembayarans.clear();
				riwayatPembayarans = null;

				List<Tagihan> tagihans = session.createCriteria(Tagihan.class)

						.add(Restrictions.or(
								Restrictions.and(Restrictions.isNotNull("pembayaranBerakhirPada"),
										Restrictions
												.sqlRestriction("this_.pembayaran_berakhir_pada < CURRENT_TIMESTAMP")),
								Restrictions.isNull("pembayaranSiswaDetail")))

						.add(Restrictions.or(Restrictions.eq("bukanTagihan", true), Restrictions.lt("nominal", 0.1)))
						.add(Restrictions.eq("siswa", siswa)).addOrder(Order.asc("id")).list();

				for (Tagihan tagihan : tagihans) {
					if ((tagihan.getNominal() < 0.1 || tagihan.ambilBukanTagihanData()) && ((tagihan.getAktif() &&  !tagihan.ambilBukanTagihanData()) && !tagihan.getNominalBiaya().getBukanTagihan())) {
//						Long jenisId = tagihan.getPengaturanBiaya() != null
//								&& tagihan.getPengaturanBiaya().getJenisBiayaSekolah() != null
//										? tagihan.getPengaturanBiaya().getJenisBiayaSekolah().getId()
//										: -1L;
						Long pengId = tagihan.getPengaturanBiaya() != null ? tagihan.getPengaturanBiaya().getId() : -1L;

						if (tagihan.getPengaturanBiaya().getJenisBiayaSekolah().getPeriode().equals("Bulanan")) {
							riwayatPengaturanPembayaran += riwayatPengaturanPembayaran.isEmpty()
									? (pengId + "_" + tagihan.getBulan() + "_" + tagihan.getTahun())
									: "," + (pengId + "_" + tagihan.getBulan() + "_" + tagihan.getTahun());
						} else {
							riwayatPengaturanPembayaran += riwayatPengaturanPembayaran.isEmpty() ? pengId.toString()
									: "," + pengId;
						}

//						riwayatJenisPembayaran += riwayatJenisPembayaran.isEmpty() ? jenisId.toString() : "," + jenisId;

						riwayatTagihan += riwayatTagihan.isEmpty() ? tagihan.getId().toString() : "," + tagihan.getId();
					}
				}
				tagihans.clear();
				tagihans = null;

				// Evict semua entitas dari session (termasuk Tagihan yang mungkin
				// kotor/computed kodeUnik) sebelum update Siswa, agar session.flush
				// tidak mencoba UPDATE Tagihan dengan kodeUnik duplikat.
				try { session.clear(); } catch (Exception ignored) { ais.common.ErrorAuditUtil.record(ignored, "auto-audit(empty-catch) src/ais/database/model/sekolah/Siswa.java:2741");}
				// Re-attach siswa ke session setelah clear.
				try { session.refresh(siswa); } catch (Exception ignored) { ais.common.ErrorAuditUtil.record(ignored, "auto-audit(empty-catch) src/ais/database/model/sekolah/Siswa.java:2743");}

				siswa.setRiwayatPengaturanPembayaran(riwayatPengaturanPembayaran);
				siswa.setRiwayatJenisPembayaran(riwayatJenisPembayaran);
				siswa.setRiwayatPembayaran(riwayatPembayaran);
				siswa.setRiwayatTagihan(riwayatTagihan);

				session.getTransaction().begin();
				Common.refreshUpdate(session, siswa);
				session.getTransaction().commit();

				// session.disconnect();
				if (session.isOpen()) {session.disconnect();session.close();}

			} catch (Exception e) {
				e.printStackTrace(); ais.common.ErrorAuditUtil.record(e, "auto-audit src/ais/database/model/sekolah/Siswa.java:2758");
			}

			HibernateUtil.closeSession();

		}
	}

