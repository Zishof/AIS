	/**
	 * Memasok path berkas <b>kop surat</b> dan <b>stempel</b> yayasan ini ke peta parameter
	 * laporan JasperReports.
	 *
	 * <p><b>Tujuan.</b> Berkas {@code .jrxml} merujuk gambar kop/stempel lewat nama parameter,
	 * bukan lewat path. Method ini mengisi parameter-parameter itu tepat sebelum laporan
	 * dijalankan, sehingga templat laporan tidak perlu tahu di mana berkas disimpan.</p>
	 *
	 * <p><b>Alur untuk masing-masing dari dua jenis berkas</b>
	 * ({@code LampiranLain.KOP_YAYASAN} = "KOP Yayasan", {@code LampiranLain.STEMPEL_YAYASAN} =
	 * "Stempel Yayasan"):</p>
	 * <ol>
	 *   <li>coba jalur cepat {@code FileFoto.fileAdaDiFolder(jenis, getId())} — berkas yang sudah
	 *   tersimpan di folder unggahan;</li>
	 *   <li>bila berkas itu ada dan lolos {@code Common.isGambarLaporanValid(...)}, path
	 *   absolutnya dipasang;</li>
	 *   <li>bila tidak, jatuh ke {@code LampiranLain.ambil(false, getId(), jenis)} (baris lampiran
	 *   di basis data) dan {@code kop.ambilFile()}; path dipasang hanya bila berkas hasilnya juga
	 *   lolos validasi;</li>
	 *   <li>bila kedua jalur gagal, <b>tidak ada parameter yang dipasang sama sekali</b> — method
	 *   berakhir senyap tanpa melempar exception. Laporan akan dirender tanpa kop/stempel, bukan
	 *   gagal. Ini disengaja (laporan tetap keluar walau gambar belum diunggah), tetapi berarti
	 *   ketiadaan kop pada hasil cetak tidak menghasilkan pesan kesalahan apa pun untuk
	 *   ditelusuri.</li>
	 * </ol>
	 *
	 * <p><b>Tiga kunci dipasang untuk tiap berkas</b> agar templat laporan lama maupun baru
	 * sama-sama menemukannya:</p>
	 * <ul>
	 *   <li>{@code "KOP_YAYASAN"} / {@code "STEMPEL_YAYASAN"} — kunci polos, dipakai laporan yang
	 *   hanya mengenal satu yayasan;</li>
	 *   <li>{@code "KOP_YAYASAN_" + getId()} — kunci ber-id, untuk laporan lintas yayasan;</li>
	 *   <li>{@code "KOP_YAYASAN_" + getNama()} — kunci ber-nama. <b>Perhatian:</b> pemanggilan
	 *   {@link #getNama()} di sini ikut memicu penulisan balik destruktif dari {@link Pendaftar}
	 *   bila relasi itu terisi (lihat {@link #getNama()}), sehingga <b>mencetak laporan dapat
	 *   mengubah nama yayasan di basis data</b>. Selain itu kunci ini rapuh: nama yayasan bisa
	 *   berisi spasi dan tanda baca, dan bila nama berubah maka kunci di {@code .jrxml} lama tidak
	 *   lagi cocok.</li>
	 * </ul>
	 *
	 * <p><b>Efek samping:</b> memutasi {@code parameters} yang diberikan pemanggil (hingga enam
	 * entri baru); melakukan I/O berkas; dan berpotensi memicu tulis basis data lewat
	 * {@link #getNama()}. Tidak ada nilai kembali dan tidak ada exception yang dilempar.</p>
	 *
	 * <p><b>Dipanggil dari:</b> {@code ais.action.master.surat.util.SuratUtil} (dua titik: alur
	 * cetak surat generik dan alur cetak berbasis manajemen properti) — selalu bersama
	 * {@code Sekolah.putFile}/{@code PerguruanTinggi.putFile}/{@code Fakultas.putFile}/
	 * {@code Jurusan.putFile} sehingga satu laporan bisa memuat kop dari beberapa tingkat
	 * hierarki sekaligus. {@code ais.common.ManajemenProperty} memanggil varian sejenis untuk
	 * entity lain.</p>
	 *
	 * @param parameters peta parameter laporan JasperReports yang akan <b>dimutasi di tempat</b>;
	 *                   tipe mentah ({@code raw}) mengikuti API Jasper lama, karena itu ada
	 *                   {@code @SuppressWarnings}. Tidak boleh {@code null}
	 */
	@SuppressWarnings({ "unchecked", "rawtypes" })
	public void putFile(Map parameters) {
		Yayasan yayasan = this;
		File file = FileFoto.fileAdaDiFolder(LampiranLain.KOP_YAYASAN, yayasan.getId());
		if (Common.isGambarLaporanValid(file)) {
			parameters.put("KOP_YAYASAN", file.getAbsolutePath());
			parameters.put("KOP_YAYASAN_" + yayasan.getId(), file.getAbsolutePath());
			parameters.put("KOP_YAYASAN_" + yayasan.getNama(), file.getAbsolutePath());
		} else {
			LampiranLain kop = LampiranLain.ambil(false, yayasan.getId(), LampiranLain.KOP_YAYASAN);
			if (kop != null) {
				File fileKop = kop.ambilFile();
				if (Common.isGambarLaporanValid(fileKop)) {
					parameters.put("KOP_YAYASAN", fileKop.getAbsolutePath());
					parameters.put("KOP_YAYASAN_" + yayasan.getId(), fileKop.getAbsolutePath());
					parameters.put("KOP_YAYASAN_" + yayasan.getNama(), fileKop.getAbsolutePath());
				}
			}
		}

		file = FileFoto.fileAdaDiFolder(LampiranLain.STEMPEL_YAYASAN, yayasan.getId());
		if (Common.isGambarLaporanValid(file)) {
			parameters.put("STEMPEL_YAYASAN", file.getAbsolutePath());
			parameters.put("STEMPEL_YAYASAN_" + yayasan.getId(), file.getAbsolutePath());
			parameters.put("STEMPEL_YAYASAN_" + yayasan.getNama(), file.getAbsolutePath());
		} else {
			LampiranLain kop = LampiranLain.ambil(false, yayasan.getId(), LampiranLain.STEMPEL_YAYASAN);
			if (kop != null) {
				File fileKop = kop.ambilFile();
				if (Common.isGambarLaporanValid(fileKop)) {
					parameters.put("STEMPEL_YAYASAN", fileKop.getAbsolutePath());
					parameters.put("STEMPEL_YAYASAN_" + yayasan.getId(), fileKop.getAbsolutePath());
					parameters.put("STEMPEL_YAYASAN_" + yayasan.getNama(), fileKop.getAbsolutePath());
				}
			}
		}
	}

