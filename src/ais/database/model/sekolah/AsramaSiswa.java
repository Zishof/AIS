	/**
	 * Mengembalikan yayasan pemilik asrama (FK {@code yayasan_id}).
	 *
	 * <p>Relasi {@code LAZY}, sehingga nilai mentahnya bisa berupa proxy Hibernate. Karena itu getter
	 * menjalankan {@link GeneralValueObject#check(Object)} lalu <b>menugaskan kembali</b> hasilnya ke
	 * field &mdash; pola standar AIS untuk mengubah proxy detached menjadi objek yang aman dibaca; ia
	 * tidak mengubah nilai kolom FK. Cascade {@code PERSIST}/{@code MERGE} terpasang, tetapi cabang
	 * {@code PERSIST} praktis tidak terjangkau karena {@link #setYayasan(Yayasan)} sudah lebih dulu
	 * menolak objek yang belum punya id (kuirk 4).</p>
	 *
	 * <p><b>Bisa mengembalikan {@code null}</b>: kolomnya tidak ditandai {@code nullable = false},
	 * dan {@code PengaturanBiayaAction} memang menyiapkan cabang {@code Restrictions.isNull("yayasan")}
	 * untuk asrama "global". Namun {@code AsramaSiswaRenderer#render(...)} memanggil
	 * {@code getYayasan().getNama()} tanpa penjagaan &mdash; lihat kuirk 9.</p>
	 *
	 * @return yayasan pemilik, atau {@code null} untuk asrama yang tidak terikat yayasan mana pun
	 */
	@ManyToOne(cascade = { CascadeType.PERSIST, CascadeType.MERGE }, fetch = FetchType.LAZY)
	@JoinColumn(name = "yayasan_id")
	public Yayasan getYayasan() {
		yayasan = check(yayasan);
		return this.yayasan;
	}

	/**
	 * Menyetel yayasan pemilik asrama.
	 *
	 * <p><b>Menormalkan diam-diam:</b> bila {@code yayasan} bernilai {@code null} <i>atau</i> belum
	 * punya id (objek transient/belum tersimpan), field disetel ke {@code null}. Jadi memasang
	 * {@code Yayasan} baru yang belum di-{@code save} tidak akan menghasilkan kesalahan &mdash;
	 * asramanya sekadar berakhir tanpa pemilik. Pola ini seragam di seluruh entity AIS dan disengaja
	 * agar salah pasang objek transient tidak menciptakan baris master baru lewat cascade.</p>
	 *
	 * <p>Dipanggil dari {@code AsramaSiswaAction#onSave(...)} setelah memvalidasi combo "Yayasan"
	 * wajib terisi. Untuk pengguna yang terikat sebuah yayasan, combo itu dipaksa ke yayasan pengguna
	 * dan dinonaktifkan; untuk pengguna yang tidak terikat yayasan mana pun, ia bebas memilih yayasan
	 * apa saja (kuirk 6).</p>
	 *
	 * @param yayasan yayasan pemilik baru; {@code null} atau objek tanpa id akan tersimpan sebagai
	 *                {@code null}
	 */
	public void setYayasan(Yayasan yayasan) {
		this.yayasan = yayasan==null||yayasan.getId()==null?null:yayasan;
	}

	/**
	 * Mengembalikan nama asrama, dengan <b>normalisasi</b>: hasil di-{@code trim}, dan string yang
	 * kosong setelah di-{@code trim} dikembalikan sebagai {@code null}.
	 *
	 * <p><b>Efek samping tidak langsung (kuirk 1) &mdash; penting.</b> Kelas ini dipetakan dengan
	 * <i>property access</i> ({@code @Id} berada di {@link #getId()}), jadi Hibernate memakai getter
	 * ini untuk dirty-check <b>dan</b> untuk menyusun nilai {@code INSERT}/{@code UPDATE}. Dua
	 * akibatnya: (a) baris lama yang kolom {@code nama}-nya menyisakan spasi di ujung dianggap kotor
	 * begitu dibaca &mdash; getter mengembalikan versi ter-trim sementara snapshot hasil muat berisi
	 * versi asli &mdash; sehingga bisa ter-{@code UPDATE} beserta satu revisi Envers tanpa ada yang
	 * mengubah apa pun; (b) nama yang kosong dikembalikan sebagai {@code null} padahal kolomnya
	 * {@code nullable = false}, sehingga kegagalan muncul sebagai pelanggaran constraint saat flush.
	 * {@code AsramaSiswaAction#onSave(...)} menutup kasus (b) untuk jalur UI dengan memvalidasi nama
	 * wajib isi; jalur impor Excel tidak.</p>
	 *
	 * <p>Nilai getter ini juga yang tampil di mana-mana: label kolom "Nama Asrama" pada grid, isi
	 * {@code Combobox} pemilih asrama ({@code SiswaAction}, {@code PengaturanBiayaAction}), kunci
	 * baris pada laporan tombol "Singkronkan", dan &mdash; lewat
	 * {@link GeneralValueObject#toString()} &mdash; representasi teks default objek ini. Perhatikan
	 * bahwa pengurutan grid dilakukan SQL-side ({@code Order.asc("nama")}) memakai nilai kolom
	 * mentah, jadi urutan yang tampil bisa sedikit berbeda dari urutan teks yang ditampilkan bila ada
	 * baris ber-spasi di depan.</p>
	 *
	 * @return nama asrama sudah ter-{@code trim}, atau {@code null} bila kosong/berisi spasi saja
	 */
	@Column(name = "nama", nullable = false)
	public String getNama() {
		return this.nama == null || this.nama.trim().isEmpty() ? null : nama.trim();
	}

	/**
	 * Menyetel nama asrama. Menyimpan nilai <b>apa adanya</b> tanpa {@code trim} &mdash; normalisasi
	 * baru terjadi saat dibaca lewat {@link #getNama()}, dan justru ketidaksimetrisan inilah sumber
	 * kuirk 1.
	 *
	 * @param nama nama baru; secara teknis boleh {@code null}, tetapi kolomnya wajib isi sehingga
	 *             menyimpan objek dengan nama kosong akan gagal di tingkat database
	 */
	public void setNama(String nama) {
		this.nama = nama;
	}

	/**
	 * Mengembalikan saklar aktif katalog, dengan <b>normalisasi</b>: {@code null} dianggap
	 * {@code true}.
	 *
	 * <p><b>Mekanisme yang perlu dipahami (kuirk 2).</b> Kelas ini dipetakan dengan <i>property
	 * access</i>, sehingga nilai {@code true} hasil normalisasi inilah yang benar-benar ikut ditulis
	 * pada {@code INSERT}. Akibatnya baris yang lahir lewat {@code AsramaSiswaAction#onSave(...)}
	 * selalu berakhir dengan {@code aktif = true} di database, walaupun jalur Tambah tidak pernah
	 * memanggil {@link #setAktif(Boolean)} &mdash; jadi katalog ini <b>tidak</b> mengalami kegagalan
	 * bootstrap "baris baru tidak pernah muncul di combo". Baris ber-{@code aktif} {@code NULL} hanya
	 * mungkin lahir dari SQL mentah/migrasi; untuk baris seperti itu getter ini membuat dirty-check
	 * selalu menemukan selisih ({@code true} vs snapshot {@code null}), sehingga sekadar membacanya
	 * lalu ikut ter-flush dapat menghasilkan {@code UPDATE} beserta satu revisi Envers.</p>
	 *
	 * <p>Tiga pembaca katalog menyaring kolom ini dengan cara berbeda &mdash; lihat kuirk 3;
	 * {@code SiswaAction} adalah satu-satunya yang ketat ({@code eq("aktif", true)}), sehingga baris
	 * ber-{@code NULL} tidak akan pernah tampil pada formulir biodata siswa.</p>
	 *
	 * @return {@code true} bila asrama aktif atau belum pernah ditentukan; {@code false} hanya bila
	 *         field secara eksplisit bernilai {@code false}
	 */
	public Boolean getAktif() {
		return aktif == null ? true : aktif;
	}

	/**
	 * Menyetel saklar aktif katalog.
	 *
	 * <p>Satu-satunya pemanggil adalah listener {@code onCheck} checkbox "Aktif" pada grid layar
	 * master, yang langsung disusul {@code Common.refreshSaveOrUpdate(...)} &mdash; jadi mencentang
	 * checkbox itu menyimpan perubahan seketika, tanpa tombol Simpan. Checkbox tersebut digerbangi
	 * hak {@code UPDATE} ({@code setDisabled(!edit)}), tetapi perlu diingat hak itu diukur terhadap
	 * layar <i>induk</i> tempat layar ini disisipkan (kuirk 7).</p>
	 *
	 * <p>Menonaktifkan sebuah asrama <b>tidak</b> memutus keanggotaan penghuninya: baris
	 * {@link AsramaSiswaPunyaSiswa} dan kolom {@code Siswa.asrama} tetap utuh, dan
	 * {@code DetailTagihanSiswaHelper} yang menargetkan tagihan berdasarkan asrama tidak menyaring
	 * {@code aktif} sama sekali &mdash; sehingga tagihan asrama tetap terbit untuk asrama yang sudah
	 * dinonaktifkan.</p>
	 *
	 * @param aktif penanda baru; {@code null} akan tetap terbaca sebagai {@code true} oleh
	 *              {@link #getAktif()}
	 */
	public void setAktif(Boolean aktif) {
		this.aktif = aktif;
	}

