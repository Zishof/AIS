	/**
	 * Mengembalikan satuan kerja (modul RAB) pelaku login — getter dengan rantai penurunan
	 * TERPANJANG di kelas ini. Urutan prioritas: (1) satuan kerja akun {@link Tbmuser}
	 * ({@code ambilSatuanKerja()}), (2) satuan kerja {@link #getSekolah()}, (3) satuan kerja
	 * {@link #getFakultas()}, (4) satuan kerja perguruan tinggi induk fakultas tersebut,
	 * (5) nilai field tersimpan lewat {@link GeneralValueObject#check(Object)}.
	 *
	 * <p>Dipakai {@code DashboardStatistikKunjunganSatuanKerja} untuk mengelompokkan kunjungan
	 * per unit kerja. <b>Efek samping:</b> menulis balik ke field {@code satuanKerja}, dan
	 * memicu berantai {@link #getTbmuser()}, {@link #getSekolah()}, {@link #getFakultas()},
	 * {@link #getJurusan()} beserta seluruh efek samping masing-masing — termasuk kuirk
	 * penihilan {@code tbmuser}. Hindari memanggilnya di dalam <i>loop</i> baris log.</p>
	 *
	 * @return satuan kerja pelaku, atau {@code null} bila tidak dapat ditentukan
	 */
	@ManyToOne(cascade = { CascadeType.PERSIST, CascadeType.MERGE }, fetch = FetchType.LAZY)
	@JoinColumn(name = "satuan_kerja", nullable = true)
	public SatuanKerja getSatuanKerja() {
		if (getTbmuser() != null && getTbmuser().ambilSatuanKerja() != null) {
			satuanKerja = getTbmuser().ambilSatuanKerja();
		} else if (getSekolah() != null && getSekolah().getSatuanKerja() != null) {
			satuanKerja = getSekolah().getSatuanKerja();
		} else if (getFakultas() != null && getFakultas().getSatuanKerja() != null) {
			satuanKerja = getFakultas().getSatuanKerja();
		} else if (getFakultas() != null && getFakultas().getPerguruanTinggi() != null
				&& getFakultas().getPerguruanTinggi().getSatuanKerja() != null) {
			satuanKerja = getFakultas().getPerguruanTinggi().getSatuanKerja();
		} else {
			satuanKerja = check(satuanKerja);
		}
		return satuanKerja;
	}

