	/**
	 * Pengurai angka <b>defensif</b> untuk ruas numerik pada string terpadat
	 * {@link #getSyaratPembayaran()}, yang isinya bisa berasal dari data lama, hasil impor, atau
	 * pemformatan lokal yang berbeda.
	 *
	 * <p>Berbeda dari {@code Double.parseDouble}, method ini tidak pernah melempar exception dan
	 * mampu memungut angka dari teks yang tercampur. Aturannya: koma diubah menjadi titik; tanda
	 * {@code '+'}/{@code '-'} hanya diterima di posisi paling depan; digit dikumpulkan; satu titik
	 * desimal pertama diterima, titik berikutnya menghentikan pemungutan; karakter lain
	 * <b>dilewati selama angka belum mulai</b>, dan menghentikan pemungutan begitu angka sudah
	 * mulai.</p>
	 *
	 * <p>Konsekuensi yang perlu disadari: {@code "99,9"} &rarr; {@code 99.9}; {@code "80%"} &rarr;
	 * {@code 80.0}; {@code "Rp 1.500"} &rarr; {@code 1.5} (titik ribuan dibaca sebagai desimal);
	 * {@code "abc12"} &rarr; {@code 12.0} (sampah di depan diabaikan diam-diam). Bila sama sekali
	 * tidak ada digit, {@code defaultValue} dikembalikan.</p>
	 *
	 * @param nilai        teks yang akan diurai; {@code null} langsung menghasilkan
	 *                     {@code defaultValue}
	 * @param defaultValue nilai balikan bila teks tidak memuat angka atau gagal diurai
	 * @return angka hasil urai, atau {@code defaultValue}
	 * @see #daftarJadwal()
	 */
	private static Double parseAngkaAman(String nilai, Double defaultValue) {
		if (nilai == null) {
			return defaultValue;
		}
		String teks = nilai.trim().replace(',', '.');
		StringBuilder angka = new StringBuilder();
		boolean sudahTitik = false;
		boolean sudahAngka = false;
		for (int i = 0; i < teks.length(); i++) {
			char c = teks.charAt(i);
			if ((c == '-' || c == '+') && angka.length() == 0) {
				angka.append(c);
			} else if (c >= '0' && c <= '9') {
				angka.append(c);
				sudahAngka = true;
			} else if (c == '.' && !sudahTitik) {
				angka.append(c);
				sudahTitik = true;
			} else if (sudahAngka) {
				break;
			}
		}
		if (!sudahAngka) {
			return defaultValue;
		}
		try {
			return Double.valueOf(angka.toString());
		} catch (Exception e) {
			return defaultValue;
		}
	}

