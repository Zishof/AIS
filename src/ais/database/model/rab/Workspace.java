	/**
	 * Membandingkan dua workspace untuk keperluan pengurutan default, dengan aturan yang perlu
	 * dibaca teliti karena <b>terbalik dan tidak total</b>.
	 *
	 * <p>Aturannya:</p>
	 * <ul>
	 *   <li>Bila {@code object} bukan {@code Workspace}, hasilnya {@code 0} — artinya objek dari
	 *   kelas lain dianggap "setara" dengan workspace mana pun. Ini melanggar sifat transitif
	 *   {@link Comparable}: {@code a} setara {@code x}, {@code b} setara {@code x}, tetapi {@code a}
	 *   dan {@code b} belum tentu setara satu sama lain.</li>
	 *   <li>Bila salah satu {@code id} masih {@code null} (entity belum tersimpan), hasilnya juga
	 *   {@code 0}. Sekumpulan baris baru karena itu akan dianggap setara semua dan urutannya
	 *   bergantung pada stabilitas algoritma pengurutan, bukan pada isinya.</li>
	 *   <li>Selebihnya perbandingan dilakukan sebagai {@code workspace.id.compareTo(id)} —
	 *   perhatikan urutan operandnya <b>dibalik</b> terhadap konvensi {@code this} lebih dulu.
	 *   Efeknya, pengurutan menaik menghasilkan id besar lebih dulu, yaitu data terbaru di atas.
	 *   Ini pola yang konsisten dipakai entity-entity AIS lain, jadi jangan "memperbaikinya" tanpa
	 *   memeriksa seluruh layar yang mengandalkan urutan ini.</li>
	 * </ul>
	 *
	 * <p>Karena perbandingan sepenuhnya berbasis id, urutan ini <b>tidak</b> mencerminkan struktur
	 * pohon anggaran (kode, kedalaman, atau induk). Layar yang menampilkan pohon RAB memakai
	 * {@code WorkspaceTreeModel} dan pengurutan eksplisit di query, bukan {@code compareTo}. Juga
	 * perlu dicatat bahwa {@code compareTo} di sini tidak konsisten dengan {@code equals}: dua baris
	 * berbeda yang sama-sama belum bersimpan akan menghasilkan {@code 0} tanpa menjadi
	 * {@code equals}, sehingga memakai workspace sebagai kunci {@code TreeSet}/{@code TreeMap} dapat
	 * membuat elemen hilang secara diam-diam. Gunakan {@code List} + {@code Comparator} eksplisit
	 * bila butuh urutan lain.</p>
	 *
	 * @param object objek pembanding; boleh bertipe apa pun turunan {@link GeneralValueObject}
	 * @return bilangan negatif/nol/positif sesuai aturan di atas
	 */
	@Override
	public int compareTo(GeneralValueObject object) {
		if (object instanceof Workspace) {
			Workspace workspace = (Workspace) object;
			if (id == null || workspace.id == null) {
				return 0;
			}
			return workspace.id.compareTo(id);
		}
		return 0;
	}

