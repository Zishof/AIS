	/**
	 * Mengembalikan {@link Yayasan} induk satuan kerja ini — <b>sumbu tenant satu tingkat di ATAS
	 * entity ini</b> — setelah resolusi proxy lazy melalui {@code check(...)}.
	 *
	 * <p>
	 * Keberadaan relasi ini adalah jawaban tegas atas pertanyaan apakah {@code SatuanKerja} benar
	 * benar "akar" segala tenant: <b>tidak sepenuhnya</b>. {@code SatuanKerja} adalah akar bagi
	 * hampir seluruh data OPERASIONAL (akunting, asset, payroll, inventory, koperasi, surat), tetapi
	 * ia sendiri berada di bawah {@code Yayasan}. Sementara itu sumbu akademik
	 * ({@code Sekolah}/{@code Fakultas}/{@code Jurusan}/{@code Program}) berjalan PARALEL dan justru
	 * masing-masing memiliki {@code getSatuanKerja()} sendiri yang memetakan balik ke entity ini —
	 * lihat {@code Tbmuser.getSatuanKerja()} yang menurunkan satuan kerja pengguna secara
	 * berjenjang dari {@code Pegawai}, lalu sekolah, jurusan, dan fakultas.
	 * </p>
	 * <p>
	 * Relasi ini juga satu-satunya properti pada kelas ini yang dikenali whitelist
	 * {@code GenericCrudAutoEntityAdapter.scopeBindings()} — konsekuensi lengkapnya diuraikan pada
	 * Javadoc kelas.
	 * </p>
	 *
	 * @return yayasan induk yang sudah diresolusi, atau {@code null} bila satuan kerja belum
	 *         ditautkan ke yayasan mana pun
	 */
	@ManyToOne(cascade = { CascadeType.PERSIST, CascadeType.MERGE }, fetch = FetchType.LAZY)
	@JoinColumn(name = "yayasan")
	public Yayasan getYayasan() {
		yayasan = check(yayasan);
		return yayasan;
	}

	/**
	 * Menetapkan yayasan induk, dengan <b>normalisasi objek setengah jadi menjadi {@code null}</b>.
	 *
	 * <p>
	 * Setter ini tidak menyimpan argumen apa adanya: bila {@code yayasan} bernilai {@code null}
	 * ATAU {@code yayasan.getId()} bernilai {@code null}, field diisi {@code null}. Dengan kata
	 * lain, objek {@code Yayasan} yang belum tersimpan (belum berkunci primer) DITOLAK dan
	 * diperlakukan sebagai "tidak ada yayasan".
	 * </p>
	 * <p>
	 * <b>Mengapa demikian.</b> Komponen pemilih ZK lazim membuat objek kosong sebagai placeholder
	 * saat pengguna belum memilih apa pun, atau saat sebuah bandbox dibersihkan. Tanpa penjagaan
	 * ini, objek kosong tersebut akan diteruskan ke Hibernate dan — karena relasi memakai
	 * {@code CascadeType.PERSIST} — berpotensi menciptakan baris {@code Yayasan} KOSONG yang tidak
	 * pernah diminta siapa pun. Penjagaan ini menutup jalur tersebut secara efektif untuk relasi
	 * yayasan.
	 * </p>
	 * <p>
	 * <b>Catatan konsistensi.</b> Penjagaan serupa TIDAK dipasang pada
	 * {@link #setParent(SatuanKerja)}, {@link #setKppn(Kppn)}, {@link #setSatuanLokasi(SatuanLokasi)},
	 * maupun {@link #setPendaftar(Pendaftar)}, padahal keempatnya juga memakai
	 * {@code CascadeType.PERSIST}. Ketidakseragaman ini bersifat historis dan berarti jalur pembuatan
	 * baris kosong akibat cascade masih terbuka untuk keempat relasi tersebut.
	 * </p>
	 * <p>
	 * Efek samping lain yang perlu diketahui: karena setter ini menormalkan nilai, memanggil
	 * {@code setYayasan(getYayasan())} tidaklah bebas efek — objek yang gagal diresolusi
	 * {@code check(...)} dan kebetulan tanpa id akan berubah menjadi {@code null}, memutus tautan
	 * tenant secara diam-diam.
	 * </p>
	 *
	 * @param yayasan yayasan induk; objek {@code null} atau tanpa kunci primer disimpan sebagai
	 *                {@code null}
	 */
	public void setYayasan(Yayasan yayasan) {
		this.yayasan = yayasan == null || yayasan.getId() == null ? null : yayasan;
	}
