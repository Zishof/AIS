	/**
	 * Mengembalikan satuan kerja induk pada hierarki, dengan <b>penjagaan siklus derajat satu</b> dan
	 * resolusi proxy lazy.
	 *
	 * <p>
	 * Inilah relasi yang membuat entity ini <b>berjenjang, bukan flat</b>. Kolom {@code parent}
	 * bersifat {@code nullable}, dan node dengan {@code parent == null} adalah akar pohon. Tidak ada
	 * batas kedalaman yang dipaksakan model; bentuk pohon sepenuhnya data.
	 * </p>
	 *
	 * <p>
	 * <b>Langkah pertama — memutus self-loop.</b> Bila {@code parent} terisi, {@code parent.getId()}
	 * dan {@code getId()} sama-sama non-null, dan keduanya SAMA, maka field {@code parent}
	 * ditimpa {@code null}. Ini mencegah kasus paling umum "node menjadi induk dirinya sendiri" yang
	 * akan membuat penelusuran rekursif di {@code SatuanKerjaTreeModel.getParentCount(...)} dan
	 * {@code getParentSet(...)} berputar tanpa henti hingga {@code StackOverflowError}.
	 * </p>
	 * <p>
	 * <b>Batas penjagaan ini.</b> Hanya siklus derajat SATU yang dijaga. Siklus derajat dua atau
	 * lebih ({@code A.parent = B}, {@code B.parent = C}, {@code C.parent = A}) TIDAK terdeteksi di
	 * lapisan model dan tetap berpotensi membuat penelusuran pohon berputar. Penjagaan terhadap
	 * bentuk itu, bila ada, harus dilakukan di layar master saat menyimpan. Perlu dicatat pula bahwa
	 * pemeriksaan ini melewatkan objek yang BELUM tersimpan ({@code getId() == null}), yang memang
	 * benar karena objek tanpa id belum bisa menjadi induk siapa pun.
	 * </p>
	 * <p>
	 * <b>Langkah kedua — resolusi lazy.</b> Pemanggilan {@code parent = check(parent)} mewarisi
	 * mekanisme {@link GeneralValueObject#check(Object)}: ia berusaha mengubah proxy Hibernate yang
	 * belum ter-inisialisasi menjadi objek nyata melalui beberapa sumber (cache konstanta, sesi
	 * aktif, dan lain-lain), dan bila semuanya gagal ia mengembalikan argumen apa adanya. Ini
	 * membuat relasi {@code FetchType.LAZY} tetap dapat dibaca dari lapisan UI ZK yang sering
	 * berjalan di luar sesi Hibernate asal objek.
	 * </p>
	 * <p>
	 * <b>Efek samping yang perlu disadari.</b> Kedua langkah di atas MENULIS ke field
	 * {@code parent}, menjadikan method ini <b>getter destruktif</b>. Pada objek yang masih
	 * ter-{@code attach}, penulisan tersebut dapat memicu dirty checking dan menerbitkan
	 * {@code UPDATE} tak terduga saat {@code flush} — yang selanjutnya memicu {@link #onUpdate()}
	 * dan menambah revisi Envers. Khusus untuk kasus self-loop, {@code UPDATE} tersebut justru
	 * BERGUNA karena membersihkan data rusak, tetapi ia terjadi secara implisit tanpa jejak niat.
	 * </p>
	 * <p>
	 * <b>Cascade.</b> Relasi ini memakai {@code CascadeType.PERSIST} dan {@code CascadeType.MERGE}
	 * tetapi TIDAK {@code REMOVE}, sehingga menghapus sebuah node tidak akan menghapus induknya —
	 * perilaku yang tepat untuk pohon. Namun karena {@code PERSIST} menyalir ke atas, menyimpan
	 * sebuah node akan ikut menyimpan seluruh rantai leluhur yang belum tersimpan.
	 * </p>
	 *
	 * @return satuan kerja induk yang sudah diresolusi, atau {@code null} bila node ini adalah akar
	 *         atau bila self-loop baru saja diputus
	 */
	@ManyToOne(cascade = { CascadeType.PERSIST, CascadeType.MERGE }, fetch = FetchType.LAZY)
	@JoinColumn(name = "parent", nullable = true)
	public SatuanKerja getParent() {

		if (parent != null && parent.getId() != null && getId() != null && parent.getId().equals(getId())) {
			parent = null;
		}
		parent = check(parent);
		return parent;
	}

