	/**
	 * Mengembalikan daftar jenis pengguna yang terkait dengan pejabat ini, <b>dinormalkan menjadi
	 * bentuk berpembatas koma di kedua ujung</b>.
	 *
	 * <p>
	 * <b>Bentuk kanonik.</b> Nilai dikembalikan dalam bentuk {@code ",nilai1,nilai2,"} — diawali dan
	 * diakhiri koma. Bentuk itu bukan kebetulan: ia memungkinkan pengujian keanggotaan yang aman
	 * lewat idiom {@code daftar.contains("," + nilai + ",")} tanpa perlu memecah string, dan tanpa
	 * risiko {@code "budi"} salah cocok dengan {@code "budiman"}. Idiom yang sama dipakai di seluruh
	 * AIS — lihat {@code BroadcastHelper} yang menguji
	 * {@code getUsernamePengguna().contains("," + tbmuser.getUserId() + ",")}, serta bidang serupa
	 * pada {@code JenisJabatan}, {@code JenisCutiDanIzin}, dan {@code JenisPengajuanPegawai}.
	 * </p>
	 *
	 * <p>
	 * <b>Cara normalisasinya.</b> Bila nilai {@code null} atau tepat berisi {@code ","}, hasil awal
	 * adalah string kosong; selain itu nilai dipangkas spasinya lalu dibungkus koma di kedua ujung.
	 * Setelah itu {@code replaceAll(",,", ",")} dijalankan <b>tiga kali berturut-turut</b> untuk
	 * meruntuhkan koma ganda yang timbul dari pembungkusan berulang. Pengulangan tiga kali itu adalah
	 * pendekatan empiris, bukan algoritma yang terbukti konvergen: {@code replaceAll} sekali jalan
	 * tidak menangani koma bertumpuk secara rekursif, sehingga rentetan koma yang sangat panjang
	 * secara teoretis masih dapat menyisakan koma ganda. Untuk data yang lahir dari layar
	 * {@code PejabatAction} hal itu tidak pernah terjadi.
	 * </p>
	 * <p>
	 * Terakhir, sebuah tangga {@code if/else if} membersihkan sisa-sisa yang hanya berisi pembatas —
	 * {@code ","}, {@code ",,"}, {@code ",,,"}, {@code ",,,,"} — beserta kasus khusus {@code ",-,"}
	 * (tanda hubung sebagai penanda "tidak ada") menjadi string kosong. Tangga eksplisit ini
	 * berlebihan setelah tiga kali peruntuhan di atas, tetapi tidak berbahaya dan berfungsi sebagai
	 * jaring pengaman untuk data lama.
	 * </p>
	 *
	 * <p>
	 * <b>Getter destruktif.</b> Seluruh normalisasi di atas <b>ditulis balik ke field</b>
	 * {@code jenisPengguna}, bukan sekadar dihitung untuk nilai kembalian. Konsekuensinya sama
	 * dengan getter destruktif lain di kelas ini: pada objek ter-{@code attach}, pembacaan pertama
	 * setelah pemuatan dapat memicu {@code UPDATE} yang mempersistenkan bentuk kanonik ke basis data
	 * beserta revisi Envers baru. Untuk baris yang isinya sudah kanonik, {@code replaceAll} tidak
	 * mengubah apa pun dan tidak ada {@code UPDATE} yang lahir — jadi biaya ini hanya sekali per
	 * baris yang belum ternormalkan.
	 * </p>
	 * <p>
	 * <b>Baris terakhir adalah kode mati.</b> Pemeriksaan {@code jenisPengguna == null ? "" : ...}
	 * tidak pernah mengambil cabang {@code null}, karena ekspresi ternary di awal method selalu
	 * menghasilkan {@code String} non-null. Ia tidak berbahaya, hanya sisa pola defensif.
	 * </p>
	 * <p>
	 * Kolom dipetakan {@code columnDefinition = "text"} sehingga panjangnya tidak dibatasi 255
	 * karakter — perlu, karena daftar dapat memuat banyak entri.
	 * </p>
	 *
	 * @return daftar jenis pengguna dalam bentuk berpembatas koma di kedua ujung, atau string kosong
	 *         bila tidak ada; tidak pernah {@code null}
	 */
	@Column(name = "jenis_pengguna", nullable = true, columnDefinition = "text")
	public String getJenisPengguna() {

		jenisPengguna = (jenisPengguna == null || jenisPengguna.trim().equalsIgnoreCase(",") ? ""
				: "," + jenisPengguna.trim() + ",").replaceAll(",,", ",").replaceAll(",,", ",").replaceAll(",,", ",");

		if (jenisPengguna.equals(",")) {
			jenisPengguna = "";
		} else if (jenisPengguna.equals(",,")) {
			jenisPengguna = "";
		} else if (jenisPengguna.equals(",,,")) {
			jenisPengguna = "";
		} else if (jenisPengguna.equals(",,,,")) {
			jenisPengguna = "";
		}

		if (jenisPengguna.equals(",-,")) {
			jenisPengguna = "";
		}

		return jenisPengguna == null ? "" : jenisPengguna.trim();
	}

