	/**
	 * Mengembalikan daftar tahun angkatan yang boleh mendaftar, dalam bentuk CSV yang sudah
	 * dinormalkan.
	 *
	 * <p><b>Normalisasi:</b> nilai dibungkus koma di kedua ujung (<code>",2020,2021,"</code>) agar
	 * pencocokan satu angkatan cukup memakai <code>contains(",2020,")</code>. Koma ganda dirapikan
	 * dengan tiga kali <code>replaceAll(",,", ",")</code> berurutan, lalu tiga cabang
	 * <code>if</code> menangkap sisa string yang isinya hanya koma dan mengubahnya jadi string
	 * kosong. Nilai <code>null</code> atau yang isinya persis <code>","</code> juga menjadi string
	 * kosong.</p>
	 *
	 * <p><b>Efek samping:</b> hasil normalisasi DITULIS BALIK ke field <code>hanyaUntukAngkatan</code>
	 * — jadi getter ini mengubah state objek dan berpotensi memicu <code>UPDATE</code> pada objek
	 * yang masih terikat session.</p>
	 *
	 * <p><b>Batasan:</b> pengulangan <code>replaceAll(",,", ",")</code> sebanyak tiga kali hanya
	 * mampu meruntuhkan sampai sekitar delapan koma beruntun; masukan yang lebih kotor dari itu
	 * masih menyisakan koma ganda. Cabang <code>equals(",,")</code> dan <code>equals(",,,")</code>
	 * praktis tak pernah tercapai karena sudah diruntuhkan oleh <code>replaceAll</code>
	 * sebelumnya.</p>
	 *
	 * @return daftar angkatan berpembatas koma, atau string kosong bila tidak dibatasi; tidak pernah
	 *         <code>null</code>
	 */
	public String getHanyaUntukAngkatan() {
		hanyaUntukAngkatan = (hanyaUntukAngkatan == null || hanyaUntukAngkatan.trim().equalsIgnoreCase(",") ? ""
				: "," + hanyaUntukAngkatan.trim() + ",").replaceAll(",,", ",").replaceAll(",,", ",")
				.replaceAll(",,", ",");

		if (hanyaUntukAngkatan.equals(",")) {
			hanyaUntukAngkatan = "";
		} else if (hanyaUntukAngkatan.equals(",,")) {
			hanyaUntukAngkatan = "";
		} else if (hanyaUntukAngkatan.equals(",,,")) {
			hanyaUntukAngkatan = "";
		}
		return hanyaUntukAngkatan;
	}

