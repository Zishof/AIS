	public static String ambilTunjangans(Date sekarang, List<JabatanStruktural> labatanStrukturals) throws Exception {
		return ambilTunjangans(sekarang, "", labatanStrukturals);
	}

	/**
	 * Titik masuk yang DIPANGGIL LANGSUNG oleh mesin formula gaji ({@code
	 * ItemGajiPegawaiTreeModel}) untuk me-resolve token {@code TUNJ_SRTK_<kode>} — lihat
	 * dokumentasi kelas. Method ini menjumlahkan nilai tunjangan efektif dari {@link #tunjangans}
	 * SETIAP jabatan struktural dalam {@code labatanStrukturals} (biasanya seluruh jabatan
	 * struktural yang sedang dipegang satu pegawai) untuk sub-komponen {@code kode} tertentu pada
	 * tanggal {@code sekarang}, lalu menghasilkan SATU nilai gabungan.
	 *
	 * <p>Untuk setiap jabatan dalam daftar, logika pemilihan entri riwayat efektif IDENTIK dengan
	 * {@link #ambilTunjangan(Date, String)} (parse JSON, filter berdasar kecocokan {@code kode},
	 * urutkan menurun berdasar tanggal, pilih entri efektif terbaru yang tidak melewati
	 * {@code sekarang}) — logikanya diduplikasi inline di sini alih-alih memanggil ulang
	 * {@link #ambilTunjangan(Date, String)} pada instance yang bersangkutan (duplikasi kode, bukan
	 * pemanggilan silang; perubahan pada satu method TIDAK otomatis tercermin di method lain).
	 * Hasil per-jabatan ({@code hasil}, default {@code "0.0"} bila tidak ada entri cocok) kemudian
	 * di-trim; string kosong dilewati (tidak ikut diagregasi), sisanya dicoba
	 * {@code Double.parseDouble}:</p>
	 * <ul>
	 *   <li>Bila BERHASIL diparse sebagai angka, nilainya ditambahkan ke akumulator
	 *   {@code totalHasil} (numerik murni).</li>
	 *   <li>Bila GAGAL diparse ({@code NumberFormatException}, artinya nilai berupa fragmen
	 *   ekspresi seperti {@code "0.05 * GP"}), teksnya diapit {@code "+(" + nilai + ")"} dan
	 *   ditambahkan ke {@link StringBuilder} {@code formulaHasil} terpisah — nilai formula
	 *   dipertahankan sebagai teks alih-alih dipaksa menjadi angka, karena penuh dievaluasi baru
	 *   terjadi belakangan bersama seluruh formula {@code ItemGaji} oleh exp4j di
	 *   {@code ItemGajiPegawaiTreeModel}, bukan di sini.</li>
	 * </ul>
	 * <p>Kegagalan pada SATU jabatan (mis. JSON {@code tunjangans} korup) ditangkap per-iterasi
	 * (blok {@code try/catch} di dalam loop {@code for}): exception dicetak ke stack trace dan
	 * dicatat ke {@code ErrorAuditUtil} dengan label baris kode sumber statis (label ini bersifat
	 * kosmetik pada teks log, tidak lagi presisi menunjuk baris setelah javadoc ini menggeser
	 * nomor baris file), TANPA menghentikan agregasi jabatan lain dalam daftar — satu baris data
	 * korup tidak menggagalkan seluruh perhitungan gaji pegawai yang memegang banyak jabatan.</p>
	 *
	 * <p>Hasil akhir digabung sebagai {@code totalHasil.toString() + formulaHasil.toString()} —
	 * yaitu representasi teks angka total (mis. {@code "150000.0"}) diikuti (bila ada) rangkaian
	 * fragmen formula (mis. {@code "+(0.05 * GP)+(0.02 * GP)"}). String gabungan inilah yang
	 * disubstitusikan ke posisi token {@code TUNJ_SRTK_<kode>} dalam teks formula {@code ItemGaji}
	 * sebelum keseluruhan formula dievaluasi exp4j — sehingga bagian angka murni dan bagian fragmen
	 * formula sama-sama valid secara sintaks sebagai satu ekspresi tunggal saat digabung dengan
	 * bagian formula lain di sekitarnya.</p>
	 *
	 * @param sekarang            tanggal acuan efektif
	 * @param kode                sub-kode komponen tunjangan (dari {@code KodeTunjangan.getKode()});
	 *                            kosong berarti hanya mencocokkan entri riwayat tanpa sub-kode
	 * @param labatanStrukturals daftar jabatan struktural yang nilai tunjangannya dijumlahkan (typo
	 *                            nama parameter dipertahankan dari kode asli)
	 * @return teks gabungan total numerik dan (bila ada) fragmen formula, siap disubstitusi ke
	 *         token formula {@code ItemGaji}
	 */
	public static String ambilTunjangans(Date sekarang, String kode, List<JabatanStruktural> labatanStrukturals)
			throws Exception {
		String s = Common.dateFormat1.get().format(sekarang);
		Double totalHasil = 0.0;
		StringBuilder formulaHasil = new StringBuilder();
		for (JabatanStruktural jabatanStruktural : labatanStrukturals) {
			try {
				JSONArray jsonArray = new JSONArray(jabatanStruktural.getTunjangans());
				TreeMap<String, String> formulas = new TreeMap<String, String>(Collections.reverseOrder());
				for (int i = 0; i < jsonArray.length(); i++) {
					JSONObject jsonObject = jsonArray.getJSONObject(i);
					if (!jsonObject.isNull("tgl") && !jsonObject.isNull("nilai")) {

						String kd = "";
						if (!jsonObject.isNull("kode")) {
							kd = jsonObject.get("kode") + "";
						}
						if ((kd.trim().isEmpty() && kode.trim().isEmpty())
								|| (kode != null && kd.trim().equalsIgnoreCase(kode.trim()))) {
							Date tgl = Common.dateFormat1.get().parse(jsonObject.get("tgl").toString());
							formulas.put(Common.dateFormat8.get().format(tgl), jsonObject.get("nilai") + "");
						}
					}
				}

				String hasil = "0.0";
				for (String ss : formulas.keySet()) {
					Date tanggalEfektif = Common.dateFormat8.get().parse(ss);
					if (tanggalEfektif.before(sekarang) || Common.dateFormat1.get().format(tanggalEfektif).equals(s)) {
						hasil = formulas.get(ss);
						break;
					}
				}
				formulas = null;
				jsonArray = null;

				String nilai = hasil == null ? "" : hasil.trim();
				if (!nilai.isEmpty()) {
					try {
						totalHasil += Double.parseDouble(nilai);
					} catch (NumberFormatException e) {
						formulaHasil.append("+(").append(nilai).append(")");
					}
				}
			} catch (Exception e) {
				e.printStackTrace(); ais.common.ErrorAuditUtil.record(e, "auto-audit src/ais/database/model/employ/JabatanStruktural.java:225");
			}
		}
		return totalHasil.toString() + formulaHasil.toString();
	}

