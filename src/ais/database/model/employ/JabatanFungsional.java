	/**
	 * Titik masuk yang DIPANGGIL LANGSUNG oleh mesin formula gaji ({@code
	 * ItemGajiPegawaiTreeModel}) untuk me-resolve token {@code TUNJ_FUNG_<kode>} — lihat
	 * dokumentasi kelas. Method ini menjumlahkan nilai tunjangan efektif dari {@link #tunjangans}
	 * SETIAP jabatan fungsional dalam {@code jabatanFungsionals} (biasanya seluruh jabatan
	 * fungsional yang sedang dipegang satu pegawai) untuk sub-komponen {@code kode} tertentu pada
	 * tanggal {@code sekarang}, lalu menghasilkan SATU nilai gabungan.
	 *
	 * <p>Alur kerja, duplikasi logika pemilihan entri riwayat efektif (inline, bukan memanggil
	 * ulang {@link #ambilTunjangan(Date, String)} pada instance masing-masing jabatan), agregasi
	 * numerik ke {@code totalHasil} vs. penyimpanan fragmen non-numerik ke {@link StringBuilder}
	 * {@code formulaHasil} lewat {@code "+(" + nilai + ")"}, penanganan galat per-jabatan yang
	 * tidak menghentikan agregasi jabatan lain (dicatat ke {@code ErrorAuditUtil}), serta format
	 * hasil akhir gabungan ({@code totalHasil.toString() + formulaHasil.toString()}) — SEPENUHNYA
	 * IDENTIK dengan {@link JabatanStruktural#ambilTunjangans(Date, String, List)}. Satu-satunya
	 * perbedaan substansial adalah komentar penjelas tambahan pada blok {@code catch
	 * (NumberFormatException e)} di kode sumber kelas ini (menjelaskan bahwa nilai tunjangan boleh
	 * berupa rumus payroll seperti {@code "0.07 * GP"} dan alasan mempertahankannya sebagai teks
	 * alih-alih memaksa menjadi {@link Double} pada tahap agregasi jabatan) — lihat javadoc
	 * {@link JabatanStruktural#ambilTunjangans(Date, String, List)} untuk penjelasan
	 * langkah-demi-langkah lengkap yang berlaku sama persis di sini.
	 *
	 * @param sekarang           tanggal acuan efektif
	 * @param kode                sub-kode komponen tunjangan (dari {@code KodeTunjangan.getKode()});
	 *                            kosong berarti hanya mencocokkan entri riwayat tanpa sub-kode
	 * @param jabatanFungsionals daftar jabatan fungsional yang nilai tunjangannya dijumlahkan
	 * @return teks gabungan total numerik dan (bila ada) fragmen formula, siap disubstitusi ke
	 *         token formula {@code ItemGaji}
	 */
	public static String ambilTunjangans(Date sekarang, String kode, List<JabatanFungsional> jabatanFungsionals)
			throws Exception {
		String s = Common.dateFormat1.get().format(sekarang);
		Double totalHasil = 0.0;
		StringBuilder formulaHasil = new StringBuilder();
		for (JabatanFungsional jabatanFungsional : jabatanFungsionals) {
			try {
				JSONArray jsonArray = new JSONArray(jabatanFungsional.getTunjangans());
				TreeMap<String, String> formulas = new TreeMap<String, String>(Collections.reverseOrder());
				for (int i = 0; i < jsonArray.length(); i++) {
					JSONObject jsonObject = jsonArray.getJSONObject(i);
					if (!jsonObject.isNull("tgl") && !jsonObject.isNull("nilai")) {

						String kd = "";
						if (!jsonObject.isNull("kode")) {
							kd = jsonObject.get("kode") + "";
						}

						if ((kd.trim().isEmpty() && kode.trim().isEmpty())
								|| (kode != null && kd.trim().equalsIgnoreCase(kode.trim()))) {
							Date tgl = Common.dateFormat1.get().parse(jsonObject.get("tgl").toString());
							formulas.put(Common.dateFormat8.get().format(tgl), jsonObject.get("nilai") + "");
						}
					}
				}

				String hasil = "0.0";
				for (String ss : formulas.keySet()) {
					Date tanggalEfektif = Common.dateFormat8.get().parse(ss);
					if (tanggalEfektif.before(sekarang) || Common.dateFormat1.get().format(tanggalEfektif).equals(s)) {
						hasil = formulas.get(ss);
						break;
					}
				}
				formulas = null;
				jsonArray = null;

				String nilai = hasil == null ? "" : hasil.trim();
				if (!nilai.isEmpty()) {
					try {
						totalHasil += Double.parseDouble(nilai);
					} catch (NumberFormatException e) {
						// Nilai tunjangan boleh berupa rumus payroll (mis. "0.07 * GP").
						// Pertahankan rumus agar dievaluasi bersama formula item gaji, bukan
						// memaksanya menjadi Double pada tahap agregasi jabatan.
						formulaHasil.append("+(").append(nilai).append(")");
					}
				}
			} catch (Exception e) {
				e.printStackTrace(); ais.common.ErrorAuditUtil.record(e, "auto-audit src/ais/database/model/employ/JabatanFungsional.java:293");
			}
		}
		return totalHasil.toString() + formulaHasil.toString();
	}

