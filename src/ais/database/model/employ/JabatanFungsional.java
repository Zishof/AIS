	/**
	 * Mengambil SATU nilai tunjangan dari riwayat {@link #tunjangans} yang berlaku efektif pada
	 * tanggal {@code sekarang}, opsional dipersempit ke sub-komponen {@code kode}. Logika,
	 * struktur JSON yang diproses, aturan pencocokan {@code kode} (case-insensitive-trim, kosong
	 * hanya cocok dengan kosong), pemilihan entri efektif TERBARU yang tidak melewati
	 * {@code sekarang} (diurutkan menurun lewat {@link TreeMap} berbasis kunci tanggal
	 * ter-format-ulang {@code Common.dateFormat8}), dan nilai kembalian sebagai {@link String} apa
	 * adanya (bukan {@link Double}, mengizinkan fragmen formula seperti {@code "0.07 * GP"})
	 * SEPENUHNYA IDENTIK dengan {@link JabatanStruktural#ambilTunjangan(Date, String)} — lihat
	 * javadoc method tersebut untuk penjelasan langkah-demi-langkah lengkap. Bila tidak ada entri
	 * yang cocok, method mengembalikan default {@code "0.0"}.
	 *
	 * @param sekarang tanggal acuan efektif
	 * @param kode     sub-kode komponen tunjangan untuk mempersempit pencarian; string kosong/
	 *                 {@code null} berarti hanya mencocokkan entri riwayat yang juga tanpa sub-kode
	 * @return nilai tunjangan sebagai teks (angka atau fragmen formula), atau {@code "0.0"} bila
	 *         tidak ada entri efektif yang cocok
	 */
	public String ambilTunjangan(Date sekarang, String kode) throws Exception {
		String s = Common.dateFormat1.get().format(sekarang);
		JSONArray jsonArray = new JSONArray(getTunjangans());
		TreeMap<String, String> formulas = new TreeMap<String, String>(Collections.reverseOrder());
		for (int i = 0; i < jsonArray.length(); i++) {
			JSONObject jsonObject = jsonArray.getJSONObject(i);
			if (!jsonObject.isNull("tgl") && !jsonObject.isNull("nilai")) {

				String kd = "";
				if (!jsonObject.isNull("kode")) {
					kd = jsonObject.get("kode") + "";
				}

				if ((kd.trim().isEmpty() && kode.trim().isEmpty())
						|| (kode != null && kd.trim().equalsIgnoreCase(kode.trim()))) {
					Date tgl = Common.dateFormat1.get().parse(jsonObject.get("tgl").toString());
					formulas.put(Common.dateFormat8.get().format(tgl), jsonObject.get("nilai") + "");
				}
			}
		}

		String hasil = "0.0";
		for (String ss : formulas.keySet()) {
			Date tanggalEfektif = Common.dateFormat8.get().parse(ss);
			if (tanggalEfektif.before(sekarang) || Common.dateFormat1.get().format(tanggalEfektif).equals(s)) {
				hasil = formulas.get(ss);
				break;
			}
		}
		formulas = null;
		jsonArray = null;
		return hasil;
	}

