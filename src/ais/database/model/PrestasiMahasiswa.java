	/**
	 * Mengembalikan tahun prestasi, <b>diturunkan ulang dari {@link #getTahunAkademik()} setiap
	 * kali dipanggil</b>.
	 *
	 * <p><b>Getter yang menulis — perhatikan baik-baik.</b> Bila field {@code tahunAkademik} tidak
	 * {@code null}, method ini mengurai potongan pertamanya (teks sebelum {@code "/"}, mis.
	 * {@code "2025"} dari {@code "2025/2026"}) lalu <b>menimpa field {@code tahun}</b> — bukan
	 * sekadar mengisi bila kosong. Karena {@code tahun} adalah kolom terpetakan, membaca properti
	 * ini pada entity yang sedang <i>managed</i> dapat menyebabkan {@code UPDATE} pada
	 * {@code flush} berikutnya <b>tanpa ada aksi simpan dari pengguna</b>.</p>
	 *
	 * <p>Konsekuensi lain: nilai yang disetel lewat {@link #setTahun(Integer)} praktis <b>tidak
	 * bertahan</b> begitu {@code tahunAkademik} terisi. Di form, hal ini memang disengaja — kotak
	 * isian "Tahun" dibuat {@code readonly} dan diperbarui otomatis ketika kotak "Tahun Akademik"
	 * diubah.</p>
	 *
	 * <p>Perhatikan pula bahwa pemeriksaan dilakukan atas <b>field</b> {@code tahunAkademik},
	 * bukan lewat {@link #getTahunAkademik()}. Jadi pada object baru yang tahun akademiknya belum
	 * pernah dibaca, method ini melewati perhitungan dan mengembalikan {@code tahun} apa adanya —
	 * urutan pemanggilan getter memengaruhi hasil.</p>
	 *
	 * <p>Kegagalan penguraian (format {@code tahunAkademik} tak terduga) ditelan blok
	 * {@code catch} yang hanya mencatat ke audit kesalahan, dan nilai {@code tahun} sebelumnya
	 * dipertahankan.</p>
	 *
	 * @return tahun prestasi, atau {@code null} bila belum pernah diturunkan maupun disetel
	 */
	public Integer getTahun() {
		if (tahunAkademik != null) {
			try {
				tahun = Integer.parseInt(tahunAkademik.split("/")[0]);
			} catch (Exception e) { ais.common.ErrorAuditUtil.record(e, "auto-audit(empty-catch) src/ais/database/model/PrestasiMahasiswa.java:353");

			}
		}
		return tahun;
	}

