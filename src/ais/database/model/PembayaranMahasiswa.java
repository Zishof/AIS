	/**
	 * Mengembalikan kode unik tagihan (kolom {@code kodeunik}, {@code unique = true},
	 * {@code nullable = false}) — <b>dan sekaligus MENIMPA field {@link #kodeunik} pada objek
	 * ini</b>. Ini getter berefek samping, bukan pembaca murni.
	 *
	 * <p>Perilakunya:</p>
	 * <ul>
	 *   <li>bila {@link #getMahasiswa()}, {@link #getJenisKegiatan()} dan {@link #getSemster()}
	 *   ketiganya terisi → {@code kodeunik} disusun ulang sebagai rangkaian
	 *   {@code idMahasiswa + idJenisKegiatan + semster};</li>
	 *   <li>bila salah satu saja {@code null} → {@code kodeunik} <b>di-set {@code null}</b>.</li>
	 * </ul>
	 *
	 * <p><b>Jebakan 1 — melanggar {@code NOT NULL}.</b> Karena akses Hibernate pada entity ini
	 * bertipe <i>property</i> (anotasi {@code @Id} menempel di getter), Hibernate memanggil method
	 * ini sendiri saat pemeriksaan kotor (<i>dirty checking</i>) dan saat INSERT/UPDATE. Bila objek
	 * dimuat/dibentuk dengan graf tidak lengkap — mis. tagihan <b>calon mahasiswa</b> yang
	 * {@code mahasiswa}-nya memang {@code null} karena kolom {@code calon_mahasiswa} tidak dipetakan
	 * kelas ini, atau baris hasil restore audit yang {@code semster}-nya kosong — maka penyimpanan
	 * akan gagal di level database dengan pesan <i>"null value in column kodeunik violates not-null
	 * constraint"</i>, yang di aplikasi tampil sebagai {@code TransactionException} yang
	 * membingungkan. Kasus PERSIS INI sudah pernah terjadi dan <b>sudah diperbaiki di
	 * {@link Kegiatan#getKodeunik()}</b> dengan fallback {@code Common.getGeneratedBarCode()} —
	 * perbaikan itu <b>tidak pernah disalin ke sini</b>. Dicatat apa adanya; perbaikannya di luar
	 * lingkup pekerjaan dokumentasi ini.</p>
	 *
	 * <p><b>Jebakan 2 — format berbeda untuk baris yang sama.</b> Untuk baris {@code kegiatan} yang
	 * identik, {@link Kegiatan#generateKodeUnik(Mahasiswa, BiodataCalonMahasiswa, JenisKegiatan, Integer, String, Integer)}
	 * menghasilkan {@code "MHS_<idMhs>-<idJenis>-<smt>"} (berawalan, berpemisah), sedangkan method
	 * ini menghasilkan {@code "<idMhs><idJenis><smt>"} — <b>tanpa awalan dan tanpa pemisah apa
	 * pun</b>. Dua akibatnya: (a) menyimpan lewat entity ini akan menimpa kode unik yang formatnya
	 * dicari oleh pencari berbasis {@code Restrictions.eq("kodeunik", ...)} di
	 * {@code KegiatanHelper} dan {@code VOMahasiswa}, sehingga tagihan bisa "hilang" dari
	 * pencarian; (b) tanpa pemisah, kode berbeda dapat bertabrakan — mahasiswa 1/jenis 23/semester 4
	 * dan mahasiswa 12/jenis 3/semester 4 sama-sama menghasilkan {@code "1234"} — padahal kolomnya
	 * {@code unique}, dan nilai inilah yang dijadikan <i>natural key</i> oleh
	 * {@code StudentPaymentWorkflowGenericCrudAdapter}.</p>
	 *
	 * <p>Selama entity ini dipakai hanya untuk MEMBACA (jalur REST {@code lihat_pembayaran}), kedua
	 * jebakan di atas tidak muncul; keduanya baru menggigit pada operasi tulis/ubah, termasuk lewat
	 * dasbor CRUD generik.</p>
	 *
	 * @return kode unik hasil hitung ulang, atau {@code null} bila mahasiswa/jenis kegiatan/semester
	 *         tidak lengkap
	 * @see Kegiatan#getKodeunik()
	 */
	@Column(name = "kodeunik", unique = true, nullable = false)
	public String getKodeunik() {
		if (mahasiswa != null && jenisKegiatan != null && semster != null) {
			kodeunik = "" + mahasiswa.getId() + "" + jenisKegiatan.getId() + "" + semster;
		} else {
			kodeunik = null;
		}
		return kodeunik;
	}

