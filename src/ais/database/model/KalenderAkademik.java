	/**
	 * Mengembalikan label status kegiatan relatif terhadap hari ini — properti <b>turunan</b>,
	 * salah satu dari {@code "Berlangsung"}, {@code "Sudah Selesai"}, {@code "Belum Mulai"}, atau
	 * string kosong.
	 *
	 * <p><b>Getter yang menulis balik ke field (dan karenanya ke database):</b> field
	 * {@code status} selalu dihitung ulang dan ditimpa setiap kali method ini dipanggil.</p>
	 *
	 * <h4>Cara kerja perbandingannya</h4>
	 * <p>Kode ini menggeser <b>dua</b> titik acuan mundur satu hari sekaligus, sehingga terlihat
	 * membingungkan padahal hasil akhirnya wajar:</p>
	 * <ul>
	 *   <li>{@code tglMulai} = {@link #getTanggalMulai()} dikurangi 1 hari (jam 00:00, karena
	 *   kolomnya {@code DATE}).</li>
	 *   <li>{@code tglSelesai} = {@link #getTanggalSelesai()} apa adanya (jam 00:00).</li>
	 *   <li>{@code tglHariIni} = waktu server sekarang dikurangi 1 hari, <b>dengan jam berjalan
	 *   tetap dipertahankan</b>.</li>
	 * </ul>
	 * <p>Setelah kedua pengurangan itu saling meniadakan, kondisinya setara dengan: "berlangsung"
	 * bila sekarang berada setelah {@code tanggalMulai} pukul 00:00 dan sebelum
	 * {@code tanggalSelesai + 1 hari} pukul 00:00 — yakni rentang <b>inklusif</b> di kedua ujung.
	 * Sesudah itu "Sudah Selesai" bila sudah melewati akhir hari {@code tanggalSelesai}, dan
	 * "Belum Mulai" bila belum sampai {@code tanggalMulai}.</p>
	 *
	 * <p><b>Kapan mengembalikan string kosong.</b> Cabang terakhir tercapai hanya pada kesamaan
	 * persis (mis. dijalankan tepat pukul 00:00:00,000 di hari mulai) atau bila rentangnya
	 * terbalik ({@code tanggalSelesai} lebih awal daripada {@code tanggalMulai}) — kelas ini tidak
	 * memvalidasi urutan tanggal. String kosong ini <b>ikut tersimpan</b> ke kolom {@code status}.</p>
	 *
	 * <p><b>Bukan sumber kebenaran gerbang konfigurasi.</b> Label di sini murni untuk tampilan
	 * grid ({@code KalenderAkademikAction}, {@code KalenderAkademikMahasiswaAction},
	 * {@code DasbordKalenderAkademik}). Keputusan aktif/tidaknya konfigurasi dihitung <b>ulang</b>
	 * dan dengan aturan batas yang <b>berbeda</b> di {@link Konfigurasi#getNilai()} (perbandingan
	 * string tanggal) dan di {@code KonfigurasiManager.fetchKonfigurasiKalender} (perbandingan
	 * awal/akhir hari di tingkat SQL). Bila label layar dan perilaku fitur terlihat tidak sinkron
	 * di sekitar tengah malam, ketiga implementasi inilah penyebabnya.</p>
	 *
	 * @return label status berjalan; bisa string kosong pada kasus batas/rentang terbalik
	 * @see #getWarna()
	 */
	public String getStatus() {
		Calendar calendar = ais.ui.util.WaktuUtil.getCalendar();
		calendar.setTime(getTanggalMulai());
		calendar.set(Calendar.DATE, calendar.get(Calendar.DATE) - 1);

		Date tglMulai = calendar.getTime();
		Date tglSelesai = getTanggalSelesai();
		calendar = ais.ui.util.WaktuUtil.getCalendar();
		calendar.set(Calendar.DATE, calendar.get(Calendar.DATE) - 1);
		Date tglHariIni = calendar.getTime();

		status = tglHariIni.before(tglSelesai) && tglHariIni.after(tglMulai) ? "Berlangsung"
				: tglHariIni.after(tglSelesai) ? "Sudah Selesai" : tglHariIni.before(tglMulai) ? "Belum Mulai" : "";

		return status;
	}

