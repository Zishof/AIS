	@OrderBy(value = "kode asc, nama asc")
	@JoinTable(name = "alur_sop_has_dokumen", joinColumns = @JoinColumn(name = "alur_sop"), inverseJoinColumns = @JoinColumn(name = "dokumen"))
	public Set<DokumenAlurSop> getDokumenAlurSops() {
		if (id == null) {
			return dokumenAlurSops == null ? new HashSet<DokumenAlurSop>() : dokumenAlurSops;
		}

		Set<DokumenAlurSop> cached = mapDokumens.get(id);
		if (cached != null) {
			try {
				if (!Hibernate.isInitialized(cached)) {
					dokumenAlurSops = loadDokumenAlurSopDetached(id, ambilSopIdAman());
				} else {
					dokumenAlurSops = filterDokumenAlurSop(cached, ambilSopIdAman());
				}
			} catch (Exception e) {
				dokumenAlurSops = loadDokumenAlurSopDetached(id, ambilSopIdAman());
			}
			mapDokumens.put(id, dokumenAlurSops);
			return dokumenAlurSops;
		}

		try {
			if (dokumenAlurSops != null && !Hibernate.isInitialized(dokumenAlurSops)) {
				dokumenAlurSops = loadDokumenAlurSopDetached(id, ambilSopIdAman());
			} else {
				dokumenAlurSops = filterDokumenAlurSop(dokumenAlurSops, ambilSopIdAman());
			}
		} catch (Exception e) {
			dokumenAlurSops = loadDokumenAlurSopDetached(id, ambilSopIdAman());
		}

		mapDokumens.put(id, dokumenAlurSops);
		return dokumenAlurSops;
	}

