	private Set<DokumenAlurSop> filterDokumenAlurSop(Set<DokumenAlurSop> sumber, Long sopId) {
		Set<DokumenAlurSop> hasil = new TreeSet<DokumenAlurSop>();
		if (sumber == null || sumber.isEmpty()) {
			return hasil;
		}

		java.util.HashSet<Long> idSudahAda = new java.util.HashSet<Long>();
		for (DokumenAlurSop dokumenAlurSop : sumber) {
			if (dokumenAlurSop == null || !Boolean.TRUE.equals(dokumenAlurSop.getAktif())) {
				continue;
			}
			try {
				if (dokumenAlurSop.getId() != null && idSudahAda.contains(dokumenAlurSop.getId())) {
					continue;
				}
				if (sopId != null && dokumenAlurSop.getSop() != null && dokumenAlurSop.getSop().getId() != null
						&& !sopId.equals(dokumenAlurSop.getSop().getId())) {
					continue;
				}
			} catch (Exception e) { ais.common.ErrorAuditUtil.record(e, "auto-audit(empty-catch) src/ais/database/model/sop/AlurSop.java:299");
				// Relasi alur_sop_has_dokumen sudah cukup menjadi dasar bahwa dokumen ini milik alur.
			}
			if (dokumenAlurSop.getId() != null) {
				idSudahAda.add(dokumenAlurSop.getId());
			}
			hasil.add(dokumenAlurSop);
		}
		return hasil;
	}

