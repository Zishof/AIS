	/**
	 * Pusat pengecekan hak akses SOP global.
	 *
	 * Jangan membuat helper serupa di class dashboard/action lain. Semua akses
	 * "melihat semua SOP" harus melewati AktorSop agar perilakunya konsisten
	 * untuk dashboard, menu SOP, daftar disposisi, dan popup detail.
	 *
	 * <p><b>Detail mekanisme:</b> hak "melihat semua SOP" BUKAN properti dari {@code AktorSop}
	 * (kelas ini), melainkan properti hak akses (role) milik {@code tbmuser} itu sendiri, dibaca
	 * lewat {@code tbmuser.hakAkses().getMelihatSemuaSop()}. Bila bernilai {@code true},
	 * pemanggil ({@link #buatCriterion(Tbmuser, boolean, Criteria)} dan
	 * {@link #buatCriterionPengaju(Tbmuser, String)}) langsung mengembalikan kriteria
	 * "selalu benar" ({@code Restrictions.sqlRestriction("true")}), memotong seluruh evaluasi
	 * wewenang berbasis {@code aktorSop} lainnya — sehingga method ini efektif berfungsi
	 * sebagai bypass administratif yang sah (super-akses), bukan celah. Setiap exception yang
	 * terjadi saat mengakses {@code hakAkses()} (mis. {@code NullPointerException} bila relasi
	 * belum ter-load) ditelan (fail-closed: dikembalikan {@code false}, BUKAN dilempar ulang)
	 * dan direkam lewat {@code ErrorAuditUtil.record} — pola fail-closed ini penting: kegagalan
	 * teknis pada pemeriksaan hak akses tidak boleh secara diam-diam berubah menjadi akses
	 * penuh.</p>
	 *
	 * @param tbmuser pengguna yang sedang diperiksa; boleh {@code null} (akan mengembalikan
	 *                {@code false}).
	 * @return {@code true} hanya bila {@code tbmuser} tidak null dan hak aksesnya secara
	 *         eksplisit menyatakan {@code melihatSemuaSop = true}; {@code false} untuk semua
	 *         kasus lain termasuk saat terjadi galat pemeriksaan.
	 */
	public static boolean bolehMelihatSemuaSop(Tbmuser tbmuser) {
		try {
			return tbmuser != null && tbmuser.hakAkses() != null
					&& Boolean.TRUE.equals(tbmuser.hakAkses().getMelihatSemuaSop());
		} catch (Exception e) { ais.common.ErrorAuditUtil.record(e, "auto-audit(empty-catch) src/ais/database/model/sop/AktorSop.java:324");
		}
		return false;
	}

	/**
	 * Criterion pengaju/pemilik data SOP.
	 *
	 * Method ini dipakai untuk entity yang tidak memiliki alias aktorSop, misalnya
	 * DisposisiSop langsung. Jika role boleh melihat semua SOP maka otomatis true.
	 *
	 * <p><b>Detail mekanisme:</b> berbeda dari {@link #buatCriterion(Tbmuser, boolean, Criteria)}
	 * yang menjawab "apakah tbmuser berwenang BERTINDAK sebagai aktor pada langkah ini", method
	 * ini menjawab pertanyaan yang lebih sempit: "apakah tbmuser adalah PENGAJU/PEMILIK baris
	 * data ini". Urutan evaluasi: (1) bila {@link #bolehMelihatSemuaSop(Tbmuser)} true, kembalikan
	 * kriteria selalu-benar; (2) bila {@code tbmuser} berstatus mahasiswa ATAU siswa, cocokkan
	 * field {@code mahasiswa}/{@code siswa} pada entity target (memakai {@code prefix} bila
	 * diberikan, mis. {@code "disposisiSop."}); (3) selain itu, cocokkan field
	 * {@code diajukanOleh} terhadap {@code tbmuser} itu sendiri. Bila {@code tbmuser} null,
	 * kembalikan kriteria selalu-salah (fail-closed — tidak ada pengaju yang cocok dengan
	 * pengguna anonim).</p>
	 *
	 * @param tbmuser pengguna yang sedang diperiksa; boleh {@code null} (menghasilkan kriteria
	 *                selalu-salah).
	 * @param prefix  alias/prefix path Hibernate menuju entity yang memiliki field
	 *                {@code mahasiswa}/{@code siswa}/{@code diajukanOleh} (mis. {@code ""} untuk
	 *                root entity, atau {@code "disposisiSop"} untuk field pada entity yang
	 *                dialiaskan sebagai {@code disposisiSop}); boleh {@code null}/kosong yang
	 *                berarti tanpa prefix.
	 * @return kriteria Hibernate yang bernilai benar bila {@code tbmuser} adalah pengaju/pemilik
	 *         baris yang diperiksa, atau bila {@code tbmuser} berhak melihat semua SOP.
	 */
	public static Criterion buatCriterionPengaju(Tbmuser tbmuser, String prefix) {
		if (bolehMelihatSemuaSop(tbmuser)) {
			return Restrictions.sqlRestriction("true");
		}
		String p = prefix == null || prefix.trim().isEmpty() ? "" : prefix.trim() + ".";
		if (tbmuser != null && (tbmuser.getMahasiswa() != null || tbmuser.getSiswa() != null)) {
			return Restrictions.or(Restrictions.eq(p + "mahasiswa", tbmuser.getMahasiswa()),
					Restrictions.eq(p + "siswa", tbmuser.getSiswa()));
		}
		return tbmuser == null ? Restrictions.sqlRestriction("false") : Restrictions.eq(p + "diajukanOleh", tbmuser);
	}

	/**
	 * Method sentral yang membangun kriteria Hibernate untuk menjawab pertanyaan "apakah
	 * {@code tbmuser} ini berwenang bertindak sebagai {@code aktorSop} pada baris yang sedang
	 * diperiksa (satu {@link AlurSop}/langkah alur)?". Ini adalah SATU-SATUNYA implementasi
	 * resmi evaluasi wewenang berbasis {@code AktorSop} di seluruh codebase — semua pemanggil
	 * (dashboard, listing riwayat, API tampilan) mendelegasikan ke sini alih-alih menduplikasi
	 * logikanya sendiri.
	 *
	 * <p><b>Alur evaluasi, langkah demi langkah:</b></p>
	 * <ol>
	 * <li><b>Fail-closed pada input tidak valid.</b> Bila {@code tbmuser} null atau
	 * {@code tbmuser.getUserId()} null, langsung kembalikan {@code Restrictions.sqlRestriction("false")}
	 * — tidak ada baris yang cocok untuk pengguna anonim/tidak lengkap.</li>
	 * <li><b>Bypass administratif.</b> Bila {@link #bolehMelihatSemuaSop(Tbmuser)} true,
	 * langsung kembalikan kriteria selalu-benar — pengguna dengan hak akses global melihat
	 * segalanya tanpa perlu evaluasi lebih lanjut.</li>
	 * <li><b>Kriteria dasar (role + username).</b> Dibangun kriteria OR antara: (a)
	 * {@code aktorSop.jenisPengguna ILIKE '%,<roleId>,%'} — cocok bila {@code roleId} milik
	 * {@code tbmuser} (dari {@code tbmuser.hakAkses().getRoleId()}, atau string kosong bila
	 * hak akses/role tidak tersedia) terdaftar sebagai salah satu role yang diizinkan aktor
	 * ini; dan (b) {@code aktorSop.usernamePengguna ILIKE '%,<userId>,%'} — cocok bila username
	 * {@code tbmuser} terdaftar secara eksplisit. Kegagalan membaca {@code hakAkses()} ditelan
	 * (fail-closed ke {@code roleId=""}) dan direkam via {@code ErrorAuditUtil}.</li>
	 * <li><b>Evaluasi Pegawai</b> (bila {@code tbmuser.getPegawai() != null}): jika parameter
	 * {@code criteria} (objek {@link Criteria} Hibernate yang SEDANG DIBANGUN oleh pemanggil)
	 * disediakan, method ini men-JOIN langsung ke {@code criteria} tersebut — membuat alias
	 * {@code diajukanOlehData}/{@code pegawaiData} untuk menavigasi ke data pegawai PENGAJU
	 * (subjek baris yang diperiksa, BUKAN {@code tbmuser} yang sedang login) — lalu menambahkan
	 * dua sub-kriteria relasional: (a) <i>atasan pejabat</i> — mengumpulkan seluruh
	 * {@link ais.database.model.employ.JenisJabatan} milik {@link Pejabat} aktif yang
	 * {@code pegawai}-nya adalah {@code tbmuser} sendiri (menandakan {@code tbmuser} MENJABAT
	 * posisi tersebut), lalu mencocokkan apakah jenis jabatan itu tercatat sebagai
	 * {@code atasan}/{@code atasanPendukung}/{@code atasanPendukungCadangan} milik pegawai
	 * PENGAJU, DIKUNCI oleh flag {@link #semuaAtasanPejabat} bernilai true; (b) <i>atasan
	 * langsung</i> — mencocokkan field {@code atasanlangsung}/{@code atasanlangsung2}/
	 * {@code atasanlangsung3} milik pegawai pengaju terhadap {@code tbmuser.getPegawai()}
	 * secara langsung, DIKUNCI oleh flag {@link #semuaAtasanLangsungPegawai}, ATAU flag
	 * {@link #semuaPegawai} bernilai true (yang meloloskan SEMUA pegawai tanpa syarat
	 * relasional). Bila {@code criteria} TIDAK disediakan (null), method mundur ke evaluasi
	 * yang jauh lebih longgar: hanya mengecek {@link #semuaPegawai} true, TANPA pengecekan
	 * relasi atasan sama sekali (karena join yang dibutuhkan tidak tersedia tanpa
	 * {@code criteria}) — pemanggil yang tidak menyediakan {@code criteria} rinci akan
	 * mendapat hasil yang secara sengaja lebih permisif untuk flag {@code semuaPegawai} namun
	 * TIDAK PERNAH true untuk skenario atasan (pejabat/langsung), sehingga kriteria menjadi
	 * lebih SEMPIT untuk kasus tersebut dibanding varian dengan {@code criteria} lengkap.</li>
	 * <li><b>Evaluasi Guru</b>: hanya mengecek {@link #semuaGuru} true; tidak ada sub-relasi
	 * guru-spesifik seperti pada pegawai/dosen.</li>
	 * <li><b>Evaluasi Dosen</b> (bila {@code tbmuser.getDosen() != null}): dengan
	 * {@code criteria}, di-JOIN ke {@code mahasiswa}/{@code jurusan_mahasiswa}/
	 * {@code fakultas_mahasiswa} milik subjek baris, lalu dicocokkan tiga peran relasional:
	 * {@link #semuaDosen} (longgar, semua dosen), {@code mahasiswa.dosenPa == tbmuser.getDosen()}
	 * DIKUNCI {@link #dosenPaPengajuMahasiswa}, {@code jurusan.kaprodi == tbmuser.getDosen()}
	 * DIKUNCI {@link #kaprodiPengajuMahasiswa}, dan {@code fakultas.dekan == tbmuser.getDosen()}
	 * DIKUNCI {@link #dekanPengajuMahasiswa}. Tanpa {@code criteria}, mundur ke evaluasi
	 * {@link #semuaDosen} saja (pola fallback yang sama seperti pada evaluasi Pegawai).</li>
	 * <li><b>Evaluasi Siswa &amp; Mahasiswa</b>: masing-masing hanya mengecek
	 * {@link #semuaSiswa}/{@link #semuaMahasiswa} — sesederhana evaluasi Guru, tidak ada
	 * sub-relasi granular seperti Pegawai/Dosen (mis. tidak ada analog "wali kelas siswa" di
	 * sini).</li>
	 * <li><b>Penelusuran mundur ke disposisi sebelumnya</b> (hanya bila
	 * {@code cariKeDisposisiAlurSop} true): menambahkan kriteria tambahan yang mencocokkan
	 * {@code sebelumnya.usernamePengguna ILIKE '%;<userId>;%'} — perhatikan PEMISAHnya adalah
	 * TITIK KOMA ({@code ;}), BUKAN KOMA seperti kriteria lain di method ini; ini menandakan
	 * {@code sebelumnya.usernamePengguna} berasal dari sumber/format yang berbeda dari
	 * {@link #usernamePengguna} milik {@code AktorSop} (kemungkinan field pada
	 * {@link AlurSop}/{@link DisposisiAlurSop} dengan konvensi pemisah sendiri) — WASPADAI
	 * inkonsistensi format pemisah ini bila mengubah salah satu sisi tanpa yang lain.</li>
	 * </ol>
	 *
	 * <p><b>Implikasi untuk investigasi bypass-persetujuan:</b> seluruh logika di atas — sekuat
	 * dan serinci apa pun — HANYA bermakna bila benar-benar dipanggil di titik yang tepat.
	 * Penelusuran seluruh pemanggil method ini (lihat javadoc kelas {@link AktorSop} untuk
	 * daftar lengkap) menunjukkan seluruhnya berada di jalur QUERY/LISTING, bukan di titik
	 * mutasi ({@code DisposisiAlurSopAction.onSave}/{@code DisposisiSopAction.onSave}). Method
	 * ini sendiri TIDAK MEMILIKI cacat logika yang teridentifikasi — ia adalah "kunci" yang utuh
	 * dan berfungsi; masalahnya ada pada "pintu" (titik mutasi) yang tidak pernah menguncinya.</p>
	 *
	 * @param tbmuser               pengguna yang wewenangnya sedang diperiksa.
	 * @param cariKeDisposisiAlurSop bila {@code true}, tambahkan kriteria kecocokan terhadap
	 *                                {@code sebelumnya.usernamePengguna} (lihat langkah 8 di
	 *                                atas); dipakai pada query yang perlu menjangkau langkah
	 *                                disposisi sebelumnya dalam satu alur.
	 * @param criteria              objek {@link Criteria} Hibernate yang sedang dibangun oleh
	 *                               pemanggil, dipakai untuk menambahkan alias JOIN yang
	 *                               dibutuhkan evaluasi relasional granular (atasan pejabat/
	 *                               langsung, kaprodi/dekan/dosen-PA); boleh {@code null} — bila
	 *                               null, evaluasi Pegawai dan Dosen MUNDUR ke bentuk yang lebih
	 *                               sempit (hanya flag "semua X", tanpa sub-relasi granular;
	 *                               lihat langkah 4 dan 6 di atas).
	 * @return kriteria Hibernate (kombinasi OR dari seluruh kondisi yang berlaku) yang bernilai
	 *         benar bila {@code tbmuser} berwenang sebagai {@code aktorSop} pada baris yang
	 *         diperiksa.
	 */
	public static Criterion buatCriterion(Tbmuser tbmuser, boolean cariKeDisposisiAlurSop, Criteria criteria) {
		if (tbmuser == null || tbmuser.getUserId() == null) {
			return Restrictions.sqlRestriction("false");
		}
		if (bolehMelihatSemuaSop(tbmuser)) {
			return Restrictions.sqlRestriction("true");
		}

		String roleId = null;
		try {
			roleId = tbmuser.hakAkses() == null ? null : tbmuser.hakAkses().getRoleId();
		} catch (Exception e) { ais.common.ErrorAuditUtil.record(e, "auto-audit(empty-catch) src/ais/database/model/sop/AktorSop.java:358");
		}
		if (roleId == null || roleId.trim().isEmpty()) {
			roleId = "";
		}

		// Kriteria Dasar Pengguna
		Criterion criterion = Restrictions.or(
				Restrictions.ilike("aktorSop.jenisPengguna", "," + roleId.trim() + ",", MatchMode.ANYWHERE),
				Restrictions.ilike("aktorSop.usernamePengguna", "," + tbmuser.getUserId() + ",", MatchMode.ANYWHERE));

		// Evaluasi Pegawai
		if (tbmuser.getPegawai() != null) {
			if (criteria != null) {
				criteria.createAlias("disposisiSop.diajukanOleh", "diajukanOlehData", Criteria.LEFT_JOIN)
						.createAlias("diajukanOlehData.pegawai", "pegawaiData", Criteria.LEFT_JOIN);

				List<JenisJabatan> jenisJabatans = new ArrayList<JenisJabatan>();
				for (Object o : ConstantValues.ambilBerdasarClass(Pejabat.class).values()) {
					try {
						Pejabat pejabat = (Pejabat) o;
						// Penambahan null check pada aktif untuk mencegah NullPointerException
						if (pejabat != null && pejabat.getPegawai() != null && pejabat.getAktif() != null
								&& pejabat.getAktif() && pejabat.getJenisJabatan() != null
								&& pejabat.getPegawai().getId().equals(tbmuser.getPegawai().getId())) {

							jenisJabatans.add(pejabat.getJenisJabatan());
						}
					} catch (Exception e) { ais.common.ErrorAuditUtil.record(e, "auto-audit(empty-catch) src/ais/database/model/sop/AktorSop.java:386");
						// Teruskan eksekusi
					}
				}

				Criterion atasanPejabatCrit = jenisJabatans
						.isEmpty()
								? Restrictions.sqlRestriction("false")
								: Restrictions.and(
										Restrictions.or(Restrictions.in("pegawaiData.atasan", jenisJabatans),
												Restrictions.or(
														Restrictions.in("pegawaiData.atasanPendukung", jenisJabatans),
														Restrictions.in("pegawaiData.atasanPendukungCadangan",
																jenisJabatans))),
										Restrictions.eq("aktorSop.semuaAtasanPejabat", true));

				Criterion atasanLangsungCrit = Restrictions.or(Restrictions.eq("aktorSop.semuaPegawai", true),
						Restrictions.or(
								Restrictions.and(Restrictions.eq("pegawaiData.atasanlangsung", tbmuser.getPegawai()),
										Restrictions.eq("aktorSop.semuaAtasanLangsungPegawai", true)),
								Restrictions.or(
										Restrictions.and(
												Restrictions.eq("pegawaiData.atasanlangsung2", tbmuser.getPegawai()),
												Restrictions.eq("aktorSop.semuaAtasanLangsungPegawai", true)),
										Restrictions.and(
												Restrictions.eq("pegawaiData.atasanlangsung3", tbmuser.getPegawai()),
												Restrictions.eq("aktorSop.semuaAtasanLangsungPegawai", true)))));

				criterion = Restrictions.or(criterion, Restrictions.or(atasanPejabatCrit, atasanLangsungCrit));
			} else {
				criterion = Restrictions.or(criterion, Restrictions.eq("aktorSop.semuaPegawai", true));
			}
		}

		// Evaluasi Guru
		if (tbmuser.getGuru() != null) {
			criterion = Restrictions.or(criterion, Restrictions.eq("aktorSop.semuaGuru", true));
		}

		// Evaluasi Dosen
		if (tbmuser.getDosen() != null) {
			if (criteria != null) {
				criteria.createAlias("disposisiSop.mahasiswa", "mahasiswa", Criteria.LEFT_JOIN)
						.createAlias("mahasiswa.jurusan", "jurusan_mahasiswa", Criteria.LEFT_JOIN)
						.createAlias("jurusan_mahasiswa.fakultas", "fakultas_mahasiswa", Criteria.LEFT_JOIN);

				Criterion dosenCrit = Restrictions.or(
						Restrictions.or(
								Restrictions.or(Restrictions.eq("aktorSop.semuaDosen", true),
										Restrictions.and(Restrictions.eq("mahasiswa.dosenPa", tbmuser.getDosen()),
												Restrictions.eq("aktorSop.dosenPaPengajuMahasiswa", true))),
								Restrictions.and(Restrictions.eq("jurusan_mahasiswa.kaprodi", tbmuser.getDosen()),
										Restrictions.eq("aktorSop.kaprodiPengajuMahasiswa", true))),
						Restrictions.and(Restrictions.eq("fakultas_mahasiswa.dekan", tbmuser.getDosen()),
								Restrictions.eq("aktorSop.dekanPengajuMahasiswa", true)));
				criterion = Restrictions.or(criterion, dosenCrit);

			} else {
				criterion = Restrictions.or(criterion, Restrictions.eq("aktorSop.semuaDosen", true));
			}
		}

		// Evaluasi Siswa & Mahasiswa
		if (tbmuser.getSiswa() != null) {
			criterion = Restrictions.or(criterion, Restrictions.eq("aktorSop.semuaSiswa", true));
		}
		if (tbmuser.getMahasiswa() != null) {
			criterion = Restrictions.or(criterion, Restrictions.eq("aktorSop.semuaMahasiswa", true));
		}

		// Evaluasi Ke Disposisi Alur Sop Sebelumnya
		if (cariKeDisposisiAlurSop) {
			criterion = Restrictions.or(criterion, Restrictions.ilike("sebelumnya.usernamePengguna",
					";" + tbmuser.getUserId() + ";", MatchMode.ANYWHERE));
		}

		return criterion;
	}
