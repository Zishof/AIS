	/**
	 * Mengembalikan pengenal unik objek di sisi DSpace, dinormalkan menjadi string kosong bila
	 * {@code null} dan dipangkas spasi tepinya.
	 *
	 * <p>
	 * Inilah inti dari seluruh entitas: uuid yang menghubungkan satu objek AIS dengan padanannya di
	 * DSpace. Normalisasi ke string kosong disengaja agar alur pemrosesan dapat langsung memanggil
	 * pemeriksaan kosong tanpa penjagaan {@code null}; efek sampingnya, pemanggil tidak dapat
	 * membedakan "belum pernah tersinkron" dari "tersinkron dengan uuid kosong".
	 * </p>
	 *
	 * <p>
	 * Uuid yang tersimpan <b>tidak dijamin masih berlaku</b>: objek dapat dihapus di sisi DSpace tanpa
	 * sepengetahuan AIS (lihat {@link #delete(String, String, String)}). Karena itu setiap alur
	 * pemrosesan selalu memverifikasi keberadaannya sebelum memutuskan membuat atau memperbarui.
	 * </p>
	 *
	 * @return uuid objek di DSpace; tidak pernah {@code null}
	 */
	@Column(name = "uuid_", nullable = true, length = 50)
	public String getUuid() {
		return uuid == null ? "" : uuid.trim();
	}

