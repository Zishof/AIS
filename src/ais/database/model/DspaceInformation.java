	/**
	 * Mengambil baris pemetaan yang sudah ada, atau <b>membuatnya bila belum ada</b> — dengan
	 * penanganan perlombaan penulisan paralel.
	 *
	 * <h4>Cara kerja</h4>
	 * <p>
	 * Method mencari baris berdasarkan nama kelas dan id objek. Bila ketemu, baris itu dikembalikan.
	 * Bila tidak, baris baru dibentuk dan disimpan pada transaksi tersendiri. Seluruh langkah itu
	 * diulang <b>sampai dua kali</b>: bila penyimpanan gagal karena pelanggaran batasan keunikan —
	 * pertanda proses lain baru saja membuat baris yang sama — transaksi dibatalkan dan pencarian
	 * diulang pada sesi baru, yang kali ini akan menemukan baris milik pemenang perlombaan. Galat
	 * jenis lain dilempar apa adanya tanpa diulang.
	 * </p>
	 *
	 * <p>
	 * Perhatikan bahwa method memakai sesi Hibernate <b>tersendiri</b> beserta transaksinya sendiri,
	 * bukan sesi yang sedang berjalan. Ini disengaja: pembuatan baris pemetaan harus tetap tersimpan
	 * meski transaksi bisnis yang memanggilnya kemudian dibatalkan.
	 * </p>
	 *
	 * <h4>Peringatan: id pendamping ditulis tetapi tidak dicari</h4>
	 * <p>
	 * Kriteria pencarian <b>hanya</b> memakai nama kelas dan id objek — {@code refIdLagi} sengaja
	 * dikeluarkan, karena kunci unik tabel dibentuk dari kedua unsur itu saja (lihat
	 * {@link #getKodeUnik()}). Menyertakan id pendamping dalam pencarian dulu membuat baris yang
	 * sebenarnya sudah ada tidak ditemukan, sehingga penyisipan kedua melanggar batasan keunikan.
	 * </p>
	 * <p>
	 * Konsekuensi yang tersisa: id pendamping tetap <b>disimpan</b> pada baris yang baru dibuat,
	 * tetapi pemanggilan kedua dengan pendamping berbeda akan mengembalikan baris pertama beserta
	 * pendamping lamanya. Dengan kata lain, <b>satu objek AIS hanya dapat memiliki satu pemetaan</b>,
	 * dan id pendamping bersifat informatif belaka. Bila benar-benar memerlukan dua pemetaan untuk
	 * satu objek, gunakan penanda pembalikan id pada
	 * {@link #dspaceProcess(String, GeneralValueObject, GeneralValueObject, String, String, boolean, String, String, String, Boolean)}.
	 * </p>
	 *
	 * @param nama       nama kelas objek AIS yang dipetakan
	 * @param refId      id objek AIS; boleh {@code null}
	 * @param refIdLagi  id objek pendamping; disimpan tetapi tidak ikut dicari
	 * @return baris pemetaan; tidak pernah {@code null}
	 * @throws IllegalStateException bila baris tidak dapat dibuat setelah pengulangan
	 */
	public static DspaceInformation getDspaceInformation(String nama, Long refId, Long refIdLagi) {
		RuntimeException errorTerakhir = null;
		for (int percobaan = 0; percobaan < 2; percobaan++) {
			Session session = null;
			org.hibernate.Transaction transaksi = null;
			try {
				session = HibernateUtil.openSession();
				/*
				 * Unique key tabel dibentuk oleh refId + nama (lihat getKodeUnik), bukan
				 * refIdLagi. Kriteria lama memasukkan refIdLagi sehingga baris yang sebenarnya
				 * sudah ada tidak ditemukan lalu INSERT kedua melanggar unique constraint.
				 */
				DspaceInformation data = (DspaceInformation) session.createCriteria(DspaceInformation.class)
						.add(Restrictions.eq("nama", nama))
						.add(refId == null ? Restrictions.isNull("refId") : Restrictions.eq("refId", refId))
						.setMaxResults(1).uniqueResult();
				if (data != null) {
					return data;
				}
				data = new DspaceInformation();
				data.setRefId(refId);
				data.setRefIdLagi(refIdLagi);
				data.setNama(nama);
				transaksi = session.beginTransaction();
				session.save(data);
				transaksi.commit();
				transaksi = null;
				return data;
			} catch (org.hibernate.exception.ConstraintViolationException e) {
				errorTerakhir = e;
				if (transaksi != null && transaksi.isActive()) {
					try { transaksi.rollback(); } catch (Exception ignored) { }
				}
				// INSERT paralel memenangkan unique key; ulangi SELECT pada session baru.
			} catch (RuntimeException e) {
				if (transaksi != null && transaksi.isActive()) {
					try { transaksi.rollback(); } catch (Exception ignored) { }
				}
				throw e;
			} finally {
				HibernateUtil.closeSessionQuietly(session);
			}
		}
		throw errorTerakhir == null ? new IllegalStateException("Data DSpace tidak dapat dibuat") : errorTerakhir;
	}

	/**
	 * Menyimpan baris pemetaan pada sesi dan transaksi Hibernate <b>tersendiri</b>.
	 *
	 * <p>
	 * Pemakaian sesi terpisah disengaja agar hasil interaksi dengan DSpace tetap tercatat meski
	 * transaksi bisnis pemanggil kemudian dibatalkan — kehilangan uuid berarti kehilangan jejak objek
	 * yang sudah terlanjur dibuat di sisi DSpace, dan itu akan menghasilkan duplikat pada pemanggilan
	 * berikutnya.
	 * </p>
	 *
	 * <p>
	 * Transaksi dibatalkan bila terjadi galat, lalu galatnya dilempar ulang; sesi selalu ditutup pada
	 * blok penutup.
	 * </p>
	 *
	 * @param data baris pemetaan yang disimpan
	 */
	private static void simpanInformasi(DspaceInformation data) {
		Session session = null;
		org.hibernate.Transaction transaksi = null;
		try {
			session = HibernateUtil.openSession();
			transaksi = session.beginTransaction();
			session.saveOrUpdate(data);
			transaksi.commit();
			transaksi = null;
		} catch (RuntimeException e) {
			if (transaksi != null && transaksi.isActive()) {
				try { transaksi.rollback(); } catch (Exception ignored) { }
			}
			throw e;
		} finally {
			HibernateUtil.closeSessionQuietly(session);
		}
	}

