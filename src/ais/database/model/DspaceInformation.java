	private String postInfo;

	/**
	 * Kunci unik pemetaan berbentuk gabungan id objek dan nama kelas. Field ini tidak pernah
	 * dipercaya — {@link #getKodeUnik()} merakitnya ulang pada setiap pembacaan.
	 */
	private String kodeUnik;

	/**
	 * Menyerap jawaban JSON dari DSpace ke dalam baris pemetaan.
	 *
	 * <p>
	 * (Nama method mengandung salah ketik yang sudah telanjur dipakai lintas modul; dibiarkan apa
	 * adanya demi kesinambungan.)
	 * </p>
	 *
	 * <h4>Yang diambil</h4>
	 * <ul>
	 * <li><b>uuid</b> — diambil wajib. Bila kunci ini tidak ada pada jawaban, method melempar galat,
	 * sehingga jawaban yang tidak sesuai bentuk tidak akan menghasilkan pemetaan setengah jadi.</li>
	 *
	 * <li><b>tautan</b> — diambil dari kunci tautan pengambilan berkas bila ada, kalau tidak dari
	 * kunci pegangan, dan bila keduanya tidak ada diisi string kosong. Urutan ini mencerminkan dua
	 * bentuk sumber daya DSpace: berkas memiliki tautan pengambilan, sedangkan butir metadata memiliki
	 * pegangan permanen.</li>
	 *
	 * <li><b>keterangan</b> — diisi <b>seluruh jawaban JSON apa adanya</b>. Kolom ini karena itu
	 * berfungsi sebagai arsip mentah jawaban DSpace, berguna untuk penelusuran ketika terjadi
	 * ketidakcocokan.</li>
	 * </ul>
	 *
	 * <p>
	 * Method menulis langsung ke field tanpa melewati setter, sehingga tidak ada normalisasi maupun
	 * penjagaan tambahan yang berlaku.
	 * </p>
	 *
	 * @param jsonObject jawaban JSON dari DSpace
	 * @throws Exception bila jawaban tidak memuat uuid
	 */
	public void putJosnObject(JSONObject jsonObject) throws Exception {
		uuid = jsonObject.getString("uuid");
		link = !jsonObject.isNull("retrieveLink") ? jsonObject.getString("retrieveLink")
				: !jsonObject.isNull("handle") ? jsonObject.getString("handle") : "";
		keterangan = jsonObject.toString();
	}

