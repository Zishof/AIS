	/**
	 * Mengembalikan <b>nama kelas Java</b> objek AIS yang dipetakan, dengan spasi tepi dipangkas.
	 *
	 * <p>
	 * Meski namanya "nama", kolom ini bukan judul melainkan penanda jenis: ia berisi nama kelas yang
	 * memenuhi syarat lengkap, hasil pemanggilan atas objek sumber. Bersama {@link #getRefId()} ia
	 * membentuk kunci unik pemetaan (lihat {@link #getKodeUnik()}).
	 * </p>
	 *
	 * <p>
	 * Konsekuensi yang perlu diketahui: karena identitas pemetaan bertumpu pada <b>nama kelas dalam
	 * bentuk teks</b>, <b>memindahkan atau mengganti nama kelas entitas akan memutus seluruh
	 * pemetaan</b> objek jenis itu — baris lama menjadi yatim dan objek yang sama akan dikirim ulang
	 * ke DSpace sebagai objek baru. Tidak ada mekanisme migrasi untuk keadaan tersebut.
	 * </p>
	 *
	 * @return nama kelas objek yang dipetakan; {@code null} bila belum diisi
	 */
	@Column(name = "nama", nullable = false, length = 255)
	public String getNama() {
		return this.nama == null ? null : this.nama.trim();
	}

