	/**
	 * Mengembalikan <b>kunci unik pemetaan</b>, yaitu gabungan id objek dan nama kelas yang dipisah
	 * tanda hubung.
	 *
	 * <h4>Getter ini bermutasi</h4>
	 * <p>
	 * Nilai <b>dihitung ulang dan ditugaskan ke field pada setiap pemanggilan</b>. Field yang
	 * tersimpan tidak pernah dipercaya. Karena kolomnya diberi batasan keunikan pada tingkat basis
	 * data, kombinasi ini pula yang menegakkan aturan "satu objek AIS hanya boleh punya satu
	 * pemetaan" — dan yang memicu pelanggaran batasan yang ditangani
	 * {@link #getDspaceInformation(String, Long, Long)} ketika dua proses berlomba.
	 * </p>
	 *
	 * <h4>Dua kehalusan</h4>
	 * <ul>
	 * <li><b>Perakitan memakai field mentah, bukan getter.</b> Nama kelas diambil langsung dari field
	 * tanpa pemangkasan spasi, sedangkan {@link #getNama()} memangkasnya. Bila kolom nama pernah
	 * tersimpan dengan spasi tepi, kunci unik yang dihasilkan akan berbeda dari yang diperkirakan
	 * seseorang yang membacanya lewat getter.</li>
	 *
	 * <li><b>Id pendamping tidak ikut.</b> Inilah alasan struktural mengapa satu objek AIS hanya dapat
	 * memiliki satu pemetaan, dan mengapa id pendamping tidak dapat dipakai untuk memisahkan dua
	 * pemetaan. Lihat pembahasan pada {@link #getDspaceInformation(String, Long, Long)}.</li>
	 * </ul>
	 *
	 * <p>
	 * Sebagai getter yang bermutasi, method ini juga dapat menandai entitas kotor bila dipanggil pada
	 * objek yang masih terikat sesi Hibernate — pola yang sama seperti yang tersebar di paket
	 * {@code ais.database.model}. Untungnya nilai hasil perhitungannya hampir selalu identik dengan
	 * yang tersimpan, sehingga dampak praktisnya kecil.
	 * </p>
	 *
	 * @return kunci unik berbentuk {@code <refId>-<namaKelas>}
	 */
	@Column(unique = true)
	public String getKodeUnik() {
		kodeUnik = refId + "-" + nama;
		return kodeUnik;
	}

