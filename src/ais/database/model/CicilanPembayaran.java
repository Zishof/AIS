	/**
	 * Mengembalikan tanggal jatuh tempo tagihan yang dibayar cicilan ini (bandingkan dengan
	 * {@link #getTanggal()} yang merupakan tanggal uang benar-benar masuk).
	 *
	 * <p><b>Getter ini menghitung ulang dan menulis balik</b> — tetapi hanya bila SEMUA syarat
	 * berikut terpenuhi: {@code pengaturanPembayaranBulanan} terisi <i>dan</i> menyalakan flag
	 * {@link PengaturanPembayaranBulanan#getTanggalTagihanSelaluDibuatAwalBulan()},
	 * {@code kegiatan} terisi, dan {@code kegiatan.getTahunAkademik()} tidak {@code null}. Dalam
	 * kondisi itu jatuh tempo dipaksa ke <b>tanggal 1 pukul 07:00:00</b> pada bulan
	 * {@link PengaturanPembayaranBulanan#getRealBulan()}, dengan tahun ditentukan dari tahun
	 * akademik berformat {@code "2025/2026"}:</p>
	 * <ul>
	 *   <li>semester genap dan bulan riil &lt; 10 → paruh kedua tahun akademik ({@code "2026"});</li>
	 *   <li>semester ganjil dan bulan riil &gt; 5 → paruh pertama ({@code "2025"});</li>
	 *   <li>selain itu → paruh kedua. Cabang {@code else} ini menghasilkan nilai yang sama dengan
	 *   cabang pertama, jadi efektifnya hanya kasus "ganjil dan bulan &gt; 5" yang memakai paruh
	 *   pertama.</li>
	 * </ul>
	 *
	 * <p>Bila salah satu syarat tidak terpenuhi, nilai kolom {@code tanggal_tagihan} yang
	 * tersimpan dikembalikan apa adanya (bisa {@code null}).</p>
	 *
	 * <p><b>Catatan risiko (tidak diperbaiki, hanya dicatat):</b> tidak ada penjagaan
	 * {@code null}/format pada {@code kegiatan.getSemster()} maupun pada hasil
	 * {@code getTahunAkademik().split("/")}. Data kegiatan dengan semester kosong atau tahun
	 * akademik yang tidak memuat garis miring akan membuat method ini melempar
	 * {@code NullPointerException} / {@code ArrayIndexOutOfBoundsException} — dan berbeda dengan
	 * getter lain di kelas ini, di sini tidak ada {@code try/catch} penyelamat.</p>
	 *
	 * @return tanggal jatuh tempo, atau {@code null} bila belum pernah disetel/dihitung
	 */
	@Temporal(TemporalType.TIMESTAMP)
	@Column(name = "tanggal_tagihan", nullable = true)
	public Date getTanggalTagihan() {

		if (pengaturanPembayaranBulanan != null && pengaturanPembayaranBulanan.getTanggalTagihanSelaluDibuatAwalBulan()
				&& kegiatan != null && kegiatan.getTahunAkademik() != null) {

			int tahun = 0;
			if (kegiatan.getSemster() % 2 == 0 && pengaturanPembayaranBulanan.getRealBulan() < 10) {
				tahun = Integer.parseInt(kegiatan.getTahunAkademik().split("/")[1]);
			} else if (kegiatan.getSemster() % 2 == 1 && pengaturanPembayaranBulanan.getRealBulan() > 5) {
				tahun = Integer.parseInt(kegiatan.getTahunAkademik().split("/")[0]);
			} else {
				tahun = Integer.parseInt(kegiatan.getTahunAkademik().split("/")[1]);
			}

			Calendar calendar = ais.ui.util.WaktuUtil.getCalendar();
			calendar.set(Calendar.YEAR, tahun);
			calendar.set(Calendar.MONTH, pengaturanPembayaranBulanan.getRealBulan() - 1);
			calendar.set(Calendar.DATE, 1);
			calendar.set(Calendar.HOUR_OF_DAY, 7);
			calendar.set(Calendar.MINUTE, 0);
			calendar.set(Calendar.SECOND, 0);
			tanggalTagihan = calendar.getTime();
		}

		return tanggalTagihan;
	}

