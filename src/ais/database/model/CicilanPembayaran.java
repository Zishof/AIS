	/**
	 * Mengembalikan deskripsi cicilan yang tampil pada kwitansi, daftar riwayat pembayaran, dan
	 * kolom pencarian window revisi.
	 *
	 * <p><b>Getter ini menulis balik.</b> Bila {@code keterangan} masih kosong, method merakit
	 * kalimat deskripsi dan <b>menyimpannya ke field</b> — jadi pada flush berikutnya teks itu
	 * ikut tersimpan ke database dan tercatat sebagai revisi Envers baru. Bila {@code keterangan}
	 * sudah terisi, nilai lama dipertahankan apa adanya (deskripsi tidak pernah dihitung ulang,
	 * sehingga teks lama bisa "basi" terhadap nominal yang belakangan berubah).</p>
	 *
	 * <p>Dua bentuk kalimat yang mungkin dirakit:</p>
	 * <ol>
	 *   <li><b>Tagihan bulanan/angsuran</b> (bila {@code pengaturanPembayaranBulanan} terisi):
	 *   {@code "<kode>-<nama item biaya>, bulan <namaBulan> , nominal Rp. <nilai>"} diikuti
	 *   potongan opsional validator, denda, dan tagihan sebelum denda.</li>
	 *   <li><b>Tagihan biasa</b> (bila hanya {@code itemBiaya} yang tersedia):
	 *   {@code "<kode>-<nama item biaya>, nominal Rp. <nilai>"} dengan potongan opsional yang
	 *   sama.</li>
	 * </ol>
	 *
	 * <p>Efek samping lain dan kejanggalan yang perlu diketahui:</p>
	 * <ul>
	 *   <li>Baris pertama method memanggil {@link #getItemBiaya()} dan menugaskannya ke field,
	 *   sehingga seluruh efek samping getter itu ikut terjadi.</li>
	 *   <li>Cabang bulanan menelusuri {@code pengaturanPembayaranBulanan.getDetailBiaya()
	 *   .getItemBiaya()} — rantai lazy yang rawan {@code LazyInitializationException} pada
	 *   instance canonical/detached. Karena itu seluruh perakitan dibungkus {@code try/catch};
	 *   bila gagal, {@code keterangan} tetap kosong dan method mengembalikan {@code null}
	 *   ketimbang melempar exception ke layar keuangan.</li>
	 *   <li>Potongan validator memakai {@link #getValidator()}, yang bila {@code kegiatan} terisi
	 *   mewarisi {@link Kegiatan#getValidator()} — dan getter induk itu mengembalikan
	 *   {@code "-"} (bukan string kosong) ketika validator belum diisi. Akibatnya syarat
	 *   {@code getValidator().trim().isEmpty()} praktis tidak pernah benar, dan deskripsi
	 *   umumnya selalu memuat {@code ", validator : -"}.</li>
	 *   <li>Pemisah pada cabang bulanan menghasilkan spasi ganda sebelum koma
	 *   ({@code "bulan Januari , nominal"}) karena rangkaian {@code + " " + ", nominal Rp. "}.
	 *   Kosmetik, tapi terlihat di kwitansi.</li>
	 *   <li>Syarat {@code getNilai() != null} pada cabang kedua tidak pernah gagal:
	 *   {@link #getNilai()} dirancang tidak pernah mengembalikan {@code null}.</li>
	 *   <li>Karena {@link GeneralValueObject#compareTo(GeneralValueObject)} untuk entity ini
	 *   jatuh ke {@code keterangan}, <b>menyortir daftar cicilan akan memicu seluruh efek samping
	 *   di atas</b> untuk setiap elemen.</li>
	 * </ul>
	 *
	 * @return deskripsi cicilan, bisa {@code null} bila belum diisi dan perakitan tidak memenuhi
	 *         syarat (atau gagal karena relasi lazy yang sudah lepas dari session)
	 */
	@Column(name = "keterangan", columnDefinition = "text")
	public String getKeterangan() {

		itemBiaya = getItemBiaya();

		if ((keterangan == null || keterangan.trim().isEmpty()) && pengaturanPembayaranBulanan != null) {
			try {
				// FIX LazyInitializationException: pengaturanPembayaranBulanan/detailBiaya bisa berupa
				// instance canonical/shared (AuditTimestampInterceptor) yang proxy-nya terikat ke Session
				// lain yang sudah closed -> jangan biarkan getter ini crash, kembalikan fallback aman.
				keterangan = pengaturanPembayaranBulanan.getDetailBiaya().getItemBiaya().getKode() + "-"
						+ pengaturanPembayaranBulanan.getDetailBiaya().getItemBiaya().getNama() + ", bulan "
						+ pengaturanPembayaranBulanan.getNamaBulan() + " " + ", nominal Rp. "
						+ Common.numberFormat.get().format(getNilai())
						+ (getValidator().trim().isEmpty() ? "" : ", validator : " + getValidator())
						+ (getDenda() < 1.1 ? "" : ", Denda : " + getDenda())
						+ (getDenda() < 1.1 ? "" : ", Tagihan sebelum denda : " + getNilaiAsli());
			} catch (Exception exLazy) { ais.common.ErrorAuditUtil.record(exLazy, "auto-audit(empty-catch) src/ais/database/model/CicilanPembayaran.java:getKeterangan-lazy");
			}
		} else if ((keterangan == null || keterangan.trim().isEmpty()) && itemBiaya != null && getNilai() != null) {
			keterangan = itemBiaya.getKode() + "-" + itemBiaya.getNama() + ", nominal Rp. "
					+ Common.numberFormat.get().format(getNilai())
					+ (getValidator().trim().isEmpty() ? "" : ", validator : " + getValidator())
					+ (getDenda() < 1.1 ? "" : ", Denda : " + getDenda())
					+ (getDenda() < 1.1 ? "" : ", Tagihan sebelum denda : " + getNilaiAsli());

		}
		return this.keterangan;
	}

