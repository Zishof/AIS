	/**
	 * Mengembalikan {@link ItemBiaya} (jenis biaya) yang dibayar cicilan ini.
	 *
	 * <p><b>Nilainya terutama diturunkan, bukan disimpan.</b> Urutan penentuannya:</p>
	 * <ol>
	 *   <li>Bila {@link #getPengaturanPembayaranBulanan()} punya {@link DetailBiaya} yang punya
	 *   {@link ItemBiaya}, itulah yang dipakai (tagihan bulanan/angsuran).</li>
	 *   <li>Selain itu, bila {@link #getDetailBiaya()} punya {@link ItemBiaya}, itulah yang
	 *   dipakai.</li>
	 *   <li>Bila keduanya gagal, nilai kolom {@code item_biaya} yang tersimpan dipertahankan.</li>
	 * </ol>
	 *
	 * <p><b>Efek samping:</b> method menugaskan ulang <i>tiga</i> field sekaligus —
	 * {@code pengaturanPembayaranBulanan}, {@code detailBiaya}, dan {@code itemBiaya} — lalu
	 * menjalankan {@link GeneralValueObject#check(Object)} pada hasilnya untuk meresolusi proxy
	 * lazy yang mungkin sudah lepas dari session. Karena {@link #getDetailBiaya()} sendiri juga
	 * menurunkan nilainya dari {@code pengaturanPembayaranBulanan}, satu panggilan ke sini bisa
	 * menimpa {@code detailBiaya} yang tadinya disetel eksplisit lewat
	 * {@link #setDetailBiaya(DetailBiaya)} atau lewat konstruktor
	 * {@link #CicilanPembayaran(DetailBiaya)}.</p>
	 *
	 * <p>Berbeda dari getter lain di kelas ini, kegagalan lazy di sini dicatat ke log
	 * {@code log4j} tingkat {@code warn} (memuat id cicilan) alih-alih ditelan diam-diam —
	 * berguna saat melacak FK rusak pada data lama.</p>
	 *
	 * @return item biaya yang dibayar, atau {@code null} bila tidak ada satu pun sumber yang bisa
	 *         diresolusi
	 * @see GeneralValueObject#check(Object)
	 */
	@ManyToOne(cascade = { CascadeType.PERSIST, CascadeType.MERGE }, fetch = FetchType.LAZY)
	@JoinColumn(name = "item_biaya", nullable = true)
	public ItemBiaya getItemBiaya() {
		try {
			pengaturanPembayaranBulanan = getPengaturanPembayaranBulanan();
			detailBiaya = getDetailBiaya();
			if (pengaturanPembayaranBulanan != null && pengaturanPembayaranBulanan.getDetailBiaya() != null
					&& pengaturanPembayaranBulanan.getDetailBiaya().getItemBiaya() != null) {
				itemBiaya = pengaturanPembayaranBulanan.getDetailBiaya().getItemBiaya();
			} else if (detailBiaya != null && detailBiaya.getItemBiaya() != null) {
				itemBiaya = detailBiaya.getItemBiaya();
			}
		} catch (Exception e) {
			org.apache.log4j.Logger.getLogger(CicilanPembayaran.class).warn("[getItemBiaya] id=" + id + " lazy-load FK rusak (ditangani): " + e.getMessage());
		}

		itemBiaya = check(itemBiaya);

		return itemBiaya;
	}

