	/**
	 * Mengembalikan <b>nominal efektif</b> yang dibayarkan pada cicilan ini — angka inilah yang
	 * dipakai kwitansi, rekap penerimaan, dan posting jurnal.
	 *
	 * <p><b>Getter ini menulis balik ke field {@code nilai}</b> pada ketiga cabang di bawah,
	 * sehingga nilai hasil turunan bisa ikut ter-flush ke database dan menghasilkan revisi Envers
	 * baru. Urutan penentuannya:</p>
	 * <ol>
	 *   <li>{@code nilai} yang {@code null} dinormalkan menjadi {@code 0.0} — karena itu method
	 *   ini tidak pernah mengembalikan {@code null}.</li>
	 *   <li><b>Intervensi manual menang.</b> Bila {@link #getNilaiDiubah()} terisi dan bagian
	 *   bulatnya bukan nol, {@code nilai} <b>ditimpa</b> dengan {@code nilaiDiubah}. Nominal asli
	 *   yang tertimpa tidak disimpan di mana pun oleh method ini (lihat
	 *   {@link #getNilaiAsli()}), dan nominal pecahan di bawah 1 ({@code intValue() == 0})
	 *   dianggap "tidak ada intervensi".</li>
	 *   <li><b>Nominal dari referensi virtual account.</b> Bila tidak ada intervensi manual dan
	 *   {@code ref} diawali {@code "ntt"} serta memuat token {@code "Bulanan"}, nominal dibaca
	 *   dari dalam string {@code ref} itu sendiri. Format yang dibentuk servlet gateway adalah
	 *   <pre>ntt-&lt;idKegiatan&gt;-Bulanan-&lt;idPengaturanPembayaranBulanan&gt;-&lt;nominal&gt;-&lt;idVirtualAccount&gt;</pre>
	 *   yaitu tepat <b>6</b> potongan bila dipecah dengan {@code "-"}; nominal berada pada
	 *   potongan kedua dari belakang. Nilai hanya dipakai bila lebih besar dari 0,1. Prasyarat
	 *   "tepat 6 potongan" itu ketat: bentuk {@code ref} untuk item non-bulanan
	 *   ({@code "Item-..."}) atau varian gateway lain tidak akan pernah lolos, dan itu memang
	 *   disengaja.</li>
	 *   <li><b>Pembalikan tanda untuk diskon.</b> Terakhir, bila {@link #getItemBiaya()} punya
	 *   cara penghitungan {@link ItemBiaya#DIKALI_NILAI_MINUS} (diskon/pengurangan), nominal
	 *   dipaksa negatif dengan {@code -Math.abs(nilai)}. Operasi ini idempoten, jadi pemanggilan
	 *   berulang tidak menggandakan tanda minus — tetapi nilai negatif itu tetap ditulis ke field
	 *   dan bisa tersimpan.</li>
	 * </ol>
	 *
	 * <p>Semua parsing {@code ref} dibungkus dua lapis {@code try/catch}: {@code ref} datang dari
	 * pihak luar (bank/gateway) sehingga formatnya tidak dijamin, dan kegagalan parsing tidak
	 * boleh menggagalkan pembacaan nominal.</p>
	 *
	 * @return nominal efektif cicilan; tidak pernah {@code null}, bisa negatif untuk item diskon
	 * @see #getNilaiAsli()
	 * @see #getNilaiDiubah()
	 * @see #getDenda()
	 */
	public Double getNilai() {
		if (nilai == null) {
			nilai = 0.0;
		}

		if (getNilaiDiubah() != null && getNilaiDiubah().intValue() != 0) {
			nilai = getNilaiDiubah();
		} else {

			try {

				if (ref != null && ref.startsWith("ntt") && ref.contains("Bulanan")) {
					Double subtotal = 0.0;
					try {
						String[] spl = ref.split("-");
						if (spl.length == 6) {
							subtotal = Double.parseDouble(spl[spl.length - 2]);
							if (subtotal > 0.1) {
								nilai = subtotal;
							}
						}
					} catch (Exception e) { ais.common.ErrorAuditUtil.record(e, "auto-audit(empty-catch) src/ais/database/model/CicilanPembayaran.java:250");
					}

				}

			} catch (Exception e) { ais.common.ErrorAuditUtil.record(e, "auto-audit(empty-catch) src/ais/database/model/CicilanPembayaran.java:255");
			}
		}
		if (getItemBiaya() != null && getItemBiaya().getPenghitungan().equals(ItemBiaya.DIKALI_NILAI_MINUS)) {
			nilai = -Math.abs(nilai);
		}

		return nilai;
	}

