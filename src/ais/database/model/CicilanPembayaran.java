	/**
	 * Mengembalikan {@link Kegiatan} (tagihan induk) yang dibayar cicilan ini.
	 *
	 * <p><b>Getter ini memutakhirkan object lain.</b> Sebelum mengembalikan nilai, method
	 * melebarkan rentang tanggal pembayaran pada {@code kegiatan}: bila
	 * {@link #getTanggal()} lebih akhir dari {@link Kegiatan#getTanggalBayarTerakhir()} (atau
	 * rentangnya masih {@code null}) maka {@code tanggalBayarTerakhir} disetel ke tanggal cicilan
	 * ini; hal yang sama berlaku untuk {@link Kegiatan#getTanggalBayarAwal()} pada sisi paling
	 * awal. Karena relasi {@code kegiatan} dipetakan dengan {@code CascadeType.MERGE} dan
	 * {@code PERSIST}, perubahan itu bisa ikut tersimpan pada flush berikutnya.</p>
	 *
	 * <p>Logikanya persis sama dengan yang ada di {@link #setKegiatan(Kegiatan)} — duplikasi
	 * sengaja bersifat "self-healing": kegiatan yang dimuat ulang dari database (jadi tidak
	 * pernah melewati setter Java) tetap mendapat rentang tanggal yang benar begitu salah satu
	 * cicilannya dibaca. Konsekuensinya, rentang tanggal pada {@link Kegiatan} hanya pernah
	 * <b>melebar</b>, tidak pernah menyempit; menghapus cicilan paling awal/akhir tidak
	 * mengoreksinya.</p>
	 *
	 * <p>Seluruh blok dibungkus {@code try/catch} karena {@code kegiatan} bisa berupa proxy lazy
	 * yang session-nya sudah tertutup — kegagalan diabaikan (dicatat ke audit) dan referensi tetap
	 * dikembalikan apa adanya.</p>
	 *
	 * @return kegiatan induk, atau {@code null} bila cicilan belum dikaitkan (mis. cicilan pada
	 *         alur keranjang sementara yang memakai {@link #getKegiatanTemporary()})
	 */
	@ManyToOne(cascade = { CascadeType.PERSIST, CascadeType.MERGE })
	@Fetch(FetchMode.SELECT)
	@JoinColumn(name = "kegiatan", nullable = true)
	public Kegiatan getKegiatan() {
		if (kegiatan != null) {
			try {
				Date tglMax = kegiatan.getTanggalBayarTerakhir();
				Date tglMin = kegiatan.getTanggalBayarAwal();

				if (tglMax == null || getTanggal().after(tglMax)) {
					tglMax = getTanggal();
				}
				if (tglMin == null || getTanggal().before(tglMin)) {
					tglMin = getTanggal();
				}

				kegiatan.setTanggalBayarAwal(tglMin);
				kegiatan.setTanggalBayarTerakhir(tglMax);
			} catch (Exception e) { ais.common.ErrorAuditUtil.record(e, "auto-audit(empty-catch) src/ais/database/model/CicilanPembayaran.java:188");
				// TODO: handle exception
			}
		}

		return kegiatan;
	}

