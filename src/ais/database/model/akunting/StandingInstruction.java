	/**
	 * Hitung status bisnis secara eksplisit tanpa membuat getter persistence bermutasi.
	 *
	 * <p>
	 * <b>Tujuan:</b> menjawab pertanyaan "apakah instruksi ini masih layak diproses?"
	 * berdasarkan keadaan alur SOP dan dokumen penggajian, <b>tanpa</b> menyentuh field
	 * persisten {@link #aktif} &mdash; pemisahan yang sengaja dibuat agar pembacaan status
	 * tidak lagi menerbitkan {@code UPDATE} seperti pada implementasi lama
	 * {@link #getAktif()}.
	 * </p>
	 *
	 * <p>
	 * <b>Cara kerja (urutan singkat-hubung, keputusan pertama yang cocok menang):</b>
	 * </p>
	 * <ol>
	 * <li>Ambil {@link #getDisposisiSop()}. Bila disposisi ada dan {@code getAktif()}-nya
	 * {@code false} &rarr; kembalikan {@code false} (alur SOP-nya sudah dimatikan).</li>
	 * <li>Bila disposisi ada, punya {@code disposisiEnd} dengan {@code alurSop}, dan alur itu
	 * menandai {@code getPenolakanAdaDiSini()} &rarr; kembalikan {@code false} (pengajuan
	 * berakhir di simpul penolakan).</li>
	 * <li>Bila SI ini terkait dokumen penggajian &rarr; status mengikuti dokumen tersebut:
	 * {@code true} hanya bila {@code pembayaranGaji.getDisetujuiOleh() != null}, yakni
	 * penggajiannya sudah disetujui.</li>
	 * <li>Selain itu, jatuh kembali ke nilai kolom lewat {@link #getAktif()}.</li>
	 * </ol>
	 *
	 * <p>
	 * <b>Efek samping:</b> tidak mengubah field mana pun pada objek ini. Namun perlu dicatat
	 * bahwa {@link #getDisposisiSop()} dan {@link #getPembayaranGaji()} yang dipanggil di sini
	 * <i>sendiri</i> dapat menimbulkan pemuatan lazy dan, khusus {@link #getDisposisiSop()},
	 * penimpaan field {@code disposisiSop} dari dokumen gaji.
	 * </p>
	 *
	 * <p>
	 * <b>Kasus tepi:</b> langkah 3 mendereferensi field {@link #pembayaranGaji} secara
	 * langsung setelah memanggil {@link #getPembayaranGaji()}; keduanya merujuk objek yang
	 * sama sehingga aman, tetapi jangan mengubahnya menjadi pemanggilan bersyarat yang
	 * berbeda. Bila {@code disposisiEnd} atau {@code alurSop} bernilai {@code null},
	 * pemeriksaan penolakan dilewati dengan aman berkat rangkaian penjaga {@code null}.
	 * </p>
	 *
	 * <p>
	 * <b>Kapan dipanggil:</b> <span style="font-weight:bold">tidak pernah</span> &mdash;
	 * penelusuran seluruh repo tidak menemukan satu pun pemanggil. Method ini adalah
	 * penampung niat bisnis hasil pembersihan r77032 yang <b>belum dipasang</b> ke layar
	 * mana pun. Selama belum ada pemanggil, aturan "SOP ditolak &rarr; SI tidak aktif" tetap
	 * tidak berlaku di produksi (lihat {@link #getAktif()}). Bila kelak dipasang, kandidat
	 * lokasinya adalah penyaring {@code aktif} di
	 * {@code AmbilDataStandingInstructionBanyak} dan pemilihan SI ke dalam batch di
	 * {@code ProsesTransferStandingInstructionAction}.
	 * </p>
	 *
	 * @return {@code true} bila instruksi ini masih layak diproses menurut SOP dan status
	 *         dokumen penggajian; {@code false} bila alur SOP dimatikan/ditolak atau dokumen
	 *         penggajiannya belum disetujui
	 */
	public Boolean hitungAktifDariStatus() {
		DisposisiSop currentDisposisi = getDisposisiSop();
		if (currentDisposisi != null && !currentDisposisi.getAktif()) return false;
		if (currentDisposisi != null && currentDisposisi.getDisposisiEnd() != null
				&& currentDisposisi.getDisposisiEnd().getAlurSop() != null
				&& currentDisposisi.getDisposisiEnd().getAlurSop().getPenolakanAdaDiSini()) return false;
		if (getPembayaranGaji() != null) return pembayaranGaji.getDisetujuiOleh() != null;
		return getAktif();
	}

