	/**
	 * Apakah cara pembayaran ini masih boleh dipakai.
	 *
	 * <p><b>Getter menormalkan <code>null</code> menjadi {@code true}</b> &mdash; kebalikan dari
	 * {@link #getDefaultPembayaran()}. Artinya baris lama yang kolomnya belum pernah diisi
	 * dianggap <b>aktif</b>. Semua query pemakainya menirukan aturan ini secara eksplisit dengan
	 * <code>aktif IS NULL OR aktif = true</code> (layar ZK, {@code ProsesTransferAction},
	 * {@code NewUiTransferWorkflowService}), dan SQL REST memakai
	 * <code>COALESCE(m.aktif, true)</code> &mdash; jadi perilakunya konsisten di semua jalur.</p>
	 *
	 * <p><b>Efek menonaktifkan:</b> baris hilang dari combo &quot;Cara Transfer&quot; sehingga
	 * tidak dapat dipilih untuk proses transfer baru, dan {@code NewUiTransferWorkflowService
	 * .createProcess} menolak membuat proses dengan cara transfer non-aktif. Dokumen lama yang
	 * sudah terlanjur memakainya <b>tidak</b> terpengaruh &mdash; relasi FK-nya tetap dan mesin
	 * posting tidak memeriksa bendera ini, sehingga dokumen lama tetap bisa diposting.</p>
	 *
	 * @return {@code true} bila aktif (termasuk bila kolomnya <code>null</code>); {@code false} bila dinonaktifkan
	 */
