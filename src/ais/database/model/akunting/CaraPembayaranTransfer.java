	/**
	 * Memuat ulang cache {@link #DEFAULT_JENIS_PEMBAYARAN} dan &mdash; bila belum ada baris bawaan
	 * &mdash; <b>membuat baris &quot;Tunai&quot; baru di database</b>.
	 *
	 * <p><b>Tujuan.</b> Menjamin instalasi baru selalu memiliki satu cara pembayaran bertanda
	 * default, agar layar Proses Transfer punya nilai awal.</p>
	 *
	 * <p><b>Kapan dipanggil.</b> Terverifikasi hanya dari satu tempat:
	 * {@code InitData.reloadDefaults()} (baris ~714), yaitu rangkaian penyemaian yang berjalan
	 * <b>saat aplikasi start</b> dan setiap kali penyemaian itu dijalankan ulang. Tidak dipanggil
	 * dari layar mana pun.</p>
	 *
	 * <p><b>Cara kerja &amp; efek samping (penting):</b></p>
	 * <ol>
	 *   <li>Mengambil sesi native milik thread ({@code HibernateUtil.currentNativeSession()}).</li>
	 *   <li>Mencari satu baris ber-<code>defaultPembayaran = true</code> &mdash; <b>tanpa</b>
	 *       filter satuan kerja, <b>tanpa</b> filter {@code aktif}, <b>tanpa</b> syarat punya akun,
	 *       dan <b>tanpa</b> urutan yang ditentukan. Baris mana yang terpilih karena itu tidak
	 *       dapat diandalkan bila ada lebih dari satu default (dan memang bisa ada lebih dari satu,
	 *       lihat Javadoc kelas: keunikan default hanya per satuan kerja di jalur ZK).</li>
	 *   <li><b>Bila tidak ketemu, method ini MENULIS ke database</b>: membuka transaksi dan
	 *       menyimpan baris baru bernama <code>&quot;Tunai&quot;</code>, deskripsi
	 *       <code>&quot;Bayar Tunai&quot;</code>, {@code defaultPembayaran = true}. Baris hasil
	 *       penyemaian ini <b>tidak punya kode, tidak punya akun, tidak punya akun transitori, dan
	 *       tidak punya satuan kerja</b>. Karena tanpa akun, ia otomatis <b>tersaring keluar</b>
	 *       dari combo maupun pencarian default {@code ProsesTransferAction} (yang mensyaratkan
	 *       {@code akun IS NOT NULL}) &mdash; jadi ia menempati bendera default secara global
	 *       tanpa pernah benar-benar terpakai, dan di daftar REST ia muncul dengan
	 *       <code>akunLengkap = false</code>. Pada instalasi yang sudah berjalan, keberadaan baris
	 *       ini juga membuat penyemaian tidak pernah berulang.</li>
	 *   <li>Menutup sesi: {@code session.disconnect()}, {@code session.close()}, lalu
	 *       {@code HibernateUtil.closeSession()}.</li>
	 * </ol>
	 *
	 * <p><b>Bahaya kontrak sesi (pola yang sama sudah dicatat pada {@link JenisKasBesar}).</b>
	 * Langkah penutupan di atas menutup <i>sesi milik thread pemanggil</i>, bukan sesi lokal milik
	 * method ini. Selama pemanggilnya hanya {@code InitData} pada saat startup (tidak ada request
	 * ZK yang sedang berjalan di thread itu) hal ini tidak terasa; tetapi memanggil
	 * {@code reloadDefault()} dari dalam event ZK akan <b>menutup sesi Hibernate yang sedang
	 * dipakai halaman</b> dan membuat operasi berikutnya di request yang sama gagal. Jangan
	 * menambahkan pemanggil baru dari lapisan UI.</p>
	 *
	 * <p><b>Penanganan error:</b> tidak ada. Tidak ada <code>try/catch</code> dan tidak ada
	 * rollback; kegagalan {@code commit()} akan menyebar ke {@code InitData} dan sesi berpotensi
	 * tidak tertutup karena baris penutupan berada setelah blok transaksi.</p>
	 *
	 * @see #DEFAULT_JENIS_PEMBAYARAN
	 */
	public static void reloadDefault() {
		Session session = HibernateUtil.currentNativeSession();
		DEFAULT_JENIS_PEMBAYARAN = (CaraPembayaranTransfer) session.createCriteria(CaraPembayaranTransfer.class)
				.add(Restrictions.eq("defaultPembayaran", true)).setMaxResults(1).uniqueResult();

		if (DEFAULT_JENIS_PEMBAYARAN == null) {
			DEFAULT_JENIS_PEMBAYARAN = new CaraPembayaranTransfer();
			DEFAULT_JENIS_PEMBAYARAN.setNama("Tunai");
			DEFAULT_JENIS_PEMBAYARAN.setDeskripsi("Bayar Tunai");
			DEFAULT_JENIS_PEMBAYARAN.setDefaultPembayaran(true);
			session.getTransaction().begin();
			session.save(DEFAULT_JENIS_PEMBAYARAN);
			session.getTransaction().commit();
		}
		// session.disconnect();
		if (session.isOpen()) {session.disconnect();session.close();}
		HibernateUtil.closeSession();
	}

