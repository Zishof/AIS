	@Fetch(FetchMode.SELECT)
	@JoinColumn(name = "tagihan", nullable = true)
	public Tagihan getTagihan() {
		return tagihan;
	}

	/**
	 * Menetapkan tagihan modul sekolah yang dibayar baris ini.
	 *
	 * @param tagihan tagihan sekolah; boleh {@code null}.
	 */
	public void setTagihan(Tagihan tagihan) {
		this.tagihan = tagihan;
	}

	/**
	 * Mengembalikan referensi cicilan sekunder baris ini.
	 * <p>
	 * Pendamping {@link #getIdCicilan()} untuk skenario ketika satu rincian
	 * berkaitan dengan lebih dari satu jejak cicilan.
	 *
	 * @return referensi cicilan, atau {@code null}.
	 */
	public Long getCicilanref() {
		return cicilanref;
	}

	/**
	 * Menetapkan referensi cicilan sekunder baris ini.
	 *
	 * @param cicilanref referensi cicilan.
	 */
	public void setCicilanref(Long cicilanref) {
		this.cicilanref = cicilanref;
	}

