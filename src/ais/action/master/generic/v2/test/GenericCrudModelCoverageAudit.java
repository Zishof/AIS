package ais.action.master.generic.v2.test;

import java.util.List;
import java.util.Map;
import java.util.HashMap;

import ais.action.master.generic.v2.GenericCrudAutoDefinitionFactory;
import ais.action.master.generic.v2.GenericCrudDefinition;
import ais.action.master.generic.v2.GenericCrudDefinitionRegistry;

/** Audit read-only cakupan model Hibernate terhadap lifecycle Action existing. */
@SuppressWarnings("rawtypes")
public final class GenericCrudModelCoverageAudit {
    private GenericCrudModelCoverageAudit() { }

    public static void main(String[] args) {
        List models = GenericCrudAutoDefinitionFactory.listAdministrativeModels();
        Map explicitByClass = new HashMap();
        List explicitDefinitions = GenericCrudDefinitionRegistry.listDefinitions();
        for (int e = 0; e < explicitDefinitions.size(); e++) {
            GenericCrudDefinition definition = (GenericCrudDefinition) explicitDefinitions.get(e);
            if (!definition.isAutoGenerated() && definition.getEntityClass() != null) {
                explicitByClass.put(definition.getEntityClass().getName(), definition);
            }
        }
        int restricted = 0, registered = 0, create = 0, update = 0, delete = 0;
        int actionBound = 0, metadataBound = 0, explicit = 0, unbound = 0;
        for (int i = 0; i < models.size(); i++) {
            Map row = (Map) models.get(i);
            if (Boolean.TRUE.equals(row.get("restricted"))) restricted++;
            String entityKey = String.valueOf(row.get("entityKey"));
            GenericCrudDefinition definition = GenericCrudDefinitionRegistry.tryAdministrativeRegister(
                    "generic", "model_" + i, entityKey);
            if (definition == null) continue;
            registered++;
            GenericCrudDefinition routed = (GenericCrudDefinition) explicitByClass.get(entityKey);
            if (routed != null) {
                explicit++;
                definition = routed;
            }
            if (definition.isExistingActionLifecycleBound()) actionBound++;
            if (definition.isMetadataLifecycleBound()) {
                metadataBound++;
                if (metadataBound <= 10) System.out.println("METADATA entity=" + entityKey);
            }
            if (!Boolean.TRUE.equals(row.get("restricted"))
                    && definition.isAutoGenerated()
                    && !definition.isExistingActionLifecycleBound()
                    && !definition.isMetadataLifecycleBound()) {
                unbound++;
                System.out.println("UNBOUND entity=" + entityKey + " action="
                        + definition.getSourceActionClassName());
            }
            if (definition.isCreateEnabled()) create++;
            if (definition.isUpdateEnabled()) update++;
            if (definition.isDeleteEnabled()) delete++;
        }
        System.out.println("GenericCrudModelCoverageAudit models=" + models.size()
                + " registered=" + registered + " restricted=" + restricted
                + " actionBound=" + actionBound + " metadataBound=" + metadataBound
                + " explicit=" + explicit + " unbound=" + unbound + " create=" + create
                + " update=" + update + " delete=" + delete);
        if (models.isEmpty() || registered != models.size()) {
            throw new IllegalStateException("Metadata model Hibernate tidak dapat diaudit seluruhnya.");
        }
        System.exit(0);
    }
}
