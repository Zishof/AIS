    public String getIdentifierProperty() { return identifierProperty; }
    public void setIdentifierProperty(String value) { identifierProperty = value; }
    public String getVersionProperty() { return versionProperty; }
    public void setVersionProperty(String value) { versionProperty = value; }
    public String getDefaultSortProperty() { return defaultSortProperty; }
    public void setDefaultSortProperty(String value) { defaultSortProperty = value; }
    public boolean isDefaultSortAscending() { return defaultSortAscending; }
    public void setDefaultSortAscending(boolean value) { defaultSortAscending = value; }
    public int getDefaultPageSize() { return defaultPageSize; }
    public void setDefaultPageSize(int value) { defaultPageSize = value; }
    public int getMaxPageSize() { return maxPageSize; }
    public void setMaxPageSize(int value) { maxPageSize = value; }
    public int getLookupThreshold() { return lookupThreshold; }
    public void setLookupThreshold(int value) { lookupThreshold = value; }
    public int getMaxExportRows() { return maxExportRows; }
    public void setMaxExportRows(int value) { maxExportRows = value; }
    public int getMaxImportRows() { return maxImportRows; }
    public void setMaxImportRows(int value) { maxImportRows = value; }
    public int getSynchronousExportLimit() { return synchronousExportLimit; }
    public void setSynchronousExportLimit(int value) { synchronousExportLimit = value; }
    public String getFormMode() { return formMode; }
    public void setFormMode(String value) { formMode = value; }
    public GenericCrudEntityAdapter getAdapter() { return adapter; }
    public void setAdapter(GenericCrudEntityAdapter value) { adapter = value; }
    public GenericCrudAuditRevisionAdapter getAuditRevisionAdapter() { return auditRevisionAdapter; }
    public void setAuditRevisionAdapter(GenericCrudAuditRevisionAdapter value) { auditRevisionAdapter = value; }
