    private GenericCrudAuditRevisionAdapter auditRevisionAdapter;
    private GenericCrudScopeAdapter scopeAdapter;
    private GenericCrudRestorePolicy restorePolicy;
    private GenericCrudPermanentDeletePolicy permanentDeletePolicy;
    private GenericCrudFormOverrideProvider formOverrideProvider;

