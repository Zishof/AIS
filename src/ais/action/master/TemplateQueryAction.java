	public boolean onSave(Event event) throws Exception {
		if (nama.getValue().trim().equals("")) {
			PesanFormalHelper.tampilkanGagal("penyimpanan data Template Query",
					"Kolom Nama Template Query belum Bapak/Ibu isi, padahal kolom ini wajib diisi sebelum data dapat disimpan.",
					new String[] {
							"Isi/pilih terlebih dahulu Nama Template Query.",
							"Ulangi proses penyimpanan setelah kolom tersebut terisi."
					});
			return false;
		}
		if (query.getValue().trim().equals("")) {
			PesanFormalHelper.tampilkanGagal("penyimpanan data Isi Template Query",
					"Kolom Isi Template Query belum Bapak/Ibu isi, padahal kolom ini wajib diisi sebelum data dapat disimpan.",
					new String[] {
							"Isi/pilih terlebih dahulu Isi Template Query.",
							"Ulangi proses penyimpanan setelah kolom tersebut terisi."
					});
			return false;
		}

		if (query.getValue().trim().toLowerCase().contains("update")) {
			MyMessageboxConfig.show("Isi Template Query tidak boleh ada kata update",
					"Peringatan", MyMessageboxConfig.OK, MyMessageboxConfig.INFORMATION);
			return false;
		}

		if (query.getValue().trim().toLowerCase().contains("delete")) {
			MyMessageboxConfig.show("Isi Template Query tidak boleh ada kata delete",
					"Peringatan", MyMessageboxConfig.OK, MyMessageboxConfig.INFORMATION);
			return false;
		}

		if (query.getValue().trim().toLowerCase().contains("truncate")) {
			MyMessageboxConfig.show("Isi Template Query tidak boleh ada kata truncate",
					"Peringatan", MyMessageboxConfig.OK, MyMessageboxConfig.INFORMATION);
			return false;
		}

		if (query.getValue().trim().toLowerCase().contains("drop")) {
			MyMessageboxConfig.show("Isi Template Query tidak boleh ada kata drop",
					"Peringatan", MyMessageboxConfig.OK, MyMessageboxConfig.INFORMATION);
			return false;
		}

		if (query.getValue().trim().toLowerCase().contains("alter")) {
			MyMessageboxConfig.show("Isi Template Query tidak boleh ada kata alter",
					"Peringatan", MyMessageboxConfig.OK, MyMessageboxConfig.INFORMATION);
			return false;
		}

		boolean i = checkNamaTemplateQuery();
		if (i) {
			PesanFormalHelper.tampilkanGagal("penyimpanan data Template Query",
					"Nama Template Query sudah terdaftar sebelumnya di database, sehingga tidak dapat disimpan kembali untuk menghindari duplikasi data.",
					new String[] {
							"Gunakan nama template query yang berbeda dari data yang sudah ada.",
							"Periksa kembali daftar data yang sudah tersimpan apabila Bapak/Ibu ragu."
					});
			return false;
		}

		TemplateQueryDao templateQueryDao = DaoFactory.getInstance()
				.getTemplateQueryDao();
		if (templateQuery.getId() != null) {
			templateQuery = templateQueryDao.load(templateQuery.getId());

		}

		templateQuery.setNama(nama.getValue());
		templateQuery.setKeterangan(keterangan.getValue());
		templateQuery.setQuery(query.getValue());

		if (templateQuery.getId() != null) {
			templateQueryDao.update(templateQuery);
		} else {
			templateQueryDao.save(templateQuery);
		}

		return true;
	}

	public Criteria initCriteria(boolean order) {
		Session session = HibernateUtil.currentSession();
		Criteria criteria = session.createCriteria(TemplateQuery.class);

		if (order)
			criteria.addOrder(Order.asc("nama"));
		criteria.add(Restrictions.ilike("nama", searchnama.getValue(),
				MatchMode.ANYWHERE));
		return criteria;
	}

	@SuppressWarnings("unchecked")
	public void onSearchDefault(Event event) {
		Common.initPaging(initCriteria(false), paging);

		List<TemplateQuery> templateQuery = initCriteria(true)
				.setMaxResults(Common.ROWS_COUNT_ON_PAGE)
				.setFirstResult(
						Common.ROWS_COUNT_ON_PAGE
								* (paging == null ? 0 : paging.getActivePage()))
				.list();
		ListModel strset = new SimpleListModel(templateQuery);
		grid.setRowRenderer(new TemplateQueryRenderer());
		grid.setModelCheckMobile(strset);

		

	}

	public Boolean checkNamaTemplateQuery() {

		Integer kotaCount = null;
		Session session = HibernateUtil.currentSession();
		kotaCount = ((Number) session
				.createCriteria(TemplateQuery.class)
				.setProjection(Projections.rowCount())
				.add(Restrictions.eq("nama", nama.getValue().trim()))
				.add(this.templateQuery.getId() == null ? Restrictions
						.sqlRestriction("1=1") : Restrictions.ne("id",
						this.templateQuery.getId())).uniqueResult()).intValue();

		return !kotaCount.equals(0);
	}

