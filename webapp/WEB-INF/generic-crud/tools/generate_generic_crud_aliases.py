#!/usr/bin/env python3
"""
Generate alias JSP/service files and disabled SQL seeds from the inventory made by
scan_general_value_objects.py.

This tool deliberately does NOT generate business logic and does NOT enable any
entity. It creates thin aliases that delegate to the shared Generic CRUD renderer
and dispatcher. Hibernate runtime metadata, menu binding, scope, privilege, and
adapter review remain mandatory before activation.
"""
from __future__ import print_function

import argparse
import csv
import hashlib
import json
import os
import re
import sys
from collections import defaultdict

MARKER = "@generated by generate_generic_crud_aliases.py"
ALLOWED_DEFAULT = set(["ELIGIBLE_METADATA_FIRST", "ELIGIBLE_PARITY_FIRST", "REVIEW_REQUIRED"])


def read_rows(path):
    with open(path, "r", encoding="utf-8-sig", newline="") as fh:
        return list(csv.DictReader(fh))


def snake(name):
    value = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", name)
    value = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", value)
    value = re.sub(r"[^A-Za-z0-9]+", "_", value).strip("_").lower()
    return value or "entity"


def java_string(value):
    return (value or "").replace("\\", "\\\\").replace('"', '\\"').replace("\r", " ").replace("\n", " ")


def sql_string(value):
    if value is None:
        return "NULL"
    return "'" + str(value).replace("'", "''") + "'"


def action_to_module(path):
    p = (path or "").replace("\\", "/").strip("/")
    prefix = "ais/action/"
    if not p.startswith(prefix):
        return None
    rel = p[len(prefix):]
    parts = rel.split("/")
    if not parts:
        return None
    if parts[0] == "master":
        rest = parts[1:]
        if len(rest) <= 1:  # file directly under master
            return "root"
        first = rest[0]
        if first in ("pmb", "psb"):
            return "root/" + first
        return first
    first = parts[0]
    if first in ("pmb", "psb", "maintenance", "report", "servlet", "ws", "mobile", "iso8583"):
        return "root/" + first
    return "root/" + first


def model_fallback_module(row):
    module = (row.get("module") or "root").strip().replace("\\", "/")
    if not module or module == "external":
        return "root"
    if module in ("pmb", "psb"):
        return "root/" + module
    return module


def modules_for_row(row):
    modules = []
    for action in (row.get("existing_actions") or "").split("|"):
        mod = action_to_module(action)
        if mod and mod not in modules:
            modules.append(mod)
    fallback = model_fallback_module(row)
    if fallback not in modules:
        modules.append(fallback)
    # Keep root first, then root/*, then alphabetical for deterministic canonical route.
    modules.sort(key=lambda x: (0 if x == "root" else 1 if x.startswith("root/") else 2, x))
    return modules


def ensure_parent(path):
    parent = os.path.dirname(path)
    if not os.path.isdir(parent):
        os.makedirs(parent)


def write_generated(path, content, force=False):
    if os.path.exists(path):
        with open(path, "r", encoding="utf-8", errors="ignore") as fh:
            current = fh.read(2048)
        if MARKER not in current:
            return "SKIPPED_MANUAL"
        if not force:
            return "SKIPPED_GENERATED"
    ensure_parent(path)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(content)
    return "WRITTEN"


def ui_jsp(row, module, page_key):
    template = """<%@ page contentType=\"text/html; charset=UTF-8\" pageEncoding=\"UTF-8\" %>
<%-- {marker}
     Thin alias only. All authorization, metadata, query, mutation, and audit
     must be handled by the Java Generic CRUD service/facade. --%>
<%
request.setAttribute(\"genericCrudEntityKey\", \"{entity_key}\");
request.setAttribute(\"genericCrudModuleKey\", \"{module}\");
request.setAttribute(\"genericCrudPageKey\", \"{page_key}\");
request.setAttribute(\"genericCrudDisplayName\", \"{display_name}\");
pageContext.include(\"/WEB-INF/new/_shared/generic-crud/ui/crud_page.jsp\", true);
%>
"""
    return template.format(marker=MARKER,
                           entity_key=java_string(row["entity_key"]),
                           module=java_string(module),
                           page_key=java_string(page_key),
                           display_name=java_string(row.get("display_name")))


def service_jsp(row, module, page_key):
    template = """<%@ page contentType=\"application/json; charset=UTF-8\" pageEncoding=\"UTF-8\" %>
<%-- {marker}
     Thin service alias. Dispatcher must perform authentication, active-role,
     menu privilege, object scope, CSRF, validation, audit, and error mapping. --%>
<%
request.setAttribute(\"genericCrudEntityKey\", \"{entity_key}\");
request.setAttribute(\"genericCrudModuleKey\", \"{module}\");
request.setAttribute(\"genericCrudPageKey\", \"{page_key}\");
request.getRequestDispatcher(\"/WEB-INF/new/_shared/generic-crud/services/dispatcher.jsp\")
       .forward(request, response);
return;
%>
"""
    return template.format(marker=MARKER,
                           entity_key=java_string(row["entity_key"]),
                           module=java_string(module),
                           page_key=java_string(page_key))


def disambiguated_page_key(base, row, module, used):
    key = (module, base)
    if key not in used:
        used[key] = row["entity_key"]
        return base, ""
    if used[key] == row["entity_key"]:
        return base, "DUPLICATE_SAME_ENTITY"
    package_tail = snake((row.get("package") or "").replace("ais.database.model", ""))
    candidate = base + ("_" + package_tail if package_tail else "")
    key2 = (module, candidate)
    if key2 not in used:
        used[key2] = row["entity_key"]
        return candidate, "RENAMED_PACKAGE"
    digest = hashlib.sha1(row["entity_key"].encode("utf-8")).hexdigest()[:8]
    candidate = base + "_" + digest
    used[(module, candidate)] = row["entity_key"]
    return candidate, "RENAMED_HASH"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--inventory", required=True, help="general_value_object_inventory.csv")
    parser.add_argument("--output-root", required=True, help="Output root; generated webapp/sql/manifests are placed here")
    parser.add_argument("--statuses", default=",".join(sorted(ALLOWED_DEFAULT)),
                        help="Comma-separated eligibility statuses")
    parser.add_argument("--force-generated", action="store_true",
                        help="Overwrite only files carrying this generator marker")
    parser.add_argument("--include-not-entity", action="store_true")
    args = parser.parse_args()

    rows = read_rows(args.inventory)
    statuses = set(x.strip() for x in args.statuses.split(",") if x.strip())
    output_root = os.path.abspath(args.output_root)
    used = {}
    bindings = []
    file_results = defaultdict(int)
    collisions = []

    eligible_rows = []
    for row in rows:
        if str(row.get("abstract", "")).lower() == "true":
            continue
        if not args.include_not_entity and str(row.get("entity", "")).lower() != "true":
            continue
        if row.get("eligibility") not in statuses:
            continue
        eligible_rows.append(row)

    # Stable order prevents noisy diffs.
    eligible_rows.sort(key=lambda r: (r.get("entity_key") or ""))

    for row in eligible_rows:
        base = snake(row.get("class_name") or "entity")
        modules = modules_for_row(row)
        for index, module in enumerate(modules):
            page_key, collision = disambiguated_page_key(base, row, module, used)
            if collision and collision != "DUPLICATE_SAME_ENTITY":
                collisions.append({
                    "entity_key": row["entity_key"],
                    "module_key": module,
                    "requested_page_key": base,
                    "generated_page_key": page_key,
                    "resolution": collision,
                })
            ui_path = os.path.join(output_root, "webapp", "WEB-INF", "new", *module.split("/"), "uiux", page_key + ".jsp")
            service_path = os.path.join(output_root, "webapp", "WEB-INF", "new", *module.split("/"), "services", page_key + "_service.jsp")
            ui_result = write_generated(ui_path, ui_jsp(row, module, page_key), args.force_generated)
            service_result = write_generated(service_path, service_jsp(row, module, page_key), args.force_generated)
            file_results["ui_" + ui_result] += 1
            file_results["service_" + service_result] += 1
            bindings.append({
                "entity_key": row["entity_key"],
                "class_name": row.get("class_name"),
                "display_name": row.get("display_name"),
                "module_key": module,
                "page_key": page_key,
                "canonical": index == 0,
                "eligibility": row.get("eligibility"),
                "review_reason": row.get("eligibility_reason"),
                "ui_path": os.path.relpath(ui_path, output_root).replace("\\", "/"),
                "service_path": os.path.relpath(service_path, output_root).replace("\\", "/"),
                "existing_actions": row.get("existing_actions"),
            })

    manifest_dir = os.path.join(output_root, "manifests")
    if not os.path.isdir(manifest_dir):
        os.makedirs(manifest_dir)
    fields = [
        "entity_key", "class_name", "display_name", "module_key", "page_key",
        "canonical", "eligibility", "review_reason", "ui_path", "service_path",
        "existing_actions"
    ]
    with open(os.path.join(manifest_dir, "generic_crud_page_bindings.csv"), "w", encoding="utf-8", newline="") as fh:
        wr = csv.DictWriter(fh, fieldnames=fields)
        wr.writeheader(); wr.writerows(bindings)
    with open(os.path.join(manifest_dir, "generic_crud_page_bindings.json"), "w", encoding="utf-8") as fh:
        json.dump(bindings, fh, ensure_ascii=False, indent=2)
    with open(os.path.join(manifest_dir, "alias_collisions.json"), "w", encoding="utf-8") as fh:
        json.dump(collisions, fh, ensure_ascii=False, indent=2)

    sql_dir = os.path.join(output_root, "sql")
    if not os.path.isdir(sql_dir):
        os.makedirs(sql_dir)
    seed_path = os.path.join(sql_dir, "seed_generic_crud_entities_disabled.sql")
    canonical_by_entity = {}
    for b in bindings:
        if b["canonical"] and b["entity_key"] not in canonical_by_entity:
            canonical_by_entity[b["entity_key"]] = b

    with open(seed_path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("-- %s\n" % MARKER)
        fh.write("-- All entities and page bindings are disabled/review-required by design.\nBEGIN;\n\n")
        for row in eligible_rows:
            b = canonical_by_entity.get(row["entity_key"])
            if not b:
                continue
            status = "REVIEW_REQUIRED"
            note = (row.get("eligibility") or "") + ": " + (row.get("eligibility_reason") or "")
            fh.write("INSERT INTO generic_crud_entity_config\n")
            fh.write("    (entity_key, entity_class, module_key, page_key, display_name, lifecycle_status, enabled, read_only, review_notes)\n")
            fh.write("SELECT %s, %s, %s, %s, %s, %s, false, true, %s\n" % (
                sql_string(row["entity_key"]), sql_string(row["entity_key"]),
                sql_string(b["module_key"]), sql_string(b["page_key"]),
                sql_string(row.get("display_name") or row.get("class_name")),
                sql_string(status), sql_string(note)))
            fh.write("WHERE NOT EXISTS (SELECT 1 FROM generic_crud_entity_config WHERE entity_key = %s);\n\n" % sql_string(row["entity_key"]))
        for b in bindings:
            fh.write("INSERT INTO generic_crud_page_binding\n")
            fh.write("    (entity_config_id, module_key, page_key, display_name_override, enabled)\n")
            fh.write("SELECT e.id, %s, %s, %s, false\n" % (
                sql_string(b["module_key"]), sql_string(b["page_key"]), sql_string(b["display_name"])))
            fh.write("FROM generic_crud_entity_config e\n")
            fh.write("WHERE e.entity_key = %s\n" % sql_string(b["entity_key"]))
            fh.write("  AND NOT EXISTS (SELECT 1 FROM generic_crud_page_binding x WHERE x.module_key = %s AND x.page_key = %s);\n\n" % (
                sql_string(b["module_key"]), sql_string(b["page_key"])))
        fh.write("COMMIT;\n")

    report = {
        "inventory_rows": len(rows),
        "eligible_entity_rows": len(eligible_rows),
        "page_bindings": len(bindings),
        "collisions": len(collisions),
        "file_results": dict(sorted(file_results.items())),
        "output_root": output_root,
        "warning": "Generated aliases and SQL seeds are disabled. Verify Hibernate runtime metadata, menu IDs, privilege, scope, fields, and adapters before activation."
    }
    with open(os.path.join(manifest_dir, "alias_generation_report.json"), "w", encoding="utf-8") as fh:
        json.dump(report, fh, ensure_ascii=False, indent=2)
    print(json.dumps(report, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
